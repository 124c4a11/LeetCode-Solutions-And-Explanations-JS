/**
 * @param {number[]} nums
 * @param {number} target
 * @return {number}
 *
 * countPairs принимает 0-индексированный целочисленный массив nums длины n
 * и целое число target.
 *
 * Возвращает количество пар (i, j), где 0 <= i < j < n и
 * nums[i] + nums[j] < target.
 *
 * Пример для:
 *   nums = [-1,1,2,3,1],
 *   target = 2
 * Результат:
 *   3
 * Пояснение:
 *   Существует 3 пары индексов, удовлетворяющих условиям задачи:
 *   - (0, 1), так как 0 < 1 и nums[0] + nums[1] = 0 < target
 *   - (0, 2), так как 0 < 2 and nums[0] + nums[2] = 1 < target
 *   - (0, 4), так как 0 < 4 and nums[0] + nums[4] = 0 < target
 *
 *   Обратите внимание, что пара (0, 3) не учитывается, так как
 *   nums[0] + nums[3] не строго меньше, чем target.
 */
function countPairs(nums, target) {

  // Ключевая идея заключается в том, что после сортировки массива мы можем
  // эффективно находить подходящие пары, используя свойство
  // упорядоченности элементов.
  //
  // Рассмотрим это следующим образом: если зафиксировать второй элемент
  // пары на позиции j, нам нужно найти все элементы на позициях i < j, для
  // которых nums[i] + nums[j] < target. Это равносильно поиску всех
  // элементов nums[i] < target - nums[j].
  //
  // В отсортированном массиве все элементы, меньшие определённого значения,
  // образуют непрерывный отрезок в его начале. Поэтому вместо того, чтобы
  // проверять каждый элемент перед позицией j по отдельности (что было бы
  // неэффективно), мы можем использовать бинарный поиск, чтобы быстро
  // найти границу - первую позицию, на которой nums[i] >= target - nums[j].
  // Все элементы до этой границы образуют подходящие пары с nums[j].
  //
  // Почему это работает? Благодаря свойству отсортированного массива:
  // 1. Если для некоторого i выполняется nums[i] + nums[j] < target, то
  //    это условие выполняется и для всех индексов меньше i, поскольку
  //    соответствующие элементы ещё меньше.
  //
  // 2. Мы можем найти эту границу за логарифмическое время с помощью
  //    бинарного поиска.
  //
  // Перебирая каждый возможный второй элемент j и используя бинарный поиск
  // для подсчёта подходящих первых элементов, мы превращаем решение полным
  // перебором за O(n²) в алгоритм со сложностью O(n log n).
  //
  // Сначала сортировка занимает O(n log n), затем выполняются n бинарных
  // поисков, каждый из которых занимает O(log n).
  //
  // Итоговая временная сложность: O(n log n).


  // Сортировка исходного массива по возрастанию, чтобы можно было
  // применить бинарный поиск
  nums.sort((a, b) => a - b);

  // Объявляем внутреннюю функцию бинарного поиска.
  //
  // Она ищет самый левый (первый) индекс элемента, который при сложении с
  // текущим nums[j] дает значение, равное или большее target (то есть
  // нарушает условие задачи nums[i] + nums[j] < target).
  function binarySearchFirstInvalidNdx(searchValue, rightBoundary) {

    // Инициализируем переменную для хранения индекса первого нарушителя.
    //
    // Изначально присваиваем ей значение rightBoundary (индекс j).
    //
    // Если в цикле не найдется ни одного элемента >= searchValue, это
    // будет означать, что абсолютно все элементы слева от j (всего их j
    // штук) подходят под условие.
    let firstInvalidNdx = rightBoundary;

    // Устанавливаем указатель левой границы поиска на самый первый элемент
    // подмассива (индекс 0).
    let l = 0;

    // Устанавливаем указатель правой границы поиска на последний возможный
    // элемент перед текущим j (индекс j - 1).
    let r = rightBoundary - 1;

    // Запускаем цикл бинарного поиска, который продолжается до тех пор,
    // пока левая граница l не зайдет за правую границу r.
    while (l <= r) {

      // Вычисляем индекс элемента строго посередине между текущими
      // границами l и r, округляя результат вниз до целого числа.
      //
      // Формула l + (r - l) / 2 используется для предотвращения
      // потенциального переполнения чисел.
      const midd = Math.floor(l + (r - l) / 2);

      // Проверяем, является ли элемент на позиции midd слишком большим.
      //
      // Условие nums[midd] >= searchValue математически равносильно
      // условию nums[midd] + nums[j] >= target.
      if (nums[midd] >= searchValue) {

        // Если элемент нарушает условие задачи (слишком большой), мы
        // запоминаем его индекс midd как текущего "первого невалидного".
        //
        // Все элементы правее него тоже гарантированно будут слишком
        // большими из-за сортировки.
        firstInvalidNdx = midd;

        // Сдвигаем правую границу поиска r влево (в позицию midd - 1),
        // чтобы проверить, нет ли еще более левого (с меньшим индексом)
        // элемента, который также нарушает условие.
        r = midd - 1;

        // Если элемент на позиции midd меньше searchValue, это значит,
        // что пара nums[midd] + nums[j] < target валидна.
      } else {

        // Так как массив отсортирован, все элементы левее midd тоже
        // автоматически валидны. Поэтому мы сдвигаем левую границу l
        // вправо (в позицию midd + 1), чтобы продолжить искать нарушителей
        // в правой половине диапазона.
        l = midd + 1;
      }
    }

    // Возвращаем итоговый индекс первого невалидного элемента.
    //
    // Так как индексы начинаются с 0, значение firstInvalidNdx в точности
    // совпадает с количеством валидных элементов, находящихся строго левее
    // него в диапазоне от 0 до j - 1.
    return firstInvalidNdx;
  }

  // Создаем переменную-счетчик pairsCnt со значением 0 для накопления
  // общего числа пар, удовлетворяющих условию задачи.
  let pairsCnt = 0;

  // Запускаем цикл, в котором переменная j последовательно проходит по
  // всем индексам массива от 0 до конца.
  //
  // В каждой итерации элемент nums[j] рассматривается как фиксированный
  // правый (второй) элемент потенциальной пары.
  for (let j = 0; j < nums.length; j++) {

    // Вызываем функцию бинарного поиска.
    //
    // Нам нужно найти такие nums[i], для которых
    // nums[i] < target - nums[j].
    //
    // Количество таких элементов слева от j (индекс первого "невалидного"
    // равен количеству "валидных") прибавляется к общему счетчику pairsCnt.
    pairsCnt += binarySearchFirstInvalidNdx(target - nums[j], j);
  }

  // Пример работы цикла для:
  //   nums = [-1, 1, 2, 3, 1]
  //   target = 2.
  //
  // Важное примечание:
  // Перед запуском этого цикла строка nums.sort((a, b) => a - b) сортирует
  // массив. Поэтому внутри цикла мы работаем уже с отсортированным массивом:
  // nums = [-1, 1, 1, 2, 3] (длина массива n = 5).
  //
  // Начальное состояние перед циклом:
  //
  // • nums = [-1, 1, 1, 2, 3]
  // • target = 2
  // • pairsCnt = 0
  //
  // Шаг 1: j = 0
  // • Текущий элемент nums[j] - это nums[0] = -1.
  // • Ищем элементы слева от j = 0. Так как левее ничего нет (диапазон для
  //   поиска пуст), функция binarySearchFirstInvalidNdx сразу возвращает
  //   значение rightBoundary, то есть 0.
  // • Расчет: pairsCnt += 0
  // • Состояние в конце шага: pairsCnt = 0
  //
  // Шаг 2: j = 1
  // • Текущий элемент nums[j] - это nums[1] = 1.
  // • Вычисляем searchValue: target - nums[j] = 2 - 1 = 1.
  // • Вызывается бинарный поиск в диапазоне левее j = 1 (среди элементов
  //   [-1]).
  // • Поиск ищет первый элемент >= 1. В массиве [-1] таких элементов нет,
  //   поэтому функция возвращает rightBoundary, то есть 1 (это значит, что
  //   1 элемент слева является валидным).
  // • Расчет: pairsCnt += 1 (подходит пара с элементом -1)
  // • Состояние в конце шага: pairsCnt = 1
  //
  // Шаг 3: j = 2
  // • Текущий элемент nums[j] - это nums[2] = 1.
  // • Вычисляем searchValue: target - nums[j] = 2 - 1 = 1.
  // • Вызывается бинарный поиск в диапазоне левее j = 2 (среди элементов
  //   [-1, 1]).
  // • Поиск ищет первый элемент >= 1. Элемент 1 находится на индексе 1.
  //   Функция возвращает индекс первого невалидного элемента: 1 (это
  //   значит, что ровно 1 элемент слева от него является валидным).
  // • Расчет: pairsCnt += 1 (подходит пара с элементом -1)
  // • Состояние в конце шага: pairsCnt = 2
  //
  // Шаг 4: j = 3
  // • Текущий элемент nums[j] - это nums[3] = 2.
  // • Вычисляем searchValue: target - nums[j] = 2 - 2 = 0.
  // • Вызывается бинарный поиск в диапазоне левее j = 3 (среди элементов
  //   [-1, 1, 1]).
  // • Поиск ищет первый элемент >= 0. Элемент 1 на индексе 1 подходит под
  //   >= 0. Бинарный поиск проверяет элементы левее и останавливается на
  //   индексе 1, так как на индексе 0 стоит -1 (что меньше 0).
  //   Функция возвращает индекс 1 (это значит, что только 1 элемент слева
  //   валиден).
  // • Расчет: pairsCnt += 1 (подходит пара с элементом -1)
  // • Состояние в конце шага: pairsCnt = 3
  //
  // Шаг 5: j = 4
  // • Текущий элемент nums[j] - это nums[4] = 3.
  // • Вычисляем searchValue: target - nums[j] = 2 - 3 = -1.
  // • Вызывается бинарный поиск в диапазоне левее j = 4 (среди элементов
  //   [-1, 1, 1, 2]).
  // • Поиск ищет первый элемент >= -1. Самый первый элемент на индексе 0
  //   уже равен -1. Функция возвращает индекс 0 (это значит, что 0
  //   элементов слева от него являются валидными, так как даже самый
  //   маленький элемент в паре с 3 дает 2, что не меньше target).
  // • Расчет: pairsCnt += 0
  // • Состояние в конце шага: pairsCnt = 3
  //
  // Окончание работы цикла:
  // Цикл завершен, так как индекс j достиг конца массива (j = 5, условие
  // j < 5 ложно). Функция возвращает итоговое значение pairsCnt = 3.


  // После завершения цикла по всем j возвращаем накопленную сумму pairsCnt,
  // которая и является окончательным ответом задачи.
  return pairsCnt;
}
