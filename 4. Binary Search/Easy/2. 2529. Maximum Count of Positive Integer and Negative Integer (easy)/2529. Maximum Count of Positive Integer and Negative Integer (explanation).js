/**
 * @param {number[]} nums
 * @return {number}
 *
 * maximumCount принимает массив nums, отсортированный в порядке неубывания.
 *
 * Возвращает максимальное значение между количеством положительных чисел и
 * количеством отрицательных чисел. Иными словами, если количество
 * положительных чисел в nums равно pos, а количество отрицательных чисел
 * равно neg, то возвращает максимум из pos и neg.
 *
 * Обратите внимание, что 0 не является ни положительным, ни отрицательным
 * числом.
 *
 *
 * Пример для:
 *   nums = [-2,-1,-1,1,2,3]
 * Результат:
 *   3
 * Пояснение:
 *   Здесь 3 положительных числа и 3 отрицательных числа.
 *
 *   Максимальное количество среди них равняется 3.
 */
function maximumCount(nums) {
  const n = nums.length;

  // Создаем внутреннюю функцию бинарного поиска, которая возвращает индекс
  // первого элемента, который больше или равен числу target
  function binarySearchLowerBound(target) {

    // Устанавливаем стартовый указатель левой границы поиска на самый
    // первый элемент массива (индекс 0)
    let l = 0;

    // Устанавливаем стартовый указатель правой границы на n (индекс за
    // последним элементом), чтобы сужать диапазон со знаком равенства
    let r = n;

    // Запускаем цикл, который будет делить массив пополам до тех пор, пока
    // левый и правый указатели не встретятся в одной точке
    while (l < r) {

      // Ищем индекс центрального элемента текущего диапазона, используя
      // формулу для предотвращения переполнения памяти при больших числах
      const midd = Math.floor(l + (r - l) / 2);

      // Если центральный элемент больше или равен target, значит, нужная
      // нам граница находится на индексе midd или где-то левее
      if (nums[midd] >= target) r = midd;

      // Если же центральный элемент меньше target, то все элементы левее и
      // включая midd нам не подходят, сдвигаем левую границу вправо на
      // midd + 1
      else l = midd + 1;
    }

    // После завершения цикла указатели l и r совпадают и указывают точно
    // на наименьший индекс элемента, который >= target
    return l;
  }

  // Считаем отрицательные числа:
  //
  // Функция ищет первый элемент >= 0. Так как массив отсортирован, его
  // индекс в точности равен количеству элементов, которые строго меньше 0
  const negCnt = binarySearchLowerBound(0);

  // Считаем положительные числа:
  //
  // Ищем первый элемент >= 1. Вычитая этот индекс из общей длины массива n,
  // мы получаем количество всех элементов строго больше 0 (нули остаются
  // отброшенными)
  const posCnt = n - binarySearchLowerBound(1);

  // Сравниваем полученные счетчики положительных и отрицательных чисел и
  // возвращаем наибольшее из них
  return Math.max(negCnt, posCnt);
}
