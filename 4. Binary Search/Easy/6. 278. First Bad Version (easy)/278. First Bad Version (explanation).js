/**
 * Definition for isBadVersion()
 *
 * @param {integer} version number
 * @return {boolean} whether the version is bad
 * isBadVersion = function(version) {
 *     ...
 * };
 */

/**
 * @param {function} isBadVersion()
 * @return {function}
 *
 * Вы - менеджер по продукту и в данный момент возглавляете команду,
 * разрабатывающую новый продукт. К сожалению, последняя версия вашего
 * продукта не прошла проверку качества. Поскольку каждая версия
 * разрабатывается на основе предыдущей, все версии после бракованной также
 * являются бракованными.
 *
 * Предположим, у вас есть n версий [1, 2, ..., n] и вы хотите найти первую
 * бракованную версию, из-за которой все последующие тоже стали
 * бракованными.
 *
 * Вам предоставлен API bool isBadVersion(version), который возвращает,
 * является ли версия бракованной.
 *
 * Реализуйте функцию для поиска первой бракованной версии. Вы должны
 * минимизировать количество вызовов API.
 *
 * Эта функция находит самую первую бракованную версию продукта среди всех
 * существующих версий от 1 до n, используя алгоритм бинарного поиска.
 *
 * Она спроектирована так, чтобы минимизировать количество запросов к
 * системе проверки, что позволяет быстро отыскать точку, в которой код или
 * продукт был испорчен.
 *
 *
 * Пример для:
 *   n = 5,
 *   bad = 4
 * Результат:
 *   4
 * Пояснение:
 *   вызов isBadVersion(3) → false
 *   вызов isBadVersion(5) → true
 *   вызов isBadVersion(4) → true
 *
 *   Значит, 4 - первая бракованная версия.
 */
function solution(isBadVersion) {
  /**
   * @param {integer} n Total versions
   * @return {integer} The first bad version
   */
  return function (n) {

    // Поскольку версии упорядочены от 1 до n и известно, что если одна из
    // версий является плохой, то все последующие версии тоже плохие,
    // возникает чёткая закономерность: существует точка, в которой версии
    // переходят из хороших в плохие.
    //
    // Последовательность выглядит примерно так:
    // [false, false, false, true, true, true], где true означает, что
    // версия плохая. Необходимо найти место этого перехода, а именно
    // индекс первой плохой версии.
    //
    // Именно для такого случая подходит наш шаблон бинарного поиска!
    // Функция-предикат - это isBadVersion(mid), которая возвращает:
    //   false - если версия хорошая;
    //   true  - если версия плохая.
    //
    // Последовательность [false, false, ..., true, true, ...] является
    // монотонной, и наша задача - найти первое значение true (первую
    // плохую версию).
    //
    // Используем бинарный поиск:
    //   1. Если isBadVersion(mid) возвращает true, значит, найдена плохая
    //      версия. Сохраняем её и продолжаем поиск в левой части, чтобы
    //      найти более раннюю плохую версию.
    //
    //   2. Если isBadVersion(mid) возвращает false, значит, первая плохая
    //      версия находится правее.
    //
    // Такой подход позволяет найти первую плохую версию за O(log n)
    // вызовов API вместо O(n), поскольку при каждой проверке мы исключаем
    // половину диапазона поиска.


    // Инициализируем указатель левой границы поиска 'l' значением 1, так
    // как нумерация версий продукта начинается с первой
    let l = 1;

    // Инициализируем указатель правой границы поиска 'r' значением 'n', то
    // есть самой последней существующей версией продукта
    let r = n;

    // Запускаем цикл, который будет сужать диапазон поиска [l, r].
    //
    // Цикл выполняется до тех пор, пока левая граница строго меньше правой
    // (l < r)
    while (l < r) {

      // Находим центральный элемент текущего диапазона.
      //
      // Формула l + (r - l) / 2 используется вместо (l + r) / 2 для
      // предотвращения переполнения памяти при работе с очень большими
      // числами
      const midd = Math.floor(l + (r - l) / 2);

      // Вызываем API-функцию isBadVersion для проверки средней версии.
      //
      // Если она возвращает true (версия испорчена), сужаем диапазон:
      // первая плохая версия - это либо сам midd, либо она находится
      // где-то левее него, поэтому сдвигаем правую границу 'r' на позицию
      // midd
      if (isBadVersion(midd)) r = midd;

      // Если midd возвращает false (версия хорошая), то все версии от 'l'
      // до 'midd' гарантированно исправны.
      //
      // Значит, первая плохая версия находится строго правее, и мы
      // сдвигаем левую границу 'l' на позицию midd + 1
      else l = midd + 1;
    }

    // Когда цикл завершается, указатели 'l' и 'r' сходятся на одном и том
    // же элементе (l === r).
    //
    // Этот индекс и является самой первой бракованной версией, возвращаем
    // его
    return l;
  };
}
