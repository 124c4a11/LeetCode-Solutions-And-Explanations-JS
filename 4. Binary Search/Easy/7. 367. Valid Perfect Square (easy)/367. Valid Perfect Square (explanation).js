/**
 * @param {number} num
 * @return {boolean}
 *
 * isPerfectSquare принимает положительное целое число num.
 *
 * Возвращает true, если num является точным квадратом, или false в
 * противном случае.
 *
 * Точный квадрат — это целое число, которое является квадратом некоторого
 * целого числа. Иными словами, это произведение некоторого целого числа на
 * самого себя.
 *
 * Вы не должны использовать встроенные библиотечные функции, такие как sqrt.
 *
 *
 * Пример для:
 *   num = 16
 * Результат:
 *   true
 * Пояснение:
 *   Мы возвращаем true, так как 4 * 4 = 16 и 4 является целым числом.
 *
 *
 * Пример для:
 *   num = 14
 * Результат:
 *   false
 * Пояснение:
 *   Мы возвращаем false, так как 3.742 * 3.742 = 14 и 3.742 не является
 *   целым числом.
 */
function isPerfectSquare(num) {

  // Поскольку нам нужно определить, существует ли целое число x, для
  // которого x * x = num, по сути, нам необходимо найти это значение x в
  // диапазоне от 1 до num.
  //
  // Ключевая идея заключается в том, что если num является полным
  // квадратом, то его квадратный корень должен быть целым числом в
  // диапазоне от 1 до num. Вместо того чтобы проверять каждое число
  // от 1 до num (что было бы неэффективно для больших чисел), мы можем
  // использовать бинарный поиск, чтобы быстро сузить диапазон поиска.
  //
  // Почему здесь работает бинарный поиск?
  // Потому что функция f(x) = x * x является монотонно возрастающей:
  // чем больше x, тем больше значение x * x.
  //
  // Это означает, что если мы выберем среднее значение и возведём его в
  // квадрат:
  // - Если квадрат меньше num, значит, нужно искать в правой половине
  //   диапазона.
  //
  // - Если квадрат больше num, значит, нужно искать в левой половине
  //   диапазона.
  //
  // - Если квадрат равен num, значит, мы нашли искомое значение.
  //
  // Решение выполняет бинарный поиск по значениям x от 1 до num, чтобы
  // найти наименьшее целое число l, для которого l * l >= num.
  //
  // Это значение соответствует позиции, на которой num могло бы находиться
  // в последовательности полных квадратов [1, 4, 9, 16, 25, ...].
  //
  // В конце остаётся только проверить, равно ли l * l числу num. Если
  // равно, значит, num является полным квадратом. В противном случае num
  // не является полным квадратом.
  //
  // Такой подход позволяет уменьшить временную сложность алгоритма:
  // с O(num) при обычном линейном поиске до O(log num) при использовании
  // бинарного поиска.


  // Если число меньше 1, оно не может быть точным квадратом натурального
  // числа, возвращаем false
  if (num < 1) return false;

  // Инициализируем левую границу поиска единицей, так как это минимальный
  // возможный корень
  let l = 1;

  // Инициализируем правую границу поиска самим числом num
  let r = num;

  // Запускаем цикл бинарного поиска, который продолжается, пока левая
  // граница не превысит правую
  while (l <= r) {

    // Вычисляем центральное значение (середину текущего диапазона).
    //
    // Формула l + (r - l) / 2 используется вместо (l + r) / 2 для
    // предотвращения потенциального переполнения чисел, а Math.floor()
    // округляет результат до ближайшего целого вниз.
    const midd = Math.floor(l + (r - l) / 2);

    // Возводим найденное среднее значение midd в квадрат (умножаем его на
    // самого себя) для последующего сравнения с целевым числом num
    const square = midd * midd;

    // Если полученный квадрат square в точности равен числу num, значит,
    // мы нашли корень, число является точным квадратом - возвращаем true
    if (square === num) return true;

    // Если квадрат середины меньше целевого числа num, это означает, что
    // искомый корень находится строго правее midd, поэтому мы переносим
    // левую границу поиска на midd + 1
    if (square < num) l = midd + 1;

    // Если же квадрат середины больше num, значит, искомый корень
    // находится строго левее midd, и мы переносим правую границу поиска на
    // midd - 1
    else r = midd - 1;
  }

  // Если цикл завершился и границы l и r пересеклись, но точное совпадение
  // не было найдено, значит, число num не является полным квадратом -
  // возвращаем false
  return false;
}
