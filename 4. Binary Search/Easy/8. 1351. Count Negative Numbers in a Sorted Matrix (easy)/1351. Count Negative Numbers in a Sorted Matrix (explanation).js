/**
 * @param {number[][]} grid
 * @return {number}
 *
 * countNegatives принимает матрицу grid размером m x n, элементы которой
 * отсортированы в порядке невозрастания как по строкам, так и по столбцам.
 *
 * Возвращает количество отрицательных чисел в матрице.
 *
 *
 * Пример для:
 *   grid = [[4,3,2,-1],[3,2,1,-1],[1,1,-1,-2],[-1,-1,-2,-3]]
 * Результат:
 *   8
 * Пояснение:
 *   В матрице содержится 8 отрицательных чисел.
 *
 *
 * Пример для:
 *   grid = [[3,2],[1,0]]
 * Результат:
 *   0
 * Пояснение:
 *   В матрице нет отрицательных чисел.
 */
function countNegatives(grid) {

  // Определяем и сохраняем в константу ROWS общее количество строк
  // (вложенных массивов) в переданной матрице
  const ROWS = grid.length;

  // Определяем и сохраняем в константу COLS количество столбцов в матрице,
  // ориентируясь на длину первой (нулевой) строки
  const COLS = grid[0].length;

  // Создаем переменную-аккумулятор negativeCnt со стартовым значением 0
  // для накопления итогового числа отрицательных элементов
  let negativeCnt = 0;

  // Запускаем цикл for с индексом r для последовательного прохода по
  // каждой строке матрицы сверху вниз
  for (let r = 0; r < ROWS; r++) {

    // Вызываем функцию бинарного поиска для текущей строки grid[r], чтобы
    // найти индекс первого элемента, значение которого <= -1 (то есть
    // первого отрицательного числа)
    const c = binarySearchFirstLessOrEqual(grid[r], -1);

    // Вычисляем количество отрицательных чисел в текущей строке по формуле
    // COLS - c и прибавляем результат к общему счетчику.
    //
    // Так как элементы идут по невозрастанию, все числа от позиции c до
    // конца строки гарантированно отрицательные.
    //
    // Если отрицательных чисел в строке нет, бинарный поиск вернет c
    // равное COLS, и к счетчику прибавится COLS - COLS = 0
    negativeCnt += COLS - c;
  }

  // После того как цикл проверил все строки матрицы, возвращаем итоговое
  // накопленное количество отрицательных элементов в матрице
  return negativeCnt;
}

// Объявляем вспомогательную функцию левостороннего бинарного поиска,
// которая находит в отсортированном по невозрастанию одномерном массиве
// arr индекс самого первого элемента, значение которого меньше или равно
// target
function binarySearchFirstLessOrEqual(arr, target) {

  // Инициализируем левый указатель l нулем - это левая граница текущего
  // диапазона поиска (включается в проверяемый интервал)
  let l = 0;

  // Инициализируем правый указатель r длиной массива arr.length - это
  // правая граница текущего диапазона поиска (не включается в проверяемый
  // интервал, поэтому алгоритм работает с полуинтервалом [l, r))
  let r = arr.length;

  // Запускаем цикл while, который будет повторяться до тех пор, пока
  // границы поиска не сойдутся в одной точке (когда l станет равно r,
  // поиск завершится)
  while (l < r) {

    // Вычисляем средний индекс текущего отрезка с округлением вниз с
    // помощью Math.floor.
    //
    // Запись l + (r - l) / 2 эквивалентна (l + r) / 2, но защищает от
    // возможного переполнения числового типа при работе с большими
    // индексами
    const midd = Math.floor(l + (r - l) / 2);

    // Если элемент в середине диапазона меньше или равен искомому значению
    // target, значит мы нашли подходящее число, но левее могут находиться
    // другие подходящие числа, поэтому сужаем область поиска влево,
    // перенося правую границу r на позицию midd (включительно)
    if (arr[midd] <= target) r = midd;

    // В противном случае (когда arr[midd] > target) средний элемент
    // слишком велик и не удовлетворяет условию, как и все элементы слева
    // от него, поэтому отбрасываем левую часть диапазона вместе с
    // серединой, сдвигая левую границу l на позицию midd + 1
    else l = midd + 1;
  }

  // Возвращаем значение левого указателя l, который после выхода из цикла
  // точно указывает либо на индекс первого элемента <= target, либо на
  // arr.length (если абсолютно все элементы в массиве оказались больше
  // target)
  return l;
}
