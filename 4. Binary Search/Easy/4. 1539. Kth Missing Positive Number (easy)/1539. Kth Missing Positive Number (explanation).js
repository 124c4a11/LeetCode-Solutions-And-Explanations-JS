/**
 * @param {number[]} arr
 * @param {number} k
 * @return {number}
 *
 * findKthPositive принимает массив arr положительных целых чисел,
 * отсортированных в строго возрастающем порядке, и целое число k.
 *
 * Возвращает k-е положительное целое число, которое отсутствует в этом
 * массиве.
 *
 *
 * Пример для:
 *   arr = [2,3,4,7,11],
 *   k = 5
 * Результат:
 *   9
 * Пояснение:
 *   Отсутствующими положительными целыми числами являются
 *   [1,5,6,8,9,10,12,13,...]. 5-м отсутствующим положительным целым числом
 *   является 9.
 */
function findKthPositive(arr, k) {

  // Алгоритм использует бинарный поиск для поиска первого элемента в
  // массиве, перед которым количество пропущенных чисел становится больше
  // или равно k. Вместо перебора всех чисел по порядку, мы ищем "точку
  // перелома", что сокращает время работы до логарифмического - O(log n).
  //
  // 1. КАК ИЗМЕРЯЮТСЯ ПРОПУЩЕННЫЕ ЧИСЛА?
  //    Если бы в массиве arr не было пропущенных чисел, то на любой позиции
  //    mid находилось бы число mid + 1 (так как индексация начинается с 0).
  //
  //    Отсюда формула количества пропущенных чисел перед индексом mid:
  //    missingBeforeMid = arr[mid] - (mid + 1) = arr[mid] - mid - 1
  //
  // 2. ПОЧЕМУ В КОНЦЕ ВОЗВРАЩАЕТСЯ l + k?
  //    Когда цикл while (l < r) завершается, указатели l и r сходятся в
  //    одной точке. Индекс l указывает на первый элемент, перед которым
  //    количество пропущенных чисел >= k.
  //
  //    Это означает, что искомое k-е пропущенное число находится между
  //    arr[l-1] и arr[l].
  //
  //    Математический расчет:
  //    а) Количество пропущенных чисел перед элементом arr[l-1] равно:
  //       missing = arr[l-1] - (l - 1) - 1 = arr[l-1] - l
  //
  //    б) Нам нужно найти k-е пропущенное число. Мы знаем, сколько
  //       пропущено перед arr[l-1]. Значит, после самого числа arr[l-1]
  //       нам нужно отсчитать еще столько пропущенных шагов:
  //       осталось шагов = k - missing = k - (arr[l-1] - l)
  //
  //    в) Прибавим этот остаток к значению arr[l-1], чтобы получить
  //       искомое число:
  //       Результат = arr[l-1] + (k - arr[l-1] + l)
  //
  //       При раскрытии скобок значения arr[l-1] и -arr[l-1] взаимно
  //       уничтожаются:
  //       Результат = l + k
  //
  // КРАЙНИЕ СЛУЧАИ:
  // - Если l == 0: все пропущенные числа меньше первого элемента массива.
  //   Ответ: просто k (или 0 + k), что абсолютно верно.
  //
  // - Если l == arr.length: k-е пропущенное число находится за пределами
  //   массива. Формула превращается в arr.length + k, что тоже верно, так
  //   как мы берем длину массива и добавляем к ней смещение k.


  // Задаем начальный индекс левой границы поиска (0), указывающий на самый
  // первый элемент исходного массива
  let l = 0;

  // Задаем начальный индекс правой границы поиска (длина массива), что
  // позволяет искать ответ вплоть до позиции за последним элементом
  // массива
  let r = arr.length;

  // Начинаем цикл сужения диапазона поиска.
  //
  // Он остановится, когда левая и правая границы сойдутся в одной точке
  // (l === r)
  while (l < r) {

    // Находим индекс середины текущего диапазона, складывая l и r, деля на
    // 2 и округляя до целого числа вниз через Math.floor во избежание
    // дробных чисел
    const mid = Math.floor(l + (r - l) / 2);

    // Вычисляем, сколько всего чисел пропущено от 1 до arr[mid].
    //
    // Если бы пропусков не было, значением arr[mid] было бы (mid + 1).
    //
    // Разница между реальным значением и идеальным показывает количество
    // пропущенных чисел.
    //
    //
    // Подробный разбор формулы arr[mid] - mid - 1
    //
    // 1. Идеальный сценарий (без пропусков):
    //    Если бы массив состоял из последовательных чисел
    //    [1, 2, 3, 4, 5...], то на любом индексе mid находилось бы число,
    //    равное (mid + 1).
    //
    //    Например: индекс 0 → число 1, индекс 3 → число 4.
    //
    // 2. Влияние пропусков:
    //    Каждое пропущенное число сдвигает реальные значения в массиве в
    //    большую сторону.
    //
    //    Чтобы узнать, сколько чисел пропущено до текущего элемента, нужно
    //    из реального  значения вычесть то идеальное значение, которое
    //    должно было там стоять.
    //
    // 3. Математический вывод:
    //    Количество пропусков = Реальное значение - Идеальное значение
    //    Количество пропусков = arr[mid] - (mid + 1)
    //    Раскрываем скобки: arr[mid] - mid - 1
    //
    // 4. Живой пример на массиве [2, 3, 4, 7, 11] для индекса mid = 3
    //    (число 7):
    //    - Реальное значение: arr[3] = 7
    //
    //    - Идеальное значение: 3 + 1 = 4
    //
    //    - Расчет: 7 - 3 - 1 = 3
    //      (действительно, до 7 пропущены 3 числа: 1, 5, 6)
    const missingBeforeMid = arr[mid] - mid - 1;

    // Если количество пропущенных чисел перед arr[mid] больше или равно k,
    // это означает, что искомое k-е пропущенное число находится в левой
    // половине (или левее текущего индекса mid). Поэтому мы сдвигаем
    // правую границу диапазона поиска к mid.
    if (missingBeforeMid >= k) r = mid;

    // Если пропущенных чисел перед arr[mid] строго меньше, чем k, значит,
    // искомое число находится в правой половине диапазона (правее индекса
    // mid).
    //
    // Мы сдвигаем левую границу поиска к mid + 1.
    else l = mid + 1;
  }

  // Возвращаем итоговое k-е пропущенное число.
  //
  // После завершения цикла левая граница l указывает на количество
  // элементов в исходном массиве, которые меньше искомого числа.
  //
  // Математически результат рассчитывается как:
  // arr[l-1] + (k - missingBeforeL), что после сокращения формулы всегда
  // сводится к лаконичному l + k.
  return l + k;
}
