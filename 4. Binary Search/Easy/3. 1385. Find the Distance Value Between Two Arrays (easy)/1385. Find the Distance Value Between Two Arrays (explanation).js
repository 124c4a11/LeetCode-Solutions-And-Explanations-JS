/**
 * @param {number[]} arr1
 * @param {number[]} arr2
 * @param {number} d
 * @return {number}
 *
 * findTheDistanceValue принимает два целочисленных массива arr1 и arr2, а
 * также целое число d.
 *
 * Возвращает значение расстояния между двумя массивами.
 *
 * Значение расстояния определяется как количество элементов arr1[i], для
 * которых не существует ни одного элемента arr2[j], такого что
 * |arr1[i] - arr2[j]| <= d.
 *
 * Пример для:
 *   arr1 = [4, 5, 8],
 *   arr2 = [10, 9, 1, 8], d = 2
 * Результат:
 *   2
 * Пояснение:
 *   Для arr1[0] = 4:
 *     |4 - 10| = 6 > d = 2
 *     |4 - 9|  = 5 > d = 2
 *     |4 - 1|  = 3 > d = 2
 *     |4 - 8|  = 4 > d = 2
 *
 *   Для arr1[1] = 5:
 *     |5 - 10| = 5 > d = 2
 *     |5 - 9|  = 4 > d = 2
 *     |5 - 1|  = 4 > d = 2
 *     |5 - 8|  = 3 > d = 2
 *
 *   Для arr1[2] = 8:
 *     * |8 - 10| = 2 <= d = 2
 *     * |8 - 9|  = 1 <= d = 2
 *     |8 - 1|  = 7 > d = 2
 *     * |8 - 8|  = 0 <= d = 2
 *
 *   Элементы 4 и 5 из массива arr1 находятся на расстоянии больше d от
 *   каждого элемента массива arr2.
 *
 *   Элемент 8 не подходит, так как в arr2 есть элементы, расстояние до
 *   которых не превышает d.
 */
function findTheDistanceValue(arr1, arr2, d) {

  // Наивный подход заключается в том, чтобы проверить каждый элемент arr1
  // относительно каждого элемента arr2. Это потребует O(n * m) времени.
  //
  // Однако мы можем оптимизировать решение, обратив внимание на ключевую
  // идею: для каждого элемента x из arr1 нужно проверить, существует ли в
  // arr2 хотя бы один элемент в диапазоне [x - d, x + d].
  //
  // Эта задача поиска элементов в заданном диапазоне естественным образом
  // приводит нас к сортировке и бинарному поиску. Если отсортировать arr2,
  // элементы, которые могут нарушить условие расстояния (то есть находятся
  // на расстоянии не более d от x), будут образовывать непрерывный отрезок
  // в отсортированном массиве.
  //
  // Для любого элемента x из arr1 элементы arr2, которые делают его
  // неподходящим, удовлетворяют условию |x - arr2[j]| <= d. Это условие
  // можно переписать следующим образом: x - d <= arr2[j] <= x + d.
  //
  // В отсортированном массиве arr2 все такие элементы будут расположены
  // последовательно.
  //
  // С помощью бинарного поиска можно быстро найти самую левую позицию,
  // начиная с которой элемент может быть больше или равен x - d.
  //
  // Если такой позиции не существует (мы вышли за пределы массива) или
  // элемент в найденной позиции больше x + d, значит, в arr2 нет элементов,
  // находящихся на расстоянии не более d от x. Следовательно, элемент x
  // учитывается в ответе.
  //
  // Такой подход снижает временную сложность с O(n * m) до
  // O(m log m + n log m):
  // - O(m log m) — сортировка массива arr2;
  // - O(n log m) — выполнение бинарного поиска для каждого элемента arr1.
  //
  // Преимущество этого решения заключается в том, что мы преобразуем
  // задачу "проверить все пары элементов" в задачу "проверить, существует
  // ли хотя бы один элемент в заданном диапазоне". Эту задачу можно
  // эффективно решить с помощью сортировки и бинарного поиска.


  // Сортируем массив arr2 по возрастанию (сложность O(M log M)), чтобы
  // внутри цикла можно было использовать эффективный бинарный поиск вместо
  // последовательного перебора
  arr2.sort((a, b) => a - b);

  // Создаем переменную-счетчик, в которой будем накапливать количество
  // элементов из arr1, прошедших проверку на "безопасное расстояние"
  let cnt = 0;

  // Проходим по массиву arr1
  for (const num of arr1) {

    // Ищем в отсортированном arr2 индекс первого элемента, который равен
    // или больше, чем левая граница диапазона (num - d)
    const i = binarySearchLowerBound(arr2, num - d);

    // Открываем условную конструкцию if, которая проверяет, попал ли хоть
    // один элемент из arr2 в запрещенный интервал значений
    // от [num - d] до [num + d] включительно.
    if (

      // Условие 1:
      //
      // Если возвращенный индекс равен длине массива arr2, это
      // означает, что абсолютно все элементы в arr2 меньше, чем нижняя
      // граница (num - d). Следовательно, "близких" чисел в arr2 нет.
      i === arr2.length

      // Условие 2 (вычисляется, только если Условие 1 ложно):
      //
      // Проверяем, строго ли больше найденный элемент arr2[i], чем верхняя
      // граница диапазона (num + d). Если больше, то между
      // (num - d) и (num + d) элементов в arr2 нет.
      || arr2[i] > num + d

      // Если Условие 1 ИЛИ Условие 2 истинно, значит в arr2 нет чисел на
      // расстоянии <= d от num.
      //
      // В этом случае мы увеличиваем наш итоговый счетчик cnt на единицу.
    ) cnt++;
  }

  // После завершения проверки всех элементов из arr1, возвращаем итоговое
  // накопленное значение счетчика
  return cnt;
}

// Вспомогательная функция бинарного поиска (Lower Bound), которая ищет
// наименьший индекс, где элемент массива >= target
function binarySearchLowerBound(arr, target) {

  // Задаем начальную левую границу поискового диапазона на самый первый
  // элемент массива (индекс 0)
  let l = 0;

  // Инициализируем правую границу области поиска r индексом, равным длине
  // массива (указывает на элемент за концом массива).
  let r = arr.length;

  // Запускаем цикл поиска, который продолжает сужать диапазон до тех пор,
  // пока левый указатель l строго меньше правого r.
  while (l < r) {

    // Вычисляем индекс среднего элемента midd в текущем диапазоне.
    //
    // Формула l + (r - l) / 2 используется для предотвращения переполнения
    // памяти при работе с большими числами, а Math.floor округляет
    // результат до целого вниз.
    const midd = Math.floor(l + (r - l) / 2);

    // Если элемент в центре массива arr[midd] больше или равен искомой
    // цели target, это значит, что нужный нам первый подходящий элемент
    // находится либо на позиции midd, либо еще левее.
    //
    // Смещаем правую границу r в позицию midd.
    if (arr[midd] >= target) r = midd;

    // Если же центральный элемент arr[midd] строго меньше target, то все
    // элементы левее и включая midd нам точно не подходят.
    //
    // Мы смещаем левую границу l на позицию midd + 1, исключая пройденную
    // левую половину.
    else l = midd + 1
  }

  // Когда цикл завершается (l становится равно r), указатель l
  // гарантированно содержит индекс самого первого элемента,
  // который >= target.
  //
  // Если такого элемента нет, l будет указывать на arr.length.
  //
  // Возвращаем этот индекс.
  return l;
}
