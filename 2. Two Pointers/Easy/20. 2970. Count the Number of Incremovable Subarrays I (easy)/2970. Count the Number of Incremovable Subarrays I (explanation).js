/**
 * @param {number[]} nums
 * @return {number}
 *
 * incremovableSubarrayCount массив положительных целых чисел nums.
 *
 * Возвращает общее количество "удаляемо-возрастающих" (incremovable)
 * подмассивов в исходном массиве.
 *
 * Подмассив считается удаляемо-возрастающим, если после его полного
 * удаления из исходного массива оставшиеся элементы образуют строго
 * возрастающую последовательность (или становятся пустым массивом, который
 * по условию задачи также считается строго возрастающим).
 *
 *
 * Пример для:
 *   nums = [1, 2, 3, 4]
 * Результат:
 *   10
 * Пояснение:
 *   Существует 10 удаляемых подмассивов (incremovable subarrays):
 *   [1], [2], [3], [4],
 *   [1,2], [2,3], [3,4],
 *   [1,2,3], [2,3,4],
 *   [1,2,3,4],
 *   потому что после удаления любого из этих подмассивов массив nums
 *   становится строго возрастающим.
 *
 *   Обратите внимание: нельзя выбрать пустой подмассив.
 *
 *
 * Пример для:
 *   nums = [8,7,6,6]
 * Результат:
 *   3
 * Пояснение:
 *   Существует 3 подмассива, удаление которых делает массив строго
 *   возрастающим:
 *   [8,7,6], [7,6,6] и [8,7,6,6].
 *
 *   Обратите внимание, что [8,7] не является incremovable-подмассивом,
 *   потому что после его удаления nums станет [6,6].
 *
 *   Этот массив отсортирован по возрастанию, но не является строго
 *   возрастающим.
 */
function incremovableSubarrayCount(nums) {

  // Ключевая идея заключается в том, чтобы думать о том, что останется
  // после удаления подмассива, а не о том, что именно мы удаляем.
  //
  // Когда мы удаляем непрерывный подмассив, у нас может остаться:
  //
  // 1. Ничего (если удалить весь массив).
  // 2. Только префикс исходного массива.
  // 3. Только суффикс исходного массива.
  // 4. И префикс, и суффикс (между ними образуется разрыв).
  //
  // Чтобы результат был строго возрастающим, всё, что осталось,
  // должно образовывать строго возрастающую последовательность.
  //
  // Начнём с самого простого случая: если весь массив уже является
  // строго возрастающим, то удаление ЛЮБОГО подмассива оставит
  // строго возрастающую последовательность (или пустой массив,
  // который также считается строго возрастающим).
  //
  // В этом случае общее количество подмассивов равно:
  // n * (n + 1) / 2.
  //
  // Для общего случая нам нужно найти корректные префиксы и суффиксы,
  // которые можно оставить.
  //
  // Корректный префикс — это префикс, элементы которого строго
  // возрастают от начала массива.
  //
  // Аналогично, корректный суффикс — это суффикс, элементы которого
  // строго возрастают до конца массива.
  //
  // Ключевое наблюдение состоит в том, что все варианты удаления
  // можно разделить на два типа:
  //
  // 1. Удалить всё, начиная с некоторой позиции, — оставить только префикс.
  // 2. Удалить среднюю часть — оставить одновременно префикс и суффикс.
  //
  // Для типа 1, если у нас есть строго возрастающий префикс длины i + 1
  // (индексы от 0 до i), мы можем удалить:
  //
  // - всё начиная с индекса i + 1: [i + 1, n - 1]
  // - всё начиная с индекса i:     [i, n - 1]
  // - всё начиная с индекса i - 1: [i - 1, n - 1]
  // - и так далее, вплоть до удаления всего массива: [0, n - 1]
  //
  // Таким образом, получается i + 2 возможных удалений.
  //
  // Для типа 2 нужно убедиться, что если мы оставляем одновременно
  // префикс и суффикс, то последний элемент префикса меньше первого
  // элемента суффикса. Только в этом случае итоговая последовательность
  // останется строго возрастающей.
  //
  // Мы перебираем возможные точки начала суффикса справа налево.
  // Для каждого суффикса, начинающегося в позиции j, мы находим
  // самый длинный корректный префикс, для которого nums[i] < nums[j].
  //
  // Каждая такая корректная комбинация даёт i + 2 различных удаления:
  // удаление может начинаться с любой позиции от 0 до i + 1,
  // а заканчиваться непосредственно перед j.
  //
  // Алгоритм эффективно подсчитывает оба типа вариантов:
  // сначала находит самый длинный строго возрастающий префикс,
  // а затем перебирает корректные суффиксы, двигая указатель префикса
  // так, чтобы сохранялось условие строгого возрастания между префиксом
  // и суффиксом.


  const n = nums.length;

  // Инициализируем индекс prefixEndNdx, который будет указывать на
  // последний элемент максимально длинного строго возрастающего префикса.
  let prefixEndNdx = 0;

  // Запускаем цикл для расширения префикса. Мы двигаемся слева направо,
  // пока элементы последовательно увеличиваются.
  while (

    // Проверяем, что индекс следующего элемента (prefixEndNdx + 1) не
    // выходит за пределы массива (меньше, чем общая длина n).
    prefixEndNdx + 1 < n

    // Проверяем ключевое условие: текущий элемент должен быть строго
    // меньше следующего за ним элемента, чтобы сохранялось возрастание.
    && nums[prefixEndNdx] < nums[prefixEndNdx + 1]

    // Если оба условия истинны, то сдвигаем указатель вправо, тем самым
    // увеличивая длину найденного строго возрастающего префикса.
  ) prefixEndNdx++;

  // Если индекс конца префикса равен (n - 1), это означает, что весь
  // массив изначально является строго возрастающим.
  if (prefixEndNdx === n - 1) {

    // Если весь массив строго возрастает, то удаление абсолютно ЛЮБОГО
    // подмассива оставит валидный результат.
    //
    // Возвращаем общее число подмассивов по формуле n * (n + 1) / 2.
    return n * (n + 1) / 2;
  }

  // Начинаем подсчет комбинаций.
  //
  // Инициализируем счетчик вариантов для "Типа 1" (когда мы полностью
  // удаляем суффикс и оставляем только часть префикса).
  //
  // Всего доступно (prefixEndNdx + 2) вариантов удаления: мы можем начать
  // удаление с любого индекса от 0 до (prefixEndNdx + 1) и продолжить до
  // самого конца массива.
  //
  // Почему в формуле (prefixEndNdx + 2) добавляется именно 2?
  //
  // Эта формула считает, сколькими способами можно выбрать левую границу
  // удаляемого подмассива. Цифра 2 складывается из двух логических
  // частей: (+1) и (+1).
  //
  // Часть 1: Переход от индекса к количеству элементов (+1)
  // В JavaScript индексация начинается с 0. Если prefixEndNdx — это
  // ИНДЕКС последнего элемента префикса, то физическое КОЛИЧЕСТВО
  // элементов в нем равно (prefixEndNdx + 1).
  // Пример:
  //   Если prefixEndNdx = 2, то в префиксе 3 элемента
  //   (с индексами 0, 1, 2).
  //
  // Часть 2: Вариант с полным удалением префикса (еще +1)
  // Мы можем начать удаление после любого элемента префикса, но мы также
  // имеем право начать удаление с самого начала (с индекса 0), вообще не
  // оставляя от префикса ничего. Этот сценарий ("удалить префикс
  // полностью") добавляет ровно 1 дополнительный вариант.
  //
  // НАГЛЯДНЫЙ ПРИМЕР:
  // Допустим, префикс состоит из 3 элементов (индексы 0, 1, 2). Значит,
  // prefixEndNdx = 2. Формула дает: 2 + 2 = 4 варианта выбора левой
  // границы для удаления:
  //
  // Вариант 1 (Индекс 0):
  //   Удаляем всё с самого начала. Префикс становится пустым.
  //
  // Вариант 2 (Индекс 1):
  //   Оставляем элемент 0, а удаление начинаем с элемента 1.
  //
  // Вариант 3 (Индекс 2):
  //   Оставляем элементы 0, 1, а удаление начинаем с элемента 2.
  //
  // Вариант 4 (Индекс 3) (prefixEndNdx + 1):
  //   Оставляем весь префикс (0, 1, 2), а удаление начинаем сразу за ним.
  //
  // Поскольку правая граница удаления в момент расчета уже жестко
  // зафиксирована текущим суффиксом, общее количество комбинаций зависит
  // только от выбора левой границы. Их всегда получается ровно
  // prefixEndNdx + 2.
  let incremovableCnt = prefixEndNdx + 2;

  // Переходим к "Типу 2" (когда остаются и префикс, и суффикс).
  //
  // Перебираем индекс начала суффикса (suffixStartNdx), двигаясь справа
  // налево от последнего элемента массива.
  for (let suffixStartNdx = n - 1; suffixStartNdx > 0; suffixStartNdx--) {

    // Запускаем внутренний цикл для проверки стыковки текущего префикса и
    // текущего суффикса.
    //
    // Нам нужно, чтобы последний элемент префикса был строго меньше
    // первого элемента суффикса.
    while (

      // Убеждаемся, что указатель префикса prefixEndNdx остается в
      // пределах массива (не ушел ниже нуля), то есть у нас еще остался
      // хоть какой-то префикс для стыковки.
      prefixEndNdx >= 0

      // Если последний элемент префикса больше или равен первому элементу
      // суффикса, они не могут быть состыкованы (это нарушит строгое
      // возрастание итогового массива).
      && nums[prefixEndNdx] >= nums[suffixStartNdx]

      // Если стыковка невозможна, мы вынуждены сокращать префикс:
      //
      // Сдвигаем его указатель влево на одну позицию и снова проверяем
      // условие.
    ) prefixEndNdx--;

    // После того как стык префикса и суффикса стал валидным, добавляем к
    // счетчику количество возможных вариантов удалений.
    //
    // Мы можем начать удаление с любого индекса от 0 до prefixEndNdx + 1,
    // а закончить строго перед suffixStartNdx.
    //
    // Это дает ровно prefixEndNdx + 2 новых вариантов.
    incremovableCnt += prefixEndNdx + 2;

    // Проверяем, можно ли расширить наш строго возрастающий суффикс дальше
    // влево на следующей итерации цикла.
    //
    // Если элемент слева (nums[suffixStartNdx - 1]) больше или равен
    // текущему элементу суффикса, значит, суффикс при движении влево
    // перестанет быть строго возрастающим.
    if (nums[suffixStartNdx - 1] >= nums[suffixStartNdx]) break;
  }

  // Возвращаем итоговое накопленное количество удаляемо-возрастающих
  // подмассивов, которое включает в себя как комбинации с суффиксами, так
  // и комбинации только с префиксом.
  return incremovableCnt;
}
