/**
 * @param {number[]} g
 * @param {number[]} s
 * @return {number}
 *
 * findContentChildren принимает два параметра:
 * - g (Greed) — массив чисел, где каждое число представляет собой фактор
 *   жадности ребенка. Это минимальный размер печенья, который необходим
 *   конкретному ребенку, чтобы он остался доволен.
 *
 * - s (Size) — массив чисел, содержащий размеры всех доступных печений.
 *
 * У каждого ребенка i есть фактор жадности g[i] — это минимальный размер
 * печенья, которым ребенок будет удовлетворен. У каждого печенья j есть
 * размер s[j]. Если s[j] >= g[i], мы можем направить печенье j ребенку i,
 * и ребенок будет доволен.
 *
 * Функция возвращает максимальное количество детей, которых можно сделать
 * довольными, выдав каждому максимум по одному печенью.
 *
 *
 * Пример для:
 *   g = [1,2,3],
 *   s = [1, 1]
 * Результат:
 *   1
 * Пояснение:
 *   Всего есть 3 детей и 2 печенья. Факторы жадности 3 детей равны 1, 2, 3.
 *
 *   И хотя есть 2 печенья, поскольку размер каждого из них равен 1, можно
 *   удовлетворить только того ребенка, чей фактор жадности равен 1.
 *
 *   Вам нужно вывести 1.
 */
function findContentChildren(g, s) {

  // Сортируем массив жадности детей по возрастанию, чтобы в первую очередь
  // удовлетворять наименее требовательных
  g.sort((a, b) => a - b);

  // Сортируем массив размеров печенья по возрастанию, чтобы рационально
  // использовать самые маленькие печенья.
  //
  // Мы хотим отдавать самое маленькое из возможных печений наименее
  // требовательному ребенку.
  s.sort((a, b) => a - b);

  // Вычисляем и сохраняем общее количество детей в константу n.
  const n = g.length;

  // Вычисляем и сохраняем общее количество доступных печений в константу m.
  const m = s.length;


  // Объявляем переменную-указатель i, которая хранит индекс текущего
  // ребенка в массиве g.
  //
  // Так как мы продвигаемся к следующему ребенку только тогда, когда
  // успешно накормили текущего, i также служит счетчиком сытых детей.
  let i = 0;

  // Объявляем переменную-указатель j, которая хранит индекс текущего
  // проверяемого печенья в массиве s.
  let j = 0;

  // Запускаем цикл для обхода каждого ребенка, пока не проверим всех детей
  while (i < n) {

    // Внутренний цикл выполняет поиск подходящего печенья для текущего
    // ребенка i.
    //
    // Условие j < m гарантирует, что мы не выйдем за пределы массива
    // печений s.
    //
    // Условие g[i] > s[j] проверяет, является ли текущее печенье слишком
    // маленьким для текущего ребенка.
    //
    // Если печенье меньше, чем нужно ребенку, мы просто пропускаем его
    // (сдвигаем указатель j вправо), так как для следующих (еще более
    // жадных) детей оно тем более не подойдет.
    while (
      j < m
      && g[i] > s[j]
    ) j++;

    // Проверяем состояние указателя печений после завершения внутреннего
    // цикла.
    //
    // Если j стало равно m, это означает, что мы перебрали все оставшиеся
    // печенья и ни одно из них не подошло текущему ребенку.
    //
    // Поскольку массив детей отсортирован по возрастанию жадности, для
    // всех последующих детей печений тоже гарантированно не хватит,
    // поэтому мы досрочно возвращаем текущее количество сытых детей i.
    //
    // Возвращаем текущее число довольных детей
    if (j == m) return i;

    // Сюда код доходит, только если условие g[i] > s[j] нарушилось, а
    // значит s[j] >= g[i] (печенье подошло ребенку).
    //
    // Мы успешно отдаем печенье ребенку и переходим к следующему ребенку в
    // массиве g, увеличивая указатель i на 1.
    i++;

    // Текущее печенье j уже использовано, поэтому мы сдвигаем указатель j
    // на 1 вперед, чтобы на следующей итерации начать проверку уже со
    // следующего печенья.
    j++;
  }

  // Если цикл успешно завершился и мы проверили всех детей, возвращаем
  // финальное количество довольных детей
  return i;
}
