/**
 * @param {string} sentence
 * @param {string} searchWord
 * @return {number}
 *
 * isPrefixOfWord проверяет, является ли строка searchWord префиксом
 * какого‑либо слова в предложении sentence. Она просматривает слова
 * в предложении слева направо и возвращает индекс первого слова
 * (нумерация с 1), у которого searchWord является префиксом этого
 * слова. Если ни одно слово не начинается с searchWord, функция
 * возвращает -1.
 *
 *
 * Пример для:
 *   sentence = "i love eating burger",
 *   searchWord = "burg"
 * Результат:
 *   4
 * Пояснение:
 *   "burg" является префиксом слова "burger", которое является 4-м
 *   словом в предложении.
 */
function isPrefixOfWord(sentence, searchWord) {
  const n = sentence.length;
  const m = searchWord.length;

  // Инициализируем счётчик номера текущего слова в предложении.
  //
  // Индексация слов в задаче идёт с 1, поэтому начальное значение 1.
  let wordNdx = 1;

  // Указатель i - позиция текущего символа в sentence, начинаем с 0
  // (первый символ).
  let i = 0;

  // Внешний цикл проходит по всей строке sentence, пока i не
  // достигнет конца (n).
  while (i < n) {

    // j - указатель для прохода по символам searchWord при попытке
    // сопоставления префикса.
    let j = 0;

    // Флаг, показывающий, что до сих пор все проверенные символы
    // совпадают.
    //
    // Если в процессе сравнения найдётся несовпадение, флаг станет
    // false.
    let isMatch = true;

    // Внутренний цикл пытается пройти по всем символам searchWord
    // (от 0 до m-1).
    //
    // Цикл прерывается либо при несовпадении, либо когда j
    // достигнет m (весь searchWord совпал).
    while (j < m) {

      // Проверяем два условия одновременно:
      // 1. i < n - не вышли за пределы строки sentence.
      //
      // 2. sentence[i] === searchWord[j] - текущие символы
      //   совпадают.
      if (
        i < n
        && sentence[i] === searchWord[j]
      ) {

        // Если мы не вышли за предеры sentence и символы совпадают,
        // сдвигаем оба указателя:
        // i - переходит к следующему символу в предложении,
        // j - переходит к следующему символу в искомом префиксе.
        i++;
        j++
      } else {

        // Если мы вышли за пределы sentence (длинна последнего
        // слова sentence меньше длинны searchWord), или символы не
        // совпадают, отмечаем, что текущая проверка совпадения
        // префикса неудачна.
        isMatch = false;

        // Прерываем внутренний цикл, потому что дальнейшее
        // сравнение этого префикса бессмысленно.
        break;
      }
    }

    // После выхода из внутреннего цикла проверяем флаг isMatch.
    //
    // Если он true, это означает, что мы успешно прошли все символы
    // searchWord и они совпали с началом текущего слова в sentence
    // - возвращаем индекс этого слова.
    if (isMatch) return wordNdx;

    // Если префикс не подошёл (isMatch === false), нужно пропустить
    // остаток текущего слова.
    //
    // Этот цикл продвигает i до конца текущего слова или до конца
    // строки, останавливаясь на пробеле или на достижении n.
    while (
      i < n
      && sentence[i] !== ' '
    ) i++

    // После пропуска остатка слова проверяем, не достигли ли мы
    // конца строки и действительно ли текущий символ - пробел
    // (граница между словами).
    if (
      i < n
      && sentence[i] === ' '
    ) {

      // Если встретили пробел, значит мы переходим к следующему
      // слову - увеличиваем счётчик номера слова.
      wordNdx++;

      // Пропускаем сам пробел, чтобы i указывал на первый символ
      // следующего слова (или на n, если пробел был последним
      // символом).
      i++;
    }
  }

  // Если мы прошли всю строку и ни для одного слова не нашёлся
  // префикс searchWord, возвращаем -1 согласно условию задачи.
  return -1;
}
