/**
 * @param {string} s
 * @return {string}
 *
 * reverseOnlyLetters принимает строку s и возвращает новую строку,
 * в которой все английские буквы (латинские символы A–Z и a–z)
 * расположены в обратном порядке, тогда как все остальные символы
 * остаются на своих исходных позициях.
 *
 *
 * Пример для:
 *   s = "Test1ng-Leet=code-Q!"
 * Результат:
 *   "Qedo1ct-eeLg=ntse-T!"
 */
function reverseOnlyLetters(s) {

  // Преобразуем входную строку в массив символов, чтобы иметь
  // возможность менять символы по индексам (строки в JS неизменяемы).
  const chars = s.split('');

  // Инициализируем левый указатель l, который будет двигаться слева
  // направо.
  //
  // Начинаем с 0 - индекса первого символа массива.
  let l = 0;

  // Инициализируем правый указатель r, который будет двигаться справа
  // налево.
  //
  // Устанавливаем его в индекс последнего символа строки.
  let r = s.length - 1;

  // Запускаем цикл, который выполняется до тех пор, пока левый
  // указатель находится слева от правого (пока есть пары для
  // возможного обмена).
  while (l < r) {

    // Сдвигаем левый указатель вправо, пока он не укажет на
    // английскую букву или пока l не встретится с r.
    //
    // Регулярное выражение /[a-zA-Z]/ проверяет, является ли символ
    // латинской буквой (нижнего или верхнего регистра).
    //
    // Условие l < r в проверке предотвращает выход за границы и
    // лишние сдвиги, когда указатели встретились.
    //
    // Это позволяет пропускать все не-буквенные символы с левой
    // стороны, сохраняя их на месте.
    while (!/[a-zA-Z]/.test(chars[l]) && l < r) l++;

    // Аналогично сдвигаем правый указатель влево, пока он не укажет
    // на английскую букву или пока l не встретится с r.
    //
    // Это позволяет пропускать все не-буквенные символы с правой
    // стороны, сохраняя их на месте.
    while (!/[a-zA-Z]/.test(chars[r]) && l < r) r--;

    // Сохраняем текущий символ с позиции l во временную переменную
    // tmp.
    //
    // Это нужно для безопасного обмена значений между позициями l и r
    // без потери данных.
    const tmp = chars[l];

    // Копируем символ с позиции r в позицию l - первая часть обмена.
    //
    // После этой операции символ на позиции l заменён символом с
    // правой стороны.
    chars[l] = chars[r];

    // Записываем сохранённый ранее символ tmp в позицию r - завершаем
    // обмен двух символов.
    //
    // В результате буквы на позициях l и r поменялись местами.
    chars[r] = tmp;

    // После успешного обмена сдвигаем оба указателя к центру, чтобы
    // перейти к обработке следующей пары символов.
    l++;
    r--;
  }

  // После завершения всех обменов объединяем массив символов обратно
  // в строку и возвращаем полученную строку как результат работы
  // функции.
  return chars.join('');
}
