/**
 * @param {string} s
 * @return {string}
 *
 * reverseVowels принимает строку и возвращает новую строку s, в которой
 * порядок всех гласных символов обращён, а все остальные символы остаются
 * на своих исходных позициях.
 *
 * Гласные:
 * 'a', 'e', 'i', 'o', 'u' - могут встречаться в нижнем и верхнем регистре
 * и повторяться.
 *
 *
 * Пример для:
 *   s = "IceCreAm"
 * Результат:
 *   "AceCreIm"
 * Пояснение:
 *   Гласные в s: ['I', 'e', 'e', 'A'].
 *
 *   При обращении порядка гласных строка становится "AceCreIm".
 */
function reverseVowels(s) {

  // Создаём множество гласных для быстрой проверки принадлежности символа
  // к гласным.
  //
  // Использование Set обеспечивает амортизированное за амортизированное
  // время O(1).
  //
  // Включаем как строчные, так и заглавные варианты - это позволяет
  // быстро и корректно обрабатывать регистр.
  const vowelSet = new Set(['a', 'e', 'i', 'o', 'u', 'A', 'E', 'I', 'O', 'U']);

  // Преобразуем строку в массив символов, потому что строки в JavaScript
  // неизменяемы, что не позволяет менять символы местами.
  //
  // Массив позволяет менять символы местами по индексам.
  const chars = s.split('');

  // Инициализируем левый указатель l на начало массива (индекс 0).
  //
  // Этот указатель будет двигаться вправо в поисках гласной для обмена.
  let l = 0;

  // Инициализируем правый указатель r на индекс последнего символа строки.
  //
  // Этот указатель будет двигаться влево в поисках гласной для обмена.
  let r = s.length - 1;

  // Запускаем цикл, который продолжается, пока левый указатель находится
  // слева от правого.
  //
  // Это гарантирует, что каждая пара гласных будет обработана ровно один
  // раз.
  while (l < r) {

    // Сдвигаем левый указатель вправо до тех пор, пока он не укажет на
    // гласную или пока не пересечётся с правым.
    //
    // Условие l < r предотвращает выход за границы и лишние проверки после
    // пересечения указателей.
    while (l < r && !vowelSet.has(chars[l])) l++;

    // Сдвигаем правый указатель влево до тех пор, пока он не укажет на
    // гласную или пока не пересечётся с левым.
    //
    // Аналогично, проверка l < r защищает от ненужных итераций и
    // гарантирует корректность при нечётном количестве символов.
    while (l < r && !vowelSet.has(chars[r])) r--;

    // Сохраняем символ по левому указателю во временную переменную tmp для
    // выполнения обмена, так как символ в этой позиции будет перезаписан
    // символом из правой позиции.
    //
    // На этом этапе оба указателя указывают на гласные (если они не
    // пересеклись).
    const tmp = chars[l];

    // Копируем символ с позиции правого указателя в позицию левого.
    chars[l] = chars[r];

    // Вставляем ранее сохранённый левый символ в позицию правого, завершая
    // обмен.
    chars[r] = tmp;

    // После успешного обмена сдвигаем левый указатель вправо, чтобы
    // продолжить обработку следующих символов.
    l++;

    // Сдвигаем правый указатель влево по той же причине.
    r--;
  }

  // Собираем изменённый массив символов обратно в строку и возвращаем её.
  //
  // join('') объединяет элементы массива без разделителей, восстанавливая
  // строковое представление.
  //
  // Все гласные теперь расположены в обратном порядке относительно
  // исходной строки.
  return chars.join('');
}
