/**
 * @param {number[]} nums
 * @param {number} k
 * @return {number[]}
 *
 * limitOccurrences принимает отсортированный массив целых чисел nums
 * и целое число k.
 *
 * Возвращает массив, в котором каждый различный элемент встречается
 * не более k раз, при этом сохраняется относительный порядок
 * элементов из nums.
 *
 * Примечание:
 * Если некоторый различный элемент встречается как минимум k раз, то
 * в результирующем массиве он должен встречаться ровно k раз.
 *
 *
 * Пример для:
 *   nums = [1,1,1,2,2,3],
 *   k = 2
 * Результат:
 *   [1,1,2,2,3]
 * Пояснение:
 * Каждый элемент может появляться не более 2 раз.
 * - Элемент 1 встречается 3 раза, поэтому сохраняются только 2
 *   вхождения.
 *
 * - Элемент 2 встречается 2 раза, поэтому оба вхождения сохраняются.
 *
 * - Элемент 3 встречается 1 раз, поэтому сохраняется.
 *
 * В результате массив: [1, 1, 2, 2, 3].
 */
function limitOccurrences(nums, k) {

  // Инициализация счётчика текущей последовательности одинаковых
  // чисел.
  //
  // currNumFreq хранит, сколько раз подряд встретился текущий
  // элемент (включая уже обработанный).
  //
  // Начинаем с 1, потому что при входе в функцию мы считаем первый
  // элемент (nums[0]) уже встреченным один раз.
  let currNumFreq = 1;

  // Указатель l указывает на позицию в массиве nums, куда будет
  // записан следующий допустимый элемент.
  //
  // Инициализируем 1, потому что первый элемент массива всегда
  // остаётся (мы сохраняем относительный порядок), и следующая
  // свободная позиция для записи - индекс 1.
  let l = 1;

  // Проходим по массиву правым указателем r, начиная со второго
  // элемента (индекс 1).
  //
  // r - индекс текущего рассматриваемого элемента.
  for (let r = 1; r < nums.length; r++) {

    // Сравниваем предыдущий элемент nums[r - 1] с текущим nums[r].
    //
    // Поскольку массив отсортирован, равенство означает, что мы всё
    // ещё в той же группе одинаковых чисел.
    //
    // Если элементы различны, это начало новой группы одинаковых
    // значений, поэтому сбрасываем счётчик частоты в 1, потому что
    // nums[r] - первое вхождение нового значения.
    if (nums[r - 1] !== nums[r]) currNumFreq = 1;

    // Если текущий элемент равен предыдущему, то мы продолжаем ту
    // же группу одинаковых значений, поэтому увеличиваем счётчик
    // частоты на 1.
    else currNumFreq++;

    // Если частота текущего числа превысила допустимый лимит k, этот
    // элемент нужно пропустить.
    //
    // Мы не перемещаем указатель l и не записываем nums[r] в массив
    // - удаляем лишние вхождения.
    if (currNumFreq > k) continue;

    // Если частота текущего числа не превышает k, то текущий элемент
    // допустим и должен быть сохранён.
    //
    // Записываем nums[r] в позицию nums[l]. Это выполняет сжатие
    // массива "влево" без использования дополнительной памяти.
    nums[l] = nums[r];

    // После записи увеличиваем l, чтобы следующая допустимая запись
    // попала в следующую позицию.
    l++;
  }

  // После прохода по массиву l указывает на длину "сжатой" части
  // массива, содержащей все допустимые элементы.
  //
  // Возвращаем новый массив, состоящий из первых l элементов nums.
  return nums.slice(0, l);
}
