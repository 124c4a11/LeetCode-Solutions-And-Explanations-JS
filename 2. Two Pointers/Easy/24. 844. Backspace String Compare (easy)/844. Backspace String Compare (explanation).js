/**
 * @param {string} s
 * @param {string} t
 * @return {boolean}
 *
 * backspaceCompare принимает две строки s и t.
 *
 * Функция определяет, будут ли две строки равны друг другу после того, как
 * в них применят все символы удаления # (работающие как клавиша Backspace
 * на клавиатуре).
 *
 * Символ # интерпретируется как нажатие клавиши Backspace, то есть он
 * "удаляет" один предыдущий (стоящий слева от него) символ.
 *
 * Возвращает true, если итоговые строки совпадают, и false, если они
 * различаются.
 *
 *
 * Пример для:
 *   s = "ab#c",
 *   t = "ad#c"
 * Результат:
 *   true
 * Пояснение:
 *   Обе строки s и t превращаются в "ac".
 *
 *
 * Пример для:
 *   s = "ab##",
 *   t = "c#d#"
 * Результат:
 *   true
 * Пояснение:
 *   Обе строки s и t превращаются в "".
 *
 *
 * Пример для:
 *   s = "a#c",
 *   t = "b"
 * Результат:
 *   false
 * Пояснение:
 *   Строка s превращается в "c", в то время как строка t превращается в
 *   "b".
 */
function backspaceCompare(s, t) {

  // Инициализируем указатель i для итерации по строке s с конца.
  //
  // Присваиваем ему индекс последнего элемента (длина строки минус 1).
  let i = s.length - 1;

  // Инициализируем указатель j для итерации по строке t с конца.
  //
  // Присваиваем ему индекс последнего элемента (длина строки минус 1).
  let j = t.length - 1;

  // Запускаем главный цикл, который продолжается до тех пор, пока хотя бы
  // один из указателей (i или j) не вышел за левую границу своей строки
  // (индекс < 0).
  //
  // Это нужно, так как строки могут иметь разную длину или разное
  // количество удаляемых символов.
  while (i >= 0 || j >= 0) {

    // Объявляем и обнуляем локальный счетчик backspaceCnt, который будет
    // хранить количество накопленных, но ещё не примененных символов '#'
    // (нажатий Backspace) при сканировании строки s.
    let backspaceCnt = 0;

    // Запускаем внутренний цикл для строки s.
    //
    // Его цель - пропустить все символы '#', а также те обычные символы,
    // которые должны быть удалены этими знаками '#', и остановиться на
    // первом реальном "выжившем" символе.
    while (i >= 0) {

      // Проверяем, является ли текущий символ в строке s по индексу i
      // знаком удаления '#'.
      if (s[i] === '#') {

        // Если это '#', увеличиваем счетчик накопленных удалений на 1.
        //
        // Этот символ заставит нас удалить какой-то символ левее него.
        backspaceCnt++;

        // Если текущий символ - не '#', но у нас есть накопленные удаления
        // (счетчик backspaceCnt больше нуля).
      } else if (backspaceCnt > 0) {

        // Мы виртуально "уладяем" текущий обычный символ, уменьшая счетчик
        // неиспользованных удалений на 1.
        backspaceCnt--;

        // Иначе текущий символ - обычная буква, и при этом счетчик
        // накопленных удалений равен 0.
      } else {

        // Это означает, что символ останется в текстовом редакторе и
        // должен участвовать в сравнении.
        //
        // Немедленно прерываем внутренний цикл, оставляя указатель i на
        // индексе этого символа.
        break;
      }

      // Если мы встретили '#' или стерли символ (сработал if или else if),
      // сдвигаем указатель i на один шаг влево, переходя к предыдущему
      // символу строки s для продолжения проверки.
      i--;
    }

    // Сбрасываем (переинициализируем) счетчик backspaceCnt в 0 перед
    // началом аналогичного разбора для строки t, чтобы прошлые удаления из
    // строки s не повлияли на логику строки t.
    backspaceCnt = 0;

    // Запускаем точно такой же внутренний цикл для строки t.
    //
    // Двигаемся справа налево, чтобы найти ближайший реальный (неудалённый)
    // символ в строке t.
    while (j >= 0) {

      // Проверяем, равен ли символ строки t по текущему индексу j знаку
      // '#'.
      if (t[j] === '#') {

        // Если встретили '#', увеличиваем счетчик накопленных нажатий
        // Backspace для строки t на 1.
        backspaceCnt++;

        // Если перед нами обычный символ, но счетчик накопленных удалений
        // backspaceCnt для строки t строго больше нуля.
      } else if (backspaceCnt > 0) {

        // Виртуально удаляем текущий символ, уменьшая счетчик активных
        // удалений на 1, так как данное нажатие Backspace успешно
        // применилось.
        backspaceCnt--;

        // Если перед нами обычный символ и никаких активных удалений
        // (Backspace) нет.
      } else {

        // Это означает, что символ останется в текстовом редакторе и
        // должен участвовать в сравнении.
        //
        // Немедленно прерываем внутренний цикл, оставляя указатель j на
        // индексе этого символа.
        break;
      }

      // Если мы встретили '#' или стерли символ (сработал if или else if),
      // уменьшаем указатель j на 1, продвигаясь дальше влево по строке t.
      j--;
    }

    // После того как оба внутренних цикла завершились, мы сравниваем
    // символы по индексам i и j.
    //
    // Если один из указателей ушел за левую границу (стал < 0), то
    // обращение к s[i] или t[j] вернет undefined.
    //
    // Если символы (или undefined и символ) не равны, строки
    // гарантированно отличаются - возвращаем false.
    if (s[i] !== t[j]) return false;

    // Сдвигаем указатель i на один шаг влево, чтобы на следующей итерации
    // главного цикла начать поиск нового символа в строке s, пропустив тот,
    // который мы только что успешно сравнили.
    i--;

    // Сдвигаем указатель j на один шаг влево, чтобы на следующей итерации
    // главного цикла начать поиск нового символа в строке t, пропустив тот,
    // который мы только что успешно сравнили.
    j--;
  }

  // Если главный цикл полностью завершился и ни разу не сработал возврат
  // false, значит, все реально видимые символы в обеих строках попарно
  // совпали - возвращаем true.
  return true;
}
