/**
 * @param {number[]} nums
 * @return {number}
 *
 * minimumSwaps принимает массив целых чисел nums и подсчитывает
 * минимальное количество операций обмена, необходимых для того, чтобы
 * переместить все нули в массиве в самый конец, оставив все остальные
 * числа в начале.
 *
 * Пример для:
 *   nums = [0,1,0,3,12]
 * Результат:
 *   2
 * Пояснение:
 *   Мы выполняем следующие операции обмена:
 *   - Меняем местами nums[0] и nums[3], получая nums = [3, 1, 0, 0, 12].
 *   - Меняем местами nums[2] and nums[4], получая nums = [3, 1, 12, 0, 0].
 *   Таким образом, ответ: 2.
 */
function minimumSwaps(nums) {

  // Инициализируем переменную-счетчик swapsCnt со значением 0, в которой
  // будем аккумулировать общее количество успешно произведенных обменов
  // элементов.
  let swapsCnt = 0;

  // Инициализация указателя 'l' (left) нулевым индексом.
  //
  // Он будет двигаться слева направо и искать элементы, равные 0, которые
  // стоят не на своем месте.
  let l = 0;

  // Инициализация указателя 'r' (right) индексом последнего элемента
  // массива.
  //
  // Он будет двигаться справа налево и искать ненулевые элементы для
  // переноса вперед.
  let r = nums.length - 1;

  // Цикл, который работает до тех пор, пока левый указатель строго меньше
  // правого, обеспечивая встречное сканирование массива с двух сторон.
  while (l < r) {

    // Смещаем указатель l вправо (l++), пока текущий элемент nums[l] не
    // равен нулю и указатель l не встретился с указателем r.
    //
    // Цель — найти индекс самого левого нуля, требующего перемещения.
    while (nums[l] !== 0 && l < r) l++;

    // Смещаем указатель r влево (r--), пока текущий элемент nums[r] равен
    // нулю и указатель l не встретился с указателем r.
    //
    // Цель — найти индекс самого правого ненулевого числа, которое нужно
    // перенести вперед.
    while (nums[r] === 0 && l < r) r--;

    // Если после остановки внутренних циклов левый и правый указатели
    // встретились в одной точке (l равно r), значит, весь массив nums
    // пройден и все нули гарантированно находятся в конце массива.
    // Перестановки больше не требуются - прерываем цикл.
    if (l === r) break;

    // Временно сохраняем значение элемента nums[l] (который гарантированно
    // равен 0) в константу tmp.
    const tmp = nums[l];

    // Перезаписываем элемент на позиции левого указателя (где был 0)
    // ненулевым значением, взятым из позиции правого указателя nums[r].
    nums[l] = nums[r];

    // Записываем ранее сохраненное во временной переменной tmp значение
    // (ноль) на освободившееся место правого указателя nums[r].
    nums[r] = tmp;

    // Увеличение счетчика совершенных операций обмена на единицу.
    swapsCnt++;

    // Сдвиг левого указателя на один шаг вправо, чтобы перейти к проверке
    // следующего элемента.
    l++;

    // Сдвиг правого указателя на один шаг влево, чтобы перейти к проверке
    // следующего элемента.
    r--;
  }

  // Возвращаем итоговое накопленное значение переменной swapsCnt,
  // представляющее собой минимально возможное количество перестановок для
  // выполнения условия задачи.
  return swapsCnt;
}
