/**
 * @param {string} s
 * @param {number} k
 * @return {string}
 *
 * reverseStr делит всю строку s на блоки длиной 2k символов и внутри
 * каждого такого блока берет первые k символов и меняет их порядок на
 * противоположный, а остальные k символов оставляет нетронутыми.
 *
 * Параметры:
 * - s (строка / String) - исходная текстовая строка, которую необходимо
 *   обработать.
 *
 * - k (целое число / Number) - шаг или коэффициент, определяющий размер
 *   подстрок для разворота.
 *
 *
 * Пример для:
 *   s = "abcdefg",
 *   k = 2
 * Результат:
 *   "bacdfeg"
 */
function reverseStr(s, k) {
  const n = s.length;

  // Разбиваем строку на массив отдельных символов, чтобы иметь возможность
  // менять их местами по индексам.
  //
  // В JavaScript строки являются неизменяемыми (immutable), и мы не можем
  // менять их символы местами напрямую по индексам.
  const chars = s.split('');

  // Итерируемся по строке, сдвигая индекс start на величину 2 * k на
  // каждом шаге, чтобы обрабатывать строку блоками по 2k символов.
  for (let start = 0; start < n; start += 2 * k) {

    // Инициализируем левый маркер l, который указывает на начальный индекс
    // текущего отрезка, предназначенного для разворота.
    let l = start;

    // Определяем правый указатель r как последний индекс для разворота:
    //
    // Берем либо start + k - 1, либо n - 1, если до конца строки осталось
    // меньше k символов.
    let r = Math.min(start + k - 1, n - 1);

    // Запускаем классический цикл "двух указателей", который будет
    // выполняться до тех пор, пока левый индекс строго меньше правого.
    while (l < r) {

      // Создаем временную константу tmp для сохранения символа,
      // находящегося на позиции левого указателя, чтобы не потерять его
      // при перезаписи.
      const tmp = chars[l];

      // Копируем символ из позиции правого указателя r в ячейку с индексом
      // левого указателя l.
      chars[l] = chars[r];

      // Записываем сохраненный во временной переменной tmp левый символ в
      // ячейку с индексом правого указателя r, завершая обмен элементов
      // местами.
      chars[r] = tmp;

      // Сдвигаем левый указатель вправо, к центру подстроки, чтобы на
      // следующей итерации перейти к следующему символу справа.
      l++;

      // Сдвигает правый указатель влево, к центру подстроки, чтобы на
      // следующей итерации перейти к следующему символу слева.
      r--;
    }
  }

  // Собираем все элементы массива chars обратно в единую строку без
  // разделителей и возвращаем полученный результат.
  return chars.join('');
}
