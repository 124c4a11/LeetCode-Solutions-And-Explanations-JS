/**
 * @param {number[]} forts
 * @return {number}
 *
 * captureForts принимает массив целых чисел forts с нулевой индексацией
 * длины n, представляющий позиции нескольких фортов. forts[i] может
 * принимать значения -1, 0 или 1, где:
 * - -1 означает, что на i-й позиции форта нет (пустая позиция).
 *
 * - 0 указывает на то, что на i-й позиции находится вражеский форт.
 *
 * - 1 указывает на то, что форт на i-й позиции находится под вашим
 *   командованием.
 *
 * Теперь вы решили переместить свою армию из одного из ваших фортов на
 * позиции i на пустую позицию j так, чтобы:
 * - 0 <= i, j <= n - 1
 *
 * - Армия перемещается исключительно через вражеские форты. Формально, для
 *   всех k, где min(i,j) < k < max(i,j), выполняется условие forts[k] == 0.
 *
 * Во время перемещения армии все вражеские форты, встречающиеся на пути,
 * захватываются.
 *
 * Возвращает максимальное количество вражеских фортов, которое можно
 * захватить. Если переместить армию невозможно или у вас нет ни одного
 * форта под вашим командованием, возвращает 0.
 *
 *
 * Пример для:
 *   forts = [1, 0, 0, -1, 0, 0, 0, 0, 1]
 * Результат:
 *   4
 * Объяснение:
 * - Перемещение армии с позиции 0 на позицию 3 позволяет захватить 2
 *   вражеские крепости, расположенные на позициях 1 и 2.
 *
 * - Перемещение армии с позиции 8 на позицию 3 позволяет захватить 4
 *   вражеские крепости.
 *
 * Поскольку 4 - максимальное количество вражеских крепостей, которые можно
 * захватить, возвращаем 4.
 *
 *
 * Пример для:
 *   forts = [0, 0, 1, -1]
 * Результат:
 *   0
 * Объяснение:
 * Поскольку захватить ни одну вражескую крепость невозможно, возвращаем 0.
 */
function captureForts(forts) {

  // Ключевая идея заключается в том, что корректное перемещение армии
  // состоит ровно из трёх последовательных компонентов:
  // - начальная позиция (ваш форт или пустая позиция),
  // - путь, состоящий из вражеских фортов,
  // - конечная позиция (пустая позиция или ваш форт).
  //
  // Важное наблюдение: начальная и конечная позиции должны быть
  // противоположных типов - одна должна содержать ваш форт (1), а другая
  // должна быть пустой (-1).
  //
  // Почему проверка forts[i] + forts[j] === 0 работает? Если одна позиция
  // имеет значение 1, а другая - -1, их сумма равна нулю. Таким образом,
  // мы проверяем, что начальная и конечная позиции противоположны, как и
  // требуется для корректного хода.
  //
  // Из этой закономерности естественным образом следует подход с двумя
  // указателями (two pointers).
  //
  // Мы проходим по массиву в поисках ненулевых элементов - потенциальных
  // начальной и конечной позиций. Когда находим такой элемент в позиции i,
  // ищем следующий ненулевой элемент в позиции j.
  //
  // По определению, все элементы между i и j должны быть нулями,
  // то есть представлять вражеские форты. Если бы между ними
  // встретилась позиция другого типа, указатель j остановился бы раньше.
  //
  // По сути, алгоритм находит в массиве все возможные отрезки, для которых:
  // 1. Начальный и конечный элементы не равны нулю.
  //
  // 2. Все элементы между ними равны нулю (вражеские форты).
  //
  // 3. Начальный и конечный элементы противоположны (их сумма равна нулю).
  //
  // Проверяя все такие отрезки и сохраняя максимальную длину минус 2
  // (чтобы исключить начальную и конечную позиции), мы находим
  // максимальное количество вражеских фортов, которые можно захватить за
  // один ход.
  //
  // После каждой проверки указатель i перемещается непосредственно к
  // позиции j, поскольку все элементы до j уже были рассмотрены. Это
  // позволяет избежать лишних проверок и обеспечивает линейную временную
  // сложность алгоритма - O(n).


  const n = forts.length;

  // Создаем maxCaptured, в которой мы будем хранить и обновлять наилучший
  // (максимальный) результат захвата фортов.
  let maxCaptured = 0;

  // Создаем переменную-указатель i, которая изначально указывает на начало
  // массива (индекс 0) и служит левой границей (стартовой точкой) для
  // поиска непрерывного ряда вражеских фортов.
  let i = 0;

  // Запускаем главный цикл, который будет двигать левый указатель i слева
  // направо, пока мы полностью не просканируем весь массив до самого
  // последнего элемента.
  while (i < n) {

    // Создаем правый указатель j и ставим его на позицию сразу после i
    // (i + 1), чтобы начать исследовать элементы, расположенные правее
    // нашей стартовой точки.
    let j = i + 1;

    // Элемент на позиции i не должен быть нулем.
    //
    // Нам нужен либо наш форт (1), либо пустая позиция (-1), так как
    // маневр не может начинаться из вражеского форта.
    if (forts[i] !== 0) {

      // Запускаем вложенный цикл while для сканирования и "перешагивания"
      // через вражеские форты.
      //
      // Цикл продолжает работу только тогда, когда выполняются
      // одновременно оба условия:
      while (

        // Указатель j всё еще находится внутри массива и не вышел за его
        // правый край.
        j < n

        // И элемент под этим индексом j является вражеским фортом
        // (равен 0).
        && forts[j] === 0

        // Если оба условия верны, инкрементируем j (сдвигаем вправо),
        // пошагово продвигаясь сквозь врагов.
      ) j++;

      // Когда вложенный цикл завершился (встретился не 0 или кончился
      // массив), проверяем, получился ли валидный маневр:
      if (

        // Убеждаемся, что указатель j остановился в пределах массива, а не
        // вылетел за его границы.
        j < n

        // Проверяем ключевое условие задачи через сумму:
        // forts[i] + forts[j] === 0.
        //
        // Так как оба элемента не равны нулю, их сумма будет 0 только в
        // двух случаях: 1 + (-1) = 0 или -1 + 1 = 0.
        //
        // Это гарантирует, что на одном конце цепочки находится наш форт,
        // а на другом - пустая клетка.
        && forts[i] + forts[j] === 0
      ) {

        // Если условия выполнены, вычисляем длину цепочки врагов между
        // i и j по формуле расстояния: j - i - 1.
        //
        // Например, если i = 1, а j = 4, то между ними находятся индексы
        // 2 и 3 (ровно 4 - 1 - 1 = 2 форта)
        const capturedCnt = j - i - 1;

        // Сравниваем только что найденное количество capturedCnt с текущим
        // рекордом в maxCaptured.
        //
        // Функция Math.max выбирает большее из них и перезаписывает
        // значение в переменную maxCaptured.
        maxCaptured = Math.max(maxCaptured, capturedCnt);
      }
    }

    // Переносим левый указатель i сразу на позицию j.
    //
    // Это оптимизация, которая позволяет не перепроверять элементы внутри
    // пройденной цепочки, так как они гарантированно были нулями.
    i = j;
  }

  // После завершения внешнего цикла возвращаем финальное максимальное
  // количество вражеских фортов, которое нам удалось успешно захватить в
  // ходе одного маневра.
  return maxCaptured;
}
