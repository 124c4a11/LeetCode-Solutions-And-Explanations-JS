/**
 * @param {number[]} arr
 * @return {void} Do not return anything, modify arr in-place instead.
 *
 * duplicateZeros принимает целочисленный массив фиксированной длины arr и
 * дублирует каждое вхождение нуля в этом массиве, сдвигая оставшиеся
 * элементы вправо.
 *
 * Указанные изменения вносятся во входной массив на месте и ничего не
 * возвращается.
 *
 * Элементы, выходящие за пределы длины исходного массива, не записываются.
 *
 *
 * Пример для:
 *   arr = [1,0,2,3,0,4,5,0]
 * Результат:
 *   [1,0,0,2,3,0,0,4]
 */
function duplicateZeros(arr) {

  // Главная сложность заключается в том, что нам нужно дублировать нули
  // непосредственно внутри массива, не используя дополнительную память.
  // Мы не можем просто пройти по массиву слева направо, потому что при
  // дублировании нуля мы перезапишем элементы, которые ещё не обработали.
  //
  // Давайте разберёмся, что происходит при дублировании нулей.
  // Каждый ноль занимает две позиции вместо одной, поэтому некоторые
  // элементы в конце массива будут вытеснены за его пределы.
  // Ключевая идея заключается в том, что перед началом изменений нам нужно
  // точно определить, какие элементы останутся в итоговом массиве.
  //
  // Рассмотрим такой подход: если мы знаем, на какой позиции окажется
  // каждый элемент в итоговом массиве, то можем заполнять массив с конца.
  // Почему с конца? Потому что при движении справа налево мы не будем
  // перезаписывать элементы, которые нам ещё предстоит обработать.
  //
  // Логика следующая:
  // 1. Сначала нужно определить, какие элементы исходного массива
  //    действительно поместятся в изменённый массив. Мы можем имитировать
  //    процесс дублирования, проходя по массиву и подсчитывая количество
  //    занимаемых позиций: обычные числа занимают 1 позицию, а нули - 2
  //    позиции.
  //
  // 2. После того как мы определили последний элемент, который поместится
  //    в массив (пусть он находится по индексу i), начинаем заполнять
  //    массив с самой правой позиции (j = n - 1) и двигаемся влево.
  //
  // 3. Двигаясь справа налево, копируем элементы с позиции i на позицию j.
  //    Если встречаем ноль, записываем его сразу в обе позиции - j и j - 1
  //    (то есть дублируем его), после чего сдвигаем j на две позиции влево.
  //    Для ненулевых элементов достаточно выполнить обычное копирование.
  //
  // Есть особый крайний случай: что если последний элемент, который
  // помещается, является нулём, но в массиве хватает места только для
  // одной его копии? Алгоритм обрабатывает это, проверяя, равно ли
  // значение позиции k числу n + 1 (то есть мы вышли за границу массива
  // ровно на одну позицию). В этом случае мы вручную записываем один ноль
  // в последнюю позицию массива и соответствующим образом корректируем
  // указатели.
  //
  // Такой подход в два прохода элегантно решает задачу без использования
  // дополнительной памяти и гарантирует, что мы не потеряем данные,
  // которые нам ещё нужно обработать.

  const n = arr.length;

  // Индекс элемента в исходном массиве, который мы сейчас рассматриваем.
  //
  // Инициализируем sourceNdx = -1, для того, чтобы после завершения цикла
  // он оставался в передлах входного массива
  let sourceNdx = -1;

  // Переменная для отслеживания "виртуальной" длины массива
  //
  // Этот счетчик симулирует, какой стала бы длина массива, если бы мы
  // просто расширяли его, дописывая в него дубликаты нулей.
  let virtualLength = 0;

  // Определяем, какой именно элемент исходного массива окажется самым
  // последним в рамках лимита длины 'n' после дублирования нулей.
  while (virtualLength < n) {

    // Инкрементируем указатель sourceNdx, переводя его на следующий
    // рассматриваемый элемент исходного массива.
    sourceNdx++;

    // Проверяем значение текущего элемента:
    // Если это 0, то в виртуальный массив добавляется 2 позиции (сам ноль
    // и его дубликат).
    //
    // Если это любое другое число, виртуальная длина увеличивается только
    // на 1 позицию.
    //
    // Результат прибавляется к virtualLength.
    virtualLength += (arr[sourceNdx] === 0) ? 2 : 1;
  }

  // Создаем указатель destinationNdx и устанавливаем его на самый
  // последний физический индекс реального массива (n - 1).
  //
  // С этой позиции мы начнем перезаписывать элементы в обратном
  // направлении (справа налево), чтобы не затереть еще не прочитанные
  // данные.
  let destinationNdx = n - 1;

  // Проверяем крайний случай:
  //
  // Если virtualLength стала равна n + 1, это значит, что последним
  // обработанным элементом был ноль.
  //
  // Этот ноль виртуально занял две позиции, но вторая копия ("хвост"
  // дубликата) вылетает за пределы исходной длины n и не помещается.
  if (virtualLength === n + 1) {

    // Так как копия нуля не помещается, мы берем только сам этот ноль
    // (одну позицию) и записываем его в самый последний доступный ячейку
    // массива (индекс n - 1).
    arr[destinationNdx] = 0;

    // Уменьшаем исходный указатель sourceNdx на 1, так как этот крайний
    // ноль мы уже обработали, и для следующего шага нам нужен предыдущий
    // элемент.
    sourceNdx--;

    // Сдвигаем указатель записи влево, так как последняя ячейка уже занята.
    destinationNdx--;
  }

  // Запускаем основной цикл перезаписи элементов, который двигается справа
  // налево, пока не дойдет до самого первого элемента (индекс 0).
  //
  // На этом этапе мы берем элементы из "старых" позиций (sourceNdx) и
  // переносим их на "новые" позиции (destinationNdx).
  while (destinationNdx >= 0) {

    // Копируем элемент из текущей позиции чтения sourceNdx в текущую
    // позицию записи destinationNdx.
    //
    // Если это было ненулевое число, оно просто встает на свое новое
    // правильное место.
    //
    // Если это был ноль, он записывается первый раз.
    arr[destinationNdx] = arr[sourceNdx];

    // Если скопированный элемент оказался нулем, его нужно продублировать.
    if (arr[sourceNdx] === 0) {

      // Сдвигаем указатель записи влево на предыдущую ячейку.
      destinationNdx--;

      // Записываем туда второй обязательный ноль (дубликат).
      arr[destinationNdx] = 0;
    }


    // Сдвигаем указатель чтения влево для обработки следующего элемента на
    // следующем шаге.
    sourceNdx--;

    // Сдвигаем указатель записи destinationNdx на один шаг влево,
    // подготавливая целевую позицию для записи следующего элемента на
    // следующем шаге.
    destinationNdx--;
  }
}
