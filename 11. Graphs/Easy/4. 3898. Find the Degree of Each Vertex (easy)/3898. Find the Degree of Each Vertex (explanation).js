/**
 * @param {number[][]} matrix
 * @return {number[]}
 *
 * findDegrees принимает двумерный целочисленный массив matrix размера
 * n x n, представляющий матрицу смежности неориентированного графа с n
 * вершинами, пронумерованными от 0 до n - 1.
 *
 * - matrix[i][j] = 1 указывает на то, что между вершинами i и j есть ребро.
 * - matrix[i][j] = 0 указывает на то, что между вершинами i и j нет ребра.
 *
 * Степенью вершины называется количество соединенных с ней ребер.
 *
 * Возвращает целочисленный массив degrees размера n, где degrees[i]
 * представляет собой степень вершины i.
 *
 *
 * Пример для:
 *   matrix = [[0,1,1],[1,0,1],[1,1,0]]
 * Результат:
 *   [2,2,2]
 * Пояснение:
 * - Вершина 0 соединена с вершинами 1 и 2, поэтому её степень равна 2.
 * - Вершина 1 соединена с вершинами 0 и 2, поэтому её степень равна 2.
 * - Вершина 2 соединена с вершинами 0 и 1, поэтому её степень равна 2.
 *
 * Таким образом, ответ: [2, 2, 2].
 */
function findDegrees(matrix) {

  // Вычисляем размер квадратной матрицы смежности n x n, получая
  // количество строк (что эквивалентно общему количеству вершин n в данном
  // графе).
  const n = matrix.length;

  // Создаем новый массив degrees фиксированной длины n для хранения
  // степеней всех вершин
  const degrees = new Array(n);

  // Внешний цикл для последовательного перебора каждой строки матрицы
  // (каждой вершины r)
  for (let r = 0; r < n; r++) {

    // Объявление локальной переменной-аккумулятора degree и инициализация
    // её нулем для подсчета количества ребер, соединенных именно с текущей
    // вершиной r
    let degree = 0;

    // Внутренний цикл для перебора всех столбцов (всех возможных связей c
    // с другими вершинами)
    for (let c = 0; c < n; c++) {

      // Обращаемся к элементу matrix[r][c] (где 1 означает наличие ребра,
      // а 0 - его отсутствие) и с помощью оператора += прибавляем его к
      // локальному счетчику degree, накапливая общую степень для вершины r.
      degree += matrix[r][c];
    }

    // После завершения подсчета всех ребер для текущей строки записываем
    // накопленное итоговое значение степени во внутренний массив degrees
    // под индексом r.
    degrees[r] = degree;
  }

  // Возвращаем итоговый заполненный массив degrees, в котором каждый
  // элемент с индексом i хранит целочисленное значение степени i-й вершины
  // графа.
  return degrees;
}
