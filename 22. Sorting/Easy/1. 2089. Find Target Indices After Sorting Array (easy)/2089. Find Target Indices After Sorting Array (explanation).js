/**
 * @param {number[]} nums
 * @param {number} target
 * @return {number[]}
 *
 * targetIndices принимает массив целых чисел nums с индексацией от 0 и
 * целевой элемент target.
 *
 * Целевой индекс - это такой индекс i, для которого nums[i] == target.
 *
 * Возвращает массив целевых индексов массива nums после его сортировки по
 * неубыванию. Если целевых индексов нет, возвращает пустой массив.
 * Возвращаемый массив отсортирован по возрастанию.
 *
 *
 * Пример для:
 *   nums = [1, 2, 5, 2, 3],
 *   target = 2
 * Результат:
 *   [1, 2]
 * Пояснение:
 *   После сортировки nums выглядит так: [1, 2, 2, 3, 5].
 *
 *   Индексы, по которым nums[i] == 2, - это 1 и 2.
 */
function targetIndices(nums, target) {

  // Идея этого алгоритма заключается в том, что для нахождения индексов
  // элементов после сортировки саму сортировку выполнять не нужно. Этот
  // подход основан на принципах сортировки подсчетом (Counting Sort) и
  // работает за линейное время O(n), что гораздо быстрее любой стандартной
  // сортировки O(n log n).
  //
  // Вместо изменения порядка элементов алгоритм математически вычисляет, в
  // каком диапазоне индексов окажется целевое число target, ответив на два
  // простых вопроса:
  // 1. Где начнется диапазон чисел target?
  //    Если мы посчитаем, сколько всего в массиве элементов, которые
  //    строго меньше target (переменная lessCnt), то в отсортированном по
  //    возрастанию массиве все они гарантированно встанут в самом начале.
  //    Значит, первое появление числа target будет ровно на позиции с
  //    индексом lessCnt.
  //
  // 2. Где этот диапазон закончится?
  //    Если мы посчитаем, сколько раз само число target встречается в
  //    массиве (переменная equalCnt), то мы узнаем точную длину этого
  //    целевого отрезка. Диапазон индексов для target будет идти от
  //    lessCnt (включительно) до lessCnt + equalCnt (не включая).
  //
  // Наглядный пример
  //
  // Пусть nums = [1, 2, 5, 2, 3], а target = 2.
  //
  // 1. Первый проход (цикл for...of):
  //    - Числа строго меньше 2 - это только [1]. Значит, lessCnt = 1.
  //    - Числа, равные 2, - это [2, 2]. Значит, equalCnt = 2.
  //
  // 2. Математический вывод:
  //    - Если бы мы отсортировали массив, он бы выглядел так:
  //      [1, 2, 2, 3, 5].
  //    - Единица (lessCnt = 1) заняла бы индекс 0.
  //    - Наши двойки заняли бы следующие equalCnt = 2 места, то есть
  //      индексы 1 и 2.
  //
  // 3. Второй проход (генерация ответа):
  //    - Зная, что нам нужны индексы начиная с 1 в количестве 2 штук,
  //      программа просто создает массив и заполняет его циклом: [1, 2].
  //
  // Главные преимущества такого подхода:
  // - Скорость (Time Complexity): O(n) - массив обходится один раз для
  //   подсчета, а затем создается результирующий массив
  //   (длина которого <= n). Это эффективнее, чем вызов nums.sort().
  //
  // - Память (Space Complexity): O(1) дополнительной памяти (если не
  //   считать сам массив ответа), так как мы храним только два небольших
  //   числа-счетчика.
  //
  // Хотите ли вы рассмотреть крайние случаи для этого алгоритма -
  // например, когда целевого элемента вообще нет в массиве или когда
  // массив состоит только из элементов target? Уверен, это поможет
  // окончательно закрепить понимание.


  // Переменная-счетчик для хранения общего количества элементов в массиве
  // nums, которые строго меньше target.
  //
  // Это число определит начальный индекс (смещение), с которого начнется
  // диапазон целевых элементов после сортировки.
  let lessCnt = 0;

  // Переменная-счетчик для хранения общего количества элементов в массиве
  // nums, которые в точности равны target.
  //
  // Это число определяет размер итогового массива и диапазон индексов,
  // которые займет целевое значение.
  let equalCnt = 0;

  // Проходим по всем значениям массива nums
  for (const num of nums) {

    // Если текущее число num строго меньше, чем искомое значение target,
    // то увеличиваем счетчик lessCnt на 1.
    //
    // Все эти числа в отсортированном массиве встанут левее target.
    if (num < target) lessCnt++;

    // Если текущее число num равно target, то увеличиваем счетчик equalCnt
    // на 1, фиксируя еще одно вхождение целевого элемента.
    else if (num == target) equalCnt++;
  }

  // Создание нового пустого массива с именем targetIndices.
  //
  // Конструктор new Array(equalCnt) сразу выделяет память под массив
  // нужной длины, которая в точности равна количеству найденных совпадений
  // с target.
  //
  // Выделение памяти под точное количество элементов оптимизирует
  // производительность, избегая динамического изменения размера массива.
  const targetIndices = new Array(equalCnt);

  // Локальный внутренний указатель (индекс), инициализированный нулем,
  // который используется для последовательного заполнения ячеек
  // результирующего массива targetIndices.
  let i = 0;

  // Цикл для генерации индексов в диапазоне целевых элементов, начиная от
  // количества меньших элементов (lessCnt) до их общего смещения
  // (lessCnt + equalCnt)
  for (let j = lessCnt; j < lessCnt + equalCnt; j++) {

    // Присваиваем ячейке результирующего массива с индексом i значение j
    // (которое является валидным индексом target), после чего постфиксный
    // инкремент i++ увеличивает указатель на 1 для следующей итерации.
    targetIndices[i++] = j;
  }

  // Возврат сформированного массива, содержащего упорядоченную
  // последовательность индексов, под которыми значение target
  // располагалось бы, если бы мы отсортировали исходный массив.
  return targetIndices;
}
