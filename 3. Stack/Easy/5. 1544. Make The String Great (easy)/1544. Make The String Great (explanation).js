/**
 * @param {string} s
 * @return {string}
 *
 *
 * makeGood принимает строку s, состоящую из строчных и прописных букв
 * английского алфавита.
 *
 * "Хорошей" считается строка, в которой нет двух соседних символов
 * s[i] и s[i + 1], где:
 * - 0 <= i <= s.length - 2
 *
 * - s[i] - это строчная буква, а s[i + 1] - та же буква, но прописная
 *   (или наоборот).
 *
 * Чтобы сделать строку "хорошей", функция выбирает два соседних символа,
 * которые делают строку "плохой", и удаляет их. Делает это до тех пор,
 * пока строка не станет "хорошей".
 *
 * Возвращает "хорошую строку".
 *
 * Обратите внимание, что пустая строка также считается "хорошей".
 *
 *
 * Пример для:
 *   s = "leEeetcode"
 * Результат:
 *   "leetcode"
 * Пояснение:
 *   На первом шаге вы можете выбрать либо i = 1, либо i = 2.
 *
 *   В обоих случаях строка "leEeetcode" сократится до "leetcode".
 *
 *
 * Пример для:
 *   s = "abBAcC"
 * Результат:
 *   ""
 * Пояснение:
 *   Существует множество возможных сценариев развития событий, и все они
 *   приводят к одному и тому же ответу.
 *
 *   Например:
 *     "abBAcC" → "aAcC" → "cC" → ""
 *     "abBAcC" → "abBA" → "aA" → ""
 */
function makeGood(s) {

  // Создаем пустой массив stack, выполняющий роль структуры данных "стек"
  // (LIFO - последним пришел, первым ушел) для последовательного сбора
  // символов, которые формируют правильную "хорошую" строку.
  const stack = [];

  // Проходим по символам строки s
  for (const char of s) {

    // Проверяем комплексное условие:
    //
    // 1. stack.length - проверяет, что стек не пустой (чтобы было с чем
    //    сравнивать текущий символ).
    //
    // 2. Math.abs(...) === 32 - вычисляет модуль разности Unicode-кодов
    //    последнего элемента в стеке (stack.at(-1)) и текущего символа
    //    (char).
    //
    //    В кодировках ASCII/Unicode разница между строчной и
    //    прописной версией одной и той же английской буквы
    //    (например, 'a' и 'A', 'b' и 'B') всегда равна ровно 32.
    if (
      stack.length
      && Math.abs(stack.at(-1).codePointAt(0) - char.codePointAt(0)) === 32
    ) {

      // Если оба условия верны (в стеке есть символы и текущий символ
      // образует "плохую пару" с предыдущим, то есть они представляют
      // собой одну букву в разном регистре), мы удаляем (выталкиваем)
      // последний символ из конца стека с помощью метода pop().
      //
      // Текущий символ char при этом в стек не добавляется.
      //
      // Это действие имитирует удаление смежной пары символов.
      stack.pop();
    } else {

      // Если стек пуст или текущий символ не образует запрещенную пару с
      // последним символом в стеке, мы добавляем текущий символ char в
      // конец стека с помощью метода push(), так как на данном шаге он
      // является частью "хорошей" строки.
      stack.push(char);
    }
  }

  // После завершения цикла все "плохие" смежные пары будут взаимно
  // уничтожены.
  //
  // Метод join('') объединяет все оставшиеся элементы массива stack в одну
  // результирующую "хорошую" строку без разделителей и возвращает её из
  // функции.
  return stack.join('');
}
