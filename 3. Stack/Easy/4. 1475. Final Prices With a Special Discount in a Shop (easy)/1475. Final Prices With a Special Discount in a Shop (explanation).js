/**
 * @param {number[]} prices
 * @return {number[]}
 *
 * finalPrices принимает массив целых чисел prices, где prices[i] - это
 * цена i-го товара в магазине.
 *
 * Функция вычисляет окончательную стоимость товаров в магазине с учетом
 * специальной скидки.
 *
 * Суть скидки заключается в поиске первого меньшего или равного элемента
 * справа для каждой цены.
 *
 * Если такой товар найден, его стоимость вычитается из цены текущего
 * товара (это и есть скидка).
 *
 * Если дальше по списку нет товара дешевле или с такой же ценой, текущий
 * товар продается за свою полную стоимость (скидка 0).
 *
 * Для оптимизации поиска (чтобы не запускать вложенный цикл под каждым
 * элементом) функция использует алгоритм монотонного стека, что позволяет
 * найти все скидки за один проход по массиву.
 *
 *
 * Пример для:
 *   prices = [8,4,6,2,3]
 * Результат:
 *   [4,2,4,2,3]
 * Пояснение:
 *   Для товара 0 с ценой prices[0]=8 вы получите скидку, равную
 *   prices[1]=4, поэтому окончательная цена, которую вы заплатите,
 *   составит 8 - 4 = 4.
 *
 *   Для товара 1 с ценой prices[1]=4 вы получите скидку, равную
 *   prices[3]=2, поэтому окончательная цена, которую вы заплатите,
 *   составит 4 - 2 = 2.
 *
 *   Для товара 2 с ценой prices[2]=6 вы получите скидку, равную
 *   prices[3]=2, поэтому окончательная цена, которую вы заплатите,
 *   составит 6 - 2 = 4.
 *
 *   Для товаров 3 и 4 вы вообще не получите никакой скидки.
 */
function finalPrices(prices) {

  // Инициализируем пустой массив increasingIndexStack, который будет
  // использоваться как монотонно возрастающий стек для хранения индексов
  // тех товаров, для которых мы ещё НЕ нашли подходящую скидку (то есть
  // первый меньший или равный элемент справа).
  const increasingIndexStack = [];

  // Запускаем цикл для последовательного обхода каждого товара по его
  // индексу i.
  for (let i = 0; i < prices.length; i++) {

    // Запускаем цикл "while", который работает до тех пор, пока
    // выполняются два условия одновременно:
    // 1. В стеке есть хотя бы один индекс.
    //
    // 2. Цена товара с индексом на вершине стека (последний добавленный)
    //    больше или равна цене текущего i-го товара.
    while (
      increasingIndexStack.length
      && prices[increasingIndexStack.at(-1)] >= prices[i]
    ) {

      // Извлекаем (удаляем) индекс 'j' с вершины стека через .pop().
      //
      // Текущий i-й товар - это самый первый элемент справа, который
      // меньше или равен j-му товару.
      const j = increasingIndexStack.pop();

      // Применяем скидку:
      //
      // Уменьшаем финальную стоимость j-го товара на величину цены
      // текущего i-го товара.
      prices[j] -= prices[i]
    }

    // После того как все подходящие элементы из стека обработаны (или если
    // стек был пуст), добавляем текущий индекс 'i' на вершину стека, чтобы
    // искать скидку уже для него.
    increasingIndexStack.push(i);
  }

  // После завершения внешнего цикла возвращаем заполненный массив result,
  // содержащий окончательные цены для всех товаров с учетом скидок
  return prices;
}
