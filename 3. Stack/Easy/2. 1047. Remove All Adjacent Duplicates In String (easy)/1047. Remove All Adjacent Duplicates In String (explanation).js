/**
 * @param {string} s
 * @return {string}
 *
 * removeDuplicates принимает строку и возвращает новую строку,
 * в которой последовательно удалены все соседние пары одинаковых
 * символов, пока таких пар не остаётся
 *
 *
 * Пример для:
 *   s = "abbaca"
 * Результат:
 *   "ca"
 * Пояснение:
 * Например, в строке "abbaca" можно удалить "bb", так как эти
 * буквы стоят рядом и равны. Это единственный возможный ход.
 * После этого ходa строка станет "aaca", в которой можно удалить
 * только "aa", поэтому итоговая строка - "ca".
 */
function removeDuplicates(s) {

  // Создаётся массив stack, который используется как стек для
  // обработки символов.
  //
  // В качестве начального элемента помещается s[0] - первый
  // символ строки.
  //
  // Если s пустая (s.length === 0), то s[0] даст undefined. В
  // таком случае стек будет содержать undefined, но при
  // последующем stack.join('') undefined преобразуется в
  // пустую строку, и функция вернёт ''.
  const stack = [s[0]];

  // Итерация по индексам строки, начиная со второго символа
  // (i = 1).
  //
  // Первый символ уже помещён в стек, поэтому цикл начинается с
  // 1.
  for (let i = 1; i < s.length; i++) {

    // Сравниваем последний элемент стека с текущим символом s[i].
    //
    // stack.at(-1) возвращает последний элемент массива
    // (современный эквивалент stack[stack.length-1]).
    //
    // Если символы совпадают, это означает образование пары
    // соседних одинаковых символов, которую нужно удалить,
    // поэтому вызываем stack.pop() для удаления верхнего
    // элемента стека.
    //
    // Такое удаление моделирует операцию "аннулирования" пары
    // одинаковых соседних символов.
    if (stack.at(-1) === s[i]) stack.pop();

    // Если последний элемент стека не равен текущему символу, то
    // текущий символ не образует пару с предыдущим и должен быть
    // добавлен в стек как часть результирующей
    // последовательности.
    //
    // push добавляет символ в конец массива, который мы
    // используем как вершину стека.
    else stack.push(s[i]);
  }

  // После прохода по всей строке стек содержит символы
  // результирующей строки в правильном порядке.
  //
  // Метод join('') объединяет элементы массива в строку без
  // разделителей и возвращает её.
  //
  // Временная сложность алгоритма O(n), где n - длина s.
  //
  // Память O(n) в худшем случае.
  return stack.join('');
}
