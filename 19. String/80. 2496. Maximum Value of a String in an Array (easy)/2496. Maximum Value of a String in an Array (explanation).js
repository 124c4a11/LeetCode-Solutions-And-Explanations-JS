/**
 * @param {string[]} strs
 * @return {number}
 *
 * maximumValue принимает массив строк strs. Она возвращает
 * максимальное значение, вычисленное по следующему правилу:
 * - если строка состоит только из числа, используется это
 *   число
 *
 * - в противном случае используется длина строки
 *
 *
 * Пример для:
 *   strs = ["alic3","bob","3","4","00000"]
 * Результат:
 *   5
 * Пояснение:
 *   - "alic3" состоит и из букв, и из цифр, поэтому его
 *     значение равно длине строки, то есть 5.
 *
 *   - "bob" состоит только из букв, поэтому его значение
 *     равно длине строки, то есть 3.
 *
 *   - "3" состоит только из цифр, поэтому его значение
 *     равно числовому эквиваленту, то есть 3.
 *
 *   - "4" также состоит только из цифр, поэтому его
 *     значение равно 4.
 *
 *   - "00000" состоит только из цифр, поэтому его числовое
 *     значение равно 0.
 *
 *   Следовательно, максимальное значение равно 5, у строки
 *   "alic3".
 */
function maximumValue(strs) {

  // Инициализируем переменную maxVal нулём.
  //
  // Она будет хранить текущий максимум.
  let maxVal = 0;

  // Перебираем каждый элемент входного массива strs
  for (const str of strs) {

    // Пытаемся явно преобразовать строку в число с помощью
    // конструктора Number.
    // Number('123') → 123;
    // Number('001') → 1;
    // Number('12.3') → 12.3;
    // Number('') → 0;
    // Number('   42  ') → 42;
    // Number('abc') → NaN.
    const num = Number(str);

    // Проверяем, является ли результат преобразования
    // числом.
    //
    // isNaN возвращает true для значения NaN.
    if (isNaN(num)) {

      // Если преобразование дало NaN, значит строка не
      // представляет валидное числовое значение.
      //
      // В этом случае рассматриваем "значение" элемента как
      // длину строки str.length.
      //
      // Math.max сравнивает текущий максимум и длину строки
      // и возвращает большее значение.
      maxVal = Math.max(maxVal, str.length);
    } else {

      // Если num - валидное число (не NaN), используем его
      // для сравнения с текущим максимумом.
      maxVal = Math.max(maxVal, num);
    }
  }

  // После перебора всех элементов возвращаем накопленный
  // максимум.
  return maxVal;
}
