/**
 * @param {number[]} widths
 * @param {string} s
 * @return {number[]}
 *
 * numberOfLines принимает строку s, состоящую из строчных английских букв,
 * и массив widths, где widths[0] - ширина буквы 'a' в пикселях,
 * widths[1] - ширина 'b' и так далее.
 *
 * Функция рассчитывает, на сколько строк потребуется записать строку s,
 * если каждая строка может занимать не более 100 пикселей, и возвращает
 * массив из двух чисел: первый элемент - общее количество использованных
 * строк, второй элемент - заполненная ширина последней строки в пикселях.
 *
 *
 * Пример для:
 *   widths = [10,10,10,10,10,10,10,10,10,10,10,10,10,10,10,10,10,10,10,10,
 *             10,10,10,10,10,10],
 *   s = "abcdefghijklmnopqrstuvwxyz"
 * Результат:
 *   [3, 60]
 * Пояснение:
 *   Можно записать s следующим образом:
 *   - abcdefghij   (ширина 100 пикселей)
 *   - klmnopqrst   (ширина 100 пикселей)
 *   - uvwxyz       (ширина 60 пикселей)
 *   Всего 3 строки, ширина последней строки - 60 пикселей.
 */
function numberOfLines(widths, s) {

  // Инициализация счётчика строк.
  //
  // Начинаем с 1, потому что даже пустая запись считается началом первой
  // строки.
  let lineCnt = 1;

  // Переменная для накопления текущей заполненной ширины в пикселях на
  // активной строке.
  //
  // Изначально 0, так как строка пуста.
  let currLineWidth = 0;

  // Проходим по каждому символу строки s
  for (const char of s) {

    // Получаем числовой код символа (UTF-16/Unicode code point для BMP) и
    // вычитаем код 'a' (97), чтобы получить индекс соответствующей буквы в
    // массиве widths: 'a' → 0, 'b' → 1, ..., 'z' → 25.
    const charWidth = widths[char.codePointAt(0) - 97];

    // Проверяем, поместится ли ширина текущего символа в оставшееся место
    // текущей строки, то есть не превысит ли суммарная ширина 100 пикселей
    // после добавления этого символа.
    if (currLineWidth + charWidth <= 100) {

      // Если текущий символ поместится, просто увеличиваем накопленную
      // ширину текущей строки на ширину символа.
      currLineWidth += charWidth;
    } else {

      // Если текущий символ не помещается в текущую строку, начинаем новую
      // строку:
      //
      // Увеличиваем счётчик строк, так как текущий символ будет записан на
      // следующей строке.
      lineCnt++;

      // Инициализируем ширину новой строки значением ширины текущего
      // символа, потому что этот символ первый в новой строке.
      currLineWidth = charWidth;
    }
  }

  // После обработки всех символов возвращаем массив из двух чисел:
  // - первый элемент - общее количество использованных строк,
  // - второй элемент - заполненная ширина последней строки в пикселях.
  return [lineCnt, currLineWidth];
}
