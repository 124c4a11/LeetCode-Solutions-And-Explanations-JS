/**
 * @param {string} word
 * @return {number}
 *
 * minimumPushes вычисляет минимальное суммарное количество нажатий клавиш,
 * необходимое для набора строки word при оптимальном переназначении букв
 * на клавиши 2-9 телефонной клавиатуры, при условии что все буквы в word
 * различны. Поскольку буквы различны (частота каждой буквы равна 1),
 * оптимальное распределение - заполнить по 8 букв на «уровень» нажатий:
 * первые 8 букв требуют по 1 нажатию, следующие 8 - по 2 нажатия и т.д.
 *
 *
 * Пример для:
 *   word = "xycdefghij"
 * Результат:
 *   12
 * Пояснение:
 * Переназначенная клавиатура, обеспечивает минимальную стоимость.
 * "x" → одно нажатие на клавишу 2
 * "y" → два нажатия на клавишу 2
 * "c" → одно нажатие на клавишу 3
 * "d" → два нажатия на клавишу 3
 * "e" → одно нажатие на клавишу 4
 * "f" → одно нажатие на клавишу 5
 * "g" → одно нажатие на клавишу 6
 * "h" → одно нажатие на клавишу 7
 * "i" → одно нажатие на клавишу 8
 * "j" → одно нажатие на клавишу 9
 * Общая стоимость: 1 + 2 + 1 + 2 + 1 + 1 + 1 + 1 + 1 + 1 = 12.
 * Можно показать, что никакое другое сопоставление не даст меньшей
 * стоимости.
 */
function minimumPushes(word) {

  // Поскольку все буквы в слове различны, нам не нужно учитывать частоту
  // - каждая буква встречается ровно один раз. Это значительно упрощает
  // задачу.
  //
  // Ключевая идея в том, что у нас есть 8 доступных клавиш (клавиши 2-9),
  // и мы хотим минимизировать общее число нажатий. Каждая клавиша может
  // содержать несколько букв, при этом:
  // - Первая буква на клавише требует 1 нажатия
  // - Вторая буква на клавише требует 2 нажатия
  // - Третья буква на клавише требует 3 нажатия
  // - И так далее...
  //
  // Чтобы минимизировать общее число нажатий, следует распределять буквы
  // как можно равномернее по всем 8 клавишам. Почему? Потому что иметь
  // буквы на более низких позициях (требующих меньше нажатий) на многих
  // клавишах выгоднее, чем нагружать мало клавиш большим числом букв.
  //
  // Представьте себе: если у нас 16 букв, мы могли бы:
  // - Поместить все 16 на одну клавишу: потребуется 1+2+3+...+16 = 136
  //   нажатий
  //
  // - Поместить по 2 буквы на каждую из 8 клавиш: потребуется
  //   8×1 + 8×2 = 24 нажатия
  //
  // Второй вариант явно лучше.
  //
  // Отсюда вытекает жадная стратегия:
  // - Первые 8 букв занимают позицию 1 на каждой клавише (по 1 нажатия на
  //   букву)
  //
  // - Следующие 8 букв занимают позицию 2 на каждой клавише (по 2 нажатия
  //   на букву)
  //
  // - И так далее...
  //
  // Вычисление становится простым:
  // - Посчитать, сколько полных "раундов" по 8 букв у нас есть: n // 8
  //
  // - Для каждого полного раунда k добавить k * 8 к общей сумме
  //
  // - Обработать оставшиеся буквы (n % 8), которые все требуют k нажатий,
  //   где k - следующая глубина позиции


  // Получаем длину входной строки и сохраняем в константу n.
  const n = word.length;

  // Вычисляем количество полных групп по 8 символов.
  //
  // Math.floor гарантирует целое число групп, отбрасывая неполную
  // последнюю группу.
  //
  // Пример:
  // n=17 → completeGroups = 2 (две полные группы по 8).
  const completeGroups = Math.floor(n / 8);

  // Инициализируем аккумулятор для суммарного числа нажатий.
  //
  // Начальное значение 0, далее будем накапливать вклад каждой группы и
  // остатка.
  let totalPushes = 0;

  // Инициализируем текущий "слой" или множитель для группы.
  //
  // Первая полная группа умножается на 1, следующая на 2 и т.д.
  let currentLayer = 1;

  // Проходим циклом по всем полным группам.
  //
  // Индекс groupNdx используется только для счёта итераций.
  for (let groupNdx = 0; groupNdx < completeGroups; groupNdx++) {

    // Для каждой полной группы добавляем в totalPushes вклад, равный
    // currentLayer умноженному на 8, потому что в полной группе ровно 8
    // символов, и каждый символ "стоил" currentLayer нажатий.
    totalPushes += currentLayer * 8;

    // Переходим к следующему слою (множителю) для следующей группы -
    // увеличиваем currentLayer на 1, чтобы следующая группа (если она есть)
    // учитывалась с большим множителем.
    currentLayer++;
  }

  // Вычисляем количество оставшихся символов, которые не попали в полные
  // группы по 8.
  //
  // Это остаток от деления n на 8; может быть от 0 до 7.
  const remainingLetters = n % 8;

  // Добавляем вклад оставшихся символов в totalPushes.
  //
  // Для этих символов используется текущее значение currentLayer (оно уже
  // увеличено после всех полных групп), поэтому неполная группа считается
  // с тем же множителем, что и следующая полная группа, если бы она
  // существовала.
  totalPushes += currentLayer * remainingLetters;

  // Возвращаем накопленное значение totalPushes - минимальное число
  // нажатий для всей строки.
  return totalPushes;
}
