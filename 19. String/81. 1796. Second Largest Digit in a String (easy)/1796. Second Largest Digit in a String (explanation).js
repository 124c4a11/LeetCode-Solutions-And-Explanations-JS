/**
 * @param {string} s
 * @return {number}
 *
 * secondHighest принимает строку s и возвращает вторую по величине
 * уникальную цифру (1–9), найденную в этой строке. Если во входной
 * строке меньше двух уникальных цифр, функция возвращает -1.
 *
 *
 * Пример для:
 *   s = "dfa12321afd"
 * Результат:
 *   2
 * Пояснение:
 *   В строке встречаются цифры [1, 2, 3]. Вторая по величине
 *   цифра - 2.
 *
 *
 * Пример для:
 *   s = "abc1111"
 * Результат:
 *   -1
 * Пояснение:
 *   В строке встречается только цифра [1]. Второй по величине
 *   цифры нет.
 */
function secondHighest(s) {

  // Объявляем переменную highestNum для хранения наибольшей
  // найденной цифры.
  //
  // Инициализируем значением -1, чтобы отличать "не найдено" от
  // любых допустимых цифр 0–9.
  let highestNum = -1;

  // Объявляем переменную secondHighestNum для хранения второй по
  // величине уникальной цифры.
  //
  // Инициализируем значением -1 по той же причине: -1 означает
  // "пока не найдено".
  let secondHighestNum = -1;

  // Проходим по каждому символу входной строки s
  for (const char of s) {

    // Преобразуем текущий символ в число с помощью Number.
    //
    // Для цифровых символов '0'..'9' это даст 0..9, для остальных
    // символов - NaN.
    const num = Number(char);

    // Если преобразование вернуло NaN (символ не является числом),
    // пропускаем дальнейшую обработку этого символа
    if (Number.isNaN(num)) continue;

    // Если текущая цифра больше текущего максимума, значит найден
    // новый максимум.
    //
    // В этом случае предыдущий максимум становится кандидатом на
    // второе место.
    if (num > highestNum) {

      // Сохраняем прежний максимум в secondHighestNum.
      //
      // Если до этого не было найдено ни одной цифры, highestNum
      // равен -1, и secondHighestNum станет -1.
      secondHighestNum = highestNum;

      // Обновляем highestNum новым, более высоким значением.
      highestNum = num;
    } else if (

      // Если текущая цифра не превысила highestNum, проверяем,
      // может ли она стать второй по величине.
      //
      // Сначала убеждаемся, что она больше текущего
      // secondHighestNum.
      num > secondHighestNum

      // Затем убеждаемся, что она не равна highestNum - это важно,
      // чтобы учитывать только уникальные значения
      && num != highestNum
    ) {

      // Если оба условия выполнены, обновляем secondHighestNum
      // текущим числом.
      //
      // Это гарантирует, что secondHighestNum всегда хранит
      // уникальную цифру, меньшую, чем highestNum.
      secondHighestNum = num;
    }
  }

  // После перебора всех символов возвращаем найденную вторую по
  // величине уникальную цифру.
  //
  // Если такая цифра отсутствует (например, в строке нет цифр,
  // или есть только одна уникальная цифра), вернётся -1.
  return secondHighestNum;
}
