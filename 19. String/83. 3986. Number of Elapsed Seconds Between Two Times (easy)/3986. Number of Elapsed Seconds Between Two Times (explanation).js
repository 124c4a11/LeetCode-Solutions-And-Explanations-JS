/**
 * @param {string} startTime
 * @param {string} endTime
 * @return {number}
 *
 * secondsBetweenTimes принимает два параметра: startTime и endTime,
 * оба - строки времени в формате HH:MM:SS и вычисляет разницу во времени
 * в секундах между этими двумя временными метками.
 *
 *
 * Пример для:
 *   startTime = "01:00:00",
 *   endTime = "01:00:25"
 * Результат:
 *   25
 * Пояснение:
 *   endTime на 25 секунд позже startTime.
 */
function secondsBetweenTimes(startTime, endTime) {

  // Вычисляет количество секунд для endTime и startTime с помощью
  // вспомогательной функции timeStringToSeconds и возвращает их разность
  return timeStringToSeconds(endTime) - timeStringToSeconds(startTime);
}

// Объявление вспомогательной функции timeStringToSeconds, которая
// преобразует строку времени в целое число секунд.
//
// Ожидаемый формат входной строки s: "HH:MM:SS" (двузначные часы,
// двузначные минуты, двузначные секунды).
function timeStringToSeconds(s) {

  // Преобразование часов:
  //
  // s.slice(0, 2) извлекает первые два символа строки (индексы 0 и 1),
  // Number(...) конвертирует их в числовой тип.
  //
  // Умножение на 3600 переводит часы в секунды.
  //
  // Если строка содержит ведущие нули (например, "07"), Number
  // корректно их обработает.
  return Number(s.slice(0, 2)) * 3600

    // Преобразование минут:
    //
    // s.slice(3, 5) извлекает символы на позициях 3 и 4,
    // соответствующие минутам в формате "HH:MM:SS".
    //
    // Number(...) конвертирует в число, умножение на 60 переводит
    // минуты в секунды.
    //
    // Здесь предполагается, что между часами и минутами стоит
    // разделитель ':' на позиции 2.
    + Number(s.slice(3, 5)) * 60

    // Преобразование секунд:
    //
    // s.slice(6, 8) извлекает символы на позициях 6 и 7,
    // соответствующие секундам. Number(...) конвертирует их в число и
    // добавляет к общей сумме.
    //
    // Предполагается, что строка имеет длину не менее 8 символов и
    // формат строго соблюдён.
    + Number(s.slice(6, 8));
}
