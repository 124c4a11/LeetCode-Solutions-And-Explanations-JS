/**
 * @param {string} title
 * @return {string}
 *
 * capitalizeTitle принимает строку title, состоящую из одного или
 * нескольких слов, разделенных одиночным пробелом, где каждое слово
 * состоит из английских букв и изменяет регистр строки следующим образом:
 * 1. Если длина слова составляет 1 или 2 буквы, переводит все буквы в
 *    нижний регистр.
 *
 * 2. В противном случае делает первую букву заглавной, а остальные -
 *    строчными.
 *
 * Возвращает измененную строку title.
 *
 *
 * Пример для:
 *   title = "i lOve leetcode"
 * Результат:
 *   "i Love Leetcode"
 * Пояснение:
 *   Слово "i" имеет длину 1, поэтому оно пишется строчными буквами.
 *
 *   Остальные слова имеют длину не менее 3 букв, поэтому первая буква
 *   каждого из них становится заглавной, а остальные - строчными.
 */
function capitalizeTitle(title) {

  // Вызывает метод split('') у строки title, создавая новый массив chars,
  // где каждый элемент - это один символ исходной строки.
  //
  // Это необходимо, так как строки в JavaScript неизменяемы (immutable), а
  // элементы массива можно менять по индексам.
  const chars = title.split('');

  // Создается константа n, в которую записывается общее количество
  // элементов (символов) в полученном массиве chars, чтобы использовать
  // это значение в качестве верхней границы для условий циклов.
  const n = chars.length;

  // Объявляет переменную l (left/левый указатель) и инициализирует её
  // нулем.
  //
  // Она будет хранить индекс начала (первой буквы) каждого очередного
  // слова в массиве.
  let l = 0;

  // Запускается внешний цикл while, который будет итерироваться по всей
  // строке.
  //
  // Условие l < n гарантирует, что цикл завершится только тогда, когда
  // левый указатель выйдет за пределы массива символов.
  while (l < n) {

    // Создает переменную r (right/правый указатель) и инициализирует её
    // текущим значением l.
    //
    // Эта переменная будет двигаться вперед, определяя, где заканчивается
    // текущее слово.
    let r = l;

    // Запускает внутренний цикл while для обработки букв внутри одного
    // слова.
    //
    // Цикл продолжается, пока выполняются оба условия, соединенные
    // логическим "И" (&&).
    while (

      // Проверяем, что правый указатель r находится в пределах массива и
      // не вышел за его конец (индекс строго меньше длины n).
      r < n

      // Проверяем, что символ под текущим индексом r не является пробелом,
      // то есть мы всё еще находимся внутри слова, а не на его границе.
      && chars[r] !== ' '
    ) {

      // Берет символ по индексу r, переводит его в нижний регистр с
      // помощью метода toLowerCase() и перезаписывает в ту же ячейку
      // массива chars[r].
      //
      // Это гарантирует, что все буквы в слове (включая первую) изначально
      // станут строчными.
      chars[r] = chars[r].toLowerCase();

      // Увеличивает значение правого указателя r на 1, чтобы на следующей
      // итерации внутреннего цикла проверить и обработать следующий символ.
      r++;
    }

    // Вычисляет длину найденного слова (разность между правым указателем,
    // который замер на пробеле или конце строки, и левым указателем).
    //
    // Если длина строго больше 2 символов, то символ по индексу l (первая
    // буква слова) переводится в верхний регистр с помощью toUpperCase() и
    // перезаписывается.
    //
    // Короткие слова из 1–2 букв остаются строчными
    if (r - l > 2) chars[l] = chars[l].toUpperCase();

    // Сдвигает левый указатель l на позицию r + 1.
    //
    // Поскольку r сейчас указывает на пробел (или равен n), r + 1
    // перепрыгивает этот пробел и устанавливает начало следующего
    // потенциального слова.
    l = r + 1;
  }

  // Вызываем метод join('') на массиве chars, который склеивает все
  // символы обратно в одну сплошную строку (без разделителей), и
  // возвращаем полученный результат.
  return chars.join('');
}
