/**
 * @param {string} s
 * @param {number} k
 * @param {character} fill
 * @return {string[]}
 *
 * divideString разбивает строку s на последовательные подстроки
 * длины k, дополняя последнюю подстроку справа символом(ами)
 * fill, если она короче k. В результате возвращается массив
 * таких групп.
 *
 *
 * Пример для:
 *   s = "abcdefghij",
 *   k = 3,
 *   fill = "x"
 * Результат:
 *   ["abc","def","ghi","jxx"]
 * Пояснение:
 *   Аналогично предыдущему примеру, формируем первые три группы
 *   "abc", "def" и "ghi".
 *
 *   Для последней группы из исходной строки доступен только
 *   символ 'j'. Чтобы довести эту группу до длины k, добавляем
 *   'x' дважды.
 *
 *   Таким образом, получаем 4 группы: "abc", "def", "ghi" и
 *   "jxx".
 */
function divideString(s, k, fill) {

  // Инициализация пустого массива groups, в который будут
  // поочерёдно добавляться подстроки длины k
  const groups = [];

  // Запускаем цикл for для итерации по строке s блоками по k
  // символов
  for (let i = 0; i < s.length; i += k) {

    // Получаем подстроку от текущего индекса i до i + k
    // (конечный индекс не включается).
    //
    // 1. s.slice(i, i + k) возвращает новую строку, содержащую
    //    символы s с индекса i по индекс i + k - 1. slice не
    //    изменяет исходную строку s.
    //
    // 2. Если оставшихся символов меньше k, slice вернёт более
    //    короткую строку.
    //
    // 3. padEnd(k, fill) дополняет полученную подстроку справа
    //    символами из fill до общей длины k:
    //    - если длина подстроки меньше k, padEnd дополняет её
    //      справа повторениями строки fill до длины k;
    //
    //    - если fill содержит более одного символа, padEnd
    //      будет добавлять повторяющиеся фрагменты fill и при
    //      необходимости усекать последний фрагмент, чтобы
    //      итоговая длина была ровно k;
    //
    //    - если подстрока уже длины k, padEnd возвращает её без
    //      изменений.
    //
    // Результат сохраняется в константу group.
    const group = s.slice(i, i + k).padEnd(k, fill);

    // Добавление сформированной группы в конец массива groups.
    groups.push(group);
  }

  // После завершения цикла возвращаем массив groups.
  return groups;
}
