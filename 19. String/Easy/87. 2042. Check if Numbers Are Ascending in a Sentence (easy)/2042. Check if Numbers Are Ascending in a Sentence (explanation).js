/**
 * @param {string} s
 * @return {boolean}
 *
 * areNumbersAscending принимает строку s и проверяет, идут ли все числа,
 * встречающиеся в этой строке, в строго возрастающем порядке (каждое
 * следующее число больше предыдущего).
 *
 *
 * Пример для:
 *   Вход: s = "1 box has 3 blue 4 red 6 green and 12 yellow marbles"
 * Результат:
 *   true
 * Пояснение:
 *   В строке s числа: 1, 3, 4, 6, 12.
 *   Они строго возрастают слева направо: 1 < 3 < 4 < 6 < 12.
 *
 *
 * Пример для:
 *   s = "hello world 5 x 5"
 * Результат:
 *   false
 * Пояснение:
 *   В строке s числа: 5, 5.
 *   Они не являются строго возрастающими.
 */
function areNumbersAscending(s) {

  // Разбиваем входную строку по символу пробела и получаем массив
  // токенов.
  //
  // Токены могут быть словами, числами, знаками препинания или их
  // комбинациями.
  const tokens = s.split(' ');

  // Инициализируем переменную prevNum для хранения последнего
  // обнаруженного числового значения.
  //
  // Значение -1 выбрано как безопасный нижний предел для неотрицательных
  // чисел.
  let prevNum = -1;

  // Проходим по каждому токену из массива tokens в порядке их появления
  // в исходной строке.
  for (const token of tokens) {

    // Пытаемся явно преобразовать текущий токен в число с помощью
    // конструктора Number.
    //
    // Number возвращает числовое значение для корректных цифровых строк
    // и NaN для некорректных.
    const num = Number(token);

    // Проверяем, получилось ли при преобразовании валидное число.
    //
    // Number.isNaN надежно определяет NaN и не приводит к ложным
    // срабатываниям для других значений.
    //
    // Если токен не является числом, пропускаем его и продолжаем цикл.
    if (Number.isNaN(num)) continue;

    // Сравниваем текущее найденное число с предыдущим числом.
    //
    // Условие prevNum >= num фиксирует нарушение строгого возрастания в
    // двух случаях:
    // 1. текущее число меньше предыдущего;
    // 2. текущее число равно предыдущему.
    //
    // В обоих случаях последовательность не является строго возрастающей,
    // поэтому функция возвращает false.
    if (prevNum >= num) return false;

    // Обновляем prevNum текущим числом для последующих сравнений.
    //
    // Это гарантирует, что следующая найденная числовая строка будет
    // сравниваться с этим значением.
    prevNum = num;
  }

  // Если цикл завершился без раннего выхода, значит все найденные числа
  // шли в строгом порядке возрастания.
  //
  // Возвращаем true как подтверждение корректности последовательности.
  return true;
}
