/**
 * @param {string} s
 * @return {string}
 *
 * largestEven принимает строку s, состоящую только из символов '1' и '2'.
 *
 * Функция находит максимально возможное чётное число, которое можно
 * получить из исходной строки путём удаления лишних символов (без
 * изменения порядка оставшихся цифр)
 *
 *
 * Пример для:
 *   s = "1112"
 * Результат:
 *   "1112"
 * Пояснение:
 *   Строка уже представляет собой максимально возможное четное число,
 *   поэтому удаления не требуются.
 *
 *
 * Пример для:
 *   s = "221"
 * Результат:
 *   "22"
 * Пояснение:
 *   Удаление '1' приводит к максимально возможному четному числу, которое
 *   равно 22.
 */
function largestEven(s) {

  // Запускаем цикл for для обратного обхода строки.
  //
  // Начинает обход с последнего символа строки (индекс s.length - 1)
  // и двигается справа налево (уменьшая индекс i на 1 каждую итерацию) до
  // тех пор, пока не дойдет до начала строки (i равно 0)
  //
  // Это необходимо, так как для максимизации числа нам выгодно сохранить
  // как можно больше цифр слева, отбросив единицы с самого конца строки.
  for (let i = s.length - 1; i >= 0; i--) {

    // Проверяем строгое равенство текущего символа строке '2' (поскольку
    // число четное, оно обязательно должно заканчиваться на '2')
    //
    // Движение с конца гарантирует, что мы найдем именно последнюю двойку,
    // сохранив максимальную длину и величину числа.
    //
    // Если текущий символ равен '2', значит мы нашли самую правую
    // (последнюю) четную цифру, которая обеспечит максимальную длину и
    // четность всего числа - извлекаем подстроку от начала (индекс 0) до
    // текущей двойки включительно (индекс i).
    //
    // Метод slice не включает верхнюю границу, поэтому мы передаем i + 1.
    //
    // Это автоматически удаляет все единицы, стоящие после этой двойки, и
    // возвращает максимально возможное четное число.
    if (s[i] === '2') return s.slice(0, i + 1);
  }

  // Данная строка кода выполнится только в том случае, если цикл for
  // полностью завершился и условие внутри него ни разу не выполнилось.
  //
  // Это означает, что в строке s вообще нет символов '2' (она состоит
  // только из единиц), следовательно, сформировать четное число невозможно,
  // и функция возвращает пустую строку согласно условию задачи.
  return '';
}
