/**
 * @param {string[]} words
 * @param {character} separator
 * @return {string[]}
 *
 * splitWordsBySeparator принимает два параметра - words и separator,
 * и возвращает массив непустых строк, полученных путем разбиения
 * элементов words по separator и объединения полученных строк в
 * итоговый массив.
 *
 *
 * Пример для:
 *   words = ["one.two.three","four.five","six"],
 *   separator = "."
 * Результат:
 *   ["one","two","three","four","five","six"]
 * Пояснение:
 *   В этом примере мы разбиваем следующим образом:
 *     "one.two.three" разбивается на "one", "two", "three"
 *     "four.five" разбивается на "four", "five"
 *     "six" разбивается на "six"
 *
 *   Следовательно, результирующий массив:
 *     ["one","two","three","four","five","six"]
 *
 *
 * Пример для:
 *   words = ["$easy$","$problem$"],
 *   separator = "$"
 * Результат:
 *   ["easy","problem"]
 * Пояснение:
 *   В этом примере мы разбиваем следующим образом:
 *     "$easy$" разбивается на "easy" (исключая пустые строки)
 *     "$problem$" разбивается на "problem" (исключая пустые строки)
 *
 *   Следовательно, результирующий массив: ["easy","problem"]
 */
function splitWordsBySeparator(words, separator) {

  // Возвращаем результат цепочки операций, применённых к входному
  // массиву words.
  return words

    // Преобразуем массив строк в одну строку, вставляя между
    // элементами указанный разделитель.
    //
    // Если words = ['a', 'b', 'c'] и separator = '-', результат
    // будет 'a-b-c'.
    //
    // Если words содержит пустые строки, они тоже будут включены
    // между разделителями.
    //
    // Если words пустой массив, join вернёт пустую строку ''.
    .join(separator)

    // Разбиваем полученную строку обратно на массив по тому же
    // разделителю.
    //
    // Это действие вернёт массив подстрок, полученных между
    // вхождениями separator.
    //
    // Пример:
    // 'a--b' при split('-') даст ['a', '', 'b'] - пустая строка
    // возникает из-за двух подряд разделителей.
    .split(separator)

    // Убираем из полученного массива все "ложные" значения,
    // приводимые к false при Boolean().
    //
    // filter(Boolean) удаляет пустые строки '', а также null и
    // undefined, если они вдруг появились.
    //
    // В результате остаются только непустые строки. Порядок
    // элементов сохраняется.
    //
    // Это полезно, чтобы избавиться от пустых элементов, появившихся
    // из-за соседних разделителей или из-за пустых строк в исходном
    // массиве.
    .filter(Boolean);
}
