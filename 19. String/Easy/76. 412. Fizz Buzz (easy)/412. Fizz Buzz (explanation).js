/**
 * @param {number} n
 * @return {string[]}
 *
 * fizzBuzz генерирует массив строк длины примерно n, где
 * для каждого числа от 1 до n включительно выполняются
 * следующие условия:
 * - если число делится на 3 и на 5 - в массив записывается
 *   "FizzBuzz";
 *
 * - если делится только на 3 - "Fizz";
 *
 * - если делится только на 5 - "Buzz";
 *
 * - иначе - строковое представление самого числа
 *   (например, "7").
 *
 *
 * Пример для:
 *   n = 5
 * Результат:
 *   ["1","2","Fizz","4","Buzz"]
 */
function fizzBuzz(n) {

  // Создаём массив фиксированной длины n заранее, чтобы
  // избежать динамического расширения при push.
  //
  // Это экономит время при большом n, так как выделяется
  // память под все элементы сразу.
  const result = new Array(n);

  // Цикл for используется для последовательной генерации
  // значений от 1 до n.
  //
  // Индекс i начинается с 0, что удобно для записи в
  // result[i].
  for (let i = 0; i < n; i++) {

    // Вычисляем значение числа в последовательности FizzBuzz.
    //
    // i - индекс (0-based), поэтому добавляем 1, чтобы
    // получить 1-based значение
    const num = i + 1;

    // Проверяем делимость без остатка на 3 и на 5
    // одновременно.
    //
    // Используем оператор остатка %. Выражение num % 3 === 0
    // истинно, когда num делится на 3 без остатка.
    //
    // Логический оператор && гарантирует, что оба условия
    // должны быть истинными.
    //
    // Размещение проверки "FizzBuzz" первым важно, иначе
    // числа, делящиеся на 15, попали бы под более ранние
    // ветви для 3 или 5.
    if (
      num % 3 === 0
      && num % 5 === 0
    ) result[i] = 'FizzBuzz';

    // Если число делится без остатка только на 3
    // (и не на 5), записываем 'Fizz' в соответствующую
    // позицию массива.
    //
    // Эта ветка выполняется только если предыдущая
    // (делимость на 3 и 5) была ложной.
    else if (num % 3 === 0) result[i] = 'Fizz';

    // Если число делится без остатка только на 5
    // (и не на 3), записываем 'Buzz' в соответствующую
    // позицию массива.
    else if (num % 5 === 0) result[i] = 'Buzz';

    // Если ни одно из условий делимости не выполнено,
    // записываем строковое представление числа в
    // соответствующую позицию массива.
    //
    // Используется шаблонная строка `${num}`, которая
    // гарантирует, что в массив попадёт строка, а не число.
    else result[i] = `${num}`;
  }

  // Возвращаем заполненный массив result
  return result;
}
