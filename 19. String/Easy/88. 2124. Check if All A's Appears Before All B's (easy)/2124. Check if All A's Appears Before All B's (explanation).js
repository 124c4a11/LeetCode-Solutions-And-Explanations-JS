/**
 * @param {string} s
 * @return {boolean}
 *
 * checkString принимает строку s, состоящую только из символов 'a' и 'b'.
 *
 * Возвращает true, если каждая 'a' встречается до каждой 'b' в строке.
 * Иначе вернуть false.
 *
 *
 * Пример для:
 *   s = "aaabbb"
 * Результат:
 *   true
 * Пояснение:
 *   Символы 'a' находятся на индексах 0, 1 и 2, а символы 'b' - на
 *   индексах 3, 4 и 5.
 *
 *   Следовательно, каждая 'a' встречается до каждой 'b' в строке,
 *   поэтому возвращаем true.
 *
 *
 * Пример для:
 *   s = "abab"
 * Результат:
 *   false
 * Пояснение:
 *   Есть 'a' на индексе 2 и 'b' на индексе 1.
 *
 *   Следовательно, не каждая 'a' встречается до каждой 'b', поэтому
 *   возвращаем false.
 *
 *
 * Пример для:
 *   s = "bbb"
 * Результат:
 *   true
 * Пояснение:
 *   'a' в строке нет, поэтому условие выполняется и возвращаем true.
*/
function checkString(s) {

  // Используем метод includes для поиска подстроки 'ba', то есть случая,
  // когда 'b' встречается перед 'a'.
  //
  // Если 'ba' найдено, это означает, что существует хотя бы один 'b',
  // расположенный перед некоторой 'a', следовательно условие "все 'a'
  // перед всеми 'b'" нарушено.
  //
  // s.includes('ba') возвращает true при наличии такой подстроки.
  //
  // Оператор ! инвертирует результат, поэтому функция возвращает true
  // только когда подстрока 'ba' отсутствует (все 'a' действительно идут
  // перед 'b').
  return !s.includes('ba');
}
