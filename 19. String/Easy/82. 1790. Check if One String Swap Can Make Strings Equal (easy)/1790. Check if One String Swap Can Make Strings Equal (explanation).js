/**
 * @param {string} s1
 * @param {string} s2
 * @return {boolean}
 *
 * areAlmostEqual принимает две строки s1 и s2 и проверяет, можно ли
 * сделать эти строки одинаковыми, выполнив не более одной
 * перестановки двух символов в одной из строк
 *
 *
 * Пример для:
 *   s1 = "bank",
 *   s2 = "kanb"
 * Результат:
 *   true
 * Пояснение:
 *   Например, поменяв местами первый и последний символы в s2,
 *   получим "bank".
 */
function areAlmostEqual(s1, s2) {

  // Когда мы думаем о том, чтобы сделать две строки равными с
  // помощью не более одной операции обмена символов в ровно одной
  // строке, нам нужно понять, какие шаблоны различий между строками
  // позволяют это сделать.
  //
  // Сначала рассмотрим возможные сценарии:
  // - Если строки уже идентичны, требуется 0 обменов, что
  //   удовлетворяет условию "не более одного обмена".
  //
  // - Если строки различаются ровно в двух позициях, возможно, их
  //   можно исправить одним обменом.
  //
  // - Если строки различаются в одной позиции или более чем в двух
  //   позициях, сделать их равными одним обменом невозможно.
  //
  // Ключевая мысль: при выполнении операции обмена мы меняем ровно
  // 2 символа в одной строке (или 0, если обмен позиции саму с
  // собой). Это означает, что один обмен может исправить различия
  // только в ровно двух позициях.
  //
  // Чтобы строки стали равными после одного обмена, несовпадающие
  // символы должны быть "взаимно дополняющимися". Если в позиции i
  // у нас s1[i] = 'a' и s2[i] = 'b', а в позиции j у нас
  // s1[j] = 'b' и s2[j] = 'a', то обмен позиций i и j в любой из
  // строк сделает их равными.
  //
  // Отсюда следует, что нужно отслеживать:
  // - сколько позиций имеют разные символы (cnt),
  //
  // - какие символы были в первой найденной несовпадающей паре
  //   (c1 и c2).
  //
  // - При встрече второй несовпадающей пары проверяем, являются ли
  //   её символы «обратными» по отношению к первой.
  //
  // Элегантность подхода в том, что не нужно хранить все
  // несовпадения - важно только, 0 это, 2 или какое‑то другое число.
  // Если ровно 2 несовпадения и они комплементарны (их можно
  // исправить одним обменом), возвращаем true.


  // Инициализация счётчика несовпадающих позиций между s1 и s2.
  //
  // Будем увеличивать при каждом обнаружении индекса i, где
  // s1[i] !== s2[i].
  let mismatchCnt = 0;

  // Переменная для сохранения символа из s1 на первой найденной
  // несовпадающей позиции.
  //
  // Используется позже для проверки, что вторая несовпадающая
  // позиция "взаимно" соответствует первой.
  let firstMismatchChar1 = '';

  // Переменная для сохранения символа из s2 на первой найденной
  // несовпадающей позиции.
  //
  // Нужна для сравнения с символом из s1 на второй несовпадающей
  // позиции.
  let firstMismatchChar2 = ''

  // Проход по всем индексам строк s1 и s2 одновременно.
  //
  // s1.length === s2.length.
  for (let i = 0; i < s1.length; i++) {

    // Получаем символ из s1 на текущей позиции i.
    const char1 = s1[i];

    // Получаем символ из s2 на текущей позиции i.
    const char2 = s2[i];

    // Если символы на текущей позиции различаются, обрабатываем это
    // как потенциальную позицию, которую нужно исправить одной
    // перестановкой.
    if (char1 !== char2) {

      // Увеличиваем счётчик несовпадений.
      mismatchCnt++;

      // Если обнаружено более двух несовпадений, то одной
      // перестановкой двух символов невозможно сделать строки
      // равными - можно немедленно вернуть false.
      if (mismatchCnt > 2) return false;

      // Если это вторая несовпадающая позиция, нужно проверить, что
      // обмен символов между этими двумя позициями действительно
      // сделает строки равными.
      if (mismatchCnt === 2) {

        // Текущий символ из s1 должен совпадать с символом из s2,
        // который был на первой несовпадающей позиции
        // (firstMismatchChar2), и текущий символ из s2 должен
        // совпадать с символом из s1, который был на первой
        // несовпадающей позиции (firstMismatchChar1).
        //
        // Если это не так, то даже обмен двух символов не поможет -
        // возвращаем false.
        if (
          char1 !== firstMismatchChar2
          || char2 !== firstMismatchChar1
        ) return false;
      }

      // Если это первая найденная несовпадающая позиция, сохраняем
      // соответствующие символы для последующей проверки при
      // обнаружении второй несовпадающей позиции.
      if (mismatchCnt === 1) {
        firstMismatchChar1 = char1;
        firstMismatchChar2 = char2;
      }
    }
  }

  // После прохода по всем позициям:
  // - Если mismatchCnt === 0, строки уже равны - возвращаем true
  //   (перестановка не требуется).
  //
  // - Если mismatchCnt === 2 и предыдущие проверки не вернули
  //   false, значит существует  пара позиций, обмен которых сделает
  //   строки равными - возвращаем true.
  //
  // - Если mismatchCnt === 1, ровно одна позиция отличается - одной
  //   перестановкой двух символов исправить это нельзя (нужна
  //   замена одного символа), поэтому возвращаем false.
  return mismatchCnt !== 1;
}
