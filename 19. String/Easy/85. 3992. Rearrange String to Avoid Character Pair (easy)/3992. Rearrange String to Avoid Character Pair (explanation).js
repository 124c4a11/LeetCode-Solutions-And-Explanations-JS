/**
 * @param {string} s
 * @param {character} x
 * @param {character} y
 * @return {string}
 *
 * rearrangeString принимает строку s и два символа x, y.
 *
 * Возвращает новую строку, в которой все вхождения символа y
 * перемещены в начало строки в том порядке, в котором они
 * встречались в исходной строке
 */
function rearrangeString(s, x, y) {

  // Преобразуем строку s в массив символов методом split(''),
  // чтобы иметь возможность изменять отдельные символы по
  // индексам
  const t = s.split('');

  // Инициализируем указатель i равным 0.
  //
  // Этот указатель указывает на следующую позицию в массиве t,
  // куда будет помещён следующий найденный символ y.
  let i = 0;

  // Запускаем цикл for с индексом j, который пробегает все
  // индексы исходной строки от 0 до s.length - 1.
  //
  // j используется для поиска символов, равных y, в исходном
  // порядке слева направо.
  for (let j = 0; j < s.length; j++) {

    // Если символ в текущей позиции j не равен целевому
    // символу y, то пропускаем тело цикла и переходим к
    // следующему j.
    if (t[j] !== y) continue;

    // Сохраняем текущее значение в позиции i во временную
    // переменную tmp перед обменом.
    //
    // Это нужно, потому что мы собираемся перезаписать t[i]
    // значением t[j], и нужно сохранить старое значение для
    // записи в t[j].
    const tmp = t[i];

    // Копируем найденный символ y из позиции j в позицию i.
    t[i] = t[j];

    // Возвращаем ранее сохранённое значение tmp в позицию j,
    // завершая обмен местами двух элементов.
    //
    // В результате элемент, который был в позиции i,
    // перемещается в позицию j.
    t[j] = tmp;

    // Увеличиваем указатель i на единицу, чтобы следующая
    // найденная буква y была помещена в следующую позицию.
    //
    // Таким образом все найденные y будут сгруппированы в
    // начале массива в том же порядке, в котором они
    // встречались.
    i++;
  }

  // После завершения цикла массив t содержит те же символы,
  // что и исходная строка, но все символы, равные y,
  // перемещены в первые i позиций в порядке их исходного
  // появления.
  //
  // Собираем массив обратно в строку с помощью join('') и
  // возвращаем результат.
  return t.join('');
}
