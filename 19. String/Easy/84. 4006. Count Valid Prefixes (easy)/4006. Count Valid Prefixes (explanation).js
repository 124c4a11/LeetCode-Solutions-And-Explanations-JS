/**
 * @param {string} s
 * @return {number}
 *
 * countValidPrefixes принимает бинарную строку s, состоящую только
 * из символов '0' и '1'. Подсчитывает и возвращает количество
 * префиксов входной бинарной строки, для которых выполняется
 * следующее условие: символы префикса можно переставить так, чтобы
 * получилась чередующаяся строка (то есть никакие два соседних
 * символа не равны).
 *
 *
 * Пример для:
 *   s = "00101"
 * Результат:
 *   3
 * Пояснение:
 *   Допустимые префиксы:
 *   "0": уже является чередующейся строкой.
 *   "001": можно переставить в "010", что даёт чередующуюся строку.
 *   "00101": можно переставить в "01010", что даёт чередующуюся строку.
 */
function countValidPrefixes(s) {

  // Любая идеальная чередующаяся строка (например, 010101 или 101)
  // обладает уникальным свойством: количество нулей и единиц в ней либо
  // абсолютно одинаково, либо отличается ровно на один символ.
  // - Если в наборе символов нулей будет, например, на 2 больше, чем
  //   единиц (скажем, три нуля и одна единица: 0, 0, 0, 1), то как их
  //   ни переставляй, два нуля обязательно встанут рядом (0100).
  //   Чередования не получится.
  //
  // - Значит, префикс можно перестроить в чередующуюся строку тогда и
  //   только тогда, когда: |Количество 1 - Количество 0| <= 1


  // Инициализация счётчика допустимых префиксов.
  //
  // Будет увеличиваться на 1 каждый раз, когда текущий префикс можно
  // переставить в чередующуюся строку.
  let validPrefixesCnt = 0;

  // Инициализация переменной balance
  //
  // Переменная balance хранит разность:
  // (количество '1' в текущем префиксе) − (количество '0' в текущем
  // префиксе).
  //
  // Инвариант:
  // После обработки i символов balance = ones_i - zeros_i.
  //
  // Если |balance| ≤ 1, то числа символов отличаются не более чем на 1,
  // и их можно распределить в чередующуюся последовательность.
  let balance = 0;

  // Итерация по каждому символу строки s в порядке слева направо.
  for (const char of s) {

    // Обновление balance в зависимости от текущего символа.
    //
    // Если char === '1', увеличиваем balance на 1;
    // Если char === '0', уменьшаем на 1.
    balance += char === '1' ? 1 : -1;

    // Проверка условия допустимости префикса:
    //
    // Абсолютная разность количеств символов не должна превышать 1.
    //
    // Обоснование:
    // Чтобы можно было переставить символы в чередующуюся строку, числа
    // '0' и '1' в префиксе должны отличаться не более чем на 1 (иначе
    // один тип символов будет вынужден стоять рядом с таким же).
    if (Math.abs(balance) <= 1) {

      // Если условие выполнено, увеличиваем счётчик допустимых префиксов.
      validPrefixesCnt++;
    }
  }

  // Возвращаем итоговый счётчик - количество префиксов, которые можно
  // переставить в чередующуюся строку.
  return validPrefixesCnt;
}
