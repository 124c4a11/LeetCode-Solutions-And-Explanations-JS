/**
 * @param {string} word
 * @return {number}
 *
 * Алиса пытается набрать на компьютере определенную строку. Однако она
 * бывает неуклюжей и может слишком долго удерживать клавишу нажатой, из-за
 * чего один символ печатается несколько раз подряд.
 *
 * Хотя Алиса старалась сосредоточиться на наборе текста, она понимает, что
 * всё же могла допустить такую ошибку максимум один раз.
 *
 * possibleStringCount принимет строку word, которая представляет собой
 * окончательный результат, отображаемый на экране Алисы.
 *
 * Возвращает общее количество возможных исходных строк, которые Алиса
 * изначально собиралась напечатать.
 *
 *
 * Пример для:
 *   word = "abbcccc"
 * Результат:
 *   5
 * Пояснение:
 *   Возможными исходными строками являются: "abbcccc", "abbccc", "abbcc",
 *   "abbc" и "abcccc".
 */
function possibleStringCount(word) {

  // Давайте разберёмся, что происходит, когда Алиса допускает ошибку при
  // наборе текста. Если она слишком долго удерживает клавишу, в результате
  // появляются несколько одинаковых символов подряд. Важно понимать, что
  // мы можем исправить только одну такую ошибку.
  //
  // Рассмотрим строку "aabbcc". Где могла произойти единственная ошибка
  // Алисы?
  // - Если она слишком долго удерживала клавишу 'a', исходная строка была
  //   "abbcc".
  //
  // - Если она слишком долго удерживала клавишу 'b', исходная строка была
  //   "aabcc".
  //
  // - Если она слишком долго удерживала клавишу 'c', исходная строка была
  //   "aabbc".
  //
  // - Если ошибки не было, исходная строка осталась "aabbcc".
  //
  // Обратите внимание: каждая пара одинаковых символов, стоящих рядом,
  // указывает на возможное место ошибки. Мы можем удалить один
  // повторяющийся символ из любой такой пары или вообще ничего не менять.
  //
  // Ключевая идея заключается в том, что каждая пара соседних одинаковых
  // символов добавляет ровно одну дополнительную возможность. Почему?
  // Потому что для каждой такой пары мы можем выбрать, была ли именно
  // здесь допущена единственная ошибка Алисы.
  //
  // Рассмотрим возможные случаи:
  // - 0 пар одинаковых соседних символов → 1 вариант(ошибки не было).
  //
  // - 1 пара одинаковых соседних символов → 2 варианта(ошибка в этой паре
  //   или ошибки не было).
  //
  // - 2 пары одинаковых соседних символов → 3 варианта(ошибка в первой
  //   паре, во второй паре или ошибки не было).
  //
  // - k пар одинаковых соседних символов → k + 1 вариант.
  //
  // Таким образом, решение сводится к следующему: нужно посчитать
  // количество пар одинаковых соседних символов и прибавить 1.
  //
  // Формула:
  // количество пар одинаковых соседних символов + 1 (ошибки не было).


  // Создаем переменную-счетчик adjacentPairsCnt для подсчета соседних
  // одинаковых символов.
  //
  // Каждая такая пара представляет собой потенциальное место, где Алиса
  // могла случайно зажать клавишу.
  let adjacentPairsCnt = 0;

  // Запускаем цикл для перебора строки.
  //
  // Начинаем с индекса 1 (второй символ), чтобы у каждого текущего символа
  // гарантированно был предыдущий сосед для сравнения.
  for (let i = 1; i < word.length; i++) {

    // Сравниваем символ на позиции i - 1 (предыдущий) с символом на
    // позиции i (текущий).
    //
    // Если они строго равны, значит, зафиксирован повтор знака.
    if (word[i - 1] === word[i]) adjacentPairsCnt++;
  }


  // Возвращаем возвращаем общее количество возможных исходных строк,
  // которые Алиса изначально собиралась напечатать.
  //
  // Мы прибавляем 1 к числу найденных пар, потому что к каждому варианту
  // "удаления" одного лишнего символа добавляется еще 1 исходный сценарий,
  // в котором Алиса вообще не допустила ни одной ошибки.
  return adjacentPairsCnt + 1;
}
