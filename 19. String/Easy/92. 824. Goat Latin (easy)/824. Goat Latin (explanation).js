/**
 * @param {string} sentence
 * @return {string}
 *
 * toGoatLatin принимает строку sentence, состоящую из слов, разделенных
 * пробелами. Каждое слово состоит только из строчных и прописных букв.
 *
 * Функция преобразовывает это предложение в "Козлиную латынь" (Goat Latin)
 * — вымышленный язык, похожий на поросячью латынь (Pig Latin).
 *
 * Правила Козлиной латыни следующие:
 * 1. Если слово начинается с гласной буквы ('a', 'e', 'i', 'o' или 'u' в
 *    любом регистре), добавляет "ma" в конец слова.
 *    Например, слово "apple" становится "applema".
 *
 * 2. Если слово начинается с согласной буквы (т. е. не с гласной), удаляет
 *    первую букву и перемещает её в конец, а затем добавляет "ma".
 *    Например, слово "goat" становится "oatgma".
 *
 * 3. Добавляет букву 'a' в конец каждого слова в количестве, равном его
 *    порядковому номеру в предложении (индексация начинается с 1).
 *    Например, к первому слову в конце добавляется "a", ко второму слову —
 *    "aa" и так далее.
 *
 * Возвращает итоговое предложение, полученное в результате преобразования
 * строки sentence в Козлиную латынь.
 *
 *
 * Пример для:
 *   sentence = "I speak Goat Latin"
 * Результат:
 *   "Imaa peaksmaaa oatGmaaaa atinLmaaaaa"
 *
 *
 * Пример для:
 *   sentence = "The quick brown fox jumped over the lazy dog"
 * Результат:
 *   "heTmaa uickqmaaa rownbmaaaa oxfmaaaaa umpedjmaaaaaa overmaaaaaaa
 *   hetmaaaaaaaa azylmaaaaaaaaa ogdmaaaaaaaaaa"
 */
function toGoatLatin(sentence) {

  // Разбиваем исходный текст по символу пробела и преобразует его в
  // индексированный массив строк (отдельных слов).
  const words = sentence.split(' ');

  // Обращение к свойству length созданного массива words, чтобы
  // зафиксировать общее количество слов в предложении и использовать это
  // число для оптимизации памяти и управления циклом.
  const n = words.length;

  // Создаем объект регулярного выражения (RegExp).
  //
  // Квадратные скобки [aeiou] задают набор искомых символов (гласных), а
  // флаг 'i' (ignore case) указывает, что поиск должен производиться без
  // учета регистра (как для строчных, так и для прописных букв).
  const vowelsRegExp = /[aeiou]/i;

  // Конструируем новый пустой массив с заранее заданной длиной 'n' с
  // помощью конструктора new Array(n).
  //
  // Это позволяет оптимизировать выделение памяти под итоговый набор
  // трансформированных слов.
  const goatLatinWords = new Array(n);

  // Перебираем все слова в массиве words в порядке их следования.
  for (let i = 0; i < n; i++) {

    // Извлекаем текущее слово из массива 'words' по текущему индексу 'i' и
    // присваиваем его локальной переменной 'word' для удобства дальнейшей
    // работы.
    const word = words[i];

    // Берем самый первый символ слова с помощью обращения по индексу
    // word[0] и передаем его в метод .test() регулярного выражения,
    // который возвращает true, если символ является гласной буквой,
    // и false, если согласной.
    const isStartsWithVowel = vowelsRegExp.test(word[0]);

    // Объявляем локальную переменную 'transformedWord' через 'let', так
    // как её значение будет определяться динамически в зависимости от
    // результата проверки на гласную букву.
    //
    // В ней будет сохранен результат первого этапа модификации буквенного
    // состава слова.
    let transformedWord;

    if (isStartsWithVowel) {

      // Если слово начинается с гласно, то согласно правилу 1 Козлиной
      // латыни, его основа никак не изменяется. Поэтому мы просто копируем
      // исходное слово в 'transformedWord'.
      transformedWord = word;
    } else {

      // Если логический флаг 'startsWithVowel' равен false (то есть слово
      // начинается с согласной буквы), то согласно второму правилу,
      // применяем метод .slice(1) для отсечения подстроки со второго
      // символа до конца слова и конкатенируем (склеиваем) её с помощью
      // оператора + с самой первой буквой word[0], перемещая её в конец.
      transformedWord = word.slice(1) + word[0];
    }

    // Реализуем правило 3:
    //
    // Используем встроенный метод строк .repeat(), передавая туда аргумент
    // (i + 1), чтобы сгенерировать строку из букв 'a', длина которой в
    // точности соответствует порядковому номеру слова (для 1-го слова
    // индекс 0 + 1 = одна 'a', для 2-го — две 'aa' и т.д.).
    const aSuffix = 'a'.repeat(i + 1);

    // Формируем финальное слово:
    //
    // Соединяем преобразованную основу 'transformedWord', обязательный
    // суффикс языка "ma" и динамический суффикс из букв 'a' ('aSuffix').
    const finalWord = `${transformedWord}ma${aSuffix}`;

    // Сохраняем полностью сформированное слово на Козлиной латыни в
    // массив 'goatLatinWords' строго под тем же индексом 'i', под которым
    // исходное слово находилось в начальном предложении.
    goatLatinWords[i] = finalWord;
  }

  // Вызываем метод .join(' ') у массива 'goatLatinWords', который берет
  // все трансформированные слова и объединяет их в единую строку, вставляя
  // между ними один пробел, после чего возвращаем эту строку из функции.
  return goatLatinWords.join(' ');
}
