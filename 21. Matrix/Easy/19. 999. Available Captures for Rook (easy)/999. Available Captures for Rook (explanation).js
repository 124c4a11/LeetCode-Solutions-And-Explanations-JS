/**
 * @param {character[][]} board
 * @return {number}
 *
 * numRookCaptures принимает матрицу размером 8 x 8, представляющая
 * шахматную доску. На доске находится ровно одна белая ладья, обозначенная
 * символом 'R', некоторое количество белых слонов, обозначенных символом
 * 'B', и некоторое количество чёрных пешек, обозначенных символом 'p'.
 * Пустые клетки обозначаются символом '.'.
 *
 * Ладья может перемещаться на любое количество клеток по горизонтали или
 * вертикали (вверх, вниз, влево, вправо), пока не встретит другую фигуру
 * или не достигнет края доски.
 *
 * Ладья атакует пешку, если может попасть на её клетку за один ход.
 *
 * Важно: ладья не может перепрыгивать через другие фигуры, например слонов
 * или пешек. Это означает, что ладья не может атаковать пешку, если на
 * пути к ней находится другая фигура.
 *
 * Возвращае количество пешек, которые атакует белая ладья.
 *
 *
 * Пример для:
 *   [
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".","p",".",".",".","."],
 *     [".",".",".","R",".",".",".","p"],
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".","p",".",".",".","."],
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".",".",".",".",".","."]
 *   ]
 * Результат:
 *   3
 * Пояснение:
 *   В этом примере ладья может взять все три пешки.
 *
 *
 * Пример для:
 *   [
 *     [".",".",".",".",".",".",".","."],
 *     [".","p","p","p","p","p",".","."],
 *     [".","p","p","B","p","p",".","."],
 *     [".","p","B","R","B","p",".","."],
 *     [".","p","p","B","p","p",".","."],
 *     [".","p","p","p","p","p",".","."],
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".",".",".",".",".","."]
 *   ]
 * Результат:
 *   0
 * Пояснение:
 *   Слоны блокируют ладью, поэтому она не может взять ни одну пешку.
 *
 *
 * Пример для:
 *   [
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".","p",".",".",".","."],
 *     [".",".",".","p",".",".",".","."],
 *     ["p","p",".","R",".","p","B","."],
 *     [".",".",".",".",".",".",".","."],
 *     [".",".",".","B",".",".",".","."],
 *     [".",".",".","p",".",".",".","."],
 *     [".",".",".",".",".",".",".","."]
 *   ]
 * Результаm:
 *   3
 * Пояснение:
 *   Ладья может взять пешки, расположенные на клетках b5, d6 и f5.
 *
 *
 * Ограничения:
 * - board.length == 8
 * - board[i].length == 8
 * - board[i][j] может содержать только 'R', '.', 'B' или 'p'.
 * - На доске находится ровно одна клетка, содержащая 'R'.
 */
function numRookCaptures(board) {

  // Главная идея заключается в том, что ладья атакует по прямым линиям:
  // вверх, вниз, влево и вправо. От позиции ладьи нам нужно проверить,
  // какая фигура встретится первой в каждом из этих четырёх направлений.
  //
  // Представьте, что из ладьи в каждом направлении выходит лазерный луч.
  // Он движется по прямой, пока не встретит какое-либо препятствие:
  // - Если луч встречает пешку ('p'), мы можем её взять, поэтому
  //   увеличиваем счётчик атакованных пешек.
  //
  // - Если луч встречает слона ('B'), он преграждает путь, поэтому
  //   мы не можем двигаться дальше в этом направлении.
  //
  // - Если луч встречает пустую клетку ('.'), продолжаем двигаться
  //   дальше в том же направлении.
  //
  // - Если луч достигает края доски, прекращаем проверку этого направления.
  //
  // Это естественным образом приводит нас к решению методом симуляции:
  // 1. Сначала находим координаты ладьи на шахматной доске.
  //
  // 2. Затем начинаем последовательно проверять клетки во всех четырёх
  //    направлениях от позиции ладьи.
  //
  // Для каждого направления продолжаем двигаться по одной клетке, пока не
  // произойдёт одно из трёх событий:
  // - Находим пешку: увеличиваем счётчик атакованных пешек
  //   и прекращаем проверку текущего направления.
  //
  // - Находим слона: прекращаем проверку текущего направления,
  //   не увеличивая счётчик.
  //
  // - Достигаем границы доски: прекращаем проверку текущего направления.
  //
  // Векторы направлений (-1, 0), (1, 0), (0, -1), (0, 1) соответствуют
  // перемещению вверх, вниз, влево и вправо.
  //
  // Можно элегантно получить эти четыре вектора, используя массив:
  //   dirs = [-1, 0, 1, 0, -1]
  //
  // Если брать соседние элементы массива попарно, получим:
  //   (-1, 0), (0, 1), (1, 0), (0, -1).
  //
  // Максимальное количество пешек, которые может атаковать ладья, - 4
  // (по одной в каждом направлении).
  //
  // Минимальное количество - 0 (если во всех направлениях путь
  // заблокирован слонами или пешек нет).


  const n = board.length;

  // Создаем массив векторов смещения (координатных шагов) для четырех
  // ортогональных направлений движения ладьи:
  // [-1, 0] - вверх, [1, 0] - вниз, [0, -1] - влево, [0, 1] - вправо
  const directions = [[-1, 0], [1, 0], [0, -1], [0, 1]];

  // Запускаем внешний цикл для последовательного перебора индексов всех
  // строк матрицы сверху вниз с целью найти позицию белой ладьи
  for (let r = 0; r < n; r++) {

    // Запускаем вложенный цикл для перебора индексов всех столбцов слева
    // направо внутри текущей строки r
    for (let c = 0; c < n; c++) {

      // Проверяем содержимое текущей клетки с координатами [r][c]:
      //
      // Если в ней находится не белая ладья ('R'), то пропускаем остаток
      // тела цикла и сразу переходим к проверке следующей клетки
      if (board[r][c] !== 'R') continue;

      // Как только единственная белая ладья найдена, инициализируем
      // счетчик captureCnt значением 0 для подсчета общего количества
      // черных пешек, которые ладья может атаковать во всех четырёх
      // направлениях.
      let captureCnt = 0;

      // Перебираем все четыре направления движения ладьи.
      //
      // На каждой итерации переменная dir получает очередной массив с
      // координатами направления: [-1, 0], [1, 0], [0, -1] или [0, 1].
      //
      // Для ускорения работы кода не используем деструктуризацию массива
      // dir на уровне цикла, а обращаемся к его элементам по индексу.
      for (const dir of directions) {

        // Извлекаем первый элемент вектора - шаг смещения по вертикали
        // (-1, 1 или 0)
        const dr = dir[0];

        // Извлекаем второй элемент вектора - шаг смещения по горизонтали
        // (-1, 1 или 0)
        const dc = dir[1];

        // Вычисляем начальную координату строки (nr - next row) для
        // первого шага ладьи от ее исходной позиции r в выбранном
        // вертикальном направлении dr
        let nr = r + dr;

        // Вычисляем начальную координату столбца (nc - next column) для
        // первого шага ладьи от ее исходной позиции c в выбранном
        // горизонтальном направлении dc
        let nc = c + dc;

        // Запускаем цикл while, который позволяет ладье двигаться по
        // текущему направлению до тех пор, пока все условия остаются
        // истинными.
        while (

          // Проверяем, что индекс проверяемой строки nr не ушел в
          // отрицательную область (ладья не вышла за верхний край доски)
          nr >= 0

          // Проверяем, что индекс проверяемой строки nr строго меньше
          // размера доски n (ладья не вышла за нижний край доски)
          && nr < n

          // Проверяем, что индекс проверяемого столбца nc не ушел в
          // отрицательную область (ладья не вышла за левый край доски)
          && nc >= 0

          // Проверяем, что индекс проверяемого столбца nc строго меньше
          // размера доски n (ладья не вышла за правый край доски)
          && nc < n

          // Проверяем, что на проверяемой клетке board[nr][nc] не стоит
          // союзный белый слон ('B'), так как он блокирует путь и ладья не
          // может через него перепрыгнуть
          && board[nr][nc] !== 'B'
        ) {

          // Если на текущей достигнутой клетке board[nr][nc] находится
          // вражеская черная пешка ('p')
          if (board[nr][nc] === 'p') {

            // Увеличиваем счётчик атакованных пешек на единицу.
            captureCnt++;

            // Прерываем текущий цикл while.
            //
            // После обнаружения пешки нет смысла продолжать движение в
            // этом направлении, поскольку пешка является первой фигурой
            // на пути ладьи и блокирует дальнейшее движение.
            break;
          }

          // Если текущая клетка не содержит пешку, значит, она пустая
          // ('.'). Поэтому ладья может продолжить движение в том же
          // направлении.
          //
          // Изменяем номер строки на величину dr.
          //
          // Например, при движении вверх nr уменьшается на единицу,
          // а при движении вниз увеличивается на единицу.
          nr += dr;

          // Изменяем номер столбца на величину dc.
          //
          // Например, при движении влево nc уменьшается на единицу, а при
          // движении вправо увеличивается на единицу.
          //
          // Вместе с предыдущей строкой это перемещает проверку на
          // следующую клетку в выбранном направлении.
          nc += dc;
        }
      }

      // После проверки всех четырех направлений сразу возвращаем
      // накопленное значение captureCnt.
      //
      // Продолжать поиск по доске не нужно, так как по условию белая ладья
      // на доске всего одна
      return captureCnt;
    }
  }

  // Возвращаем 0 в качестве запасного результата (на случай, если на вход
  // передали некорректную доску, на которой вообще нет белой ладьи 'R')
  return 0;
}
