/**
 * @param {number[][]} grid
 * @return {number}
 *
 * minimumOperations принимает двумерный массив grid размером m x n,
 * состоящий из неотрицательных целых чисел.
 *
 * За одну операцию можно увеличить значение любого элемента grid[i][j] на
 * 1.
 *
 * Возвращает минимальное количество операций, необходимое для того, чтобы
 * все столбцы массива grid стали строго возрастающими.
 *
 * Пример для:
 *   grid = [[3,2],[1,3],[3,4],[0,1]]
 * Результат:
 *   15
 * Пояснение:
 *   Чтобы сделать 0-й столбец строго возрастающим, можно выполнить:
 *   - 3 операции для grid[1][0];
 *   - 2 операции для grid[2][0];
 *   - 6 операций для grid[3][0].
 *
 *   Чтобы сделать 1-й столбец строго возрастающим, можно выполнить:
 *   - 4 операции для grid[3][1].
 */
function minimumOperations(grid) {
  const ROWS = grid.length;
  const COLS = grid[0].length;

  // Создаем переменную-аккумулятор operationsCnt для подсчета минимально
  // необходимого количества операций инкремента
  let operationsCnt = 0;

  // Запускаем внешний цикл для последовательного обхода всех столбцов
  // массива.
  for (let c = 0; c < COLS; c++) {

    // Сохраняем значение самого первого (верхнего) элемента текущего
    // столбца.
    //
    // Переменная prevValue будет хранить значение предыдущего элемента в
    // текущем столбце с учётом всех необходимых увеличений.
    //
    // На первой итерации внутреннего цикла предыдущим элементом будет
    // именно элемент первой строки.
    let prevValue = grid[0][c];

    // Запускаем внутренний цикл для последовательного обхода строк
    // текущего столбца.
    for (let r = 1; r < ROWS; r++) {

      // Извлекаем исходное значение текущей ячейки матрицы, находящейся в
      // строке r и столбце c
      const currValue = grid[r][c];

      // Проверяем, соблюдается ли правило строгого возрастания:
      //
      // Текущий элемент должен быть строго больше предыдущего (с учетом
      // возможных прошлых увеличений).
      if (prevValue < currValue) {

        // Если текущий элемент больше предыдущего, никаких операций
        // прибавления не требуется.
        //
        // Обновляем prevValue, делая текущее значение новым ориентиром для
        // следующей строки.
        prevValue = currValue;

        // В противном случае (когда currValue меньше или равно prevValue),
        // правило строгого возрастания нарушено, и текущий элемент
        // необходимо увеличить
      } else {

        // Вычисляем минимальное число операций:
        //
        // Чтобы currValue стал строго больше prevValue, его нужно довести
        // до значения (prevValue + 1), поэтому разница равна
        // (prevValue + 1) - currValue.
        //
        // Прибавляем её к счётчику.
        operationsCnt += prevValue + 1 - currValue;

        // Обновляем опорное значение:
        //
        // После прибавления операций текущий элемент стал равен
        // (prevValue + 1), поэтому просто инкрементируем prevValue
        prevValue++;
      }
    }
  }

  // Возвращаем общее минимальное количество операций, необходимое для
  // того, чтобы все столбцы стали строго возрастающими.
  return operationsCnt;
}
