/**
 * @param {number[][]} mat
 * @return {number[]}
 *
 * rowAndMaximumOnes принимает бинарную матрицу размером m x n.
 *
 * Функция находит индекс строки (нумерация с 0), которая содержит
 * максимальное количество единиц, а также количество единиц в этой строке.
 *
 * Если несколько строк содержат одинаковое максимальное количество единиц,
 * функция выбирает строку с наименьшим индексом.
 *
 * Возвращает массив, содержащий индекс выбранной строки и количество
 * единиц в ней.
 *
 *
 * Пример для:
 *   mat = [[0,1],[1,0]]
 * Результат:
 *   [0,1]
 * Пояснение:
 *   Обе строки содержат одинаковое количество единиц. Поэтому выбираем
 *   строку с наименьшим индексом - 0.
 *
 *   Максимальное количество единиц равно 1.
 *
 *
 * Пример для:
 *   mat = [[0,0,0],[0,1,1]]
 * Результат:
 *   [1,2]
 * Пояснение:
 *   Строка с индексом 1 содержит максимальное количество единиц - 2.
 *   Поэтому возвращаем её индекс и количество единиц.
 */
function rowAndMaximumOnes(mat) {
  const ROWS = mat.length;
  const COLS = mat[0].length;

  // Инициализируем результирующий массив из двух элементов:
  //
  // Первый (индекс 0) хранит номер лучшей строки, второй (индекс 1) -
  // максимальное найденное число единиц.
  //
  // Значение по умолчанию [0, 0] корректно сработает, даже если вся
  // матрица состоит из нулей (вернется первая строка с индексом 0).
  const rowNdxAndMaxOnes = [0, 0];

  // Запускаем внешний цикл для последовательного обхода каждой строки
  // матрицы сверху вниз
  for (let r = 0; r < ROWS; r++) {

    // Создаем локальную переменную onesCnt для подсчета количества единиц
    // исключительно в текущей рассматриваемой строке r
    let onesCnt = 0;

    // Запускаем внутренний цикл для перебора всех элементов текущей строки
    // r
    for (let c = 0; c < COLS; c++) {

      // Прибавляем значение текущего элемента матрицы mat[r][c] к счетчику
      // onesCnt.
      //
      // Поскольку матрица содержит только 0 и 1, сложение всех элементов
      // строки дает точное количество единиц без необходимости
      // использовать условный оператор if.
      onesCnt += mat[r][c];
    }

    // Сравниваем количество единиц в текущей строке (onesCnt) с текущим
    // максимумом (rowNdxAndMaxOnes[1]).
    //
    // Строгое неравенство (>) гарантирует, что при равном количестве
    // единиц сохранится строка с меньшим индексом, встреченная ранее.
    if (onesCnt > rowNdxAndMaxOnes[1]) {

      // Если найден новый максимум, перезаписываем первый элемент
      // результирующего массива, сохраняя в нем индекс текущей строки r.
      rowNdxAndMaxOnes[0] = r;

      // Перезаписываем второй элемент результирующего массива, обновляя
      // максимальное количество единиц на значение onesCnt.
      rowNdxAndMaxOnes[1] = onesCnt;

      // Досрочный выход (оптимизация):
      //
      // Если количество единиц в строке совпало с общим числом столбцов
      // COLS, значит строка целиком заполнена единицами. Больше единиц
      // быть не может, а последующие строки с таким же количеством не
      // подойдут по условию наименьшего индекса, поэтому сразу возвращаем
      // результат.
      if (onesCnt === COLS) return rowNdxAndMaxOnes;
    }
  }

  // После завершения проверки всех строк матрицы возвращаем итоговый
  // массив rowNdxAndMaxOnes, содержащий индекс первой найденной строки с
  // максимальным количеством единиц и само это количество.
  return rowNdxAndMaxOnes;
}
