/**
 * @param {number[]} original
 * @param {number} m
 * @param {number} n
 * @return {number[][]}
 *
 * construct2DArray принимает одномерный целочисленный массив original с
 * индексацией с 0, а также два целых числа m и n.
 *
 * Функция создает двумерный массив размером m x n, используя все элементы
 * массива original.
 *
 * Элементы массива original с индексами от 0 до n - 1 (включительно)
 * образовывают первую строку нового массива.
 *
 * Элементы с индексами от n до 2 * n - 1 (включительно) образовывают
 * вторую строку, и так далее.
 *
 * Возвращает двумерный массив размером m x n, созданный по описанному
 * алгоритму.
 *
 * Если создать такой массив невозможно, верните пустой двумерный массив [].
 *
 *
 * Пример для:
 *   original = [1, 2, 3, 4],
 *   m = 2,
 *   n = 2
 * Результат:
 *   [[1, 2], [3, 4]]
 * Пояснение:
 *   Необходимо создать двумерный массив из 2 строк и 2 столбцов.
 *
 *   Первые 2 элемента массива original [1, 2] становятся первой строкой.
 *
 *   Следующие 2 элемента [3, 4] становятся второй строкой.
 *
 *
 * Пример для:
 *   original = [1, 2],
 *   m = 1,
 *   n = 1
 * Результат:
 *   []
 * Пояснение:
 *   В массиве original содержится 2 элемента.
 *
 *   Невозможно разместить 2 элемента в двумерном массиве
 *   размером 1 x 1, поэтому возвращает пустой массив [].
 */
function construct2DArray(original, m, n) {

  // Проверяем базовое условие возможности построения матрицы:
  //
  // Общее количество ячеек в матрице m x n должно строго совпадать с
  // длиной исходного массива.
  //
  // Если элементов меньше или больше, заполнить матрицу целиком без
  // остатка невозможно - сразу возвращаем пустой массив []
  if (m * n !== original.length) return [];

  // Заранее выделяем память под внешний массив фиксированной длины m, где
  // каждый элемент будет представлять собой отдельную строку.
  //
  // Предварительное указание размера оптимизирует работу с памятью,
  // избавляя движок JS от необходимости динамически расширять массив
  const result = new Array(m);

  // Создаем переменную-указатель r (row), которая отслеживает индекс
  // текущей заполняемой строки в массиве result
  let r = 0;

  // Запускаем цикл по исходному массиву:
  //
  // Переменная start указывает на индекс первого элемента очередной строки.
  //
  // На каждой итерации сдвигаем start ровно на n позиций вперед (длину
  // одной строки), переходя к первому элементу следующей строки
  for (let start = 0; start < original.length; start += n) {

    // Метод slice(start, start + n) копирует участок длиной n элементов
    // (от start включительно до start + n не включительно) в новый
    // подмассив.
    //
    // Полученный подмассив длиной n записывается в result по текущему
    // индексу r, после чего постфиксный инкремент (r++) увеличивает
    // значение r на 1 для следующей итерации
    result[r++] = original.slice(start, start + n);
  }

  // Возвращаем готовый двумерный массив result размером m x n, содержащий
  // все элементы из original в исходном порядке
  return result;
}
