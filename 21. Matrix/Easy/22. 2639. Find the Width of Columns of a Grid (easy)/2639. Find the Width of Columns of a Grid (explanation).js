/**
 * @param {number[][]} grid
 * @return {number[]}
 *
 * findColumnWidth принимает целочисленную матрицу grid размером m x n с
 * индексацией с 0.
 *
 * Ширина столбца - это максимальное количество символов среди всех целых
 * чисел в этом столбце.
 *
 * Например, если grid = [[-10], [3], [12]], то ширина единственного
 * столбца равна 3, поскольку число -10 состоит из 3 символов.
 *
 * Необходимо вернуть целочисленный массив ans размером n, где
 * ans[i] - ширина i-го столбца.
 *
 * Длина целого числа x, состоящего из len цифр:
 * - равна len, если x неотрицательное;
 * - равна len + 1, если x отрицательное (учитывается знак минус).
 *
 *
 * Пример для:
 *   grid = [[1], [22], [333]]
 * Результат:
 *   [3]
 * Пояснение:
 *   В столбце с индексом 0 число 333 имеет длину 3, что и является
 *   максимальной шириной столбца.
 *
 *
 * Пример для:
 *   grid = [[-15, 1, 3], [15, 7, 12], [5, 6, -2]]
 * Результат:
 *   [3, 1, 2]
 * Пояснение:
 *   - В столбце с индексом 0 число -15 имеет длину 3.
 *   - В столбце с индексом 1 все числа имеют длину 1.
 *   - В столбце с индексом 2 числа 12 и -2 имеют длину 2.
 */
function findColumnWidth(grid) {
  const ROWS = grid.length;
  const COLS = grid[0].length;

  // Инициализируем типизированный массив Int32Array фиксированной длины
  // COLS.
  //
  // Он работает быстрее обычного Array, занимает меньше памяти и
  // автоматически заполняется нулями (0 - безопасное начальное значение,
  // так как длина любого числа минимум 1).
  //
  // Элементы будут хранить итоговую ширину каждого столбца
  const result = new Int32Array(COLS);

  // Внешний цикл по столбцам
  for (let c = 0; c < COLS; c++) {

    // Внутренний цикл для вертикального прохода по всем строкам внутри
    // текущего столбца c
    for (let r = 0; r < ROWS; r++) {

      // Получаем элемент матрицы, расположенный на в ячейке grid[r][c].
      //
      // С помощью шаблонной строки `${...}` преобразуем число в строку.
      // Например:
      //   123 превращается в "123" (длина 3),
      //   -15 превращается в "-15" (длина 3),
      //   0 превращается в "0" (длина 1).
      //
      // Свойство length возвращает количество символов в полученной строке.
      //
      // Таким образом, для отрицательных чисел знак минус тоже учитывается.
      const width = `${grid[r][c]}`.length;

      // С помощью встроенного метода Math.max сравниваем уже записанное
      // в result[c] максимальное значение ширины для текущего столбца с
      // длиной нового элемента width и перезаписываем result[c] наибольшим
      // из этих двух значений
      result[c] = Math.max(result[c], width);
    }
  }

  // Возвращаем заполненный массив result, где под каждым индексом c
  // находится максимальная длина числа в c-м столбце
  return result;
}
