/**
 * @param {number} n
 * @param {number[][]} grid
 * @param {number[]} rowShift
 * @param {number[]} colShift
 * @return {number[][]}
 *
 * cyclicShift принимает целое число n, двумерный целочисленный массив grid
 * размером n x n, а также два целочисленных массива rowShift и colShift
 * длины n, где:
 * - rowShift[r] - количество позиций, на которое нужно циклически сдвинуть
 *   r-ю строку массива grid влево.
 *
 * - colShift[c] - количество позиций, на которое нужно циклически сдвинуть
 *   c-й столбец вверх.
 *
 * Функция сначала выполняет циклический сдвиг каждой строки в соответствии
 * с массивом rowShift, а затем циклический сдвиг каждого столбца
 * полученной матрицы в соответствии с массивом colShift.
 *
 * Возвращает итоговую матрицу после выполнения всех сдвигов.
 *
 * Циклический сдвиг строки влево на k позиций означает, что элемент,
 * находящийся в столбце c, перемещается в столбец (c - k + n) % n.
 * Остальные строки остаются без изменений.
 *
 * Циклический сдвиг столбца вверх на k позиций означает, что элемент,
 * находящийся в строке r, перемещается в строку (r - k + n) % n. Остальные
 * столбцы остаются без изменений.
 *
 *
 * Пример для:
 *   n = 2
 *   grid = [[1, 2], [3, 4]]
 *   rowShift = [1, 0]
 *   colShift = [0, 1]
 * Результат:
 *   [[2, 4], [3, 1]]
 *
 *
 * Пример для:
 *   n = 3
 *   grid = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]
 *   rowShift = [1, 2, 0]
 *   colShift = [2, 2, 1]
 * Результат:
 *   [[7, 8, 5], [2, 3, 9], [6, 4, 1]]
 */
function cyclicShift(n, grid, rowShift, colShift) {

  // Создаем двумерный массив rowShiftedGrid размером n x n для
  // промежуточного хранения матрицы после сдвига строк.
  //
  // Метод Array.from({ length: n }, ...) создает внешний массив из n
  // элементов, а коллбэк () => new Array(n) заполняет его вложенными
  // массивами длины n.
  //
  // Это нужно, чтобы не изменять исходный массив grid напрямую и избежать
  // перезаписи элементов во время их перемещения.
  const rowShiftedGrid = Array.from({ length: n }, () => new Array(n));

  // Запускаем внешний цикл для последовательного обхода всех строк матрицы.
  for (let r = 0; r < n; r++) {

    // Запускаем внутренний цикл для обхода каждого элемента внутри текущей
    // строки r.
    for (let c = 0; c < n; c++) {

      // Переносим элемент grid[r][c] на его новую позицию в той же строке
      // r промежуточной матрицы rowShiftedGrid.
      //
      // Выражение (c - rowShift[r] + n) % n вычисляет новый индекс столбца
      // при циклическом сдвиге влево на rowShift[r] шагов: вычитание
      // сдвигает индекс влево, прибавление n защищает от получения
      // отрицательного числа, а остаток от деления (% n) закольцовывает
      // выход за границы массива.
      rowShiftedGrid[r][(c - rowShift[r] + n) % n] = grid[r][c];
    }
  }

  // Создаем итоговый двумерный массив result размером n x n по аналогии с
  // rowShiftedGrid.
  //
  // В него будут записаны элементы после выполнения второго этапа -
  // циклического сдвига столбцов.
  const result = Array.from({ length: n }, () => new Array(n));

  // Запускаем внешний цикл для последовательного обхода всех столбцов
  // матрицы.
  for (let c = 0; c < n; c++) {

    // Запускаем внутренний цикл для обхода всех элементов сверху вниз
    // внутри текущего столбца c.
    for (let r = 0; r < n; r++) {

      // Переносим элемент из промежуточной матрицы в итоговую в тот же
      // столбец c, но в новую строку: вычитаем сдвиг colShift[c] (движение
      // вверх к началу столбца), прибавляем n во избежание отрицательных
      // значений и берём остаток от деления на n (% n) для циклического
      // переноса верхних элементов вниз
      result[(r - colShift[c] + n) % n][c] = rowShiftedGrid[r][c];
    }
  }

  // Возвращаем готовую матрицу result, в которой применены оба вида
  // сдвигов (сначала по строкам, затем по столбцам).
  return result;
}
