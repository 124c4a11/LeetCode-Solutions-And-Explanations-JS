/**
 * @param {number[][]} accounts
 * @return {number}
 *
 * maximumWealth целочисленную матрицу accounts размером m x n, где
 * accounts[i][j] - это сумма денег, которая есть у i-го клиента в j-м
 * банке.
 *
 * Возвращает состояние (богатство) самого богатого клиента.
 *
 * Состояние клиента - это общая сумма денег на всех его банковских счетах.
 * Самым богатым считается клиент, у которого максимальное состояние.
 *
 *
 * Пример для:
 *   accounts = [[1,2,3],[3,2,1]]
 * Результат:
 *   6
 * Пояснение:
 *   У 1-го клиента состояние = 1 + 2 + 3 = 6
 *   У 2-го клиента состояние = 3 + 2 + 1 = 6
 *
 *   Оба клиента считаются самыми богатыми с состоянием 6 у каждого,
 *   поэтому возвращаем 6.
 */
function maximumWealth(accounts) {

  // Инициализируем переменную maxWealth значением 0.
  //
  // Она будет выступать в роли аккумулятора для хранения самого большого
  // суммарного капитала, найденного среди всех проверенных клиентов.
  let maxWealth = 0;

  // Запускаем цикл for...of для последовательного перебора всех элементов
  // внешнего массива accounts.
  //
  // На каждой итерации в неизменяемую переменную account записывается
  // очередной вложенный массив - список всех банковских счетов одного
  // клиента.
  for (const account of accounts) {

    // Вычисляем общий капитал текущего клиента с помощью метода массива
    // reduce().
    //
    // Метод проходит по всем числам в массиве account и складывает их:
    // параметр 'a' хранит промежуточную накопленную сумму (начиная с
    // первого элемента массива), а 'b' - текущее добавляемое значение.
    //
    // Итоговая сумма сохраняется в константу currWealth.
    const currWealth = account.reduce((a, b) => a + b);

    // Сравниваем текущее максимальное значение maxWealth с суммой текущего
    // клиента currWealth и записываем большее из них в maxWealth.
    maxWealth = Math.max(maxWealth, currWealth);
  }

  // Возвращаем итоговое значение переменной maxWealth - капитал самого
  // богатого клиента.
  return maxWealth;
}
