/**
 * @param {number} rows
 * @param {number} cols
 * @param {number} rCenter
 * @param {number} cCenter
 * @return {number[][]}
 *
 * allCellsDistOrder принимает четыре целых числа: row, cols, rCenter и
 * cCenter.
 *
 * Имеется матрица размером rows x cols, и вы находитесь в ячейке с
 * координатами (rCenter, cCenter).
 *
 * Возвращает координаты всех ячеек матрицы, отсортированные по расстоянию
 * от ячейки (rCenter, cCenter) в порядке возрастания расстояния.
 *
 * Расстояние между двумя ячейками (r1, c1) и (r2, c2) вычисляется по
 * формуле: |r1 - r2| + |c1 - c2|
 *
 *
 * Пример для:
 *   rows = 1, cols = 2, rCenter = 0, cCenter = 0
 * Результат:
 *   [[0,0],[0,1]]
 * Пояснение:
 *   Расстояния от ячейки (0, 0) до остальных ячеек: [0, 1]
 *
 *
 * Пример для:
 *   rows = 2, cols = 2, rCenter = 0, cCenter = 1
 * Результат:
 *   [[0,1],[0,0],[1,1],[1,0]]
 * Пояснение:
 *   Расстояния от ячейки (0, 1) до остальных ячеек: [0, 1, 1, 2]
 *
 *   Ответ [[0,1],[1,1],[0,0],[1,0]] также считается правильным, поскольку
 *   расстояния расположены в порядке возрастания.
 */
function allCellsDistOrder(rows, cols, rCenter, cCenter) {

  // Основная идея этого алгоритма заключается в использовании блочной
  // сортировки (Bucket Sort) или сортировки подсчетом (Counting Sort).
  // Вместо того чтобы вычислять расстояния и затем сортировать массив
  // стандартным методом (который требует сравнений и работает медленнее),
  // алгоритм сразу раскладывает ячейки по нужным «полкам» в зависимости от
  // их удаленности.
  //
  // Ключевые принципы работы
  // - Индекс массива как значение расстояния. Манхэттенское расстояние
  //   между двумя ячейками - это всегда целое неотрицательное число
  //   (0, 1, 2 и так далее). Мы создаем массив buckets, где номер (индекс)
  //   каждого элемента соответствует конкретному расстоянию от центра.
  //   Например, в buckets попадет сама центральная ячейка, в buckets - все
  //   её ближайшие соседи на расстоянии 1, в buckets - ячейки на
  //   расстоянии 2.
  //
  // - Группировка за один проход. Алгоритм по очереди проверяет каждую
  //   ячейку матрицы. Для неё вычисляется расстояние, и координаты [r, c]
  //   сразу добавляются в подмассив с соответствующим индексом. Нам не
  //   нужно сравнивать ячейки друг с другом.
  //
  // - Автоматическая сортировка при сборке. Поскольку индексы в массиве
  //   buckets изначально идут строго по возрастанию
  //   (от 0 до maxDistance - 1), нам достаточно просто пройти по всем
  //   корзинам по порядку и переложить их содержимое в итоговый массив
  //   result.
  //
  // Почему этот подход эффективен
  // - Высокая скорость (линейная сложность). Обычная сортировка через
  //   .sort() затрачивает O(N log N) операций, где N - общее количество
  //   ячеек. Данный алгоритм проходит по каждой ячейке всего два раза
  //   (один раз при распределении по корзинам, второй - при сборке ответа),
  //   что дает линейное время работы O(R × C), где R и C - размеры матрицы.
  //
  // - Предсказуемый расход памяти. Максимально возможное расстояние в
  //   прямоугольной сетке строго ограничено её размерами и не превышает
  //   rows + cols. Это позволяет заранее выделить массив нужной длины без
  //   лишних перераспределений памяти.


  // Вычисляем верхнюю границу максимально возможного манхэттенского
  // расстояния в матрице (с небольшим запасом, так как реальный максимум
  // равен rows - 1 + cols - 1), чтобы гарантированно хватило места для
  // всех возможных дистанций.
  const maxDistance = rows + cols;

  // Инициализируем двумерный массив "корзин" (реализация алгоритма блочной
  // сортировки / Bucket Sort) длиной maxDistance, заполняя каждый его
  // элемент новым независимым пустым массивом [] для хранения координат с
  // одинаковым расстоянием.
  //
  // Индекс каждой корзины будет соответствовать конкретному расстоянию до
  // центра.
  const buckets = Array.from({ length: maxDistance }, () => []);

  // Запускаем внешний цикл со счетчиком r, который последовательно
  // проходит по всем индексам строк матрицы
  for (let r = 0; r < rows; r++) {

    // Запускаем вложенный цикл, который последовательно проходит по всем
    // столбцам текущей строки r
    for (let c = 0; c < cols; c++) {

      // Вычисляем манхэттенское расстояние от текущей ячейки (r, c) до
      // центра (rCenter, cCenter) по формуле |r - rCenter| + |c - cCenter|,
      // используем полученное целое число как индекс в массиве buckets и
      // добавляем массив координат [r, c] в конец соответствующей корзины.
      buckets[Math.abs(r - rCenter) + Math.abs(c - cCenter)].push([r, c]);
    }
  }

  // Создаем пустой одномерный массив result, в который будем
  // последовательно собирать координаты ячеек в отсортированном порядке.
  const result = [];

  // Запускаем цикл for...of для последовательного перебора всех корзин в
  // массиве buckets, начиная с индекса 0 (самые близкие к центру клетки) и
  // заканчивая максимальным расстоянием.
  for (const bucket of buckets) {

    // Проходим по каждой координате cell внутри текущей корзины bucket и
    // добавляем ее в конец итогового массива result.
    for (const cell of bucket) result.push(cell);
  }

  // Возвращаем итоговый массив result, содержащий координаты всех ячеек
  // матрицы, отсортированные по возрастанию их расстояния от заданного
  // центра.
  return result;
}
