/**
 * @param {number[][]} grid
 * @return {number}
 *
 * surfaceArea принимает сетку размером n x n, в которой расположено
 * несколько кубиков размером 1 x 1 x 1. Каждое значение v = grid[i][j]
 * обозначает башню из v кубиков, поставленных друг на друга в ячейке
 * (i, j).
 *
 * После размещения кубиков все непосредственно соприкасающиеся кубики
 * склеиваются между собой, образовав несколько трёхмерных фигур
 * неправильной формы.
 *
 * Возвращает общую площадь поверхности всех получившихся фигур.
 *
 *
 * Примечание:
 * Нижняя грань каждой фигуры также учитывается при вычислении площади её
 * поверхности.
 *
 *
 * Пример для:
 *   grid = [[1,2],[3,4]]
 * Вывод:
 *   34
 */
function surfaceArea(grid) {

  // Чтобы найти общую площадь поверхности, рассмотрим, что происходит при
  // размещении кубиков на сетке.
  //
  // Сначала рассмотрим отдельную башню высотой v, расположенную в ячейке
  // (i, j). Если бы эта башня стояла отдельно, её площадь поверхности
  // составляла бы:
  // - Верхняя грань: 1 квадратная единица.
  // - Нижняя грань: 1 квадратная единица.
  // - Четыре боковые грани: по v квадратных единиц каждая.
  //
  // Таким образом, общая площадь поверхности отдельно стоящей башни равна:
  // 2 + 4 * v
  //
  // Теперь рассмотрим, что происходит, когда башни расположены рядом.
  // Когда две башни соприкасаются, их общая поверхность склеивается. Эта
  // общая площадь перестаёт быть частью внешней поверхности и становится
  // внутренней.
  //
  // Ключевая идея заключается в следующем:
  // Если две соседние башни имеют высоты h1 и h2, то площадь их
  // соприкосновения составляет ровно min(h1, h2) квадратных единиц.
  //
  // Почему? Потому что высота меньшей башни определяет площадь
  // соприкосновения. Например, если высота одной башни равна 5, а
  // соседней - 3, то соприкасаются только нижние 3 уровня.
  //
  // Поскольку обе башни теряют эту общую площадь со своих внешних
  // поверхностей, необходимо вычесть 2 * min(h1, h2) из общей площади.
  //
  // Отсюда следует наш алгоритм:
  // 1. Сначала считаем, что все башни стоят отдельно.
  //    Для каждой непустой ячейки добавляем 2 + 4 * v к общей площади.
  //
  // 2. Для каждой башни проверяем, есть ли у неё сосед слева или сверху.
  //    Проверяем только эти два направления, чтобы избежать повторного
  //    подсчёта.
  //
  // 3. Если сосед существует, вычитаем площадь общей поверхности:
  //    2 * min(текущая_высота, высота_соседа).
  //
  // Обрабатывая каждую башню и вычитая площади соприкосновения только с
  // уже обработанными соседями (слева и сверху), мы избегаем повторного
  // вычитания.
  //
  // В результате получаем правильную общую площадь внешней поверхности
  // всех фигур.


  const n = grid.length;

  // Создаем счетчик totalSurfaceArea с начальным значением 0 для
  // суммирования видимых граней всех склеенных фигур
  let totalSurfaceArea = 0;

  // Запускаем внешний цикл по индексу r (row - строка), чтобы
  // последовательно пройти по всем строкам сетки сверху вниз
  for (let r = 0; r < n; r++) {

    // Запускаем внутренний цикл по индексу c (column - столбец), чтобы
    // обойти каждую ячейку в текущей строке слева направо
    for (let c = 0; c < n; c++) {

      // Проверяем, есть ли в текущей ячейке башня из кубиков.
      //
      // Если высота равна 0, пропускаем эту ячейку и переходим к следующей
      // итерации внутреннего цикла.
      //
      // Пустая ячейка не вносит вклад в площадь поверхности.
      if (grid[r][c] === 0) continue;

      // Добавляем площадь поверхности текущей башни, предполагая, что она
      // стоит отдельно от остальных башен.
      //
      // Формула: 2 + grid[r][c] * 4.
      //
      // Число 2 учитывает две горизонтальные грани:
      // 1 - верхнюю грань
      // 1 - нижнюю грань
      //
      // grid[r][c] * 4 учитывает четыре вертикальные боковые грани. Каждая
      // боковая грань имеет высоту, равную количеству кубиков в башне,
      // и ширину, равную одной единице.
      //
      // Например, если высота башни равна 3:
      // 2 + 3 * 4 = 14.
      //
      // Таким образом, отдельно стоящая башня из трёх кубиков имеет
      // площадь поверхности 14 квадратных единиц.
      totalSurfaceArea += 2 + grid[r][c] * 4;

      // Проверяем, не находимся ли мы в самой верхней строке (r > 0),
      // чтобы безопасно обратиться к ячейке сверху без выхода за границы
      // массива
      //
      // Если r > 0, значит, текущая строка не первая и над текущей ячейкой
      // находится другая ячейка.
      if (r > 0) {

        // Вычитаем из общей площади поверхность соприкосновения текущей
        // башни с башней, расположенной непосредственно сверху.
        //
        // grid[r][c] - высота текущей башни.
        // grid[r - 1][c] - высота башни, расположенной строкой выше.
        //
        // Math.min() возвращает меньшее из двух значений. Это позволяет
        // определить фактическую высоту соприкасающихся частей башен.
        //
        // Например:
        // Текущая башня имеет высоту 4.
        // Верхняя башня имеет высоту 2.
        // Они соприкасаются на протяжении двух уровней.
        //
        // Умножаем минимальную высоту на 2, поскольку общая поверхность
        // исключается из внешней площади обеих башен:
        // одна соприкасающаяся грань принадлежит первой башне,
        // вторая - соседней башне.
        //
        // В результате в данном примере вычитаем:
        // Math.min(4, 2) * 2 = 4.
        totalSurfaceArea -= Math.min(grid[r][c], grid[r - 1][c]) * 2;
      }

      // Проверяем, не находимся ли мы в самом левом столбце (c > 0), чтобы
      // безопасно обратиться к ячейке слева без выхода за границы массива
      if (c > 0) {

        // Вычитаем из общей площади поверхность соприкосновения текущей
        // башни с башней, расположенной непосредственно слева.
        //
        // grid[r][c] - высота текущей башни.
        // grid[r][c - 1] - высота башни, расположенной в предыдущем
        //                  столбце.
        //
        // Math.min() определяет меньшую высоту из двух соседних башен.
        // Эта высота показывает, сколько единичных квадратов находится в
        // непосредственном контакте между башнями.
        //
        // Умножаем результат на 2, поскольку у двух соприкасающихся башен
        // исчезают из внешней поверхности две общие грани.
        //
        // Например:
        // Текущая башня имеет высоту 5.
        // Левая башня имеет высоту 3.
        //
        // Площадь соприкосновения:
        // Math.min(5, 3) = 3.
        //
        // Площадь, которую необходимо исключить:
        // 3 * 2 = 6 квадратных единиц.
        totalSurfaceArea -= Math.min(grid[r][c], grid[r][c - 1]) * 2;
      }
    }
  }

  // Возвращаем итоговое накопленное значение общей площади поверхности
  // всех трехмерных фигур
  return totalSurfaceArea;
}
