/**
 * @param {number[][]} mat
 * @return {number}
 *
 * numSpecial принимает бинарную матрицу mat размером m x n.
 *
 * Возвращает количество особых (special) позиций в матрице mat.
 *
 * Позиция (r, c) называется особой, если mat[r][c] == 1, а все остальные
 * элементы в строке r и столбце c равны 0 (индексация строк и столбцов
 * начинается с 0).
 *
 *
 * Пример для:
 *   mat = [[1,0,0],[0,0,1],[1,0,0]]
 * Результат:
 *   1
 * Пояснение:
 *   (1, 2) является особой позицией, так как mat[1][2] == 1, а все
 *   остальные элементы в строке 1 и столбце 2 равны 0.
 */
function numSpecial(mat) {
  const ROWS = mat.length;
  const COLS = mat[0].length;

  // Создаём типизированный массив целых чисел длиной COLS (изначально
  // заполненный нулями), где по каждому индексу c будет храниться общее
  // количество единиц в столбце c
  const colToSum = new Int32Array(COLS);

  // Создаём пустой обычный массив для хранения индексов столбцов, в
  // которых встретилась единственная единица в рамках одной строки
  const candidateCols = [];

  // Запускаем внешний цикл for для последовательного прохода по всем
  // строкам матрицы mat
  for (let r = 0; r < ROWS; r++) {

    // Инициализируем переменную-счётчик для подсчёта количества единиц
    // исключительно в текущей рассматриваемой строке r
    let rowSum = 0;

    // Инициализируем переменную для запоминания индекса столбца, в котором
    // последний раз встретилась единица в текущей строке
    let candidateCol = 0;

    // Запускаем внутренний цикл for для последовательного прохода по всем
    // элементам (столбцам) текущей строки r
    for (let c = 0; c < COLS; c++) {

      // Проверяем, равен ли элемент на пересечении строки r и столбца c
      // нулю.
      //
      // Если да, досрочно завершаем текущую итерацию и переходим к
      // следующему столбцу
      if (mat[r][c] === 0) continue;

      // Если элемент не равен 0 (значит, он равен 1), увеличиваем счётчик
      // единиц текущей строки на 1
      rowSum++;

      // Также увеличиваем общий счётчик единиц для текущего столбца c в
      // массиве colToSum на 1
      colToSum[c]++;

      // Обновляем индекс потенциального столбца-кандидата, сохраняя в него
      // текущий индекс c
      candidateCol = c;
    }

    // После проверки всех элементов строки r проверяем, была ли в ней
    // ровно одна единица.
    //
    // Если да, сохраняем индекс её столбца в список кандидатов
    if (rowSum === 1) candidateCols.push(candidateCol);
  }

  // Инициализируем итоговый счётчик для хранения количества найденных
  // особых позиций
  let specialPositionsCnt = 0;

  // Запускаем цикл для перебора каждого индекса столбца c из списка ранее
  // отобранных кандидатов
  for (const c of candidateCols) {

    // Проверяем, равна ли общая сумма единиц во всём столбце c единице
    // (условие для строки уже выполнено ранее).
    //
    // Если да, увеличиваем итоговый счётчик
    if (colToSum[c] === 1) specialPositionsCnt++;
  }

  // Возвращаем итоговое количество особых позиций из функции
  return specialPositionsCnt;
}
