/**
 * @param {number[][]} mat
 * @param {number} k
 * @return {boolean}
 *
 * areSimilar принимает целочисленную матрицу mat размером m x n и целое
 * число k. Индексация строк матрицы начинается с 0.
 *
 * Следующий процесс выполняется k раз:
 * - Строки с чётными индексами (0, 2, 4, ...) циклически сдвигаются влево.
 *
 * - Строки с нечётными индексами (1, 3, 5, ...) циклически сдвигаются
 *   вправо.
 *
 * Возвращает true, если итоговая изменённая матрица после k шагов
 * идентична исходной матрице, и false в противном случае.
 *
 *
 * Пример для:
 *   mat = [[1,2,3],[4,5,6],[7,8,9]], k = 4
 * Результат:
 *   false
 * Пояснение:
 *   На каждом шаге сдвиг влево применяется к строкам 0 и 2 (чётные
 *   индексы), а сдвиг вправо - к строке 1 (нечётный индекс).
 */
function areSimilar(mat, k) {

  // Алгоритм опирается на математическую эквивалентность сдвигов и
  // свойство периодичности строк, что позволяет решить задачу без
  // реального изменения матрицы и без симуляции каждого из k шагов.
  //
  // 1. Сведение k шагов к одному сдвигу (k %= COLS)
  // Циклический сдвиг строки длиной n (COLS) на n позиций возвращает все
  // элементы на свои исходные места. Например, для строки из 4 элементов 4
  // сдвига, 8 сдвигов или 100 сдвигов дадут исходную строку. Поэтому нам
  // не важно, сколько полных кругов сделают элементы - важен только
  // остаток от деления k % COLS. Если остаток равен 0, матрица
  // гарантированно не изменится.
  //
  // 2. Почему не важно направление сдвига (влево или вправо)
  // В условии сказано, что чётные строки сдвигаются влево, а нечётные -
  // вправо. Однако в коде для всех строк используется одна и та же
  // формула: (c + k) % COLS. Почему это работает?
  // - При сдвиге влево на k: на место элемента с индексом c приходит
  //   элемент, который стоял правее на k шагов, то есть на позиции
  //   (c + k) mod n. Чтобы строка не изменилась, должно выполняться
  //   условие:
  //     row[c] == row[(c + k) mod n]
  //
  // - При сдвиге вправо на k: на место элемента с индексом c приходит
  //   элемент, который стоял левее на k шагов:
  //     row[c] == row[(c - k + n) mod n]
  //
  //   Но если это равенство верно для каждого элемента в строке, то оно же
  //   означает, что любой элемент равен элементу через k шагов вправо
  //   (достаточно сделать замену индекса c' = (c - k + n) mod n).
  //
  // Иными словами: строка не меняется после циклического сдвига на k (в
  // любую сторону) тогда и только тогда, когда она состоит из
  // повторяющихся блоков (периодична с шагом k). Поэтому направление
  // сдвига можно полностью игнорировать.
  //
  // 3. Отказ от лишней памяти и мутации данных
  // Вместо того чтобы создавать копию матрицы и k раз сдвигать массивы
  // (что потребовало бы O(m * n) памяти и O(k * m * n) времени), алгоритм
  // просто "заглядывает вперёд" по индексам и сравнивает значения на месте:
  // - Временная сложность: O(m * n), где m - число строк, n - число
  //   столбцов. Мы проверяем каждый элемент матрицы максимум один раз и
  //   выходим досрочно (return false) при первом же несовпадении.
  //
  // - Пространственная сложность: O(1). Алгоритм использует только
  //   несколько числовых переменных (ROWS, COLS, r, c) и не выделяет
  //   память под новые массивы.
  //
  // Пример работы логики
  // Возьмём строку [1, 2, 1, 2] (длина COLS = 4) и k = 2:
  // - Для c = 0 (1): сравниваем с индексом (0 + 2) % 4 = 2 (1) - совпадает.
  // - Для c = 1 (2): сравниваем с индексом (1 + 2) % 4 = 3 (2) - совпадает.
  // - Для c = 2 (1): сравниваем с индексом (2 + 2) % 4 = 0 (1) - совпадает.
  // - Для c = 3 (2): сравниваем с индексом (3 + 2) % 4 = 1 (2) - совпадает.
  //
  // Все элементы совпали, значит при сдвиге на 2 позиции хоть влево, хоть
  // вправо строка останется [1, 2, 1, 2].


  const ROWS = mat.length;
  const COLS = mat[0].length;

  // Оптимизируем количество сдвигов с помощью оператора остатка от деления
  // (%=).
  //
  // Если строку длиной COLS сдвинуть ровно COLS раз, она вернется в
  // исходное положение, поэтому нас интересует только остаток от деления
  // k на COLS.
  k %= COLS;

  // Проверяем базовый случай: если эффективный сдвиг k равен 0 (то есть k
  // было кратно количеству столбцов или изначально равно 0), ни один
  // элемент не сдвинется, поэтому сразу возвращаем true без лишних
  // проверок.
  if (k === 0) return true;

  // Внешний цикл для последовательного обхода всех строк матрицы
  for (let r = 0; r < ROWS; r++) {

    // Внутренний цикл для последовательного обхода каждого элемента внутри
    // текущей строки r
    for (let c = 0; c < COLS; c++) {

      // Сравниваем текущий элемент mat[r][c] с элементом, находящимся на
      // расстоянии k позиций правее с учётом циклического перехода через
      // границу строки (% COLS).
      //
      // Для сохранения идентичности строки при сдвиге влево каждый элемент
      // должен равняться своему "соседу" через k шагов справа.
      //
      // Для сдвигов вправо работает ровно то же симметричное условие
      // равенства на расстоянии k, поэтому направление сдвига здесь можно
      // не проверять
      if (mat[r][c] !== mat[r][(c + k) % COLS]) {

        // Если найдено хотя бы одно несовпадение значений, итоговая
        // матрица точно будет отличаться от исходной - досрочно завершаем
        // работу функции и возвращаем false.
        return false;
      }
    }
  }

  // Если оба цикла полностью завершились и не было найдено ни одного
  // несоответствия элементов, значит после k сдвигов матрица полностью
  // идентична исходной - возвращаем true.
  return true;
}
