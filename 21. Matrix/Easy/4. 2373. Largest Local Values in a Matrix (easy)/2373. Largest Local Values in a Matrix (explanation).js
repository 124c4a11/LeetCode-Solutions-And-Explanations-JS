/**
 * @param {number[][]} grid
 * @return {number[][]}
 *
 * largestLocal принимает целочисленную матрицу grid размером n x n.
 *
 * Генерирует целочисленную матрицу maxLocal размером (n - 2) x (n - 2) так,
 * чтобы:
 * - maxLocal[i][j] был равен наибольшему значению в матрице 3 x 3 внутри
 *   grid с центром в строке i + 1 и столбце j + 1.
 *
 * Другими словами, находит наибольшее значение в каждой смежной подматрице
 * размером 3 x 3 в grid.
 *
 * Возвращает сгенерированную матрицу.
 *
 *
 * Пример для:
 *   grid = [[9,9,8,1],[5,6,2,6],[8,2,6,4],[6,2,2,2]]
 * Результат:
 *   [[9,9],[8,6]]
 */
function largestLocal(grid) {
  const n = grid.length;

  // Создаем пустую заготовку двумерного массива resultMatrix размером
  // (n - 2) на (n - 2), так как именно столько окон размером 3x3 может
  // полностью поместиться внутри матрицы n на n без выхода за ее края.
  const resultMatrix = Array.from(
    { length: n - 2 },
    () => new Array(n - 2)
  );

  // Первый внешний цикл, где индекс resultR пробегает все строки итоговой
  // матрицы (от 0 до n - 3) и одновременно служит координатой верхней
  // границы текущего проверяемого квадрата 3x3 в исходной матрице.
  for (let resultR = 0; resultR < n - 2; resultR++) {

    // Второй вложенный цикл, где индекс resultC пробегает все столбцы
    // итоговой матрицы (от 0 до n - 3) и одновременно указывает на левую
    // границу текущего проверяемого квадрата 3x3 в исходной матрице.
    for (let resultC = 0; resultC < n - 2; resultC++) {

      // Объявляем переменную max и задаем ей начальное значение 0 (по
      // условию задачи все числа в матрице положительные, поэтому первый
      // же проверенный элемент гарантированно перезапишет этот ноль).
      let max = 0;

      // Цикл для сканирования трех строк текущего окна 3x3 в исходной
      // матрице grid:
      //
      // Переменная r начинает с верхней границы resultR и последовательно
      // проходит индексы resultR, resultR + 1 и resultR + 2.
      for (let r = resultR; r < resultR + 3; r++) {

        // Цикл для сканирования трех столбцов текущего окна 3x3 в исходной
        // матрице grid:
        //
        // Переменная c начинает с левой границы resultC и последовательно
        // проходит индексы resultC, resultC + 1 и resultC + 2.
        for (let c = resultC; c < resultC + 3; c++) {

          // Обращаемся к конкретной ячейке исходной матрицы по координатам
          // [r][c], сравниваем ее числовое значение с текущим максимумом
          // max через встроенную функцию Math.max и сохраняем большее из
          // двух значений обратно в max.
          max = Math.max(max, grid[r][c]);
        }
      }

      // Записываем найденное максимальное число max в соответствующую
      // ячейку итоговой матрицы resultMatrix по координатам
      // [resultR][resultC].
      resultMatrix[resultR][resultC] = max;
    }
  }

  // Возвращаем готовую матрицу с локальными максимумами.
  return resultMatrix;
}
