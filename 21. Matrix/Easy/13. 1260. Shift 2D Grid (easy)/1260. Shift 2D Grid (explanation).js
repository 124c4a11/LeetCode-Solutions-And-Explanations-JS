/**
 * @param {number[][]} grid
 * @param {number} k
 * @return {number[][]}
 *
 * shiftGrid принимает двумерную сетку размером m x n и целое число k.
 * Выполняет сдвиг элементов сетки k раз.
 *
 * При каждой операции сдвига:
 * 1. Элемент grid[i][j] перемещается в grid[i][j + 1].
 * 2. Элемент grid[i][n - 1] перемещается в grid[i + 1][0].
 * 3. Элемент grid[m - 1][n - 1] перемещается в grid[0][0].
 *
 * Возвращает двумерную сетку после выполнения k операций сдвига.
 *
 *
 * Пример для:
 *   grid = [[1,2,3],[4,5,6],[7,8,9]],
 *   k = 1
 * Результат:
 *   [[9,1,2],[3,4,5],[6,7,8]]
 */
function shiftGrid(grid, k) {

  // Ключевая идея заключается в том, чтобы понять: операция сдвига,
  // описанная в задаче, по сути является циклическим вращением элементов,
  // если представить двумерную сетку в виде одномерного массива.
  //
  // Подумайте, как перемещаются элементы при сдвиге: они движутся вправо
  // в пределах своей строки, а когда достигают её конца, переходят в
  // начало следующей строки. Последний элемент возвращается в самую первую
  // позицию.
  //
  // Именно так мы последовательно читаем элементы двумерного массива:
  // слева направо и сверху вниз.
  //
  // Если мысленно "развернуть" двумерную сетку в одномерный массив,
  // операция сдвига становится намного проще - это просто циклическое
  // перемещение каждого элемента на одну позицию вправо.
  //
  // Например, двумерную сетку 2x3:
  // [[1, 2, 3],
  //  [4, 5, 6]]
  //
  // Можно представить в виде одномерного массива:
  // [1, 2, 3, 4, 5, 6]
  //
  // После одного сдвига получим:
  // [6, 1, 2, 3, 4, 5]
  //
  // А если преобразовать его обратно в двумерный массив:
  // [[6, 1, 2],
  //  [3, 4, 5]]
  //
  // Чтобы определить, куда попадёт каждый элемент после k сдвигов,
  // можно выполнить следующие шаги:
  // 1. Преобразовать двумерные координаты (i, j) в индекс одномерного
  //    массива по формуле:
  //      index = i * n + j
  //      где n - количество столбцов.
  //
  // 2. Прибавить k к полученному индексу, чтобы определить новую позицию
  //    элемента после k сдвигов.
  //
  // 3. Использовать операцию взятия остатка от деления (m * n),
  //    чтобы обеспечить циклическое перемещение элементов.
  //    Это позволяет последнему элементу возвращаться в начало массива.
  //
  // 4. Преобразовать новый одномерный индекс обратно в двумерные
  //    координаты:
  //      x = index // n
  //      y = index % n
  //
  // Такой подход позволяет напрямую вычислить конечную позицию каждого
  // элемента, не выполняя k отдельных операций сдвига.
  //
  // Это значительно повышает эффективность алгоритма, особенно при больших
  // значениях k.


  const ROWS = grid.length;
  const COLS = grid[0].length;

  // Создаём новую пустую матрицу result для записи сдвинутых элементов.
  //
  // Задаём количество строк равным ROWS, а для каждой строки создаём новый
  // пустой массив длиной COLS.
  const result = Array.from(
    { length: ROWS }, () => new Array(COLS)
  );

  // Запускаем внешний цикл для обхода всех строк исходной матрицы
  for (let r = 0; r < ROWS; r++) {

    // Запускаем внутренний цикл для обхода всех столбцов текущей строки
    for (let c = 0; c < COLS; c++) {

      // Переводим двумерные координаты ячейки (строка r, столбец c) в
      // единый линейный индекс, как если бы все строки матрицы вытянули в
      // один сплошной одномерный массив:
      //   r (индекс текущей строки) показывает, сколько полных строк
      //   находится выше нашего элемента.
      //
      //   COLS (количество столбцов) показывает, сколько элементов вмещает
      //   каждая полная строка.
      //
      //   r * COLS вычисляет общее количество элементов во всех предыдущих
      //   строках вместе взятых.
      //
      //   + c (индекс текущего столбца) добавляет количество элементов,
      //   стоящих левее нашего элемента в текущей строке.
      const currNdx = r * COLS + c;

      // Вычисляем новый одномерный индекс после сдвига на k позиций:
      //
      // Прибавляем величину сдвига k к линейному индексу и берём остаток
      // от деления (%) на общее число элементов (ROWS * COLS), чтобы при
      // выходе за границу массива индекс циклически вернулся в начало
      // (реализация циклического переноса элементов, вышедших за правый
      // нижний край, обратно в начало матрицы)
      const shiftedNdx = (currNdx + k) % (ROWS * COLS);

      // Преобразуем новый одномерный индекс обратно в индекс строки (nr),
      // деля на количество столбцов с округлением вниз:
      //   shiftedNdx - это итоговый одномерный индекс элемента после
      //   сдвига(счёт начинается с 0).
      //
      //   COLS - количество элементов в одной полной строке.
      //
      //   shiftedNdx / COLS показывает, сколько полных строк уместилось до
      //   этого элемента, плюс небольшой "хвостик" (дробная часть),
      //   который означает сдвиг внутри самой строки.
      //
      //   Math.floor(...) округляет результат в меньшую сторону,
      //   отбрасывая дробную часть.Это даёт точный номер строки, так как
      //   нумерация строк тоже начинается с 0.
      const nr = Math.floor(shiftedNdx / COLS);

      // Преобразуем новый одномерный индекс обратно в индекс столбца (nc),
      // находя остаток от деления на количество столбцов:
      //   shiftedNdx - общий порядковый номер элемента в одномерном списке
      //   (начиная с 0).
      //
      //   COLS - вместимость одной строки (количество столбцов).
      //
      //   % (остаток от деления) делит общий номер на длину строки и
      //   возвращает то, что "не влезло" в целые строки. Этот остаток
      //   всегда находится в диапазоне от 0 до COLS - 1, что идеально
      //   совпадает с индексами столбцов.
      const nc = shiftedNdx % COLS;

      // Записываем значение текущего элемента из исходной матрицы в
      // вычисленную новую позицию результирующей матрицы.
      result[nr][nc] = grid[r][c];
    }
  }

  // Возвращаем новую двумерную матрицу с элементами, сдвинутыми на k
  // позиций.
  return result;
}
