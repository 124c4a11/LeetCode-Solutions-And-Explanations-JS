/**
 * @param {number[][]} grid
 * @return {number}
 *
 * findChampion двумерный булевый массив grid размером n * n с индексацией
 * с нуля.
 *
 * В турнире участвуют n команд, пронумерованных от 0 до n - 1.
 *
 * Для любых i и j, где 0 <= i, j <= n - 1 и i != j:
 * - Если grid[i][j] == 1, команда i сильнее команды j.
 * - Иначе команда j сильнее команды i.
 *
 * Команда a станет чемпионом турнира, если не существует ни одной другой
 * команды b, которая сильнее команды a.
 *
 * Другими словами grid[i][j] = 1 означает, что команда iпобедила команду j.
 * Таким образом, если мы посмотрим на строку i в таблице, она покажет нам
 * все результаты матчей команды iпротив других команд.
 *
 * Чтобы команда i стала чемпионом, она должна победить все остальные
 * команды. Это означает, что в строке i должны быть 1 все позиции, кроме i
 * самой команды (поскольку команда не играет сама с собой).
 *
 * Например, если у нас есть 3 команды, и команда 0 является чемпионом, то
 * строка 0 будет выглядеть так: [?, 1, 1]где первая позиция не имеет
 * значения, поскольку она представляет собой сравнение команды 0 и команды
 * 0.
 *
 * Функция возвращает номер команды, которая станет чемпионом турнира.
 *
 * Пример для:
 *   grid = [[0, 1], [0, 0]]
 * Результат:
 *   0
 * Пояснение:
 *   В турнире участвуют две команды.
 *   grid[0][1] == 1 означает, что команда 0 сильнее команды 1.
 *   Следовательно, чемпионом станет команда 0.
 *
 *
 * Пример для:
 *   grid = [[0, 0, 1], [1, 0, 1], [0, 0, 0]]
 * Результат:
 *   1
 * Пояснение:
 *   В турнире участвуют три команды.
 *   grid[1][0] == 1 означает, что команда 1 сильнее команды 0.
 *   grid[1][2] == 1 означает, что команда 1 сильнее команды 2.
 *   Следовательно, команда 1 сильнее всех остальных и станет чемпионом.
 */
function findChampion(grid) {

  // Суть этого алгоритма заключается в последовательном отсеивании
  // проигравших команд методом "Царь горы" за один линейный проход.
  //
  // Вместо того чтобы проверять каждую команду против всех остальных (что
  // потребовало бы O(n^2) операций, алгоритм удерживает только одного
  // текущего лидера и заменяет его, как только находится кто-то сильнее.
  //
  // Главная идея алгоритма заключается в следующем:
  //
  // Нам не нужно проверять каждую команду против всех остальных.
  // Достаточно последовательно находить команду, которая сильнее текущего
  // кандидата, и делать её новым кандидатом на победу.
  //
  // 1. Понимаем условие задачи
  //
  // У нас есть n команд. Каждая команда обязательно сильнее одной другой
  // команды в каждой паре.
  //
  // Матрица grid показывает, какая команда сильнее:
  //   grid[i][j] === 1 - означает, что команда i сильнее команды j.
  //
  //    grid[i][j] === 0 - означает, что команда j сильнее команды i.
  //
  // Наша задача - найти команду, которая сильнее абсолютно всех остальных.
  //
  // 2. Основная идея алгоритма
  //
  // Представим, что в турнире участвуют 4 команды:
  //
  // const grid = [
  //   [0, 0, 1, 0],
  //   [1, 0, 1, 1],
  //   [0, 0, 0, 0],
  //   [1, 0, 1, 0]
  // ];
  //
  // Сначала мы предполагаем, что команда с индексом 0 является чемпионом.
  //
  //   let winner = 0;
  //
  // Переменная winner хранит индекс текущего кандидата на победу.
  //
  // Дальше начинаем последовательно сравнивать его с остальными командами.
  //
  // Правило очень простое:
  // - Если текущий кандидат сильнее соперника, оставляем кандидата без
  //   изменений.
  //
  // - Если соперник сильнее текущего кандидата, назначаем соперника новым
  //   кандидатом.
  //
  // Почему мы можем так делать?
  //
  // Потому что если команда проиграла хотя бы одной другой команде, она
  // уже не может быть чемпионом.
  //
  // Следовательно, её больше не нужно рассматривать.


  const n = grid.length;

  // Создаём переменную winner, в которой будем хранить номер текущего
  // кандидата на победу.
  //
  // Изначально считаем, что победителем является команда с индексом 0.
  let winner = 0;

  // Запускаем цикл, который перебирает все команды в качестве
  // потенциальных соперников.
  //
  // Переменная opponent хранит индекс команды, с которой сравниваем
  // текущего кандидата.
  for (let opponent = 0; opponent < n; opponent++) {

    // Проверяем, совпадает ли индекс соперника с индексом текущего
    // кандидата.
    //
    // Если opponent === winner, значит, мы сравниваем команду саму с собой.
    //
    // Такое сравнение не имеет смысла, поэтому с помощью continue
    // пропускаем текущую итерацию и переходим к следующему сопернику.
    if (opponent === winner) continue;

    // Проверяем, сильнее ли команда opponent текущего кандидата winner.
    //
    // grid[winner][opponent] показывает результат сравнения этих двух
    // команд:
    //   1 означает, что команда winner сильнее команды opponent;
    //   0 означает, что команда opponent сильнее команды winner.
    //
    // Поэтому, если значение равно 0, текущий кандидат проигрывает
    // сопернику.
    if (grid[winner][opponent] === 0) {

      // Если текущий кандидат проиграл сопернику, заменяем его новым
      // кандидатом на победу.
      //
      // Теперь считаем, что команда opponent может стать чемпионом.
      winner = opponent;
    }
  }

  // После завершения цикла возвращаем индекс команды winner.
  //
  // Алгоритм гарантирует, что эта команда сильнее всех остальных команд.
  return winner;
}
