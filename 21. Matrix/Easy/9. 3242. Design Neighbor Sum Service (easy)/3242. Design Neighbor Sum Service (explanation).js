/**
 * @param {number[][]} grid
 *
 * NeighborSum принимает массив grid размером n x n, содержащий уникальные
 * элементы в диапазоне от 0 до n² - 1.
 *
 * Методы:
 * - NeighborSum(int[][] grid) - инициализирует объект переданным массивом
 *   grid.
 *
 * - int adjacentSum(int value) - возвращает сумму элементов, расположенных
 *   непосредственно рядом с элементом value: сверху, снизу, слева или
 *   справа.
 *
 * - int diagonalSum(int value) - возвращает сумму элементов, расположенных
 *   по диагонали от элемента value: сверху-слева, сверху-справа,
 *   снизу-слева или снизу-справа.
 *
 *
 * Пример для:
 *   ["NeighborSum", "adjacentSum", "adjacentSum", "diagonalSum",
 *   "diagonalSum"]
 *
 *   [[[[0, 1, 2], [3, 4, 5], [6, 7, 8]]], [1], [4], [4], [8]]
 * Результат:
 *   [null, 6, 16, 16, 4]
 */
class NeighborSum {
  constructor(grid) {

    // Сохраняем размерность квадратной матрицы n
    //
    // Так как матрица имеет размер n x n, длина внешнего массива равна
    // количеству строк и столбцов.
    this.n = grid.length;

    // Сохраняем ссылку на исходную двумерную матрицу в свойство экземпляра
    // this.grid, чтобы иметь к ней доступ в других методах класса.
    this.grid = grid;

    // Инициализируем структуру данных Map (хеш-таблицу) для кэширования
    // координат.
    //
    // Это позволит находить позицию любого числа за константное время O(1)
    // вместо полного перебора матрицы O(n²) при каждом запросе.
    this.valueToPos = new Map();

    // Запускаем внешний цикл по индексу строки r (row) от 0 до n - 1,
    // чтобы последовательно обойти все горизонтальные ряды матрицы сверху
    // вниз.
    for (let r = 0; r < this.n; r++) {

      // Запускаем внутренний цикл по индексу столбца c (column) от 0 до
      // n - 1, чтобы пройти по каждой ячейке текущей строки слева направо.
      for (let c = 0; c < this.n; c++) {

        // Связываем уникальное числовое значение из ячейки grid[r][c] с
        // массивом его координат [r, c] и сохраняем эту пару в
        // this.valueToPos.
        this.valueToPos.set(grid[r][c], [r, c]);
      }
    }
  }

  /**
   * @param {number} value
   * @return {number}
   *
   * adjacentSum принимает целевое число value и вычисляет сумму его прямых
   * (ортогональных) соседей: сверху, снизу, слева и справа.
   */
  adjacentSum(value) {

    // Определяем массив векторов смещения [deltaRow, deltaCol] для 4-х
    // сторон света: шаг вверх [-1, 0], шаг вниз [1, 0], шаг влево [0, -1]
    // и шаг вправо [0, 1].
    const directions = [[-1, 0], [1, 0], [0, -1], [0, 1]];

    // Используем деструктуризацию массива, чтобы за O(1) достать из Map
    // заранее сохраненные координаты строки r и столбца c для переданного
    // числа value.
    const [r, c] = this.valueToPos.get(value);

    // Объявляем переменную-счетчик.
    //
    // В ней будет накапливаться итоговая сумма всех валидных соседей.
    let neighborsSum = 0;

    // Запускаем цикл, чтобы поочередно применить каждый из четырех
    // векторов смещения к текущей позиции [r, c].
    //
    // Для повышения производительности не используем деструктуризацию
    // массива direction внутри цикла, а обращаемся к его элементам по
    // индексу
    for (const direction of directions) {

      // Извлекаем первый элемент вектора смещения direction[0] - это сдвиг
      // по вертикали (на сколько строк нужно переместиться от r).
      const dr = direction[0];

      // Извлекаем второй элемент вектора смещения direction[1] - это сдвиг
      // по горизонтали (на сколько столбцов нужно переместиться от c).
      const dc = direction[1];

      // Вычисляем предполагаемый индекс строки соседа nr (neighbor row),
      // складывая текущую строку r и вертикальный сдвиг dr.
      const nr = r + dr;

      // Вычисляем предполагаемый индекс столбца соседа nc (neighbor
      // column), складывая текущий столбец c и горизонтальный сдвиг dc.
      const nc = c + dc;

      // Проверка границ матрицы
      if (

        // Убеждаемся, что индекс строки соседа nr не отрицательный (ячейка
        // не вышла за верхний край сетки).
        nr >= 0

        // Убеждаемся, что индекс строки nr строго меньше размера матрицы
        // this.n (ячейка не вышла за нижний край сетки).
        && nr < this.n

        // Убеждаемся, что индекс столбца nc не отрицательный (ячейка не
        // вышла за левый край сетки).
        && nc >= 0

        // Убеждаемся, что индекс столбца nc строго меньше this.n (не вышел
        // за правый край).
        && nc < this.n

        // Если сосед существует в пределах матрицы, прибавляем его
        // значение this.grid[nr][nc] к сумме neighborsCnt.
      ) neighborsSum += this.grid[nr][nc];
    }

    // Возвращаем накопленную сумму всех существующих смежных соседей.
    return neighborsSum;
  }

  /**
   * @param {number} value
   * @return {number}
   *
   * diagonalSum принимает целевое число value и вычисляет сумму его 4-х
   * диагональных соседей (по углам от ячейки).
   */
  diagonalSum(value) {

    // Определяем массив векторов смещения для четырех диагоналей:
    // вверх-влево [-1, -1], вверх-вправо [-1, 1], вниз-влево [1, -1] и
    // вниз-вправо [1, 1].
    const directions = [[-1, -1], [-1, 1], [1, -1], [1, 1]];

    // Получаем из this.valueToPos координаты [r, c] целевого числа value
    // за константное время O(1) и распаковываем их в одноименные константы.
    const [r, c] = this.valueToPos.get(value);

    // Инициализируем переменную-аккумулятор значением 0 для суммирования
    // значений всех диагональных соседей, не выходящих за пределы матрицы.
    let diagonalNeighborsSum = 0;

    // Перебираем каждый из четырех диагональных векторов смещения из
    // массива directions.
    //
    // Для повышения производительности не используем деструктуризацию
    // массива direction внутри цикла, а обращаемся к его элементам по
    // индексу
    for (const direction of directions) {

      // Берем из текущего вектора смещения изменение по вертикали
      // (direction[0], принимает значения -1 или 1).
      const dr = direction[0];

      // Берем из текущего вектора смещения изменение по горизонтали
      // (direction[1], принимает значения -1 или 1).
      const dc = direction[1];

      // Рассчитываем координату строки потенциального диагонального соседа
      // nr, прибавляя вертикальное смещение dr к строке r.
      const nr = r + dr;

      // Рассчитываем координату столбца потенциального диагонального
      // соседа nc, прибавляя горизонтальное смещение dc к столбцу c.
      const nc = c + dc;

      // Проверка границ матрицы
      if (

        // Убеждаемся, что индекс строки соседа nr не отрицательный (ячейка
        // не вышла за верхний край сетки).
        nr >= 0

        // Убеждаемся, что индекс строки nr строго меньше размера матрицы
        // this.n (ячейка не вышла за нижний край сетки).
        && nr < this.n

        // Убеждаемся, что индекс столбца nc не отрицательный (ячейка не
        // вышла за левый край сетки).
        && nc >= 0

        // Убеждаемся, что индекс столбца nc строго меньше this.n (не вышел
        // за правый край).
        && nc < this.n

        // Если сосед существует в пределах матрицы, прибавляем его
        // значение this.grid[nr][nc] к сумме diagonalNeighborsCnt.
      ) diagonalNeighborsSum += this.grid[nr][nc];
    }

    // Возвращаем итоговую сумму всех найденных в пределах сетки
    // диагональных соседей для числа value.
    return diagonalNeighborsSum;
  }
}

