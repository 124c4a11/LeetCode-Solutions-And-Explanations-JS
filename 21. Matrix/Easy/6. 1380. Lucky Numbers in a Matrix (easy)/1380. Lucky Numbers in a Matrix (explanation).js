/**
 * @param {number[][]} matrix
 * @return {number[]}
 *
 * luckyNumbers принимает матрицу размером m x n, состоящая из различных
 * чисел.
 *
 * Возвращает все "счастливые" числа в матрице в любом порядке.
 *
 * "Счастливое" число - это элемент матрицы, который является минимальным в
 * своей строке и максимальным в своём столбце.
 *
 *
 * Пример для:
 *   matrix = [[3,7,8],[9,11,13],[15,16,17]]
 * Результат:
 *   [15]
 * Пояснение:
 *   15 - единственное счастливое число, так как оно является минимальным в
 *   своей строке и максимальным в своём столбце.
 */
function luckyNumbers(matrix) {

  // Основная идея алгоритма строится на математическом свойстве матриц с
  // уникальными числами: в любой такой матрице может существовать максимум
  // одно "счастливое" число.
  //
  // Доказательство:
  // Предположим, что в матрице есть два "счастливых" числа: X (в строке r1,
  // столбце c1) и Y (в строке r2, столбце c2).
  // Возьмём элемент Z на пересечении строки r1 и столбца c2.
  // Так как X - минимум в строке r1, а все числа разные, то X < Z.
  // Так как Y - максимум в столбце c2, а все числа разные, то Z < Y.
  // Получаем цепочку неравенств: X < Z < Y, следовательно, X < Y.
  // Аналогично, рассмотрев элемент W на пересечении строки r2 и столбца c1,
  // мы получим обратное неравенство: Y < W < X, следовательно, Y < X.
  // Одновременно X < Y и Y < X невозможно, значит, двух "счастливых" чисел
  // существовать не может.
  //
  // Следствие для алгоритма:
  // 1. Поскольку "счастливое" число - это минимум в своей строке и
  //    максимум в столбце, оно обязано быть наибольшим среди всех строчных
  //    минимумов (иначе максимум его столбца был бы больше него, что
  //    противоречит условию).
  //
  // 2. Вместо того чтобы хранить все минимумы строк в дополнительном
  //    массиве (тратя O(m) памяти), мы за первый проход находим только
  //    один потенциальный кандидат - максимум среди минимумов всех строк
  //    (maxOfRowMins).
  //
  // 3. За второй проход мы вычисляем максимум для каждого столбца (colMax).
  //    Как только максимум какого-либо столбца совпадает с нашим
  //    кандидатом maxOfRowMins, мы нашли единственно возможное "счастливое"
  //    число и сразу возвращаем его.
  //
  // 4. Такой подход позволяет решить задачу за O(m * n) по времени и с
  //    константной дополнительной памятью O(1).


  // Получаем общее количество строк в матрице (длину внешнего массива) и
  // сохраняем в константу ROWS.
  const ROWS = matrix.length;

  // Получаем общее количество столбцов в матрице (длину первого
  // внутреннего массива, так как матрица прямоугольная) и сохраняем в
  // константу COLS.
  const COLS = matrix[0].length;

  // Создаём переменную maxOfRowMins для хранения наибольшего значения
  // среди минимальных элементов каждой строки.
  //
  // Начинаем с -Infinity, чтобы любое первое найденное число
  // гарантированно перезаписало это начальное значение.
  let maxOfRowMins = -Infinity;

  // Запускаем внешний цикл, чтобы последовательно обойти каждую строку
  // матрицы сверху вниз.
  for (let r = 0; r < ROWS; r++) {

    // Инициализируем переменную rowMin значением самого первого элемента
    // (с индексом 0) текущей строки r, принимая его за временный минимум.
    let rowMin = matrix[r][0];

    // Запускаем внутренний цикл, чтобы найти минимальное значение текущей
    // строки.
    for (let c = 0; c < COLS; c++) {

      // С помощью встроенного метода Math.min сравниваем текущий найденный
      // минимум строки rowMin с очередным элементом matrix[r][c] и
      // сохраняем меньшее из двух чисел.
      rowMin = Math.min(rowMin, matrix[r][c]);
    }


    // После полного прохода по строке r сравниваем её итоговый минимум
    // rowMin с глобальным максимумом среди минимумов maxOfRowMins и
    // сохраняем большее значение.
    maxOfRowMins = Math.max(maxOfRowMins, rowMin);
  }

  // Запускаем второй внешний, чтобы обойти матрицу по столбцам слева
  // направо.
  for (let c = 0; c < COLS; c++) {

    // Инициализируем переменную colMax значением самого верхнего элемента
    // (из строки с индексом 0) текущего столбца c, принимая его за
    // временный максимум.
    let colMax = matrix[0][c];

    // Запускаем внутренний цикл по индексу, чтобы найти максимальное
    // значение текущего столбца.
    for (let r = 0; r < ROWS; r++) {

      // С помощью метода Math.max сравниваем текущий максимум столбца
      // colMax с очередным элементом matrix[r][c] и сохраняем большее из
      // двух чисел.
      colMax = Math.max(colMax, matrix[r][c]);
    }

    // По законам математики в матрице с уникальными числами счастливое
    // число может быть только одно.
    //
    // Если максимум столбца равен максимуму из минимумов строк, мы нашли
    // ответ - сразу возвращаем его в виде массива
    if (colMax === maxOfRowMins) return [colMax];
  }

  // Если мы проверили все столбцы и ни один максимум столбца не совпал с
  // maxOfRowMins, значит "счастливых" чисел в данной матрице не существует
  // - возвращаем пустой массив
  return [];
}
