/**
 * @param {number[][]} grid
 * @return {number}
 *
 * projectionArea принимает двумерный массив размером n x n, на котором мы
 * размещаем несколько кубиков размером 1 x 1 x 1. Все кубики расположены
 * параллельно осям x, y и z.
 *
 * Каждое значение v = grid[i][j] обозначает башню из v кубиков,
 * расположенных друг на друге в ячейке (i, j).
 *
 * Мы рассматриваем проекции этих кубов на плоскости xy, yz и zx.
 *
 * Проекция - это своего рода тень, которая отображает нашу трёхмерную
 * фигуру на двумерную плоскость. Иными словами, мы смотрим на кубики
 * сверху, спереди и сбоку.
 *
 * Возвращает суммарную площадь всех трёх проекций.
 *
 *
 * Пример для:
 *   grid = [[1, 2], [3, 4]]
 * Результат:
 *   17
 * Пояснение:
 *   Ниже представлены три проекции («тени») фигуры на соответствующие
 *   плоскости.
 *
 *
 * Пример для:
 *   grid = [[2]]
 * Результат:
 *   5
 *
 *
 * Пример для:
 *   grid = [[1, 0], [0, 2]]
 * Результат:
 *   8
 */
function projectionArea(grid) {

  // Чтобы понять, как решить эту задачу, давайте разберёмся, что именно
  // представляет собой каждая проекция.
  //
  // Когда мы смотрим на трёхмерную конструкцию под разными углами, мы
  // фактически отображаем её на двумерную плоскость. Главное - понять,
  // какую информацию содержит каждая проекция.
  //
  // 1. Вид сверху (плоскость xy):
  //    Когда мы смотрим сверху, высота кубиков нам не видна. Мы можем
  //    увидеть только то, занята ячейка или нет. Это похоже на вид здания
  //    со спутника, когда мы видим его основание.
  //
  //    Каждая занятая ячейка даёт ровно 1 единицу площади, независимо от
  //    высоты башни.
  //
  //    Поэтому нам нужно просто посчитать количество ячеек, в которых
  //    grid[i][j] > 0.
  //
  // 2. Вид спереди (плоскость yz):
  //    Когда мы смотрим спереди, мы видим силуэт каждой строки. Высота
  //    самой высокой башни в строке определяет высоту её тени.
  //
  //    Представьте, что вы смотрите на городской пейзаж спереди:
  //    для каждой строки зданий только самое высокое здание определяет
  //    верхнюю границу силуэта.
  //
  //    Поэтому нам нужно найти максимальное значение в каждой строке и
  //    сложить все найденные максимумы.
  //
  // 3. Вид сбоку (плоскость zx):
  //    Аналогично, когда мы смотрим сбоку, мы видим силуэт каждого столбца.
  //
  //    Высота самой высокой башни в столбце определяет высоту его тени.
  //
  //    Поэтому нам нужно найти максимальное значение в каждом столбце и
  //    сложить все найденные максимумы.
  //
  //    Преимущество такого подхода заключается в том, что мы можем
  //    вычислить каждую проекцию независимо, а затем просто сложить
  //    полученные площади.
  //
  //    Нам не нужно создавать настоящую трёхмерную модель. Достаточно
  //    извлечь необходимую информацию из двумерного массива, который
  //    хранит высоты башен.
  //
  // Таким образом, решение сводится к следующему:
  // - Один раз проходим по массиву и считаем количество ненулевых
  //   элементов для проекции xy (вид сверху).
  //
  // - Находим максимальное значение в каждой строке и складываем их для
  //   проекции yz (вид спереди).
  //
  // - Находим максимальное значение в каждом столбце и складываем их для
  //   проекции zx (вид сбоку).


  const n = grid.length;

  // Переменная будет накапливать площадь проекции на горизонтальную
  // плоскость xy (тень при взгляде строго сверху: каждая непустая ячейка
  // дает 1 единицу площади)
  let xy = 0;

  // Переменная будет накапливать площадь проекции на вертикальную
  // плоскость yz (тень при взгляде сбоку, вдоль строк: определяется самой
  // высокой башней в каждой строке, так как более низкие башни в этой
  // строке полностью скрываются в ее тени)
  let yz = 0;

  // Переменная будет накапливать площадь проекции на вертикальную
  // плоскость zx (тень при взгляде спереди, вдоль столбцов: определяется
  // самой высокой башней в каждом столбце, так как более низкие башни в
  // этом столбце также полностью перекрываются)
  let zx = 0;

  // Запускаем внешний цикл со счетчиком, для обхода строк и столбцов
  for (let i = 0; i < n; i++) {

    // Инициализируем локальную переменную для поиска максимальной высоты
    // башни в текущей строке i
    let maxHeightInRow = 0;

    // Инициализируем локальную переменную для поиска максимальной высоты
    // башни в текущем столбце i
    let maxHeightInCol = 0;

    // Запускаем внутренний цикл от 0 до n - 1, чтобы последовательно
    // пройти по всем ячейкам внутри выбранной строки i и выбранного
    // столбца i.
    for (let j = 0; j < n; j++) {

      // Проверяем, есть ли в ячейке с координатами [i][j] хотя бы один куб
      // (значение строго больше нуля).
      //
      // Если да, увеличиваем площадь вида сверху (xy) на 1, так как высота
      // башни сверху не видна.
      if (grid[i][j] > 0) xy++;

      // Сравниваем текущий найденный максимум строки с высотой башни в
      // ячейке [i][j] (идем слева направо по строке i) и сохраняем
      // наибольшее значение
      maxHeightInRow = Math.max(maxHeightInRow, grid[i][j]);

      // Сравниваем текущий найденный максимум столбца с высотой башни в
      // ячейке [j][i] (меняем индексы местами, чтобы идти сверху вниз по
      // столбцу i) и сохраняем наибольшее значение
      maxHeightInCol = Math.max(maxHeightInCol, grid[j][i]);
    }

    // После прохода по всей строке i добавляем высоту её самой высокой
    // башни к площади боковой проекции yz, так как более низкие башни в
    // этой строке полностью скрываются в ее тени
    yz += maxHeightInRow;

    // После прохода по всему столбцу i добавляем высоту его самой высокой
    // башни к площади фронтальной проекции zx, так как более низкие башни
    // в этом столбце также полностью перекрываются
    zx += maxHeightInCol;
  }

  // Суммируем вычисленные площади всех трех проекций (вид сверху, вид
  // сбоку и вид спереди) и возвращаем итоговый результат
  return xy + yz + zx;
}
