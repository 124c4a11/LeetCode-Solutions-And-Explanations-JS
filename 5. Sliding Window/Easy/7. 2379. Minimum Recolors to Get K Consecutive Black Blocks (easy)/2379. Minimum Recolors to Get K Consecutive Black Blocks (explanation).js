/**
 * @param {string} blocks
 * @param {number} k
 * @return {number}
 *
 * minimumRecolors принимает строку blocks с 0-индексацией длины n, где
 * blocks[i] равен либо 'W', либо 'B', что представляет собой цвет i-го
 * блока. Символы 'W' и 'B' обозначают белый и черный цвета соответственно.
 *
 * Также принимает целое число k, которое является желаемым количеством
 * последовательных черных блоков.
 *
 * За одну операцию вы можете перекрасить белый блок так, чтобы он стал
 * черным блоком.
 *
 * Возвращает минимальное количество операций, необходимых для того, чтобы
 * появилась хотя бы одна последовательность из k подряд идущих черных
 * блоков.
 *
 *
 * Пример для:
 *   blocks = "WBBWWBBWBW",
 *   k = 7
 * Результат:
 *   3
 * Пояснение:
 *   Один из способов получить 7 последовательных черных блоков —
 *   перекрасить 0-й, 3-й и 4-й блоки, чтобы строка blocks стала равной
 *   "BBBBBBBWBW".
 *
 *   Можно доказать, что невозможно получить 7 последовательных черных
 *   блоков менее чем за 3 операции.
 *
 *   Следовательно, мы возвращаем 3.
 */
function minimumRecolors(blocks, k) {

  // Создаем переменную для хранения минимального числа перекрашиваний.
  //
  // Изначально устанавливаем её равной k, так как в самом худшем случае
  // (если подряд идут только k белых блоков) нам придется перекрасить все
  // k элементов.
  //
  // Более k перекрашиваний сделать невозможно.
  let minRecolors = k;

  // Создаем счетчик whiteCnt, который будет в реальном времени отслеживать
  // точное количество белых блоков ('W') внутри текущего активного окна
  // фиксированной длины k.
  let whiteCnt = 0;

  // Инициализируем переменную l (left), представляющую собой индекс левой
  // (начальной) границы скользящего окна.
  //
  // В начале алгоритма она указывает на самый первый символ (индекс 0).
  let l = 0;

  // Запускаем цикл по всей строке blocks.
  //
  // Переменная r (right) выступает в роли правой (конечной) границы
  // скользящего окна, которая на каждой итерации сдвигается вправо на один
  // шаг.
  for (let r = 0; r < blocks.length; r++) {

    // Если новый элемент, который только что вошел в окно справа
    // (по индексу r), является белым блоком ('W'), то увеличиваем счетчик
    // белых блоков внутри текущего окна на единицу.
    if (blocks[r] === 'W') whiteCnt++;

    // Проверяем равна ли текущая ширина окна (вычисляемая как правый
    // индекс минус левый индекс плюс один) целевому значению k.
    //
    // Если да, значит окно полностью сформировано.
    if (r - l + 1 === k) {

      // Обновляем минимальное количество перекрашиваний, выбирая
      // наименьшее значение между старым минимумом и количеством 'W' в
      // текущем окне.
      minRecolors = Math.min(minRecolors, whiteCnt);

      // Так как на следующей итерации окно сдвинется вправо, символ под
      // индексом l выйдет из него.
      //
      // Если этот покидающий окно символ был белым ('W'), мы убираем его
      // из текущего счетчика белых блоков.
      if (blocks[l] === 'W') whiteCnt--;

      // Сдвигаем левую границу окна на один символ вправо.
      //
      // Это уменьшает ширину окна обратно до (k - 1), чтобы на следующем
      // шаге цикла, когда r увеличится, окно снова стало ровно размера k.
      //
      // Это действие в сочетании с шагом r++ в цикле позволяет окну
      // "скользить" по строке, сохраняя свою постоянную ширину, равную k.
      l++;
    }
  }

  // После того как правая граница r дошла до конца строки и были проверены
  // все возможные подстроки длины k, возвращаем найденное минимальное
  // количество необходимых перекрашиваний для получения k подряд идущих
  // черных блоков.
  return minRecolors;
}
