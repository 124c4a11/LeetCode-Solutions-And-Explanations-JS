/**
 * @param {number[]} nums
 * @param {number} k
 * @return {number}
 *
 * minimumDifference принимает целочисленный массив nums с индексацией
 * от 0, где nums[i] обозначает количество баллов, набранных i-м учеником.
 * Также дано целое число k.
 *
 * Выбирает из массива баллы любых k учеников таким образом, чтобы разница
 * между максимальным и минимальным значениями среди выбранных баллов была
 * минимальной.
 *
 * Возвращает минимально возможную разницу.
 *
 *
 * Пример для:
 *   nums = [9, 4, 1, 7],
 *   k = 2
 * Результат:
 *   2
 * Пояснение:
 * Существует шесть способов выбрать баллы двух учеников:
 * - [9, 4]: разница между максимальным и минимальным значениями: 9 - 4 = 5.
 * - [9, 1]: разница между максимальным и минимальным значениями: 9 - 1 = 8.
 * - [9, 7]: разница между максимальным и минимальным значениями: 9 - 7 = 2.
 * - [4, 1]: разница между максимальным и минимальным значениями: 4 - 1 = 3.
 * - [7, 4]: разница между максимальным и минимальным значениями: 7 - 4 = 3.
 * - [7, 1]: разница между максимальным и минимальным значениями: 7 - 1 = 6.
 *
 * Минимально возможная разница равна 2.
 */
function minimumDifference(nums, k) {

  // Ключевая идея заключается в том, что для минимизации разницы между
  // максимальным и минимальным баллами необходимо выбрать такие значения,
  // которые находятся как можно ближе друг к другу.
  //
  // Представим, что все баллы расположены на числовой прямой.
  // Если мы случайным образом выберем k баллов, они могут оказаться
  // далеко друг от друга. Но если выбрать k значений, расположенных
  // максимально близко друг к другу, разница между максимальным
  // и минимальным значениями будет меньше.
  //
  // Отсюда следует важный вывод: после сортировки массива оптимальный
  // набор обязательно будет состоять из k последовательных элементов.
  //
  // Почему?
  // Рассмотрим любой набор из k элементов отсортированного массива.
  // Если выбранные элементы не являются последовательными, между ними
  // существуют пропуски.
  //
  // Мы можем заменить максимальный элемент на меньшее значение,
  // заполнив один из пропусков, или заменить минимальный элемент
  // на большее значение.
  //
  // В результате разница между максимальным и минимальным значениями
  // либо уменьшится, либо останется прежней - но никогда не увеличится.
  //
  // Например, если у нас есть отсортированный массив баллов
  // [1, 3, 5, 7, 9] и k = 3:
  //
  // - Выбираем непоследовательные элементы [1, 5, 9]:
  //   разница = 9 - 1 = 8.
  //
  // - Выбираем последовательные элементы [5, 7, 9]:
  //   разница = 9 - 5 = 4.
  //
  // Как только мы понимаем, что нужно выбирать последовательные
  // элементы отсортированного массива, решение становится простым.
  //
  // Необходимо перемещать скользящее окно размером k по отсортированному
  // массиву и находить окно, в котором разница между последним
  // и первым элементами минимальна.
  //
  // Для каждого допустимого начального индекса i вычисляем:
  //
  // nums[i + k - 1] - nums[i]
  //
  // Минимальное значение среди всех таких разниц и будет ответом.


  const n = nums.length;

  // Сортируем массив на месте по возрастанию.
  //
  // Сортировка нужна для того, чтобы k наиболее близких по значению оценок
  // оказались в массиве непрерывно друг за другом, образуя компактные
  // группы.
  nums.sort((a, b) => a - b);

  // Инициализируем переменную для хранения глобального минимума.
  //
  // Метод .at(-1) возвращает последний (самый большой после сортировки)
  // элемент массива, а nums[0] - первый (самый маленький).
  //
  // Разность между ними - это максимально возможная разница в массиве,
  // которая служит надежной стартовой точкой для поиска меньших значений.
  let minDiff = nums.at(-1) - nums[0];

  // Запускаем цикл, реализующий метод "скользящего окна" фиксированной
  // длины k.
  //
  // Индекс i указывает на начало текущего окна (минимум).
  //
  // Условие i + k - 1 < n гарантирует, что правая граница окна
  // (индекс i + k - 1, соответствующий максимуму) не выйдет за пределы
  // массива.
  for (let i = 0; i + k - 1 < n; i++) {

    // Вычисляем разницу между наибольшим элементом текущего окна
    // (находящимся на индексе i + k - 1) и наименьшим элементом этого же
    // окна (находящимся на индексе i).
    //
    // Так как массив отсортирован, это и есть разница между max и min для
    // данных k студентов.
    const currDiff = nums[i + k - 1] - nums[i];

    // Сравниваем текущую найденную разницу (currDiff) с уже известным
    // минимумом (minDiff) и перезаписываем minDiff, если текущая оказалась
    // меньше
    minDiff = Math.min(minDiff, currDiff);
  }

  // Возвращаем итоговый наименьший результат разницы баллов среди всех
  // возможных последовательных групп по k студентов
  return minDiff;
}
