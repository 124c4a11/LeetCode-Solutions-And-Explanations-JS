/**
 * @param {string} s
 * @param {number} k
 * @return {number}
 *
 * countRotations принимает строку s длины n и целое число k.
 *
 * Циклическое вращение строки s достигается путем выбора префикса строки s,
 * длина которого находится в диапазоне от 0 до n - 1 (включительно), и
 * перемещения его в конец строки с сохранением порядка всех символов.
 *
 * Для каждого циклического сдвига s функция определяет его оценку -
 * количество индексов i, для которых 0 <= i < n - 1 и символы на позициях
 * i и i + 1 совпадают.
 *
 * Возвращает количество циклических сдвигов строки s, оценка которых равна
 * k.
 *
 *
 * Пример для:
 *   s = "aab",
 *   k = 1
 * Результат:
 *   2
 * Пояснение:
 * Циклические сдвиги строки s:
 *   "aab": символы на позициях 0 и 1 совпадают, поэтому оценка равна 1.
 *   "aba": соседние символы не совпадают, поэтому оценка равна 0.
 *   "baa": символы на позициях 1 и 2 совпадают, поэтому оценка равна 1.
 *
 *   Оценка равна k для двух циклических сдвигов, поэтому ответ - 2.
 */
function countRotations(s, k) {

  // Этот подход работает и позволяет решить задачу за оптимальное линейное
  // время O(n) благодаря концепции скользящего окна (Sliding Window) на
  // циклической строке.
  //
  // Вместо того чтобы честно создавать каждую из n новых строк (что заняло
  // бы O(n^2) времени), алгоритм пересчитывает оценку динамически,
  // отслеживая только изменения на границах.
  //
  // Вот ключевые причины, почему этот подход корректен и эффективен:
  //
  // 1. Идея циклического "кругового" массива
  //
  // Любой циклический сдвиг строки - это просто перемещение взгляда по
  // кругу. Если мы мысленно замкнем строку в кольцо, то при сдвиге на один
  // символ влево:
  // - Первый символ s[i] уходит из начала.
  // - Этот же символ s[i] встает в самый конец.
  //
  // С помощью операции остатка от деления (% n) код имитирует это кольцо,
  // не создавая новые подстроки в памяти.
  //
  // 2. Пересчет оценки за O(1) вместо полного перебора
  //
  // Внутри цикла for (let i = 0; i < n; i++) мы переходим от текущего
  // циклического сдвига к следующему. При таком переходе вся центральная
  // часть строки остается неизменной, а значит, внутренние пары символов
  // не меняются. Изменения происходят только в двух местах:
  // - Разрушение старой пары: Символ s[i] отделяется от своего соседа
  //   справа s[(i + 1) % n]. Если они были одинаковыми, эта пара больше не
  //   существует в новом сдвиге, и мы делаем score--.
  //
  // - Формирование новой пары: Символ s[i], переместившись в конец,
  //   становится вплотную к символу, который в круговом массиве находится
  //   "левее" него - это s[(i - 1 + n) % n]. Если они одинаковы,
  //   формируется новая пара, и мы делаем score++.
  //
  // 3. Инвариант цикла
  //
  // Строка if (score === k) cyclicRotationsCnt++; находится в самом начале
  // цикла. Это гарантирует, что мы проверяем оценку текущего сдвига до
  // того, как пересчитаем её для следующего шага. Таким образом, за ровно
  // n итераций алгоритм безошибочно проверит все n возможных циклических
  // сдвигов.
  //
  // Хотите посмотреть на конкретный пример (например, со строкой "aab"),
  // чтобы увидеть, как именно формулы (i + 1) % n и (i - 1 + n) % n
  // находят правильных соседей на стыках строки?


  const n = s.length;

  // Объявляем изменяемую переменную-счетчик, которая будет хранить
  // количество пар одинаковых соседних элементов для текущего состояния
  // строки
  let score = 0;

  // Запускаем цикл от 0 до n-2 включительно для первичного подсчета
  // совпадений в исходной (еще не сдвинутой) строке s
  for (let i = 0; i < n - 1; i++) {

    // Если текущий символ строго равен идущему сразу за ним, то эта пара
    // вносит вклад в score
    if (s[i] === s[i + 1]) score++;
  }

  // Создаем переменную-аккумулятор для подсчета количества успешных
  // циклических сдвигов, у которых финальный score окажется равен k
  let cyclicRotationsCnt = 0;

  // Итерируемся ровно n раз, моделируя последовательный перенос символов
  // из начала строки в её конец (один шаг за итерацию)
  for (let i = 0; i < n; i++) {

    // Выполняем валидацию текущего состояния:
    //
    // Если накопленный балл (score) в точности равен целевому k,
    // регистрируем этот сдвиг как успешный
    if (score === k) cyclicRotationsCnt++;

    // Символ s[i] ("уходящий" из начала строки элемент) больше не будет
    // соседствовать со следующим элементом s[(i + 1) % n], поэтому если
    // они были равны, мы вычитаем 1 из score
    if (s[i] === s[(i + 1) % n]) score--;

    // Этот же символ s[i] теперь перемещается в самый конец строки и
    // становится справа от предыдущего "хвоста" s[(i + n - 1) % n].
    //
    // Если они равны, увеличиваем score на 1
    if (s[(i + n - 1) % n] === s[i]) score++;
  }

  // Возвращаем итоговое накопленное количество циклических сдвигов строки,
  // у которых score оказался строго равен значению k
  return cyclicRotationsCnt;
}
