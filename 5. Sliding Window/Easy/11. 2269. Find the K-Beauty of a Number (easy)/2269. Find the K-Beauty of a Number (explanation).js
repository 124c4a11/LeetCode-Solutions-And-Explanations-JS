/**
 * @param {number} num
 * @param {number} k
 * @return {number}
 *
 * divisorSubstrings принимает целые числа num и k.
 *
 * Возвращает k-красоту числа num.
 *
 * k-красота целого числа num определяется как количество подстрок числа
 * num (если рассматривать его как строку), которые удовлетворяют следующим
 * условиям:
 * 1. Подстрока имеет длину k.
 * 2. Подстрока является делителем числа num.
 *
 * Примечание:
 * - Ведущие нули допускаются.
 * - 0 не является делителем ни одного числа.
 * - Подстрока - это непрерывная последовательность символов в строке.
 *
 *
 * Пример для:
 *   num = 240,
 *   k = 2
 * Результат:
 *   2
 * Пояснение:
 * Ниже приведены подстроки числа num длины k:
 * - "24" из "240": 24 является делителем 240.
 *            ^^
 * - "40" из "240": 40 является делителем 240.
 *             ^^
 * Таким образом, k-красота равна 2.
 */
function divisorSubstrings(num, k) {

  // Приводим число к строковому типу, чтобы использовать строковые методы
  // для выделения подстрок фиксированной длины
  const numStr = num.toString();

  // Создаем счетчик kBeauty, который будет инкрементироваться каждый раз
  // при нахождении валидного делителя
  let kBeauty = 0;

  // Начинаем перебор всех возможных начальных позиций подстрок.
  //
  // Ограничение numStr - k гарантирует, что при взятии подстроки длины k
  // мы не выйдем за пределы конца строки.
  for (let i = 0; i <= numStr.length - k; i++) {

    // Метод slice(i, i + k) вырезает из строки numStr порцию символов
    // начиная с индекса i (включительно) до индекса i + k (не включая его).
    //
    // Функция Number() превращает эту вырезанную строку обратно в число
    // (при этом ведущие нули, например "04", автоматически отбрасываются и
    // превращаются в 4).
    const currNum = Number(numStr.slice(i, i + k));

    // Если текущее число currNum строго не равно нулю (это критически
    // важно, так как в математике деление на ноль не определено, а в JS
    // операция % 0 вернула бы значение NaN) и если исходное число num
    // делится на currNum без остатка, увеличиваем счетчик k-красоты на 1
    if (
      currNum !== 0
      && num % currNum === 0
    ) kBeauty++;
  }

  // После завершения цикла и проверки всех подстрок возвращаем накопленное
  // итоговое количество делителей
  return kBeauty;
}
