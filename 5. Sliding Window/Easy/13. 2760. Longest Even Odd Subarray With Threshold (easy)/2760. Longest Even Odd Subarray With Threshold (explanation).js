/**
 * @param {number[]} nums
 * @param {number} threshold
 * @return {number}
 *
 * longestAlternatingSubarray принимает целочисленный массив nums с
 * индексацией с 0 и целое число threshold.
 *
 * Функция находит длину самого длинного подмассива массива nums, который
 * начинается с индекса l и заканчивается индексом r
 * (0 <= l <= r < nums.length) и удовлетворяет следующим условиям:
 * 1. Первый элемент подмассива должен быть чётным:
 *    nums[l] % 2 == 0
 *
 * 2. Чётность соседних элементов должна чередоваться:
 *    Для всех индексов i в диапазоне [l, r - 1]:
 *    nums[i] % 2 != nums[i + 1] % 2
 *
 * 3. Все элементы подмассива должны быть меньше или равны threshold:
 *    Для всех индексов i в диапазоне [l, r]:
 *    nums[i] <= threshold
 *
 * Возвращает целое число, обозначающее длину самого длинного подмассива,
 * удовлетворяющего всем перечисленным условиям.
 *
 * Примечание: подмассив (subarray) - это непустая непрерывная
 * последовательность элементов внутри массива.
 *
 * Пример для:
 *   nums = [3, 2, 5, 4],
 *   threshold = 5
 * Результат:
 *   3
 * Пояснение:
 *   В данном примере можно выбрать подмассив, который начинается с l = 1 и
 *   заканчивается r = 3:
 *   [2, 5, 4]
 *
 *   Этот подмассив удовлетворяет всем условиям:
 *   - Первый элемент (2) является чётным.
 *
 *   - Чётность соседних элементов чередуется: 2 (чётное), 5 (нечётное),
 *     4 (чётное).
 *
 *   - Все элементы меньше или равны threshold (5).
 *
 *   Следовательно, ответ равен длине этого подмассива - 3.
 */
function longestAlternatingSubarray(nums, threshold) {
  const n = nums.length;

  // Создаем переменную-аккумулятор maxLength и инициализируем её нулем.
  //
  // В ней будет храниться наибольшая длина корректного подмассива,
  // найденная в процессе работы алгоритма
  let maxLength = 0;

  // Запускаем внешний цикл fоr, где переменная l выступает в роли левой
  // (начальной) границы исследуемого в данный момент подмассива
  for (let l = 0; l < n; l++) {

    // Начинаем проверку составного логического условия, чтобы определить,
    // может ли текущий элемент по индексу l быть началом валидного
    // подмассива
    if (

      // Проверяем первый критерий: является ли элемент nums[l] нечетным
      // (остаток от деления на 2 не равен нулю)
      nums[l] % 2 !== 0

      // Проверяем второй критерий через логическое ИЛИ: превышает ли
      // значение элемента nums[l] допустимый порог threshold
      || nums[l] > threshold

      // Если элемент nums[l] нечетный ИЛИ больше threshold, то данный
      // индекс l не подходит для старта.
      //
      // Инструкция continue немедленно завершает текущую итерацию внешнего
      // цикла и переходит к l++
    ) continue;

    // Если элемент nums[l] успешно прошел проверки
    // (он четный и <= threshold), инициализируем переменную r (правую
    // границу) значением l + 1 для проверки последующих элементов
    let r = l + 1;

    // Запускаем внутренний цикл while, который будет последовательно
    // сдвигать правую границу r и проверять элементы на соответствие
    // правилам задачи
    while (

      // Базовое условие безопасности: проверяем, что индекс r строго
      // меньше n, то есть мы все еще находимся в границах массива и не
      // вышли за его пределы
      r < n

      // Условие чередования: проверяем, что остаток от деления
      // nums[r] на 2 не равен остатку от деления nums[r - 1] на 2
      // (гарантируем строгое чередование четности соседних элементов)
      && nums[r] % 2 !== nums[r - 1] % 2

      // Ограничение по величине: проверяем, что текущий элемент подмассива
      // под индексом r не превышает заданное максимальное значение
      // threshold
      && nums[r] <= threshold

      // Если все три условия в блоке while одновременно истинны,
      // инкрементируем (увеличиваем на 1) переменную r, тем самым расширяя
      // текущий подмассив вправо
    ) r++;

    // После выхода из цикла while вычисляем длину текущего найденного
    // подмассива по формуле (r - l), сравниваем её с текущим maxLength и
    // сохраняем наибольшее значение
    maxLength = Math.max(maxLength, r - l);
  }

  // Возвращаем итоговое значение переменной maxLength, которое содержит
  // длину самого длинного подмассива, удовлетворившего всем условиям
  // задачи
  return maxLength;
}
