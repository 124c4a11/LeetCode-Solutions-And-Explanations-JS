/**
 * @param {number[]} nums
 * @param {number} indexDifference
 * @param {number} valueDifference
 * @return {number[]}
 *
 * findIndices принимает целочисленный массив nums с нумерацией элементов с
 * нуля и длиной n, целые числа indexDifference и valueDifference.
 *
 * Находит два индекса i и j в диапазоне [0, n - 1], которые удовлетворяют
 * условиям:
 * - abs(i - j) >= indexDifference и
 * - abs(nums[i] - nums[j]) >= valueDifference
 *
 * Возвращает целочисленный массив [i, j], если такие индексы существуют,
 * или [-1, -1] в противном случае.
 *
 * Примечание: i и j могут совпадать.
 *
 *
 * Пример для:
 *   nums = [5,1,4,1],
 *   indexDifference = 2,
 *   valueDifference = 4
 * Результат:
 *   [0,3]
 * Пояснение:
 *   В этом примере можно выбрать i = 0 и j = 3.
 *
 *   |0 - 3| >= 2 и |nums[0] - nums[3]| >= 4.
 *
 *   Следовательно, допустимый ответ - [0,3].
 *
 *   [3,0] также является допустимым ответом.
 */
function findIndices(nums, indexDifference, valueDifference) {

  // Ключевая идея в том, что для любого индекса i нужно найти индекс j,
  // такой что abs(i - j) >= indexDifference и
  // abs(nums[i] - nums[j]) >= valueDifference.
  //
  // Рассмотрим это системно. Для фиксированного i все допустимые j должны
  // находиться на расстоянии не менее indexDifference от i. Это означает,
  // что при i >= indexDifference нас интересуют индексы в диапазоне
  // [0, i - indexDifference].
  //
  // Для условия по значениям abs(nums[i] - nums[j]) >= valueDifference нам
  // нужно максимизировать абсолютную разницу. Абсолютная разница
  // максимальна, если nums[i] сопоставить либо с:
  // - минимальным значением в допустимом диапазоне (чтобы максимизировать
  //   nums[i] - nums[j], когда nums[i] велик),
  //
  // - либо с максимальным значением в допустимом диапазоне (чтобы
  //   максимизировать nums[j] - nums[i], когда nums[i] мал).
  //
  // Отсюда вытекает основная стратегия: при проходе по массиву по индексу
  // i достаточно хранить два значения из допустимого диапазона
  // [0, i - indexDifference]:
  // - индекс минимального элемента (mi)
  // - индекс максимального элемента (mx)
  //
  // Почему этого достаточно? Потому что если существует допустимая пара с
  // индексом i, то она обязательно включает либо минимальное, либо
  // максимальное значение из допустимого диапазона. Любое другое значение
  // даст меньшую абсолютную разницу, поэтому проверка только этих двух
  // экстремумов достаточна.
  //
  // Из этого естественно возникает скользящее окно. По мере продвижения i
  // допустимый диапазон расширяется за счёт включения элемента на позиции
  // i - indexDifference. Мы обновляем индексы минимума и максимума, если
  // новый элемент меньше или больше текущих экстремумов, а затем проверяем,
  // образует ли какой-либо из экстремумов допустимую пару с nums[i].
  //
  // Таким образом задача сводится от проверки всех пар (O(n²)) к проверке
  // только двух пар на каждой позиции (O(n)).


  // Инициализация индекса минимального элемента среди уже "доступных"
  // предыдущих элементов.
  //
  // Начальное значение 0 означает, что до тех пор, пока не появится первый
  // допустимый prevNdx, мы считаем за минимум элемент с индексом 0.
  let minPrevNumNdx = 0;

  // Инициализация индекса максимального элемента среди уже "доступных"
  // предыдущих элементов.
  //
  // Аналогично, начальное значение 0 - запасной вариант до появления
  // реальных допустимых prevNdx.
  let maxPrevNumNdx = 0;

  // Запускаем цикл по i, начиная с indexDifference и до конца массива nums.
  //
  // Мы начинаем с indexDifference, потому что только при
  // i >= indexDifference существует индекс prevNdx = i - indexDifference,
  // который удовлетворяет условию по минимальному расстоянию между
  // индексами (т.е. хотя бы один допустимый предыдущий индекс).
  for (let i = indexDifference; i < nums.length; i++) {

    // prevNdx - индекс нового элемента, который только что стал входить в
    // допустимую область [0, i - indexDifference].
    //
    // При каждом увеличении i в допустимую область добавляется ровно один
    // новый индекс - (i - indexDifference).
    const prevNdx = i - indexDifference;

    // prevNum - значение массива nums на позиции prevNdx.
    //
    // Это значение мы сравниваем с текущими экстремумами.
    const prevNum = nums[prevNdx];

    // num - значение текущего элемента nums[i], с которым будем сравнивать
    // экстремумы из допустимого диапазона.
    const num = nums[i];

    // Если значение нового предыдущего элемента меньше значения по индексу
    // minPrevNumNdx, то он становится новым минимумом в области
    // [0, i - indexDifference].
    //
    // Это поддерживает инвариант:
    // nums[minPrevNumNdx] - минимальное значение среди элементов с
    // индексами в [0, i - indexDifference].
    if (prevNum < nums[minPrevNumNdx]) minPrevNumNdx = prevNdx;

    // Если предыдущее условие не сработало, проверяем, не является ли
    // новый элемент новым максимумом.
    //
    // Если prevNum больше текущего максимума nums[maxPrevNumNdx],
    // обновляем индекс максимума.
    //
    // Важно:
    // Используем else if, чтобы при равенстве значений не перезаписывать
    // максимум (можно оставить старый индекс).
    else if (prevNum > nums[maxPrevNumNdx]) maxPrevNumNdx = prevNdx;

    // Проверяем первую из двух возможных пар, которые могут дать
    // достаточную абсолютную разницу по значениям:
    //
    // Если текущий элемент num значительно больше минимального элемента в
    // префиксе, то разность num - nums[minPrevNumNdx] - это именно
    // abs(nums[i] - nums[j]) в случае nums[i] >= nums[j].
    //
    // Если разница >= valueDifference, то найдено допустимое сочетание
    // индексов: [minPrevNumNdx, i] - возвращаем найденную пару индексов
    if (num - nums[minPrevNumNdx] >= valueDifference) {
      return [minPrevNumNdx, i];
    }

    // Проверяем вторую возможную пару:
    //
    // Если максимальный элемент префикса значительно больше текущего
    // элемента, то nums[maxPrevNumNdx] - num - это abs(nums[i] - nums[j])
    // в случае nums[j] >= nums[i].
    //
    // Если разница >= valueDifference, возвращаем пару [maxPrevNumNdx, i].
    if (nums[maxPrevNumNdx] - num >= valueDifference) {
      return [maxPrevNumNdx, i];
    }
  }

  // Если цикл завершился и ни одна из проверок не вернула результат,
  // значит ни для одного i не нашлось j в допустимом префиксе,
  // удовлетворяющего обоим условиям.
  //
  // Возвращаем [-1, -1] как индикатор отсутствия подходящей пары.
  return [-1, -1];
}
