/**
 * @param {number[]} nums
 * @param {number} k
 * @return {number}
 *
 * findMaxAverage принимает массив целых чисел nums, состоящий из n
 * элементов, и целое число k.
 *
 * Функция находит непрерывный подмассив, длина которого равна k, имеющий
 * максимальное среднее значение, и возвращает это значение. Погрешность
 * вычислений менее 10^-5.
 *
 *
 * Пример для:
 *   nums = [1,12,-5,-6,50,3],
 *   k = 4
 * Результат:
 *   12.75000
 * Пояснение:
 *   Максимальное среднее значение равно
 *   (12 - 5 - 6 + 50) / 4 = 51 / 4 = 12.75
 */
function findMaxAverage(nums, k) {

  // Создание переменной-аккумулятора currSum (текущая сумма) с начальным
  // значением 0.
  //
  // В ней будет вычисляться и храниться сумма элементов для текущего
  // рассматриваемого окна длины k.
  let currSum = 0;

  // Запуск цикла для обхода первых k элементов массива (индексы от 0 до
  // k - 1 включительно).
  //
  // Этот шаг необходим для формирования базового (самого первого) "окна"
  // фиксированной длины.
  for (let i = 0; i < k; i++) currSum += nums[i];

  // Создание переменной maxSum (максимальная сумма) и сохранение в неё
  // суммы первого окна.
  //
  // Она будет служить эталоном для поиска наибольшей суммы среди всех
  // возможных подмассивов длины k.
  let maxSum = currSum;

  // Запуск второго цикла, который реализует движение "скользящего окна"
  // вправо.
  //
  // Переменная r -это правая граница нового окна.
  //
  // Мы начинаем с индекса k (следующий элемент за границей первого окна).
  for (let r = k; r < nums.length; r++) {

    // Чтобы получить сумму нового окна, мы прибавляем текущий элемент
    // nums[r] (который входит в окно справа) и вычитаем nums[r - k] (самый
    // левый элемент, который при сдвиге окна на один шаг вправо покидает
    // окно).
    currSum += nums[r] - nums[r - k];

    // Сравниваем только что полученную сумму нового окна с текущим
    // максимумом и перезаписываем maxSum, если новая сумма оказалась
    // больше
    maxSum = Math.max(maxSum, currSum);
  }

  // Делим найденную максимальную сумму элементов подмассива на их
  // количество k, чтобы получить и вернуть искомое максимальное среднее
  // значение
  return maxSum / k;
}
