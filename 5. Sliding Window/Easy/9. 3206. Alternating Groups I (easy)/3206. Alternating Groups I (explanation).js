/**
 * @param {number[]} colors
 * @return {number}
 *
 * numberOfAlternatingGroups принимает массив целых чисел colors.
 *
 * colors[i] представляет цвет плитки i:
 * - colors[i] == 0 означает, что плитка i - красная.
 * - colors[i] == 1 означает, что плитка i - синяя.
 *
 * Красные и синие плитки расположены по кругу.
 *
 * Каждые 3 подряд идущие плитки в круге, цвета которых чередуются
 * (средняя плитка отличается по цвету от левой и правой), называются
 * чередующейся группой.
 *
 * Возвращает количество чередующихся групп.
 *
 * Обратите внимание, что поскольку массив colors представляет собой круг,
 * первая и последняя плитки считаются соседними.
 *
 *
 * Пример для:
 *   colors = [1,1,1]
 * Результат:
 *   0
 *
 *
 * Пример для:
 *   colors = [0,1,0,0,1]
 * Результат:
 *   3
 */
function numberOfAlternatingGroups(colors) {
  const n = colors.length;

  // Создаем переменную-счётчик, в которой будем аккумулировать количество
  // успешно найденных чередующихся комбинаций плиток
  let alternatingCnt = 0;

  // Поочередно рассматриваем каждую плитку в качестве начала группы
  for (let i = 0; i < n; i++) {

    // Извлекаем значение цвета для первой плитки текущей тройки по её
    // прямому индексу i из исходного массива данных
    const color1 = colors[i];

    // Извлекаем цвет второй плитки, используя оператор остатка от деления
    // (%), что позволяет при выходе индекса за границы массива (равном n)
    // автоматически вернуться к индексу 0
    const color2 = colors[(i + 1) % n];

    // Извлекаем цвет третьей плитки, где операция % n гарантирует
    // корректный переход к индексам 0 или 1, если индекс i находится в
    // самом конце массива (на предпоследней или последней позиции)
    const color3 = colors[(i + 2) % n];

    // Проверяем является ли выбранная тройка плиток чередующейся группой
    if (

      // Сравниваем цвета первой и второй плиток: для чередования они
      // обязательно должны быть строго не равны друг другу
      color1 !== color2

      // Проверяем второе обязательное условие: цвет средней (второй)
      // плитки должен строго отличаться от цвета замыкающей (третьей)
      // плитки
      && color2 !== color3

      // Если оба условия выше верны, то цвета тройки гарантированно
      // чередуются (0-1-0 или 1-0-1), и мы инкрементируем
      // (увеличиваем на 1) счетчик alternatingCnt
    ) alternatingCnt++;
  }

  // Возвращаем накопленное в переменной alternatingCnt итоговое целое
  // число, обозначающее количество подходящих групп
  return alternatingCnt;
}
