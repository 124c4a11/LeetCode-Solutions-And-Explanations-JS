/**
 * @param {string} word
 * @return {number}
 *
 * numDifferentIntegers принимает строку word и возвращает количество
 * различных целых чисел, встречающихся в переданной строке.
 *
 *
 * Пример для:
 *   word = "a123bc34d8ef34"
 *            ^^^  ^^ ^  ^^
 * Результат:
 *   3
 * Пояснение:
 *   Три различных целых числа - "123", "34" и "8". Обратите внимание,
 *   что "34" учитывается только один раз.
 *
 *
 * Пример для:
 *   word = "a1b01c001"
 * Результат:
 *   1
 * Пояснение:
 *   Три целых числа "1", "01" и "001" представляют одно и то же
 *   значение, так как при сравнении их десятичных значений
 *   ведущие нули игнорируются.
 */
function numDifferentIntegers(word) {

  // Создаём пустой Set для хранения уникальных строковых
  // представлений найденных чисел.
  //
  // Set автоматически исключит дубликаты, поэтому он удобен для
  // подсчёта уникальных значений.
  const uniqueNums = new Set();

  // Инициализируем массив currDigits, который будет временно хранить
  // отдельные символы-цифры текущей последовательности цифр при
  // проходе по строке.
  //
  // Для поэтапного накопления символов-цифр используем массив а не
  // строку, так как работа с массивом на уровне памяти эффективнее
  // и быстрее (On вместо On^2)
  const currDigits = [];

  // Проходим по каждому символу входной строки word в порядке
  // следования.
  for (const char of word) {

    // Пытаемся преобразовать текущий символ в число с помощью Number.
    //
    // Для символов '0'..'9' получится соответствующее число 0..9, для
    // остальных - NaN.
    const digit = Number(char);

    // Проверяем, является ли результат преобразования NaN - это
    // означает, что текущий символ не цифра.
    if (Number.isNaN(digit)) {

      // Если массив currDigits не пустой, значит до этого шла
      // последовательность цифр - завершение числа.
      if (currDigits.length) {

        // Объединяем накопленные элементы currDigits в строку
        // (например, [ 0, 1, 2 ] → "012").
        //
        // Затем применяем replace(/^0+/g, '') чтобы удалить все
        // ведущие нули.
        //
        // Важно:
        // Если число состояло только из нулей, то после удаления
        // ведущих нулей получится пустая строка. Это поведение
        // сохраняется намеренно, так как нам не важны сами значения,
        // а только их количество. Пустая строка представляет число 0.
        // Set будет хранить '' для "0".
        uniqueNums.add(currDigits.join('').replace(/^0+/g, ''));
      }

      // Сбрасываем массив currDigits, устанавливая его длину в 0.
      //
      // Такой приём очищает массив без создания нового объекта, что
      // эффективнее.
      currDigits.length = 0;
    } else {

      // Если символ - цифра (Number(char) вернул число 0..9),
      // добавляем это числовое значение в currDigits.
      //
      // Мы добавляем именно числовое значение digit, но при join оно
      // будет приведено к строке.
      currDigits.push(digit);
    }
  }

  // После завершения цикла может остаться незавершённая
  // последовательность цифр (если строка закончилась цифрой).
  //
  // В этом случае нужно добавить последнее накопленное число в Set.
  if (currDigits.length) {

    // Добавляем последнюю собранную последовательность цифр в Set,
    // применяя ту же нормализацию (удаление ведущих нулей).
    //
    // Это гарантирует, что число в конце строки тоже будет учтено.
    uniqueNums.add(currDigits.join('').replace(/^0+/g, ''));
  }

  // Возвращаем количество уникальных элементов в Set - это и есть
  // количество различных целых чисел, найденных в исходной строке
  // после нормализации (удаления ведущих нулей).
  return uniqueNums.size;
}
