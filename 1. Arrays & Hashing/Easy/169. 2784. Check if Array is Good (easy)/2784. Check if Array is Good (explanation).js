/**
 * @param {number[]} nums
 * @return {boolean}
 *
 * isGood проверяет, соответствует ли входной массив nums определённому
 * шаблону: максимальное значение (равное nums.length - 1) должно
 * встречаться ровно два раза, а каждое целое число от 1 до max - 1
 * должно встречаться ровно по одному разу. Если это так - возвращает
 * true, иначе - false
 *
 *
 * Пример для:
 *   nums = [2, 1, 3]
 * Результат:
 *   false
 * Пояснение:
 *   Поскольку максимальный элемент массива равен 3, единственный
 *   кандидат n, для которого этот массив мог бы быть перестановкой
 *   base[n], - n = 3.
 *
 *   Однако base[3] содержит четыре элемента, а массив nums содержит
 *   три. Поэтому nums не может быть перестановкой
 *   base[3] = [1, 2, 3, 3].
 *
 *   Ответ: false
 *
 *
 * Пример для:
 *   nums = [1, 3, 3, 2]
 * Результат:
 *   true
 * Пояснение:
 *   Поскольку максимальный элемент массива равен 3, единственный
 *   кандидат n, для которого этот массив мог бы быть перестановкой
 *   base[n], - n = 3.
 *
 *   Видно, что nums является перестановкой base[3] = [1, 2, 3, 3]
 *   (переставив второй и четвёртый элементы nums, получаем base[3]).
 *
 *   Поэтому ответ: true
 */
function isGood(nums) {

  // Чтобы проверить, является ли массив "хорошим", нужно убедиться,
  // что он соответствует шаблону base[n] для некоторого n.
  //
  // Сначала определим, чему должно быть равно n. Поскольку base[n]
  // имеет длину n + 1, а входной массив nums имеет длину len(nums),
  // можно вывести, что n = len(nums) - 1.
  //
  // Теперь нужно проверить два условия:
  // 1. наибольшее значение n встречается ровно два раза;
  // 2. все значения от 1 до n-1 встречаются ровно по одному разу.
  //
  // Самый прямой способ проверить эти условия - посчитать вхождения
  // каждого элемента в nums. Для этого используем счётчик частот,
  // который хранит, сколько раз встречается каждое число.
  //
  // - После подсчёта проверяем, что cnt[n] == 2 (наибольший элемент
  //   встречается дважды).
  //
  // - Затем проверяем, что все числа от 1 до n-1 присутствуют ровно по
  //   одному разу.
  //
  // Преимущество подхода в том, что не обязательно явно проверять
  // равенство единице для каждого счётчика - достаточно убедиться, что
  // счётчики для 1..n-1 ненулевые. Если какое‑то число в диапазоне
  // отсутствует, его счётчик будет равен 0, что укажет на нарушение
  // условия. Если какое‑то число встречается более одного раза, общее
  // количество элементов не будет соответствовать ожидаемой длине, и
  // это также будет выявлено проверками.
  //
  // Подсчёт частот даёт чистое и эффективное решение, которое напрямую
  // проверяет определение "хорошего" массива.


  // Вычисляем переменную max как длину массива минус 1.
  //
  // Семантически это "целевое" значение n, которое по условию должно
  // встречаться дважды.
  const max = nums.length - 1;

  // Создаём типизированный массив Int32Array длиной 201 для подсчёта
  // частот чисел.
  //
  // Индекс - число
  // Значение - частота вхождения этого числа в nums
  //
  // Используем длину 201, так как возможные значения в nums лежат в
  // диапазоне 1..200
  const numToFreq = new Int32Array(201);

  // Проходим по каждому элементу входного массива nums.
  //
  // Для каждого значения num увеличиваем соответствующий счётчик в
  // массиве частот numToFreq.
  for (const num of nums) numToFreq[num]++;

  // Значение, равное max, должно встречаться ровно два раза.
  //
  // Если частота max не равна 2, функция сразу возвращает false - это
  // ранний выход для экономии времени.
  //
  // Такая проверка отражает требование к структуре "хорошего" массива.
  if (numToFreq[max] !== 2) return false;

  // Цикл по всем числам от 1 до max-1 включительно.
  //
  // Для каждого такого числа ожидается ровно одна встреча в массиве
  // nums.
  //
  // Начинаем с 1, так как возможные значения чисел лежат в диапазоне
  // 1..200
  for (let num = 1; num < max; num++) {

    // Если для какого-либо числа в этом диапазоне частота отличается
    // от 1, условие нарушено - возвращаем false.
    //
    // Это обеспечивает то, что все числа 1..max-1 присутствуют ровно
    // по одному разу.
    if (numToFreq[num] !== 1) return false;
  }

  // Если все проверки пройдены (частота max равна 2 и все числа
  // 1..max-1 встречаются по одному разу), возвращаем true - массив
  // соответствует ожидаемому шаблону.
  return true;
}
