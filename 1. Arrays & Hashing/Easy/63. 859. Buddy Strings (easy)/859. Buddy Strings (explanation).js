/**
 * @param {string} s
 * @param {string} goal
 * @return {boolean}
 *
 * buddyStrings принимает две строки s и goal.
 *
 * Возвращает true, если можно поменять местами две буквы в s так, чтобы
 * полученная строка была равна goal. В противном случае возвращает
 * false.
 *
 * Поменять буквы местами означает выбрать два индекса i и j
 * (0‑индексация), i != j, и обменять символы s[i] и s[j].
 *
 * Например, обмен символов на индексах 0 и 2 в строке "abcd" даёт "cbad".
 *
 *
 * Пример для:
 *   s = "ab",
 *   goal = "ba"
 * Результат:
 *   true
 * Пояснение:
 *   Можно поменять s[0] = 'a' и s[1] = 'b', чтобы получить "ba", что
 *   равно goal.
 *
 *
 * Пример для:
 *   s = "ab",
 *   goal = "ab"
 * Результат:
 *   false
 * Пояснение:
 *   Единственная возможная перестановка - поменять
 *   s[0] = 'a' и s[1] = 'b', что даст "ba" != goal.
 */
function buddyStrings(s, goal) {

  // Чтобы ровно одна перестановка двух букв в s превратила её в goal,
  // должны выполняться следующие условия:
  //
  // Во‑первых, строки должны иметь одинаковую длину - иначе одна
  // перестановка не поможет.
  //
  // Во‑вторых, строки должны содержать одинаковые символы с одинаковыми
  // частотами - перестановка лишь меняет порядок, не добавляет и не
  // удаляет символы.
  //
  // Если длины и частоты совпадают, есть два сценария:
  //
  // Сценарий 1: строки различаются ровно в двух позициях. Пусть это
  // позиции i и j; тогда обмен s[i] и s[j] сделает строки равными при
  // условии s[i] = goal[j] и s[j] = goal[i].
  //
  // Сценарий 2: строки уже идентичны. Тогда требуется выполнить одну
  // перестановку: это возможно только если в s есть повторяющийся символ
  // - можно обменять два одинаковых символа, не изменив строку.
  //
  // Если строки различаются в 1, 3 или более позициях, либо совпадают, но
  // не содержат дубликатов, то добиться равенства одной перестановкой
  // невозможно.
  //
  // Следовательно, нужно посчитать число позиций, в которых строки
  // различаются, и при необходимости проверить наличие повторяющихся
  // символов.


  // Если длины строк различаются, никакая одна перестановка двух символов
  // не сделает строки равными - возвращаем false.
  if (s.length !== goal.length) return false;

  // Инициализация переменной для отслеживания максимальной частоты
  // появления одного и того же символа среди совпадающих позиций.
  //
  // Используется для определения, есть ли в строке повторяющиеся символы,
  // что важно в случае, когда s и goal уже идентичны.
  let maxFreq = -Infinity;

  // Массив для хранения индексов позиций, в которых s и goal различаются.
  //
  // Нам важно знать не только количество различий, но и конкретные
  // индексы, чтобы проверить возможность корректного обмена.
  let diffIndices = [];

  // Массив частот для строчных латинских букв.
  //
  // Индекс 0 соответствует 'a', индекс 25 - 'z'.
  const charToFreq = new Int32Array(26);

  // Цикл по всем индексам строк.
  //
  // Проходим одновременно по s и goal, сравнивая символы в каждой позиции,
  // так как длины равны.
  for (let i = 0; i < s.length; i++) {

    // Сравниваем символы в текущей позиции. Если они различаются, это
    // потенциальная позиция для обмена.
    if (s[i] !== goal[i]) {

      // Добавляем индекс текущей позиции в список различий.
      diffIndices.push(i);

      // Если различий стало больше двух, то одной перестановки
      // недостаточно - можно немедленно вернуть false.
      if (diffIndices.length > 2) return false;
    } else {

      // Если символы в этой позиции совпадают, учитываем частоту этого
      // символа в s.
      //
      // Это нужно для случая, когда строки полностью совпадают. Нам нужно
      // знать, есть ли повторяющиеся символы.
      //
      // s.codePointAt(i) возвращает код Unicode символа в позиции i. Для
      // латинских строчных букв 'a'..'z' это 97..122. Вычитая 97,
      // получаем индекс в диапазоне 0..25 для доступа в charToFreq
      //
      // ++ перед присваиванием увеличивает значение в массиве и
      // возвращает новое значение.
      const freq = ++charToFreq[s.codePointAt(i) - 97];

      // Обновляем максимальную встречаемость символа среди совпадающих
      // позиций.
      //
      // Это нужно, чтобы позже определить, есть ли в строке хотя бы одна
      // буква, встречающаяся дважды или чаще.
      if (freq > maxFreq) maxFreq = freq;
    }
  }

  // Если нет ни одного различия (строки идентичны), то единственная
  // допустимая операция - обмен двух одинаковых символов.
  //
  // Возвращаем true только если существует символ с частотой больше 1
  // (maxFreq > 1).
  if (diffIndices.length === 0) return maxFreq > 1;

  // Если строки различаются ровно в одной позиции, никакая одна
  // перестановка двух символов не сможет их уравнять - возвращаем false
  if (diffIndices.length === 1) return false;

  // Если мы дошли сюда, значит различия ровно в двух позициях
  // - распаковываем их в переменные i и j
  const [i, j] = diffIndices;

  // Проверяем, что обмен символов в s на позициях i и j сделает s равной
  // goal: требуется, чтобы s[i] совпадал с goal[j] и s[j] совпадал с
  // goal[i].
  //
  // Если оба равенства выполняются, возвращаем true, иначе false.
  return s[i] === goal[j] && s[j] === goal[i];
}
