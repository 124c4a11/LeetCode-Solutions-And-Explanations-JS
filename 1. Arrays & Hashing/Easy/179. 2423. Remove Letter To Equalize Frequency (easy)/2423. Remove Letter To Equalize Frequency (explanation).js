/**
 * @param {string} word
 * @return {boolean}
 *
 * equalFrequency принимает строку word, состоящую из строчных
 * английских букв, и проверяет, можно ли удалить ровно один символ
 * из входной строки так, чтобы частоты всех оставшихся букв стали
 * одинаковыми.
 *
 *
 * Пример для:
 *   word = "abcc"
 * Результат:
 *   true
 * Пояснение:
 *   Выберите индекс 3 и удалите символ: word становится "abc", и
 *   частота каждой буквы равна 1.
 *
 *
 * Пример для:
 *   word = "aazz"
 * Результат:
 *   false
 * Пояснение:
 *   Нужно удалить ровно один символ, поэтому либо частоты станут
 *   {a:1, z:2}, либо {a:2, z:1}.
 *
 *   Невозможно сделать так, чтобы частоты всех присутствующих букв
 *   были равны.
 */
function equalFrequency(word) {

  // Когда нам нужно проверить, выровняет ли удаление одной буквы
  // все частоты, ключевой момент заключается в том, что нам нужно
  // попробовать удалить каждую букву по отдельности и посмотреть,
  // что произойдет. Вместо того чтобы фактически удалять буквы из
  // строки и пересчитывать все заново (что было бы неэффективно),
  // мы можем использовать более разумный подход.
  //
  // Для начала посчитаем, как часто каждая буква встречается в
  // исходной строке. Теперь, чтобы имитировать удаление буквы, мы
  // можем просто временно уменьшить счетчик на 1. Это намного
  // быстрее, чем перестраивать строку.
  //
  // Ключевой момент заключается в том, что после удаления одного
  // вхождения буквы нам нужно проверить, имеют ли все оставшиеся
  // буквы одинаковую частоту. Но как это сделать эффективно? Если
  // мы посмотрим на все значения частоты (игнорируя буквы с
  // частотой 0, поскольку они больше не встречаются в строке), то
  // все они должны быть одинаковыми.
  //
  // Вот тут и пригодится изящный трюк: мы можем собрать все
  // ненулевые частоты в множество. Поскольку множество содержит
  // только уникальные значения, если все частоты одинаковы,
  // множество будет содержать ровно один элемент. Например, если
  // наши частоты равны [2, 2, 2, 0], то множество ненулевых
  // значений будет равно {2}, размер которого равен 1.
  //
  // Таким образом, наша стратегия сводится к следующему:
  // - Подсчитайте частоту встречаемости всех букв один раз в
  //   начале.
  //
  // - Для каждой буквы, встречающейся в строке, временно
  //   уменьшайте её счётчик на 1.
  //
  // - Проверьте, стали ли все ненулевые частоты теперь одинаковыми
  //   (проверив, имеет ли множество ненулевых частот размер 1).
  //
  // - Если да, значит, мы нашли корректное удаление. Если нет,
  //   восстановите счетчик и попробуйте следующую букву.
  //
  // Этот подход эффективен, потому что нам нужно подсчитать буквы
  // только один раз, а затем мы просто выполняем простые
  // арифметические операции и проверки множеств для каждой
  // уникальной буквы в строке.


  // Создаём массив фиксированной длины 26 для хранения частот букв
  // латинского алфавита от 'a' до 'z'.
  //
  // Используем Int32Array для экономии памяти и более быстрых
  // целочисленных операций по сравнению с обычным массивом.
  //
  // Индекс 0 соответствует 'a', индекс 25 - 'z'.
  const charToFreq = new Int32Array(26);

  // Проходим по каждому символу входной строки word
  for (const char of word) {

    // Получаем числовой код символа с помощью codePointAt(0) и
    // вычитаем 97 (код 'a'), чтобы получить индекс в диапазоне
    // 0..25.
    //
    // Затем увеличиваем соответствующий счётчик в массиве
    // charToFreq.
    charToFreq[char.codePointAt(0) - 97]++;
  }

  // Перебираем все возможные буквы алфавита по индексам 0..25,
  // чтобы попробовать удалить одну букву каждого типа.
  //
  // Мы пробуем удаление именно по типам букв, а не по позициям в
  // строке, потому что удаление любой буквы одного типа
  // эквивалентно уменьшению её счётчика на 1.
  for (let i = 0; i < 26; i++) {

    // Если текущая буква вообще не встречается в строке
    // (частота 0), пропускаем её - удалять нечего.
    if (charToFreq[i] === 0) continue;

    // Временно уменьшаем частоту буквы с индексом i на 1,
    // моделируя удаление одного вхождения этой буквы.
    //
    // Это изменение делается "на месте" в массиве частот, чтобы не
    // копировать весь массив при каждой итерации.
    charToFreq[i]--;

    // Инициализируем переменную targetFreq нулём. Она будет
    // хранить ожидаемую одинаковую частоту для всех оставшихся
    // букв.
    //
    // Значение 0 здесь служит маркером "ещё не установлено".
    let targetFreq = 0;

    // Флаг, показывающий, равны ли частоты всех оставшихся букв.
    //
    // Предполагаем, что равны, пока не найдём несоответствие.
    let isEqualFreq = true;

    // Перебираем все значения частот в массиве charToFreq для
    // проверки их равенства.
    for (const freq of charToFreq) {

      // Пропускаем буквы с частотой 0, так как они не присутствуют
      // в результирующей строке и не влияют на условие равенства.
      if (freq === 0) continue;

      // Если targetFreq ещё не установлен (равен 0), устанавливаем
      // его в текущую ненулевую частоту.
      //
      // Это задаёт эталонную частоту, с которой будут сравниваться
      // все остальные ненулевые частоты.
      if (targetFreq === 0) {
        targetFreq = freq;

        // Если targetFreq уже установлен и текущая частота
        // отличается от него, значит частоты не одинаковы.
        //
        // В этом случае помечаем isEqualFreq как false и прерываем
        // внутренний цикл - дальнейшая проверка не нужна.
      } else if (freq !== targetFreq) {
        isEqualFreq = false;
        break;
      }
    }

    // Если после проверки всех частот флаг isEqualFreq остался
    // true, значит удаление одного символа буквы i привело к тому,
    // что все оставшиеся буквы имеют одинаковую частоту -
    // возвращаем true.
    if (isEqualFreq) return true;

    // Если удаление буквы i не привело к равенству частот,
    // восстанавливаем её частоту, чтобы корректно проверить
    // следующий вариант удаления (следующую букву).
    charToFreq[i]++;
  }

  // Если ни одно из возможных удалений не дало равных частот,
  // возвращаем false.
  return false;
}
