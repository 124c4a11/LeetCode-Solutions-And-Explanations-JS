/**
 * @param {number[]} nums
 * @param {number} k
 * @return {number}
 *
 * minOperations(nums, k) принимает массив чисел nums и целое
 * число k.
 *
 * Возвращает минимальное количество операций (просмотров
 * элементов с конца массива), необходимых, чтобы встретить
 * все целые числа от 1 до k включительно при
 * последовательном просмотре массива с конца.
 *
 *
 * Пример для:
 *   nums = [3,1,5,4,2],
 *   k = 2
 * Результат:
 *   4
 * Пояснение:
 *   После 4 операций мы собрали элементы 2, 4, 5 и 1 в
 *   таком порядке.
 *
 *   В нашей коллекции присутствуют элементы 1 и 2.
 *   Следовательно, ответ - 4.
 */
function minOperations(nums, k) {

  // Инициализация переменной operationsCnt значением 0.
  //
  // Будет использоваться для подсчёта количества
  // обработанных элементов массива, то есть сколько
  // "операций" (шагов перебора с конца) выполнено до
  // текущего момента.
  let operationsCnt = 0;

  // Инициализация переменной seenCnt значением 0.
  //
  // Отслеживает, сколько уникальных чисел из диапазона 1..k
  // уже были встречены и помечены.
  //
  // Когда seenCnt достигнет k, задача считается выполненной
  // и функция вернёт operationsCnt.
  let seenCnt = 0;

  // Создание массива numToSeen длиной k+1.
  //
  // Используется как булева карта (флаг) для индексов от 0
  // до k включительно.
  //
  // Индекс i соответствует числу i.
  // Значение true означает, что число i уже встречено.
  //
  // Используем k+1, чтобы можно было напрямую использовать
  // числа 1..k как индексы без смещения.
  //
  // Элементы массива по умолчанию undefined (что эквивалентно
  // false в логическом контексте).
  const numToSeen = new Array(k + 1);

  // Цикл for, который итерирует массив nums с конца к началу.
  //
  // Начинаем с последнего индекса nums.length - 1 и уменьшаем
  // i до 0 включительно.
  //
  // Логика задачи предполагает, что мы "берём" элементы с
  // конца массива, и хотим узнать, сколько операций
  // потребуется, чтобы увидеть все числа 1..k.
  //
  // Обход с конца гарантирует, что operationsCnt отражает
  // количество взятых элементов с конца.
  for (let i = nums.length - 1; i >= 0; i--) {

    // Получаем текущее значение num из массива по индексу i.
    const num = nums[i];

    // Увеличиваем счётчик операций на 1, поскольку мы
    // "обработали" очередной элемент.
    operationsCnt++;

    // Условия, при которых текущий элемент пропускается и
    // цикл переходит к следующему элементу:
    // 1. num > k - если число больше k, оно не входит в
    //    интересующий нас диапазон 1..k и бесполезно.
    //
    // 2. numToSeen[num] - если по индексу num уже стоит true,
    //    значит это число уже было встречено ранее, и
    //    повторная обработка не нужна.
    if (
      num > k
      || numToSeen[num]
    ) continue;

    // Если мы дошли до этой строки, значит num находится в
    // диапазоне 1..k и ещё не отмечен.
    //
    // Помечаем число как встреченное, присваивая true по
    // индексу num в массиве numToSeen.
    //
    // После этого последующие вхождения того же числа будут
    // отфильтрованы условием выше.
    numToSeen[num] = true;

    // Увеличиваем счётчик уникальных встреченных чисел в
    // диапазоне 1..k.
    //
    // Это отражает, что мы "нашли" ещё одно необходимое
    // значение.
    //
    // Когда seenCnt достигнет k, это означает, что все числа
    // 1..k были найдены.
    seenCnt++;

    // Проверяем, достигли ли мы цели - увидели ли все k чисел.
    //
    // Если да, возвращаем текущее значение operationsCnt -
    // количество операций, выполненных до момента выполнения
    // условия.
    if (seenCnt === k) return operationsCnt;
  }
}
