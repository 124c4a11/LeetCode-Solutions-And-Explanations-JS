/**
 * @param {number[]} nums
 * @return {boolean}
 *
 * checkPrimeFrequency принимает массив целых чисел nums и
 * возвращает true, если в массиве есть значение, число
 * вхождений которого является простым числом. В противном
 * случае возвращает false.
 *
 *
 * Пример для:
 *   nums = [1,2,3,4,5,4]
 * Результат:
 *   true
 * Пояснение:
 *   Число 4 встречается два раза, а 2 - простое число.
 */
function checkPrimeFrequency(nums) {

  // Создаём фиксированный буфер частот длиной 101
  // элементов типа Int32Array.
  //
  // Все элементы инициализированы нулём.
  //
  // Индекс соответствует самому числу, значение -
  // количество его вхождений в nums.
  const numToFreq = new Int32Array(101);

  // Итерация по каждому элементу входного массива nums
  //
  // Для каждого значения num увеличиваем соответствующий
  // счётчик в массиве numToFreq.
  for (const num of nums) numToFreq[num]++;

  // Проходим по всем элементам массива numToFreq, где
  // каждый элемент - это частота появления конкретного
  // числа в массиве.
  for (const freq of numToFreq) {

    // Если текущая частота является простым числом,
    // функция немедленно возвращает true - достаточно
    // одной подходящей частоты.
    if (isPrime(freq)) return true;
  }

  // Если цикл завершился и ни одна частота не была
  // простой, возвращаем false.
  return false;
}

// Объявление вспомогательной функции isPrime, принимающей
// одно целое число num.
//
// Функция определяет, является ли num простым числом
// (делится только на 1 и на само себя).
function isPrime(num) {

  // Все числа меньше или равные 1 не считаются простыми
  // по определению.
  if (num <= 1) return false;

  // Обрабатываем 2 отдельно - это единственное чётное
  // простое число.
  if (num === 2) return true;

  // Быстрая проверка на чётность:
  //
  // Если число чётное и не равно 2, оно составное.
  //
  // Используется побитовое и ((num & 1) === 0) для
  // небольшой оптимизации по сравнению с num % 2 === 0.
  if ((num & 1) === 0) return false;

  // Вычисляем верхнюю границу для перебора возможных
  // делителей как квадратный корень из num.
  //
  // Достаточно проверять делители до sqrt(num)
  // включительно, потому что если num = a * b и оба > 1,
  // то один из них ≤ sqrt(num).
  const boundary = Math.sqrt(num);

  // Перебираем возможные нечётные делители начиная с 3 с
  // шагом 2, поскольку все чётные уже исключены.
  //
  // Это уменьшает количество итераций примерно вдвое по
  // сравнению с проверкой каждого числа.
  for (let i = 3; i <= boundary; i += 2) {

    // Если найден делитель без остатка, число составное
    // - возвращаем false
    if (num % i === 0) return false;
  }

  // Если ни один делитель не найден до границы, число
  // простое - возвращаем true.
  return true;
}
