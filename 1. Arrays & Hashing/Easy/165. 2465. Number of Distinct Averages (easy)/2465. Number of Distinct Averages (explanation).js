/**
 * @param {number[]} nums
 * @return {number}
 *
 * distinctAverages принимает массив чисел nums и возвращает
 * количество различных средних значений, которые получаются
 * при многократном попарном удалении минимального и
 * максимального элементов.
 *
 *
 * Пример для:
 *   nums = [4,1,4,0,3,5]
 * Результат:
 *   2
 * Пояснение:
 *   1. Удаляем 0 и 5, среднее (0 + 5) / 2 = 2.5.
 *      Теперь nums = [4,1,4,3].
 *
 *   2. Удаляем 1 и 4, среднее (1 + 4) / 2 = 2.5.
 *      Теперь nums = [4,3].
 *
 *   3. Удаляем 3 и 4, среднее (3 + 4) / 2 = 3.5.
 *
 *   Поскольку среди значений 2.5, 2.5 и 3.5 встречаются 2
 *   различных числа, возвращаем 2.
 */
function distinctAverages(nums) {
  const n = nums.length;

  // Сортируем массив по возрастанию с числовым сравнением.
  //
  // Это необходимо, чтобы гарантированно брать минимальные
  // элементы с начала и максимальные с конца.
  nums.sort((a, b) => a - b);

  // Инициализация счётчика уникальных сумм (или уникальных
  // средних - средние пропорциональны суммам).
  //
  // Поскольку нас интересуют только различные средние
  // значения, а среднее значение равно (a + b) / 2, две
  // пары будут иметь одинаковое среднее значение только в
  // том случае, если их сумма одинакова. Следовательно,
  // вместо вычисления и хранения фактических средних
  // значений (что включает деление), мы можем просто
  // отслеживать различные суммы пар.
  let uniqueSumsCnt = 0;

  // Создаём массив для отметки уже встреченных сумм.
  //
  // Размер 201 выбран явно, так как максимальная возможная
  // сумма равна 200.
  //
  // Это позволяет избежать использования структуры Set и
  // экономит память/время на хеширование.
  const sumToSeen = new Array(201);

  // Начало цикла по индексам первой половины массива.
  //
  // (n >> 1) - побитовый сдвиг вправо, эквивалент
  // Math.floor(n / 2) для неотрицательных n.
  //
  // Проходим только половину, потому что за одну итерацию
  // обрабатывается пара (i-й элемент с начала и i-й
  // элемент с конца).
  for (let i = 0; i < (n >> 1); i++) {

    // Вычисляем сумму пары: элемент с позиции i (из начала)
    // и соответствующий элемент с конца массива.
    //
    // Индекс n - i - 1 указывает на i-ый элемент с конца.
    const sum = nums[i] + nums[n - i - 1];

    // Проверяем, встречалась ли уже эта сумма.
    //
    // Поскольку элементы sumToSeen изначально undefined,
    // условие будет false для неотмеченных сумм.
    //
    // Если значение truthy (например, true), значит такую
    // сумму уже учитывали, и повторный подсчёт не нужен.
    if (sumToSeen[sum]) continue;

    // Помечаем текущую сумму как встреченную.
    //
    // После этой записи последующие одинаковые суммы будут
    // пропускаться условием выше.
    sumToSeen[sum] = true;

    // Увеличиваем счётчик уникальных сумм, так как
    // встретили новую, ранее не отмеченную сумму.
    uniqueSumsCnt++;
  }

  // Возвращаем итоговое количество уникальных сумм -
  // эквивалент количества различных средних значений.
  return uniqueSumsCnt;
}
