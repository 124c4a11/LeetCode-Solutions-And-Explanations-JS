/**
 * @param {string[]} words
 * @return {string}
 *
 * oddString принимает массив строк words. Она находит и возвращает
 * то слово из массива, чей шаблон разностей кодов соседних
 * символов уникален среди всех слов. Если такого слова нет,
 * возвращает пустую строку.
 *
 *
 * Пример для:
 *   words = ["adc","wzy","abc"]
 * Результат:
 *   "abc"
 * Пояснение:
 * - Массив разниц для "adc": [ 'd' - 'a', 'c' - 'd' ] = [3, -1].
 * - Массив разниц для "wzy": [ 'z' - 'w', 'y' - 'z' ] = [3, -1].
 * - Массив разниц для "abc": [ 'b' - 'a', 'c' - 'b' ] = [1, 1].
 * Уникальный массив разниц - [1, 1], поэтому функция возвращает
 * соответствующую строку "abc".
 */
function oddString(words) {

  // Создаём Map для группировки слов по их шаблону разностей
  // символов.
  //
  // Ключ будет строкой, полученной из массива разностей,
  // значение - массив слов.
  const diffPatternToWords = new Map();

  // Перебираем все слова из входного массива words.
  for (const word of words) {

    // Инициализируем массив для хранения разностей кодов символов
    // между соседними символами текущего слова.
    //
    // Размер массива задаётся равным word.length - 1, чтобы
    // заранее выделить память.
    //
    // Используется длина word.length - 1, потому что для слова
    // длины m существует ровно m - 1 разниц между соседними
    // символами.
    const charsDiffs = new Array(word.length - 1);

    // Внутренний цикл по индексам символов от 0 до предпоследнего
    // включительно.
    //
    // Цель - вычислить разницу кодов между следующим символом i+1
    // и текущим символом i.
    //
    // Цикл идёт до word.length - 1, так как на каждой итерации нам
    // нужен доступ к следующему символу, а для последнего символа
    // нет следующего символа для вычитания.
    for (let i = 0; i < word.length - 1; i++) {

      // Получаем числовой код символа в позиции i+1 и вычитаем код
      // символа в позиции i.
      const diff = word.charCodeAt(i + 1) - word.charCodeAt(i);

      // Сохраняем вычисленную разницу в массив charsDiffs на
      // позиции i.
      charsDiffs[i] = diff;
    }

    // Преобразуем массив разностей в строку, разделённую запятыми,
    // чтобы использовать её как стабильный и сравнимый ключ в Map.
    const diffPattern = charsDiffs.join(',');

    // Если в Map ещё нет записи для этого шаблона разниц, создаём
    // новую запись с пустым массивом слов.
    //
    // Это гарантирует, что diffPatternToWords.get(diffPattern)
    // всегда вернёт массив для push ниже.
    if (!diffPatternToWords.has(diffPattern)) {
      diffPatternToWords.set(diffPattern, []);
    }

    // Добавляем текущее слово в массив слов, соответствующих
    // вычисленному шаблону разниц.
    //
    // Map хранит для каждого шаблона список всех слов, у которых
    // одинаковая последовательность разниц.
    diffPatternToWords.get(diffPattern).push(word);
  }

  // Проходим по всем парам [ключ, значение] в Map.
  //
  // Для ускорения работы кода не используем деструктуризацию
  // массива kvp в цикле, а обращаетмся к его элементам по индексам
  for (const kvp of diffPatternToWords) {

    // В каждой паре:
    // - kvp[0] - ключ (diffPattern),
    // - kvp[1] - значение (массив слов).
    //
    // Извлекаем массив слов, соответствующих текущему шаблону
    // разниц.
    const currWords = kvp[1];

    // Если для данного шаблона найден только один элемент, значит
    // это "особое" слово, которое отличается по шаблону разниц от
    // всех остальных - возвращаем его.
    if (currWords.length === 1) return currWords[0];
  }

  // Если не найдено ни одного уникального шаблона, возвращаем
  // пустую строку.
  return '';
}
