/**
 * @param {number[]} nums1
 * @param {number[]} nums2
 * @return {number}
 *
 * minNumber принимает два массива цифр (чисел от 0 до 9) и возвращает
 * минимально возможное число, которое можно составить, соблюдая
 * правила задачи. Функция ищет сначала наименьшую общую цифру в обоих
 * массивах, если такая цифра найдена, она возвращается как
 * одноцифровое число. Если общих цифр нет, функция берёт по одной
 * минимальной цифре из каждого массива и формирует из них минимально
 * возможное двухцифровое число, ставя меньшую из двух цифр в старший
 * разряд.
 *
 *
 * Пример для:
 *   nums1 = [4,1,3],
 *   nums2 = [5,7]
 * Результат:
 *   15
 * Пояснение:
 *   Число 15 содержит цифру 1 из nums1 и цифру 5 из nums2. Можно
 *   доказать, что 15 - наименьшее возможное число.
 *
 *
 * Пример для:
 *   nums1 = [3,5,2,6],
 *   nums2 = [3,1,7]
 * Результат:
 *   3
 * Пояснение:
 *   Число 3 содержит цифру 3, которая присутствует в обоих массивах.
 */
function minNumber(nums1, nums2) {
  const n = nums1.length;
  const m = nums2.length;

  // Создаём массив длины 10 для отметки встреченных цифр в nums1.
  //
  // Индекс соответствует самой цифре (0..9).
  // Значения будут true для встреченных цифр, иначе undefined.
  const num1ToSeen = new Array(10);

  // Создаём массив длины 10 для отметки встреченных цифр в nums2.
  //
  // Индекс соответствует самой цифре (0..9).
  // Значения будут true для встреченных цифр, иначе undefined.
  const num2ToSeen = new Array(10);

  // Проходим циклом до максимальной длины между двумя входными
  // массивами, чтобы в одном цикле обработать оба массива.
  //
  // Math.max(n, m) гарантирует, что мы не пропустим элементы более
  // длинного массива.
  for (let i = 0; i < Math.max(n, m); i++) {

    // Если текущий индекс i находится в пределах первого массива,
    // помечаем соответствующую цифру как встреченную.
    if (i < n) num1ToSeen[nums1[i]] = true;

    // Если текущий индекс i находится в пределах второго массива,
    // помечаем соответствующую цифру как встреченную
    if (i < m) num2ToSeen[nums2[i]] = true;
  }

  // Инициализируем переменную для хранения минимальной найденной
  // цифры в nums1.
  //
  // Используем Infinity как маркер "ещё не найдено", и чтобы любое
  // реальное встреченное значение было мньше Infinity и могло его
  // переопределить.
  let minNum1 = Infinity;

  // Аналогично инициализируем переменную для хранения минимальной
  // найденной цифры в nums2
  let minNum2 = Infinity;

  // Перебираем возможные цифры от 1 до 9 включительно
  //
  // Начинаем с num = 1, так как возможные значения в массивах лежат
  // в диапазоне 1..9
  for (let num = 1; num < 10; num++) {

    // Если текущая цифра присутствует в обоих массивах, это наименьшая
    // общая цифра - возвращаем её как одноцифровое число (минимально
    // возможный результат).
    if (num1ToSeen[num] && num2ToSeen[num]) return num;

    // Если ещё не найден минимальный элемент для nums1 и текущая
    // цифра есть в nums1, сохраняем её как minNum1
    if (minNum1 === Infinity && num1ToSeen[num]) minNum1 = num;

    // Если ещё не найден минимальный элемент для nums2 и текущая
    // цифра есть в nums2, сохраняем её как minNum2
    if (minNum2 === Infinity && num2ToSeen[num]) minNum2 = num;
  }

  // Если не найдено общей цифры, формируем минимально возможное
  // двузначное число, используя по одной минимальной цифре из каждого
  // массива.
  //
  // Сравниваем minNum1 и minNum2, чтобы определить, какая цифра
  // должна быть старшим разрядом.
  return minNum1 < minNum2

    // Если минимальная цифра из nums1 меньше, ставим её в десятки,
    // а minNum2 в единицы.
    ? minNum1 * 10 + minNum2

    // Иначе, минимальная цифра из nums2 в десятки, а minNum1 в
    // единицы.
    : minNum2 * 10 + minNum1;
}
