/**
 * @param {number[]} arr
 * @return {boolean}
 *
 * checkIfExist(arr) массив чисел arr и возвращает true, если в
 * массиве существует пара элементов x, y, такая что один равен
 * удвоенному значению другого (то есть x = 2 * y или y = 2 * x),
 * иначе возвращает false.
 *
 *
 * Пример для:
 *   arr = [10,2,5,3]
 * Результат:
 *   true
 * Пояснение:
 *   Для i = 0 и j = 2, arr[i] == 10 == 2 * 5 == 2 * arr[j]
 */
function checkIfExist(arr) {

  // Создаём пустой Set для хранения уже просмотренных значений
  // из массива arr.
  //
  // Set обеспечивает быстрый поиск наличия элемента за
  // амортизированное O(1).
  const set = new Set();

  // Итерация по каждому элементу входного массива arr.
  for (const num of arr) {

    // Проверяем, встречалось ли ранее значение, равное
    // удвоенному текущему числу (num * 2).
    //
    // Если да - значит ранее был элемент y такой, что
    // y == 2 * num, то есть найдена пара (num, y).
    //
    // Возвращаем true.
    if (set.has(num * 2)) return true;

    // Следующая проверка обрабатывает обратный случай: если
    // текущее число чётное, то возможно, что ранее встречался
    // элемент, равный половине текущего (num / 2).
    if (

      // Битовая операция (num & 1) === 0 проверяет чётность
      // числа.
      //
      // Если результат равен 0 - число чётное.
      // Если 1 - нечётное.
      //
      // Это эквивалентно (num % 2 === 0) для целых чисел, но
      // этот способ быстрее, чем использование оператора %
      (num & 1) === 0

      // Если число чётное, дополнительно проверяем, есть ли в
      // Set значение, равное половине текущего числа (num / 2).
      //
      // Логика:
      // Если ранее встретилось значение y такое, что
      // y === num / 2, то найдена пара (num, y) где
      // num === 2 * y.
      && set.has(num / 2)

      // Если найдено значение y === num / 2, возвращаем true
    ) return true;

    // Если ни одно из условий не сработало, добавляем текущее
    // число в Set, чтобы последующие элементы могли с ним
    // сравниваться.
    set.add(num);
  }

  // Если весь массив пройден и ни одна пара не найдена,
  // возвращаем false.
  return false;
}
