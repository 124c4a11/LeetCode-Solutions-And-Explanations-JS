/**
 * @param {number[]} nums
 * @return {number}
 *
 * countSpecialIntegers принимает один аргумент nums - массив целых чисел
 * в диапазоне 0..100.
 *
 * Возвращает количество различных целых чисел x, которые являются
 * "специальными": x встречается ровно три раза в nums, и три его вхождения
 * расположены на равных расстояниях (если индексы вхождений i1 < i2 < i3,
 * то i2 - i1 = i3 - i2).
 *
 *
 * Пример для:
 *   nums = [1,8,1,5,1,5,8,5]
 * Результат:
 *   2
 * Пояснение:
 *   1 - специальное, потому что встречается ровно три раза на индексах
 *       0, 2 и 4, и эти индексы равноудалены.
 *
 *   5 - специальное, потому что встречается ровно три раза на индексах
 *       3, 5 и 7, и эти индексы равноудалены.
 *
 *   8 - не специальное, потому что встречается только два раза.
 * Следовательно, ответ равен 2.
 */
function countSpecialIntegers(nums) {

  // Создаём массив фиксированной длины 101 для сопоставления
  // число → массив индексов его вхождений.
  //
  // Используем длину 101, так как значения в nums лежат в диапазоне 0..100
  // включительно
  const numToIndices = new Array(101);

  // Проходим по всем индексам входного массива nums один раз, чтобы
  // собрать позиции каждого встреченного числа.
  for (let i = 0; i < nums.length; i++) {

    // Сохраняем текущее значение элемента массива в переменную num
    const num = nums[i];

    // Если для данного числа ещё не создан массив индексов (ячейка
    // undefined), инициализируем пустой массив.
    if (!numToIndices[num]) numToIndices[num] = [];

    // Добавляем текущий индекс i в массив индексов для числа num.
    numToIndices[num].push(i);
  }

  // Инициализируем счётчик специальных чисел нулём.
  let specialIntegersCnt = 0;

  // Перебираем все возможные значения чисел от 1 до 100 включительно.
  for (let num = 1; num < 101; num++) {

    // Получаем массив индексов вхождений текущего числа num.
    //
    // Если число не встречалось, переменная будет undefined.
    const indices = numToIndices[num];

    // Пропускаем число, если:
    // - массив индексов отсутствует (число не встречалось),
    //
    // - длина массива не равна ровно 3 (требование задачи: ровно три
    //   вхождения).
    //
    // Оператор continue пропускает текущую итерацию цикла и переходит к
    // следующему num.
    if (
      !indices
      || indices.length !== 3
    ) continue;

    // Если мы дошли до этой проверки, значит indices - массив длины 3.
    //
    // Проверяем, равны ли расстояния между первым и вторым, и между вторым
    // и третьим вхождением. То есть проверяем условие i2 - i1 === i3 - i2.
    if (indices[1] - indices[0] === indices[2] - indices[1]) {

      // Если расстояния равны, число удовлетворяет условию "все три
      // вхождения расположены на равных расстояниях".
      //
      // Увеличиваем счётчик специальных чисел на единицу.
      specialIntegersCnt++;
    }
  }

  // Возвращаем итоговое количество различных специальных чисел, найденных
  // в массиве nums.
  return specialIntegersCnt;
}
