/**
 * @param {number[]} nums
 * @param {number} key
 * @return {number}
 *
 * mostFrequent принимает массив чисел nums и число key, затем
 * находит и возвращает число, которое чаще всего встречается
 * непосредственно после заданного key в массиве nums.
 *
 *
 * Пример для:
 *   nums = [1,100,200,1,100],
 *   key = 1
 * Результат:
 *   100
 * Пояснение:
 *   Для target = 100 есть 2 вхождения на индексах 1 и 4,
 *   которые идут сразу после элемента, равного key.
 *
 *   Другие числа не следуют после key, поэтому возвращаем 100.
 */
function mostFrequent(nums, key) {

  // Инициализация переменной mostFrequentTarget значением 0.
  //
  // Будет хранить текущее значение-"победитель", то есть
  // число, которое чаще всего следует за key.
  let mostFrequentTarget = 0;

  // Инициализация переменной maxTargetFreq значением 0.
  //
  // Будет хранить частоту появления текущего
  // mostFrequentTarget.
  let maxTargetFreq = 0;

  // Создание массива целых чисел фиксированной длины 1001 для
  // подсчёта частот.
  //
  // Индекс массива соответствует значению target, а значение
  // в ячейке - сколько раз оно встретилось.
  const targetToFreq = new Int32Array(1001);

  // Цикл по индексам массива nums от 0 до nums.length - 2
  // включительно.
  //
  // Проходим до предпоследнего индекса, потому что внутри
  // цикла обращаемся к nums[i + 1].
  for (let i = 0; i < nums.length - 1; i++) {

    // Если текущий элемент не равен ключу key, пропускаем
    // оставшуюся часть тела цикла и переходим к следующему
    // индексу.
    //
    // Это экономит операции: мы считаем только те элементы,
    // которые непосредственно предшествуют потенциальным
    // целевым значениям.
    if (nums[i] !== key) continue;

    // Сохраняем значение следующего элемента после ключа в
    // константу target.
    //
    // Это значение - кандидат на то, чтобы быть наиболее
    // частым "следующим" за key.
    const target = nums[i + 1];

    // Инкрементируем счётчик для данного target в массиве
    // targetToFreq и одновременно присваиваем обновлённую
    // частоту переменной targetFreq.
    //
    // Оператор ++ перед переменной увеличивает значение в
    // массиве и возвращает новое значение.
    const targetFreq = ++targetToFreq[target];

    // Сравниваем новую частоту target с текущим максимумом.
    //
    // Если она больше, обновляем наиболее частое значение и
    // максимум.
    //
    // Это обеспечивает, что в любой момент mostFrequentTarget
    // соответствует значению с наибольшей встречаемостью после
    // key.
    if (targetFreq > maxTargetFreq) {

      // Обновляем mostFrequentTarget на текущий target, так
      // как он теперь имеет наибольшую частоту.
      mostFrequentTarget = target;

      // Обновляем maxTargetFreq до новой максимальной частоты.
      maxTargetFreq = targetFreq;
    }
  }

  // Возвращаем значение mostFrequentTarget.
  return mostFrequentTarget;
}
