/**
 * @param {number[]} nums
 * @return {number}
 *
 * maxSum принимает массив целых чисел nums и возвращает максимальную
 * возможную сумму подмассива, состоящего из уникальных элементов, при
 * условии, что перед выбором подмассива разрешено удалить любые элементы,
 * но нельзя удалить все элементы массива.
 *
 *
 * Пример для:
 *   nums = [1,2,-1,-2,1,0,-1]
 * Результат:
 *   3
 * Пояснение:
 *   Удаляем элементы nums[2] == -1 и nums[3] == -2, получаем массив
 *   [1, 2, 1, 0, -1].
 *
 *   Выбираем подмассив [2, 1] (непрерывный отрезок) из [1, 2, 1, 0, -1],
 *   сумма которого равна 3 - это максимальная возможная сумма.
 */
function maxSum(nums) {

  // Нам нужен подмассив с уникальными элементами и максимальной суммой.
  //
  // Первое наблюдение: поскольку мы можем удалить любые элементы (кроме
  // того, чтобы не оставить массив пустым), мы полностью контролируем,
  // какие элементы останутся. Это мощная возможность - мы фактически
  // можем "спроектировать" оптимальный массив.
  //
  // Второе наблюдение: для максимизации суммы при условии уникальности
  // отрицательные числа обычно вредны (они уменьшают сумму), а
  // повторяющиеся положительные числа тоже проблематичны (из‑за
  // требования уникальности можно использовать только одну копию).
  //
  // Ключевая идея: зачем оставлять отрицательные числа или дубликаты,
  // если их можно удалить? При такой свободе оптимальная стратегия
  // становится очевидной:
  // - оставить все уникальные положительные числа;
  //
  // - удалить все отрицательные числа (если только все числа не
  //   отрицательные);
  //
  // - удалить повторяющиеся вхождения положительных чисел.
  //
  // Но задача требует выбрать подмассив, а не произвольное подмножество.
  // Важное осознание: после удаления нежелательных элементов
  // (отрицательных и дубликатов) мы можем расположить оставшиеся элементы
  // так, как нам нужно. Поскольку все оставшиеся элементы положительны и
  // уникальны, выгодно поместить их в один непрерывный подмассив, чтобы
  // максимизировать сумму.
  //
  // Особый случай: если все числа в исходном массиве отрицательные или
  // нули, мы не можем удалить всё. В этом случае лучше всего выбрать
  // подмассив, содержащий только максимальный элемент (наименее
  // отрицательный или ноль).
  //
  // Этот жадный подход работает, потому что нас не ограничивает исходный
  // порядок - мы можем удалить и переставить элементы, чтобы получить
  // оптимальную конфигурацию, где все уникальные положительные числа
  // образуют один непрерывный подмассив.


  // Создаём массив фиксированной длины 101 для пометки встреченных
  // неотрицательных значений по их числовому индексу.
  //
  // Индекс соответствует самому числу.
  // Значение true будет означать, что такое число встречалось в nums.
  //
  // Используем размер 101, так как значения находятся в диапазоне 0..100
  const numToSeen = new Array(101);

  // Инициализируем переменную для хранения максимального значения в
  // исходном массиве.
  //
  // Используем -Infinity, чтобы корректно обработать массивы, содержащие
  // только отрицательные числа.
  let maxNum = -Infinity;

  // Итерация по каждому элементу входного массива nums.
  for (const num of nums) {

    // Обновляем maxNum, если текущий элемент больше найденного ранее
    // максимума.
    //
    // Это нужно для двух целей: обработать случай, когда все числа
    // меньше либо равны нулю, и ограничить последующий цикл
    // суммирования.
    if (num > maxNum) maxNum = num;

    // Если число отрицательное, пропускаем его.
    //
    // Мы не учитываем отрицательные числа при построении множества
    // положительных уникальных значений, потому что отрицательные числа
    // уменьшают сумму и по логике задачи их выгоднее удалить.
    if (num < 0) continue;

    // Помечаем, что значение num встречалось.
    //
    // Запись true в numToSeen[num] означает, что это значение доступно
    // для суммирования.
    numToSeen[num] = true;
  }

  // Если максимальный элемент массива не положителен (maxNum <= 0), это
  // означает, что все элементы либо нулевые, либо отрицательные.
  //
  // Поскольку мы не можем удалить все элементы (массив не должен стать
  // пустым), оптимальным выбором будет взять единственный наибольший
  // элемент (наименее отрицательный или ноль). Поэтому возвращаем maxNum
  // как ответ.
  if (maxNum <= 0) return maxNum;

  // Инициализируем аккумулятор суммы для итогового уникального подмассива.
  //
  // Он будет содержать сумму всех уникальных положительных чисел,
  // помеченных в numToSeen.
  let uniqueSubarraySum = 0;

  // Проходим по всем целым значениям от 1 до maxNum включительно.
  //
  // Начинаем с 1, так как 0 обработат условием выше
  for (let num = 1; num <= maxNum; num++) {

    // Если по индексу num в массиве numToSeen стоит truthy значение
    // (true), значит число num встречалось в исходном массиве.
    //
    // В этом случае добавляем значение num к сумме.
    //
    // Это обеспечивает суммирование каждого уникального положительного
    // числа один раз.
    if (numToSeen[num]) uniqueSubarraySum += num;
  }

  // Возвращаем накопленную сумму уникальных положительных значений.
  return uniqueSubarraySum;
}
