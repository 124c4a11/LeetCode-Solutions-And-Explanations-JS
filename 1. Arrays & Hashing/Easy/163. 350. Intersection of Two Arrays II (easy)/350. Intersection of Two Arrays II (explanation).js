/**
 * @param {number[]} nums1
 * @param {number[]} nums2
 * @return {number[]}
 *
 * intersect(nums1, nums2) на вход принимает два массива чисел
 * и возвращает массив, содержащий элементы, которые встречаются
 * в обоих массивах с учётом кратности (каждый общий элемент
 * появляется столько раз, сколько он встречается в обоих
 * массивах).
 *
 *
 * Пример для:
 *   nums1 = [1,2,2,1],
 *   nums2 = [2,2]
 * Результат:
 *   [2,2]
 */
function intersect(nums1, nums2) {

  // Создаём массив фиксированной длины 1001 для подсчёта частот
  // значений из nums1.
  //
  // Используем длину 1001, так как возможные значения находятся
  // в диапазоне 0..1000 включительно.
  const num1ToFreq = new Int32Array(1001);

  // Итерация по всем элементам nums1 для заполнения таблицы
  // частот.
  //
  // Для каждого числа увеличиваем соответствующий счётчик на 1.
  for (const num of nums1) num1ToFreq[num]++;

  // Создаём пустой массив для накопления результатов -
  // элементов пересечения.
  const intersection = [];

  // Итерация по всем элементам nums2 для поиска совпадений с
  // nums1.
  //
  // Для каждого числа проверяем, есть ли ещё доступные
  // вхождения этого числа в nums1 (по таблице частот).
  for (const num of nums2) {

    // Если счётчик для текущего числа равен нулю, значит либо
    // это число не встречалось в nums1, либо все его вхождения
    // уже использованы в предыдущих совпадениях - пропускаем
    // такое число.
    if (num1ToFreq[num] === 0) continue;

    // Если счётчик положителен, добавляем текущее число в
    // результирующий массив пересечения.
    //
    // Это обеспечивает учёт кратности: каждое совпадение
    // добавляется отдельно.
    intersection.push(num);

    // Уменьшаем счётчик доступных вхождений на единицу, чтобы
    // не использовать одно и то же вхождение nums1 более одного
    // раза.
    //
    // Это важно для корректного поведения при повторяющихся
    // значениях: например, если nums1 содержит две "1", а nums2
    // три "1", в результат попадут только двe "1".
    num1ToFreq[num]--;
  }

  // Возвращаем массив intersection, содержащий все найденные
  // элементы пересечения с учётом кратности.
  return intersection;
}
