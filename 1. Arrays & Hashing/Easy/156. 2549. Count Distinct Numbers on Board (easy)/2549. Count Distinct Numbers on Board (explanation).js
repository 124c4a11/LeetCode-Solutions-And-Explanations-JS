/**
 * @param {number} n
 * @return {number}
 *
 * distinctIntegers принимает целое число n, которое изначально
 * размещено на доске.
 *
 * Возвращает количество различных целых чисел, которые могут
 * оказаться на доске после 10^9 дней, в течение которых
 * выполняется следующая процедура:
 * - Для каждого числа x, присутствующего на доске, найдите все
 *   числа 1 <= i <= n такие, что x % i == 1.
 *
 * - Затем разместите эти числа на доске.
 *
 * Примечание:
 * После того, как число размещено на доске, оно останется на
 * ней до конца. % обозначает операцию по модулю. Например,
 * 14 % 3 равно 2.
 *
 *
 * Пример для:
 *   n = 5
 * Результат:
 *   4
 * Пояснение:
 *   Изначально на доске находится число 5.
 *
 *   На следующий день будут добавлены 2 и 4, так как
 *   5 % 2 == 1 и 5 % 4 == 1.
 *
 *   После этого дня на доску будет добавлено число 3, потому
 *   что 4 % 3 == 1.
 *
 *   В конце миллиарда дней на доске будут различные числа
 *   2, 3, 4 и 5.
 */
function distinctIntegers(n) {

  // Подумайте о том, что происходит, когда на доске есть число
  // x. Нас интересуют все значения i, для которых x % i == 1.
  //
  // Условие x % i == 1 означает, что при делении x на i
  // остаток равен 1. Это можно переписать как x = k * i + 1
  // для некоторого целого k ≥ 1. Переставив, получаем
  // x - 1 = k * i, что означает:
  // i должно быть делителем (x - 1).
  //
  // Теперь проследим, что происходит, начиная с n:
  // - Когда на доске есть n, проверяем: какие значения i
  //   удовлетворяют n % i == 1?
  //
  // - Очевидный ответ - i = n - 1, потому что n % (n - 1) = 1
  //   (так как n = 1 * (n - 1) + 1).
  //
  // - Значит, n - 1 добавляется на доску.
  //
  // Далее, когда на доске есть n - 1:
  // - Нам нужно, чтобы (n - 1) % i == 1, то есть i делит
  //   (n - 2).
  //
  // - Одно из таких значений - i = n - 2, потому что
  //   (n - 1) % (n - 2) = 1.
  //
  // - Значит, n - 2 добавляется на доску.
  //
  // Этот шаблон продолжается: каждое число x порождает x - 1,
  // потому что x % (x - 1) = 1 всегда верно для x > 2.
  //
  // Следуя этой цепочке: n → n - 1 → n - 2 → ... → 3 → 2
  //
  // Цепочка останавливается на 2, потому что 2 % 1 = 0 (не 1),
  // поэтому 1 никогда не добавляется на доску.
  //
  // Таким образом, начиная с n, мы в конечном итоге получаем
  // все целые числа от 2 до n, что даёт ровно n - 1 различных
  // чисел.
  //
  // Единственное исключение - n = 1, когда новых чисел
  // сгенерировать нельзя, и на доске остаётся только 1.


  // Когда n = 1, на доске остаётся только 1 (нельзя получить 0)
  //
  // Когда n > 1, мы можем получить все целые числа от n до 1
  //
  // Всего различных целых чисел: n, n-1, n-2, ..., 2, 1 = n
  // чисел
  //
  // Но поскольку 0 быть не может, количество равно
  // n - 1 + 1 = n - 1 различных положительных чисел
  //
  // На самом деле, начиная с n, мы получаем:
  // n, n-1, n-2, ..., 2, 1
  //
  // Это n различных чисел при n > 1, но формула n - 1 работает
  // потому что:
  //
  // Мы исключаем само n из подсчёта и считаем все числа
  // от 1 до n-1
  //
  // Процесс добавления чисел порождает цепочку от n вниз до 2,
  // поэтому в пределе на доске оказываются все числа от 2 до n.
  // Их количество равно n - 1.
  //
  // При этом для n = 1 новых чисел не появляется, и на доске
  // остаётся ровно одно число.
  //
  // Чтобы покрыть оба случая, возвращаем максимум между
  // 1 и n - 1.
  return Math.max(1, n - 1);
}
