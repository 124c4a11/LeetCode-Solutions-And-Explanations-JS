/**
 * @param {string[]} list1
 * @param {string[]} list2
 * @return {string[]}
 *
 * findRestaurant принимает два массива строк и возвращает массив
 * общих строк (названий ресторанов), у которых минимальна сумма
 * индексов в обоих входных списках.
 *
 *
 * Пример для:
 *   list1 = ["happy","sad","good"],
 *   list2 = ["sad","happy","good"]
 * Результат:
 *   ["sad","happy"]
 * Пояснение:
 *   Есть три общие строки:
 *   - "happy" с суммой индексов = (0 + 1) = 1.
 *   - "sad" с суммой индексов = (1 + 0) = 1.
 *   - "good" с суммой индексов = (2 + 2) = 4.
 *
 *   Строки с наименьшей суммой индексов: "sad" и "happy".
 */
function findRestaurant(list1, list2) {

  // Создаём новый Map для хранения соответствия
  // строки из list1 → её индекс в list1.
  //
  // Map выбран для O(1) амортизированного доступа по ключу, в
  // отличие от поиска по массиву.
  const list1StrToNdx = new Map();

  // Проходим по всем элементам list1, чтобы заполнить Map
  for (let i = 0; i < list1.length; i++) {

    // Вставляем в Map пару (строка из list1, её индекс i).
    list1StrToNdx.set(list1[i], i);
  }

  // Массив для накопления строк, которые являются общими и имеют
  // текущую минимальную сумму индексов.
  const commonStrings = [];

  // Переменная для хранения минимальной найденной суммы индексов.
  //
  // Инициализируем Infinity, чтобы любое реальное значение суммы
  // индексов было меньше и могло её заменить.
  let minNdxSum = Infinity;

  // Проходим по элементам list2 по индексам, чтобы вычислять
  // суммы индексов с элементами list1.
  for (let i = 0; i < list2.length; i++) {

    // Если текущий индекс i уже больше минимальной найденной
    // суммы индексов, то дальнейшие элементы не смогут дать
    // меньшую сумму (поскольку j >= 0), можно прервать цикл.
    if (i > minNdxSum) break;

    // Текущая строка из list2 на позиции i.
    const str = list2[i];

    // Получаем индекс этой строки в list1 из Map.
    //
    // Если строки нет в list1, get вернёт undefined.
    const j = list1StrToNdx.get(str);

    // Если j === undefined, значит текущая строка отсутствует в
    // list1 - пропускаем дальнейшую обработку.
    if (j === undefined) continue;

    // Вычисляем сумму индексов:
    // индекс в list2 (i) плюс индекс в list1 (j).
    const currNdxSum = i + j;

    // Если текущая сумма больше уже найденной минимальной,
    // пропускаем - нас интересуют только меньшие или равные
    // суммы.
    if (currNdxSum > minNdxSum) continue;

    // Если текущая сумма строго меньше найденной минимальной,
    // значит найдено лучшее решение.
    if (currNdxSum < minNdxSum) {

      // Очищаем массив commonStrings, сохраняя ссылку на тот же
      // массив.
      //
      // Это быстрее, чем создавать новый массив, и позволяет
      // переиспользовать память.
      //
      // Установка length = 0 - быстрый способ очистки массива
      // без выделения нового объекта.
      commonStrings.length = 0;

      // Обновляем минимальную сумму на новую, меньшую.
      minNdxSum = currNdxSum;
    }

    // Добавляем текущую строку в массив результатов.
    //
    // Этот шаг выполняется как в случае, когда мы только что
    // обновили минимум, так и когда currNdxSum === minNdxSum,
    // что позволяет собрать все строки с одинаковой минимальной
    // суммой индексов.
    commonStrings.push(str);
  }

  // Возвращаем массив найденных общих строк, имеющих минимальную
  // сумму индексов.
  //
  // Если общих строк не найдено, вернётся пустой массив.
  return commonStrings;
}
