/**
 * @param {number[]} nums
 * @return {boolean}
 *
 * isPossibleToSplit принимает массив целых чисел nums чётной длины
 * и проверяет возможно ли разделить массив на две части
 * nums1 и nums2 так, чтобы:
 * - nums1.length == nums2.length == nums.length / 2.
 * - nums1 должен содержать только различные элементы.
 * - nums2 также должен содержать только различные элементы.
 *
 * Возвращает true, если такое разбиение возможно, иначе возвращает
 * false.
 *
 *
 * Пример для:
 *   nums = [1,1,2,2,3,4]
 * Результат:
 *   true
 * Пояснение:
 *   Один из возможных вариантов разбиения nums:
 *   nums1 = [1,2,3] и nums2 = [1,2,4] - в обоих массивах все
 *   элементы различны.
 *
 *
 * Пример для:
 *   nums = [1,1,1,1]
 * Результат:
 *   false
 * Пояснение:
 *   Единственный возможный способ разделить массив на две равные
 *   части:
 *   nums1 = [1,1] и nums2 = [1,1]. В обоих частях есть
 *   повторяющиеся элементы, поэтому требование о том, чтобы каждая
 *   часть содержала только различные элементы, не выполняется, и
 *   ответ - false.

 */
function isPossibleToSplit(nums) {

  // Поскольку оба полученных массива должны содержать только
  // различные элементы, нам нужно аккуратно распределять любые
  // повторяющиеся значения из исходного массива.
  //
  // Если элемент встречается в nums один раз, мы можем поместить
  // его либо в nums1, либо в nums2 - проблем нет.
  //
  // Если элемент встречается дважды, мы обязаны поместить по одной
  // копии в nums1 и nums2, чтобы в каждом из массивов оставались
  // только уникальные значения.
  //
  // Но что если элемент встречается три раза или больше? Здесь
  // возникает непреодолимая проблема. У нас есть только два
  // массива для распределения копий, и каждая часть может принять
  // не более одной копии данного значения (чтобы сохранить
  // уникальность). Следовательно, при 3 или более копиях одного и
  // того же элемента хотя бы одна копия не найдёт допустимого
  // места.
  //
  // Это приводит нас к ключевому выводу: максимальная частота
  // любого элемента в массиве определяет, возможно ли корректное
  // разбиение. Если какой‑то элемент встречается 3 или более раз,
  // мы не сможем разделить массив, соблюдая все ограничения.
  //
  // Поэтому достаточно подсчитать частоту каждого элемента в
  // массиве. Если максимальная частота меньше 3 (то есть все
  // элементы встречаются не более двух раз), разбиение возможно.
  // В противном случае - невозможно.


  // Создаётся типизированный массив Int32Array длиной 101, все
  // элементы инициализируются нулём.
  //
  // Используется как карта частот (frequency map) для чисел в
  // диапазоне 0..100 включительно.
  //
  // Индекс - число из nums
  // Значение - частота вхождение числа в массиве nums
  const numToFreq = new Int32Array(101);

  // Перебираем все значения из входного массива nums
  for (const num of nums) {

    // Префиксный инкремент увеличивает значение счётчика в массиве
    // numToFreq по индексу num на 1, затем присваивает уже
    // увеличенное значение переменной freq.
    const freq = ++numToFreq[num];

    // Если частота текущего числа превысила 2, немедленно
    // возвращаем false, так как разбиение массива на две части с
    // учетом всех условий невозможно
    if (freq > 2) return false;
  }

  // Если цикл завершился без срабатывания раннего возврата, значит
  // разбиение массива на две части с учетом всех условий возможно
  // - возвращаем true
  return true;
}
