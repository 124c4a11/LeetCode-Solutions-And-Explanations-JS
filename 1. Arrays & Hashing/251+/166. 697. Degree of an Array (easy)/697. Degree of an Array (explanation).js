/**
 * @param {number[]} nums
 * @return {number}
 *
 * findShortestSubArray принимает массив чисел nums и вычисляет длину
 * кратчайшего подмассива исходного массива nums, у которого степень
 * (degree) равна степени всего массива.
 *
 * Степень массива - это максимальная частота (максимальное количество
 * вхождений) какого‑либо числа в массиве.
 *
 * Функция находит все числа, достигающие этой максимальной частоты, и для
 * каждого такого числа определяет минимальную длину подмассива, который
 * содержит все его вхождения (от первого до последнего вхождения). Затем
 * возвращается наименьшая из этих длин.
 *
 *
 * Пример для:
 *   nums = [1,2,2,3,1]
 * Результат:
 *   2
 * Пояснение:
 *   Входной массив имеет степень 2, потому что элементы 1 и 2 встречаются
 *   по два раза.
 *
 *   Из подмассивов, имеющих ту же степень:
 *     [1, 2, 2, 3, 1],
 *     [1, 2, 2, 3],
 *     [2, 2, 3, 1],
 *     [1, 2, 2],
 *     [2, 2, 3],
 *     [2, 2]
 *
 *   Кратчайшая длина равна 2. Поэтому возвращаем 2.
 */
function findShortestSubArray(nums) {

  // Инициализация переменной для хранения минимальной длины подмассива.
  //
  // Используем Infinity, чтобы любое реальное найденное значение было
  // меньше и корректно заменило начальное.
  let minSubarrayLength = Infinity;

  // Переменная для отслеживания текущей максимальной частоты (степени)
  // среди всех чисел, встреченных на момент обхода.
  let maxFreq = 0;

  // Map для хранения статистики по каждому уникальному числу из nums.
  //
  // Ключ - само число,
  // Значение - объект { freq, firstNdx }:
  // - freq - сколько раз число встретилось до текущего индекса
  //   включительно,
  //
  // - firstNdx - индекс первого вхождения этого числа в массив.
  const numToStats = new Map();

  // Проходим по всем индексам массива nums в порядке возрастания.
  //
  // Это позволяет в момент первого достижения некоторой частоты корректно
  // вычислять длину подмассива от первого вхождения до текущего индекса.
  for (let i = 0; i < nums.length; i++) {

    // Получаем текущее число из массива по индексу i.
    const num = nums[i];

    // Пытаемся получить уже существующую статистику для текущего числа из
    // Map.
    //
    // Если статистики нет (get вернёт undefined), используем оператор
    // nullish coalescing (??) чтобы создать новый объект статистики с
    // freq: 0 и firstNdx равным текущему индексу i.
    //
    // Это гарантирует, что firstNdx фиксируется при первом появлении
    // числа.
    const numStats = numToStats.get(num) ?? { freq: 0, firstNdx: i };

    // Увеличиваем поле freq в объекте numStats на 1 и сохраняем новое
    // значение в currFreq.
    //
    // Оператор ++ изменяет numStats.freq на месте, поэтому объект в
    // дальнейшем содержит обновлённую частоту.
    const currFreq = ++numStats.freq;

    // Сохраняем индекс первого вхождения в локальную переменную firstNdx
    // для удобства чтения.
    //
    // firstNdx не меняется после первого присвоения, даже если объект
    // numStats создавался ранее.
    const firstNdx = numStats.firstNdx;

    // Обновляем Map, записывая (или перезаписывая) статистику для
    // текущего числа.
    numToStats.set(num, numStats);

    // Если текущая частота currFreq стала больше, чем известный максимум
    // maxFreq, значит мы нашли новое число, степень которого выше прежней
    // степени массива.
    //
    // В этом случае обновляем maxFreq и устанавливаем minSubarrayLength
    // как длину подмассива от первого вхождения этого числа до текущего
    // индекса i.
    if (currFreq > maxFreq) {

      // Обновляем максимальную частоту до текущей.
      maxFreq = currFreq;

      // Длина подмассива от firstNdx до i включительно вычисляется как
      // i - firstNdx + 1.
      //
      // Это минимальная длина подмассива, обеспечивающего текущую степень
      // для этого числа.
      minSubarrayLength = i - firstNdx + 1;

    } else if (currFreq === maxFreq) {

      // Если частота текущего числа равна текущей максимальной частоте,
      // то этот элемент может дать подмассив той же степени, но возможно
      // короче.
      //
      // Сравниваем уже найденную минимальную длину с длиной подмассива
      // для этого числа и сохраняем минимальное значение.
      minSubarrayLength = Math.min(minSubarrayLength, i - firstNdx + 1);
    }
  }

  // Возвращаем minSubarrayLength - длину кратчайшего подмассива, степень
  // которого равна степени всего массива nums.
  return minSubarrayLength;
}
