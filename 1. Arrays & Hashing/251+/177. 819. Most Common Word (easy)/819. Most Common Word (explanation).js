/**
 * @param {string} paragraph
 * @param {string[]} banned
 * @return {string}
 *
 * mostCommonWord принимает два параметра: paragraph - строка с текстом
 * и banned - массив запрещённых слов.
 *
 * Возвращает самое часто встречающееся слово в paragraph, которое не
 * содержится в списке banned.
 *
 *
 * Пример для:
 *   paragraph = "Bob hit a ball, the hit BALL flew far after it was
 *                hit.",
 *   banned = ["hit"]
 * Результат:
 *   "ball"
 * Пояснение:
 * - "hit" встречается 3 раза, но это запрещённое слово.
 *
 * - "ball" встречается 2 раза (и никакое другое слово не встречается
 *    чаще), поэтому это самое частое слово, не входящее в список
 *    banned.
 *
 * Обратите внимание, что слова в параграфе не чувствительны к
 * регистру. Знаки препинания игнорируются (даже если они прилегают к
 * словам, например "ball,"). И хотя "hit" встречается чаще, оно не
 * является ответом, потому что находится в списке запрещённых слов.
 */
function mostCommonWord(paragraph, banned) {

  // Создаём Set из массива banned для O(1)-проверки принадлежности
  // слова к списку запрещённых.
  //
  // Это эффективнее, чем поиск в массиве  при большом количестве
  // проверок.
  const bannedSet = new Set(banned);

  // Приводим весь абзац к нижнему регистру, чтобы сравнения были
  // регистронезависимыми, затем разбиваем строку по любым символам, не
  // являющимся латинскими буквами (регулярное выражение /[^a-z]/).
  //
  // В результате получаем массив токенов, где между словами могут
  // появиться пустые строки из-за последовательных разделителей.
  const words = paragraph.toLowerCase().split(/[^a-z]/);

  // Инициализация переменной для хранения слова с наибольшей частотой.
  let mostFrequentWord = '';

  // Инициализация счётчика максимальной частоты.
  //
  // Используется для сравнения при обновлении наиболее частого слова.
  let maxFreq = 0;

  // Map для хранения частоты встречаемости каждого слова:
  // ключ - слово,
  // значение - количество входений этотго слова в строке paragraph.
  const wordToFreq = new Map();

  // Проходим по каждому токену из массива words
  for (const word of words) {

    // Пропускаем пустые строки, которые возникают при разбиении
    // (например, при двух подряд разделителях), а также слова,
    // которые находятся в bannedSet.
    if (
      word == ''
      || bannedSet.has(word)
    ) continue;

    // Получаем текущую частоту слова из Map.
    //
    // Если слова ещё нет в Map, get вернёт undefined, поэтому
    // используем оператор нулевого слияния ?? для подстановки 0.
    //
    // Затем увеличиваем значение на 1, получая новую частоту для
    // текущего слова.
    const freq = (wordToFreq.get(word) ?? 0) + 1;

    // Обновляем Map, записывая новую частоту для слова
    wordToFreq.set(word, freq);

    // Если частота текущего слова стала больше, чем известный максимум,
    // обновляем maxFreq и запоминаем это слово как наиболее частое.
    if (freq > maxFreq) {
      maxFreq = freq;
      mostFrequentWord = word;
    }
  }

  // После обхода всех слов возвращаем слово с максимальной частотой,
  // которое не было в списке banned.
  //
  // Если таких слов не было, вернётся пустая строка.
  return mostFrequentWord;
}
