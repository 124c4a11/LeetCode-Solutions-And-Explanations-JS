/**
 * @param {number[]} arr
 * @param {number[][]} pieces
 * @return {boolean}
 *
 * canFormArray проверяет, можно ли составить массив arr путём
 * последовательного "склеивания" фрагментов из массива pieces так,
 * чтобы порядок элементов в каждом фрагменте сохранялся и все
 * элементы arr были покрыты без пропусков и наложений.
 *
 * Возвращает true, если такое составление возможно, и false в
 * противном случае.
 *
 *
 * Пример для:
 *   arr = [91,4,64,78],
 *   pieces = [[78],[4,64],[91]]
 * Результат:
 *   true
 * Пояснение:
 *   Конкатенируем [91], затем [4,64], затем [78]
 */
function canFormArray(arr, pieces) {

  // Ключевая идея: поскольку все целые числа различны и мы не можем
  // менять порядок элементов внутри каждого фрагмента, каждый
  // элемент в arr однозначно определяет, какой фрагмент (если
  // таковой есть) должен быть использован на этой позиции.
  //
  // Когда мы встречаем элемент в arr, нужно найти фрагмент, который
  // начинается с этого элемента. Поскольку элементы различны, не
  // более одного фрагмента может начинаться с данного числа. Как
  // только мы найдём такой фрагмент, мы обязаны использовать весь
  // фрагмент в его исходном порядке - нельзя пропускать элементы
  // или переставлять их.
  //
  // Это приводит к жадному подходу:
  // - Начать с начала arr.
  //
  // - Для текущего элемента найти, какой фрагмент начинается с него.
  //
  // - Если ни один фрагмент не начинается с этого элемента, собрать
  //   arr невозможно - вернуть false.
  //
  // - Если найден подходящий фрагмент, проверить, что весь фрагмент
  //   совпадает с последующими последовательными элементами arr.
  //
  // - Сдвинуться в arr на длину совпавшего фрагмента.
  //
  // - Повторять, пока не обработаем весь arr.
  //
  // Причина, по которой этот жадный подход работает - ограничение
  // на различие элементов. Каждый элемент в arr может быть
  // предоставлен только одним фрагментом (тем, который содержит
  // этот элемент). И поскольку мы не можем менять порядок внутри
  // фрагментов, как только мы решаем использовать фрагмент в
  // определённой позиции, мы должны использовать все его элементы
  // подряд. Нет смысла откладывать использование фрагмента - если
  // он подходит сейчас, используем его сейчас.
  //
  // Алгоритм фактически рассматривает каждый фрагмент как неделимый
  // блок, который должен быть размещён целиком, а ограничение
  // различия элементов гарантирует единственный корректный способ
  // сопоставить фрагменты с позициями в arr.


  // Создаём массив фиксированной длины 101, который будет
  // использоваться как хеш-таблица/словарь:
  // - индекс - значение первого элемента фрагмента
  //
  // - значение - сам фрагмент (массив чисел)
  //
  // Используем длину 101, так как значения в arr и pieces лежат в
  // диапазоне 1..100
  const firstPieceNumToPiece = new Array(101);

  // Проходим по каждому фрагменту в массиве pieces.
  for (const piece of pieces) {

    // Сохраняем ссылку на текущий фрагмент в таблице по ключу,
    // равному его первому элементу.
    //
    // Это обеспечивает O(1)-доступ к фрагменту по значению первого
    // числа, вместо поиска по всему массиву pieces.
    firstPieceNumToPiece[piece[0]] = piece;
  }

  // Инициализируем указатель i, который будет перемещаться по
  // массиву arr слева направо, отслеживая текущую позицию, которую
  // мы пытаемся сопоставить с фрагментами.
  let i = 0;

  // Внешний цикл: продолжаем, пока не пройдём весь массив arr.
  //
  // На каждой итерации мы ожидаем найти фрагмент, начинающийся с
  // arr[i], и "вписать" его в arr.
  while (i < arr.length) {

    // Получаем фрагмент, чей первый элемент совпадает с текущим
    // элементом arr[i].
    //
    // Если такой фрагмент отсутствует, matchingPiece будет
    // undefined.
    const matchingPiece = firstPieceNumToPiece[arr[i]];

    // Если для текущего элемента arr не найдено фрагмента, значит
    // невозможно продолжить сборку arr из заданных pieces.
    //
    // Возвращаем false немедленно - дальнейшая проверка не имеет
    // смысла.
    if (!matchingPiece) return false;

    // Внутренний цикл: проходим по всем числам внутри найденного
    // фрагмента matchingPiece в порядке их следования.
    //
    // Мы должны убедиться, что последовательность чисел в
    // matchingPiece полностью совпадает с соответствующей частью
    // arr.
    for (const pieceNum of matchingPiece) {

      // Если текущий элемент arr на позиции i не совпадает с
      // ожидаемым числом pieceNum из фрагмента, это означает, что
      // фрагмент не соответствует arr в этой позиции - возвращаем
      // false.
      if (arr[i] !== pieceNum) return false;

      // Если совпадение успешно, сдвигаем указатель i на следующий
      // элемент arr, чтобы при следующей итерации либо продолжить
      // проверку текущего фрагмента, либо начать следующий фрагмент.
      i++;
    }
  }

  // Если мы вышли из внешнего цикла, это означает, что все элементы
  // arr были успешно сопоставлены последовательным применением
  // фрагментов из pieces - возвращаем true.
  return true;
}
