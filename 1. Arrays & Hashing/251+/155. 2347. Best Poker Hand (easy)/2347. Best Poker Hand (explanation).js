/**
 * @param {number[]} ranks
 * @param {character[]} suits
 * @return {string}
 *
 * bestHand принимает два массива одинаковой длины:
 * - ranks - массив чисел, представляющих ранги карт
 *
 * - suits - массив строк (по одному символу на карту), где
 *   каждая строка содержит символ масти
 *
 * Функция анализирует набор карт и возвращает название лучшей
 * из простых покерных комбинаций:
 * 1. "Flush": Пять карт одной масти.
 * 2. "Three of a Kind": Три карты одного ранга.
 * 3. "Pair": Пара - две карты одного ранга.
 * 4. "High Card": Старшая карта - отсутствие комбинации.
 *
 *
 * Пример для:
 *   ranks = [13,2,3,1,9],
 *   suits = ["a","a","a","a","a"]
 * Результат:
 *   "Flush"
 * Пояснение:
 *   В руке все 5 карт одной масти, поэтому это комбинация
 *   "Flush".
 */
function bestHand(ranks, suits) {

  // Логическая переменная, указывающая, обнаружен ли флеш
  // (все 5 карт одной масти).
  //
  // Изначально false, устанавливается в true при достижении
  // счётчика масти равного 5.
  let isFlush = false;

  // Логическая переменная, указывающая, обнаружен ли триплет
  // (Three of a Kind).
  //
  // Устанавливается в true, когда для какого‑то ранга счётчик
  // достигает 3.
  let isThreeOfAKind = false;

  // Логическая переменная, указывающая, обнаружена ли хотя бы
  // одна пара.
  //
  // Устанавливается в true, когда для какого‑то ранга счётчик
  // достигает 2.
  let isPair = false;

  // Массив частот по мастям.
  //
  // Предполагается 4 возможные масти. Индексы 0..3
  // соответствуют конкретным мастям.
  const suitToFreq = new Int32Array(4);

  // Массив частот по рангам.
  //
  // Размер 14 выбран, чтобы можно было индексировать ранги
  // напрямую по их числовому значению (например, 1..13) без
  // проверки границ в коде.
  //
  // Нулевой элемент остается неиспользуемым
  const rankToFreq = new Int32Array(14);

  // Итерация по всем картам в руке.
  for (let i = 0; i < ranks.length; i++) {

    // Получаем текущий ранг карты из массива ranks.
    const rank = ranks[i];

    // Увеличиваем счётчик входения данного ранга.
    rankToFreq[rank]++;

    // Если для этого ранга стало ровно 3 вхождения, фиксируем
    // наличие Three of a Kind.
    if (rankToFreq[rank] === 3) isThreeOfAKind = true;

    // Если для этого ранга стало ровно 2 вхождения, фиксируем
    // наличие пары.
    if (rankToFreq[rank] === 2) isPair = true;

    // Преобразуем символ масти в числовой индекс.
    //
    // codePointAt(0) возвращает код первой точки кода символа.
    // Вычитаем 97 ('a') чтобы получить 0..3 при представлении
    // мастей 'a'..'d', где 0 → 'a' ... 3 → 'd'.
    const suitNdx = suits[i].codePointAt(0) - 97;

    // Увеличиваем счётчик вхождения соответствующей масти.
    suitToFreq[suitNdx]++;

    // Если для этой масти накопилось 5 карт, фиксируем
    // наличие флеша.
    if (suitToFreq[suitNdx] === 5) isFlush = true;
  }

  // Если найден флеш, функция немедленно возвращает 'Flush'.
  //
  // Это соответствует правилам, где флеш сильнее пары и
  // тройки в данной задаче.
  if (isFlush) return 'Flush';

  // Если флеша нет, но есть тройка - возвращаем
  // 'Three of a Kind'.
  if (isThreeOfAKind) return 'Three of a Kind';

  // Если нет ни флеша, ни тройки, но есть пара - возвращаем
  // 'Pair'.
  if (isPair) return 'Pair';

  // Если ни одно из вышеуказанных сочетаний не обнаружено,
  // возвращаем 'High Card'.
  return 'High Card';
}
