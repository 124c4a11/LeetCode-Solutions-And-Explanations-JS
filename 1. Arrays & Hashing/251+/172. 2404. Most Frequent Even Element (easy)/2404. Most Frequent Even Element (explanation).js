/**
 * @param {number[]} nums
 * @return {number}
 *
 * mostFrequentEven находит среди элементов входного массива nums
 * наиболее часто встречающееся чётное число. Если несколько
 * чётных чисел имеют одинаковую максимальную частоту, функция
 * возвращает наименьшее из них. Если в массиве нет чётных чисел,
 * функция возвращает -1.
 *
 *
 * Пример для:
 *   nums = [0,1,2,2,4,4,1]
 * Результат:
 *   2
 * Пояснение:
 *   Чётные элементы: 0, 2 и 4.
 *   Из них 2 и 4 встречаются чаще всего.
 *   Возвращаем наименьшее из них - 2.
 */
function mostFrequentEven(nums) {

  // Инициализация переменной mostFreqEven значением -1 - будет
  // хранить текущее наиболее частое чётное число.
  //
  // Значение -1 используется как маркер "не найдено ни одного
  // чётного числа".
  let mostFreqEven = -1;

  // Инициализация переменной maxFreq нулём - будет хранить
  // максимальную частота вхождения среди чётных чисел.
  let maxFreq = 0;

  // Создаётся Map для подсчёта частот:
  // ключ - число,
  // значение - количество его вхождений.
  const numToFreq = new Map();

  // Итерация по каждому элементу массива nums
  for (const num of nums) {

    // Проверка на нечётность с помощью побитовой операции AND:
    //
    // (num & 1) даёт 1 для нечётных чисел.
    //
    // Если число нечётное - пропускаем итерацию
    if ((num & 1) === 1) continue;

    // Получаем текущую частоту для num из Map.
    //
    // Если ключ отсутствует, nullish coalescing даёт 0. Затем
    // увеличиваем частоту на 1 - это новая частота после учёта
    // текущего вхождения.
    const freq = (numToFreq.get(num) ?? 0) + 1;

    // Обновляем Map, записывая новую частоту для числа num.
    numToFreq.set(num, freq);

    // Если новая частота меньше текущего максимума, это число не
    // влияет на результат - пропускаем итерацию.
    if (freq < maxFreq) continue;

    // Если частота равна текущему максимуму, применяется правило
    // выбора меньшего числа:
    //
    // При равной частоте мы хотим оставить меньшее число,
    // поэтому если текущее число не меньше уже выбранного -
    // пропускаем итерацию.
    if (
      freq === maxFreq
      && num >= mostFreqEven
    ) continue;

    // Если мы дошли сюда, значит либо freq > maxFreq, либо
    // freq === maxFreq и num < mostFreqEven.
    //
    // Обновляем максимальную частоту на новую более высокую (или
    // равную, но с меньшим числом).
    maxFreq = freq;

    // Обновляем mostFreqEven на текущее число num, так как оно
    // является новым кандидатом на ответ.
    mostFreqEven = num;
  }

  // После перебора всех чисел возвращаем найденное наиболее
  // частое чётное число, либо -1 если ни одного чётного числа не
  // встретилось.
  return mostFreqEven;
}
