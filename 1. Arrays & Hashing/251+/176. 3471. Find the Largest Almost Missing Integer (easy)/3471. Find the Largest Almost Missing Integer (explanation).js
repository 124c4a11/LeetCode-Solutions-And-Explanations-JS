/**
 * @param {number[]} nums
 * @param {number} k
 * @return {number}
 *
 * largestInteger принимает массив целых чисел nums и целое число k.
 *
 * Целое число x называется почти отсутствующим в nums, если x
 * встречается ровно в одном подмассиве размера k внутри nums.
 *
 * Возвращает наибольшее целое число, которое является почти
 * отсутствующим в nums. Если такого числа нет, возвращает -1.
 *
 * Подмассив - это непрерывная последовательность элементов внутри
 * массива.
 *
 *
 * Пример для:
 *   nums = [3,9,2,1,7],
 *   k = 3
 * Результат:
 *   7
 * Пояснение:
 * 1 встречается в 2 подмассивах размера 3:
 *   [9, 2, 1] и [2, 1, 7].
 *
 * 2 встречается в 3 подмассивах размера 3:
 *   [3, 9, 2], [9, 2, 1], [2, 1, 7].
 *
 * 3 встречается в 1 подмассиве размера 3:
 *   [3, 9, 2].
 *
 * 7 встречается в 1 подмассиве размера 3:
 *   [2, 1, 7].
 *
 * 9 встречается в 2 подмассивах размера 3:
 *   [3, 9, 2] и [9, 2, 1].
 *
 * Возвращаем 7, так как это наибольшее число, которое встречается
 * ровно в одном подмассиве размера k.
 *
 *
 * Пример для:
 *   nums = [0,0],
 *   k = 1
 * Результат:
 *   -1
 * Пояснение:
 * Нет целого числа, которое встречается ровно в одном подмассиве
 * размера 1.
 */
function largestInteger(nums, k) {

  // Ключевая идея - понять, какие элементы могут быть
  // "почти отсутствующими" в зависимости от значения k.
  //
  // Когда элемент может появляться ровно в одном подмассиве размера
  // k:
  // - Когда k = 1: каждый элемент сам по себе образует подмассив
  //   размера 1. Элемент появляется ровно в одном таком подмассиве
  //   тогда и только тогда, когда он встречается в массиве ровно
  //   один раз. Это просто - достаточно посчитать вхождения каждого
  //   элемента.
  //
  // - Когда k = n (где n - длина массива): существует только один
  //   подмассив - весь массив. Любой элемент массива появляется в
  //   этом единственном подмассиве, поэтому все элементы являются
  //   "почти отсутствующими". В этом случае достаточно вернуть
  //   максимальный элемент.
  //
  // - Когда 1 < k < n: это интересный случай. Подумайте, какие
  //   элементы могут появиться ровно в одном подмассиве:
  //   - Элемент, находящийся в середине массива, будет входить во
  //     множество перекрывающихся подмассивов размера k.
  //
  //   - Например, элемент nums[i] для индексов, лежащих в
  //     "внутренней" зоне, будет появляться в нескольких
  //     подмассивах.
  //
  //   - Единственные элементы, которые теоретически могут появиться
  //     ровно в одном подмассиве, это крайние элементы:
  //     nums[0] и nums[n-1].
  //
  //   - nums[0] входит только в первый подмассив [0, k-1].
  //
  //   - nums[n-1] входит только в последний подмассив [n-k, n-1].
  //
  //   - Однако если nums[0] встречается где‑то ещё в массиве
  //     (в позициях 1..n-1), то он появится более чем в одном
  //     подмассиве.
  //
  //   - Аналогично, если nums[n-1] встречается где‑то ещё
  //     (в позициях 0..n-2), он появится более чем в одном
  //     подмассиве.
  //
  // Это наблюдение значительно упрощает задачу: вместо проверки
  // всех элементов и всех подмассивов (что было бы дорого по
  // времени), достаточно проверить только:
  // - встречается ли nums[0] где‑то ещё в массиве,
  //
  // - встречается ли nums[n-1] где‑то ещё в массиве,
  //   и вернуть максимум среди тех крайних элементов, которые
  //   удовлетворяют условию "ровно в одном подмассиве".
  //
  // Такое решение элегантно покрывает все три случая с
  // минимальными вычислениями и без явной генерации всех
  // подмассивов.


  // Инициализация переменной maxNum значением 0.
  //
  // Будет использоваться для хранения максимального значения в
  // массиве nums.
  let maxNum = 0;

  // Создание массива фиксированной длины 51 для подсчёта частот
  // чисел от 0 до 50 включительно.
  //
  // Используется Int32Array для экономии памяти и более быстрой
  // работы с целочисленными частотами.
  const numToFreq = new Int32Array(51);

  // Итерация по каждому элементу входного массива nums
  for (const num of nums) {

    // Увеличиваем счётчик в массиве частот для текущего числа num.
    numToFreq[num]++;

    // Обновляем maxNum:
    //
    // Если текущий элемент больше, сохраняем его как новый максимум.
    maxNum = Math.max(maxNum, num);
  }

  // Если длина массива nums равна k, функция сразу возвращает
  // глобальный максимум.
  //
  // Логика:
  // Если нужно выбрать все элементы (k === nums.length), то
  // наибольшим возможным результатом будет максимальный элемент
  // массива.
  if (nums.length === k) return maxNum;

  // Если k равно 1, задача сводится к поиску наибольшего
  // уникального элемента (встречающегося ровно один раз).
  //
  // Оптимизация:
  // Вместо сортировки или дополнительного прохода по массиву,
  // используется ранее построенный массив частот и известный maxNum
  // как верхняя граница.
  if (k === 1) {

    // Проходим по возможным значениям от maxNum вниз до 0, чтобы
    // найти наибольшее число с частотой 1 (уникальное).
    //
    // Обход сверху вниз гарантирует, что первый найденный
    // уникальный элемент (частота 1) будет максимальным
    for (let num = maxNum; num >= 0; num--) {
      if (numToFreq[num] === 1) return num;
    }
  }

  // Получаем первый элемент исходного массива nums
  const firstNum = nums[0];

  // Сохраняем частоту первого элемента из массива частот для
  // последующих сравнений.
  const firstNumFreq = numToFreq[firstNum];

  // Получаем последний элемент массива nums
  const lastNum = nums.at(-1);

  // Сохраняем частоту последнего элемента из массива частот для
  // последующих сравнений.
  const lastNumFreq = numToFreq[lastNum];

  // Если и первый, и последний элементы уникальны (встречаются
  // ровно по одному разу), возвращаем максимальное из них
  if (
    firstNumFreq === 1
    && lastNumFreq === 1
  ) return Math.max(firstNum, lastNum);

  // Если только первый элемент уникален (его частота равна 1),
  // возвращаем его.
  //
  // Это покрывает сценарий, когда первый уникален, а последний -
  // нет.
  if (firstNumFreq === 1) return firstNum;

  // Если только последний элемент уникален (его частота равна 1),
  // возвращаем его.
  //
  // Это покрывает сценарий, когда последний уникален, а первый -
  // нет.
  if (lastNumFreq === 1) return lastNum;

  // Если ни одно из условий не выполнено (нет уникального первого
  // или последнего, и другие ранние условия не сработали),
  // возвращаем -1 как индикатор того, что подходящего числа по
  // заданной логике не найдено.
  return -1;
}
