/**
 * @param {number[]} nums
 * @param {number} k
 * @return {number[]}
 *
 * maxSubsequence принимает массив чисел nums и число k и возвращает
 * подпоследовательность из k элементов исходного массива с
 * максимальной суммой, сохраняя их исходный порядок.
 *
 *
 * Пример для:
 *   nums = [-1,-2,3,4],
 *   k = 3
 * Результат:
 *   [-1,3,4]
 * Пояснение:
 *   Подпоследовательность имеет наибольшую сумму: -1 + 3 + 4 = 6.
 */
function maxSubsequence(nums, k) {

  // Создаём вспомагательный массив объектов.
  //
  // Каждый объект будет содержать исходный индекс элемента из nums
  // и само значение.
  //
  // Для каждого индекса создаём объект { ndx: i, num: nums[i] }:
  // - ndx хранит исходную позицию элемента в nums,
  // - num хранит само числовое значение.
  //
  // Такой формат позволяет сортировать по значению, но затем
  // вернуть элементы в исходном порядке.
  const indexedNums = Array.from(
    { length: nums.length },
    (_, i) => ({ ndx: i, num: nums[i] })
  );

  // Начинаем цепочку операций над массивом indexedNums и вернём
  // результат этой цепочки.
  return indexedNums

    // Сортируем массив объектов по полю num в порядке убывания
    // (от большего к меньшему).
    .sort((a, b) => b.num - a.num)

    // Берём первые k элементов отсортированного по значению
    // массива.
    //
    // slice(0, k) возвращает новый массив, содержащий k объектов с
    // наибольшими значениями num.
    //
    // Если k больше длины массива, slice вернёт весь массив. Если k
    // равно 0 - пустой массив.
    .slice(0, k)

    // Теперь у нас есть ровно k объектов, представляющих k
    // наибольших значений, но их индексы могут быть в произвольном
    // порядке относительно исходного массива. Чтобы вернуть
    // подпоследовательность в исходном порядке, сортируем эти
    // объекты по полю ndx в порядке возрастания.
    .sort((a, b) => a.ndx - b.ndx)

    // Преобразуем массив объектов обратно в массив чисел, извлекая
    // поле num из каждого объекта.
    //
    // map((stat) => stat.num) создаёт новый массив значений в том
    // порядке, который был восстановлен предыдущей сортировкой по
    // ndx, то есть в порядке появления в исходном массиве nums.
    .map((stat) => stat.num);
}
