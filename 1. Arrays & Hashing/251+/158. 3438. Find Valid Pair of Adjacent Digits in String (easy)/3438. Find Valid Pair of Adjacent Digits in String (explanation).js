/**
 * @param {string} s
 * @return {string}
 *
 * findValidPair принимет строку s, состоящую только из цифр.
 *
 * Возвращает первую валидную пару, найденную при обходе строки s
 * слева направо. Если подходящей пары нет, возвращает пустую
 * строку.
 *
 * Валидной парой называется две соседние цифры в s, такие что:
 * - первая цифра не равна второй;
 *
 * - каждая цифра в паре встречается в s ровно столько раз,
 *   сколько равно её числовое значение.
 *
 *
 * Пример для:
 *   s = "2523533"
 * Результат:
 *   "23"
 * Пояснение:
 *   Цифра '2' встречается в строке s ровно 2 раза, а цифра '3'
 *   встречается ровно 3 раза.
 *
 *   Каждая цифра в паре "23" появляется в s ровно столько раз,
 *   сколько равно её числовое значение.
 *
 *   Поэтому результат - строка "23".
 */
function findValidPair(s) {

  // Создаём массив фиксированной длины 101 типа Int32Array для
  // подсчёта частот чисел от 0 до 100 включительно.
  //
  // Int32Array используется для экономии памяти и более быстрой
  // работы с целыми числами по сравнению с обычным массивом.
  //
  // Все элементы инициализируются нулём автоматически.
  const numToFreq = new Int32Array(101);

  // Итерация по каждому символу строки s.
  //
  // Увеличивает счётчик в numToFreq для соответствующего
  // значения.
  for (const num of s) numToFreq[num]++;

  // Итерация по индексам строки s, начиная с 1, чтобы иметь
  // доступ к предыдущему элементу через i-1.
  //
  // Цикл проверяет каждую соседнюю пару элементов в порядке их
  // появления.
  for (let i = 1; i < s.length; i++) {

    // Берём предыдущий элемент пары и явно приводим его к числу
    // через Number.
    const prevNum = Number(s[i - 1]);

    // Берём текущий элемент пары и приводим к числу
    const currNum = Number(s[i]);

    // Условие состоит из трёх частей:
    // 1. prevNum !== currNum - числа в паре должны быть разными.
    //    Это исключает пары одинаковых чисел.
    //
    // 2. numToFreq[prevNum] === prevNum - частота появления
    //    prevNum в массиве должна равняться самому значению
    //    prevNum.
    //
    //    Это означает, что если prevNum равно, например, 3, то в
    //    массиве должно быть ровно три вхождения "3".
    //
    // 3. numToFreq[currNum] === currNum - аналогичное требование
    //    для текущего числа currNum.
    //
    // Все три условия проверяются одновременно через логическое
    // И (&&).
    //
    // Если все три проверки проходят, функция возвращает
    // строковую конкатенацию двух чисел - первую подходящую
    // соседнюю пару (ранний выход).
    if (
      prevNum !== currNum
      && numToFreq[prevNum] === prevNum
      && numToFreq[currNum] === currNum
    ) return `${prevNum}${currNum}`;
  }

  // Если цикл завершился и ни одна соседняя пара не
  // удовлетворила условию, возвращаем пустую строку.
  //
  // Это означает отсутствие подходящей пары в массиве.
  return '';
}
