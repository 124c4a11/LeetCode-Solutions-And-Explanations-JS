/**
 * @param {number[]} nums1
 * @param {number[]} nums2
 * @return {number}
 *
 * getCommon принимает два отсортированных по возрастанию массива
 * nums1 и nums2. В двух этих массивах ищет и возвращает первое
 * (наименьшее по значению) общее число. Если общего элемента нет,
 * возвращает -1.
 *
 *
 * Пример для:
 *   nums1 = [1,2,3],
 *   nums2 = [2,4]
 * Результат:
 *   2
 * Пояснение:
 *   Наименьший элемент, общий для обоих массивов - 2, поэтому
 *   возвращаем 2.
 */
function getCommon(nums1, nums2) {

  // Инициализация указателя для первого массива.
  //
  // Хранит индекс текущего рассматриваемого элемента в nums1.
  let nums1Ndx = 0;

  // Инициализация указателя для второго массива
  //
  // Хранит индекс текущего рассматриваемого элемента в nums2.
  let nums2Ndx = 0;

  // Цикл while выполняется, пока оба указателя находятся в
  // пределах соответствующих массивов.
  //
  // Это условие предотвращает выход за границы и гарантирует, что
  // сравнение выполняется только для существующих элементов.
  while (
    nums1Ndx < nums1.length
    && nums2Ndx < nums2.length
  ) {

    // Получаем текущий элемент из nums1 по индексу nums1Ndx.
    const num1 = nums1[nums1Ndx];

    // Получаем текущий элемент из nums2 по индексу nums2Ndx.
    const num2 = nums2[nums2Ndx];

    // Если текущие элементы равны, найден общий элемент.
    //
    // Возвращаем его немедленно - это обеспечивает ранний выход и
    // минимальное количество операций.
    if (num1 === num2) return num1;

    // Если элемент из nums1 меньше элемента из nums2, то сдвигаем
    // указатель nums1 вправо.
    //
    // Логика:
    // Так как массивы отсортированы, меньший элемент не может
    // совпасть с текущим элементом другого массива, поэтому нужно
    // увеличить меньший указатель, чтобы "догнать" больший
    // элемент.
    if (num1 < num2) nums1Ndx++;

    // В противном случае (num1 > num2) сдвигаем указатель nums2
    // вправо.
    //
    // Это симметричная операция для случая, когда элемент из
    // nums2 меньше.
    else nums2Ndx++;
  }

  // Если цикл завершился без нахождения совпадения, возвращаем -1.
  return -1;
}
