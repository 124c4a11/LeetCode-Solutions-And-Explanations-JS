/**
 * @param {number} n
 * @param {number} k
 * @return {number[]}
 *
 * circularGameLosers моделирует простую круговую игру передачи мяча между
 * n игроками, расположенными по кругу. На каждом ходе i мяч передаётся
 * вперёд на i * k позиций (где i - номер хода, начиная с 1). Функция
 * отслеживает, какие игроки когда‑либо получали мяч. Как только мяч
 * попадает к игроку, который уже получал его ранее, симуляция
 * останавливается. В результате функция возвращает массив номеров игроков
 * (в 1‑based нумерации), которые никогда не получали мяч, то есть
 * проигравших.
 *
 * Параметры:
 *   n - целое число, количество игроков в круге (ожидается n > 0);
 *
 *   k - целое число, множитель шага на каждом ходе (может быть любым
 *       целым).
 *
 *
 * Пример для:
 *   n = 5,
 *   k = 2
 * Результат:
 *   [4,5]
 * Пояснение:
 *   Игра проходит следующим образом:
 *   1. Начинаем с 1-го друга и передаём мяч другу, который находится на 2
 *      шага вперёд - 3-му другу.
 *
 *   2. 3-й друг передаёт мяч другу, который находится на 4 шага вперёд -
 *      2-му другу.
 *
 *   3. 2-й друг передаёт мяч другу, который находится на 6 шагов вперёд -
 *      3-му другу.
 *
 *   4. Игра заканчивается, так как 3-й друг получает мяч во второй раз.
 */
function circularGameLosers(n, k) {

  // Создаём массив длины n для отслеживания посещений игроков.
  //
  // Элементы по умолчанию равны undefined. Будем записывать true для тех,
  // кто получил мяч.
  const playerToSeen = new Array(n);

  // Инициализируем индекс текущего игрока нулём.
  //
  // Внутренне игроки нумеруются с 0 до n-1 - это упрощает вычисления по
  // модулю n.
  let player = 0;

  // Цикл моделирует последовательные ходы игры.
  //
  // Переменная turn начинается с 1 (первый ход) и увеличивается на 1
  // после каждого прохода.
  //
  // Условие !playerToSeen[player] проверяет, не был ли текущий игрок уже
  // посещён.
  //
  // Условие продолжения цикла - текущий игрок ещё не был отмечен как
  // посещённый. Как только мы вернёмся к уже посещённому игроку, цикл
  // прервётся.
  for (let turn = 1; !playerToSeen[player]; turn++) {

    // Отмечаем, что текущий игрок получил мяч в этом ходе.
    //
    // Запись true позволяет в дальнейшем однозначно отличать посещённых
    // от непосещённых.
    playerToSeen[player] = true;

    // Вычисляем индекс следующего игрока:
    //
    // Сдвигаемся на turn * k позиций вперёд по кругу и берём остаток по n,
    // чтобы оставаться в диапазоне 0..n-1 (циклическое поведение)
    player = (player + turn * k) % n;
  }

  // Создаём массив для номеров проигравших - тех игроков, которые никогда
  // не получили мяч.
  const losers = [];

  // Перебираем все индексы игроков, начиная с 1.
  //
  // Индекс 0 пропускается в переборе, потому что это стартовый игрок,
  // и он всегда будет отмечен как посещённый в первом проходе цикла.
  for (let player = 1; player < playerToSeen.length; player++) {

    // Если для данного индекса значение в playerToSeen ложно (undefined),
    // значит этот игрок не получил мяч ни разу и считается проигравшим.
    //
    // В результирующий массив добавляем номер игрока в 1‑based системе
    // (player + 1), потому что внешнее представление игроков обычно
    // начинается с 1.
    if (!playerToSeen[player]) losers.push(player + 1);
  }

  // Возвращаем массив проигравших (номера в 1‑based формате).
  return losers;
}
