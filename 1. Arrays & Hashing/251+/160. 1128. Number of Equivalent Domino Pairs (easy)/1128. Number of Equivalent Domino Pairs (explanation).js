/**
 * @param {number[][]} dominoes
 * @return {number}
 *
 * numEquivDominoPairs массив пар чисел dominoes (каждая доминошка -
 * массив длины 2). Функция подсчитывает и возвращает количество пар
 * эквивалентных доминошек в массиве. Две доминошки считаются
 * эквивалентными, если они содержат те же два числа в любом порядке
 * (например, [1,2] эквивалентно [2,1]).
 *
 *
 * Пример для:
 *   dominoes = [[1,2],[2,1],[3,4],[5,6]]
 * Результат:
 *   1
 * Пояснение:
 *   Существует только одна пара - [1,2] и [2,1]
 */
function numEquivDominoPairs(dominoes) {

  // Ключевая идея в том, чтобы понять: эквивалентные домино - по
  // сути одна и та же фишка, просто возможно повернутая. При
  // подсчёте пар нам нужен способ однозначно определять, какие
  // домино эквивалентны независимо от их ориентации.
  //
  // Представьте физическое домино с числами [1, 2]: его можно
  // положить как [1, 2] или как [2, 1] поворотом. Это одно и то же
  // домино. Поэтому нужно дать обеим ориентациям одинаковую
  // "идентичность".
  //
  // Естественный подход - ввести каноническую форму для каждого
  // домино - стандартное представление, не зависящее от поворота.
  // Добиться этого можно, всегда упорядочивая числа в одном и том
  // же порядке, например, от меньшего к большему. Тогда и [1, 2], и
  // [2, 1] будут представлены как (1, 2) в канонической форме.
  //
  // Когда у нас есть каноническое представление, подсчёт пар
  // становится простым. Обрабатывая каждое домино:
  // - проверяем, сколько домино с такой же канонической формой мы
  //   видели ранее;
  //
  // - каждое из этих ранее встреченных домино может образовать пару
  //   с текущим;
  //
  // - затем фиксируем, что мы увидели ещё одно домино этого типа.
  //
  // Формула a * 10 + b (где a <= b) - это удобный способ получить
  // уникальный идентификатор для каждой канонической формы.
  // Поскольку значения на домино - однозначные цифры (0–9),
  // умножение первого на 10 и прибавление второго даёт уникальное
  // двухзначное число. Например, [1, 2] превращается в 12,
  // [3, 4] - в 34. Это упрощает использование счётчика или массива
  // для отслеживания вхождений.
  //
  // Преимущество такого подхода в том, что требуется всего один
  // проход по массиву, что делает алгоритм эффективным с временной
  // сложностью O(n).


  // Инициализация счётчика найденных пар.
  let pairsCnt = 0;

  // Создаём массив фиксированной длины 100 для подсчёта вхождений
  // каждой канонической формы домино.
  //
  // Размер 100 выбран потому, что ключ формируется как a*10 + b,
  // где a и b - цифры 0..9, диапазон ключей 0..99.
  const dominoKeyToCnt = new Int32Array(100);

  // Итерация по каждому элементу входного массива dominoes.
  //
  // Для ускорения работы кода не используем деструктуризацию
  // массива domino внутри цикла, а обращаемся к его элементам по
  // их индексам
  for (const domino of dominoes) {

    // Извлекаем первое число текущего домино
    const num1 = domino[0];

    // Извлекаем второе число текущего домино
    const num2 = domino[1];

    // Вычисляем канонический ключ для текущего домино.
    //
    // Идея:
    // Привести оба возможных порядка [a,b] и [b,a] к одному
    // представлению.
    //
    // Если num1 < num2, используем
    // num1 * 10 + num2, иначе - num2 * 10 + num1.
    //
    // Это даёт уникальное число в диапазоне 0..99 для каждой
    // упорядоченной пары цифр 0..9.
    const dominoKey = num1 < num2
      ? num1 * 10 + num2
      : num2 * 10 + num1;

    // Добавляем к общему числу пар количество ранее встреченных
    // домино с тем же ключом.
    //
    // Обоснование:
    // Если до текущего момента встретилось k домино с этим ключом,
    // то текущий элемент может образовать пары с каждым из них, то
    // есть добавить k новых пар.
    //
    // Таким образом, суммируя для каждого элемента количество
    // предыдущих вхождений, в итоге получаем общее число пар,
    // равное сумме по ключам n*(n-1)/2.
    pairsCnt += dominoKeyToCnt[dominoKey];

    // Увеличиваем счётчик вхождений для данного ключа на 1.
    //
    // После этой строки dominoKeyToCnt[dominoKey] отражает
    // количество встреченных до и включая текущий элемент.
    dominoKeyToCnt[dominoKey]++;
  }

  // Возвращаем итоговое количество эквивалентных пар домино.
  //
  // Временная сложность алгоритма - O(n), где n - длина массива
  // dominoes, так как выполняется один проход по входному массиву.
  //
  // Память - O(1) дополнительной памяти в смысле зависимости от
  // входа, так как массив счётчиков фиксированного размера 100.
  return pairsCnt;
}
