/**
 * @param {number} n
 * @param {number[][]} pick
 * @return {number}
 *
 * winningPlayerCount принимает целое число n, обозначающее количество
 * игроков в игре, и двумерный массив pick, где pick[i] = [xi, yi]
 * означает, что игрок xi выбрал шарик цвета yi.
 *
 * Игрок i выигрывает игру, если он выбрал строго больше, чем i,
 * шариков одного и того же цвета.
 *
 * Другими словами:
 * - Игрок 0 выигрывает, если он выбрал любой шарик.
 *
 * - Игрок 1 выигрывает, если он выбрал по крайней мере два шарика
 *   одного цвета.
 *
 * - ...
 *
 * - Игрок i выигрывает, если он выбрал по крайней мере i + 1 шариков
 *   одного цвета.
 *
 * Возвращае количество игроков, которые выигрывают игру.
 *
 * Обратите внимание, что несколько игроков могут выиграть игру.
 *
 *
 * Пример для:
 *   n = 4,
 *   pick = [[0,0],[1,0],[1,0],[2,1],[2,1],[2,0]]
 * Результат:
 *   2
 * Пояснение:
 *   Игрок 0 и игрок 1 выигрывают игру, тогда как игроки 2 и 3 не
 *   выигрывают.
 *
 *
 * Пример для:
 *    n = 5,
 *    pick = [[1,1],[1,2],[1,3],[1,4]]
 * Результат:
 *   0
 * Пояснение:
 *   Ни один игрок не выигрывает игру.
 *
 *   Игрок 1 сделал четыре выбора, но все шарики разных цветов, поэтому
 *   ни один цвет не встречается более одного раза
 */
function winningPlayerCount(n, pick) {

  // Создаём массив длины n, где для каждого игрока будет свой массив
  // счётчиков по цветам.
  //
  // Индекс - индекс текущего игрока
  // Значение - массив, где
  //   индекс - цвет шара
  //   значение - сколько раз этот шар выбран текущим игроком
  const playerToBallColorToCnt = Array.from(
    { length: n },
    () => new Int32Array(11)
  );

  // Создаём пустое множество для хранения индексов игроков, которые
  // "выиграли".
  //
  // Set обеспечивает уникальность: один игрок будет учтён только один
  // раз, даже если условие выполнится несколько раз.
  const winningPlayers = new Set();

  // Проходим по всем элементам входного массива pick.
  //
  // pair - массив, где
  // [0] - индекс игрока,
  // [1] - цвет выбранного шара.
  //
  // Для ускорения работы кода не используем деструктуризацию pair
  // внутри цикла, а обращаемся к его элементам по индексу.
  for (const pair of pick) {

    // Извлекаем индекс игрока из текущей пары.
    const player = pair[0];

    // Извлекаем код цвета шарика из текущей пары.
    const ballColor = pair[1];

    // Увеличиваем счётчик цвета шара выбранного текущим игроком на 1.
    //
    // Оператор ++ в префиксной форме сначала увеличивает значение в
    // массиве, затем возвращает новое значение.
    const ballColorCnt = ++playerToBallColorToCnt[player][ballColor];

    // Если количество шариков данного цвета у игрока стало строго
    // больше значения player, то добавляем индекс игрока в множество
    // победителей.
    if (ballColorCnt > player) winningPlayers.add(player);
  }

  // Возвращаем количество уникальных игроков, которые удовлетворили
  // условию.
  //
  // Set.size - O(1) операция, возвращающая текущее количество
  // элементов в множестве.
  return winningPlayers.size;
}
