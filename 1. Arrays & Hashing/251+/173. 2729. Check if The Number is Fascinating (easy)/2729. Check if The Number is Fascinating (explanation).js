/**
 * @param {number} n
 * @return {boolean}
 *
 * isFascinating проверяет, является ли переданное число n fascinating.
 *
 * Число n является fascinating, если после конкатенации n, n*2 и n*3 в
 * одну строку, в этой строке ровно 9 символов от 1 до 9, все символы
 * уникальны и среди них нет 0.
 *
 *
 * Пример для:
 *   n = 192
 * Результат:
 *   true
 * Пояснение:
 *   Мы конкатенируем числа n = 192, 2 * n = 384 и 3 * n = 576.
 *   Получившееся число: 192384576.
 *   Это число содержит все цифры от 1 до 9 ровно по одному разу.
 *
 *
 * Пример для:
 *   n = 100
 * Результат:
 *   false
 * Пояснение:
 *   Мы конкатенируем числа n = 100, 2 * n = 200 и 3 * n = 300.
 *   Получившееся число: 100200300.
 *   Это число не удовлетворяет требованию (есть нули и повторяющиеся
 *   цифры).
 */
function isFascinating(n) {

  // Формируем строку, конкатенируя три числа в указанном порядке:
  // n, n*2, n*3.
  const str = `${n}${n * 2}${n * 3}`;

  // Проверка длины результирующей строки:
  //
  // По определению "fascinating" конкатенация должна давать ровно 9
  // цифр.
  //
  // Если длина не равна 9, дальнейшие проверки бессмысленны -
  // возвращаем false (ранний выход).
  if (str.length !== 9) return false;

  // Создаём Set из символов строки.
  //
  // Set принимает итерируемый объект (строку) и добавляет каждый
  // символ как отдельный элемент.
  //
  // В результате получаем коллекцию уникальных символов (цифр) из
  // строки. Дубликаты автоматически удаляются.
  const set = new Set(str);

  // Проверяем, содержит ли set символ '0'.
  //
  // По определению "fascinating" допустимы только цифры 1–9, поэтому
  // наличие '0' делает число недопустимым - возвращаем false.
  if (set.has('0')) return false;

  // Если в set ровно 9 уникальных символов, значит строка содержит 9
  // различных цифр.
  //
  // В сочетании с предыдущими проверками (длина строки 9 и отсутствие
  // '0') это эквивалентно тому, что строка содержит все цифры
  // от '1' до '9' ровно по одному разу.
  //
  // Возвращаем true, если условие выполнено, иначе false.
  return set.size === 9;
}
