/**
 * @param {string} s
 * @param {string} target
 * @return {number}
 *
 * rearrangeCharacters принимает две строки s и target. Возвращает
 * максимальное количество полных копий строки target, которые
 * можно составить из символов строки s, если разрешено
 * переставлять символы s и использовать каждый символ не более
 * одного раза.
 *
 *
 * Пример для:
 *   s = "ilovecodingonleetcode",
 *   target = "code"
 * Результат:
 *   2
 * Пояснение:
 *   Для первой копии "code" возьмём буквы по индексам 4, 5, 6 и 7.
 *
 *   Для второй копии "code" возьмём буквы по индексам 17, 18, 19 и
 *   20.
 *
 *   Полученные строки - "ecod" и "code" - обе могут быть
 *   переставлены в "code".
 *
 *   Максимально можно составить две полные копии "code", поэтому
 *   функция возвращает 2.
 */
function rearrangeCharacters(s, target) {

  // Создаём массив фиксированной длины 26 для хранения
  // целочисленных частот букв в target.
  //
  // Int32Array экономичнее по памяти и быстрее для числовых
  // операций по сравнению с обычным массивом объектов.
  //
  // Индекс 0 соответствует 'a', 25 - 'z'.
  const targetCharToFreq = new Int32Array(26);

  // Итерация по каждому символу в строке target.
  for (const char of target) {

    // Получаем код символа (UTF-16/Unicode) и вычитаем код 'a'
    // (97), чтобы получить индекс в диапазоне 0..25.
    //
    // Увеличиваем счётчик для соответствующей буквы в массиве
    // частот на 1.
    targetCharToFreq[char.codePointAt(0) - 97]++;
  }

  // Создаём аналогичный массив частот для символов из строки s.
  //
  // Он будет использоваться для сравнения с требуемыми частотами
  // из target.
  const sCharToFreq = new Int32Array(26);

  // Проходим по каждому символу в s и считаем, сколько раз каждая
  // буква встречается в исходной строке.
  for (const char of s) {

    // Аналогично: вычисляем индекс буквы относительно 'a' и
    // инкрементируем соответствующую ячейку.
    sCharToFreq[char.codePointAt(0) - 97]++;
  }

  // Инициализируем переменную copiesCnt значением Infinity, чтобы
  // при первом вычислении минимального ограничения она была
  // заменена.
  let copiesCnt = Infinity;

  // Перебираем все возможные буквы алфавита (индексы 0..25
  // соответствуют 'a'..'z').
  for (let i = 0; i < 26; i++) {

    // Считываем, сколько раз буква с индексом i требуется в target.
    const targetCharFreq = targetCharToFreq[i];

    // Если буква не используется в target (частота 0), она не
    // влияет на ограничение числа копий - пропускаем.
    if (targetCharFreq === 0) continue;

    // Считываем, сколько раз та же буква доступна в s.
    const sCharFreq = sCharToFreq[i];

    // Если в s отсутствует хотя бы одна буква, которая требуется
    // в target, невозможно составить ни одной полной копии -
    // возвращаем 0 немедленно.
    //
    // Это ранний выход, экономящий дальнейшие вычисления.
    if (sCharFreq === 0) return 0;

    // Вычисляем максимально возможное число копий target,
    // ограниченное текущей буквой: целочисленное деление
    // количества доступных символов на количество требуемых в
    // одной копии.
    //
    // Math.floor используется для явного округления вниз.
    const possibleCopiesCnt = Math.floor(sCharFreq / targetCharFreq);

    // Обновляем глобальное ограничение copiesCnt как минимум по
    // всем буквам:
    //
    // Итоговое число копий равно минимальному из возможных по
    // каждой требуемой букве, потому что каждая буква должна
    // присутствовать в достаточном количестве одновременно.
    copiesCnt = Math.min(copiesCnt, possibleCopiesCnt);
  }

  // Возвращаем найденное максимальное количество полных копий
  // target, которое можно составить из s.
  return copiesCnt;
}
