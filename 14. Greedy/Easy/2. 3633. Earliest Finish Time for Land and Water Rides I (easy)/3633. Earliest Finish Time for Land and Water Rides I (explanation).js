/**
 * @param {number[]} landStartTime
 * @param {number[]} landDuration
 * @param {number[]} waterStartTime
 * @param {number[]} waterDuration
 * @return {number}
 *
 * Даны две категории аттракционов в тематическом парке: наземные и водные.
 *
 * Наземные аттракционы:
 *  landStartTime[i] - самое раннее время, когда можно начать кататься
 *  на i-м наземном аттракционе.
 *
 *  landDuration[i] - продолжительность поездки на i-м наземном аттракционе.
 *
 * Водные аттракционы:
 *   waterStartTime[j] - самое раннее время, когда можно начать кататься
 *   на j-м водном аттракционе.
 *
 *   waterDuration[j] - продолжительность поездки на j-м водном аттракционе.
 *
 * Турист должен посетить ровно по одному аттракциону каждой категории.
 * Порядок посещения может быть любым.
 *
 * Правила:
 *  1. Начать кататься на аттракционе можно в момент его открытия
 *     или в любое более позднее время.
 *
 *  2. Если поездка начинается в момент времени t, то она заканчивается
 *     в момент времени t + duration.
 *
 *  3. Сразу после завершения одной поездки турист может отправиться
 *     на другой аттракцион, если тот уже открыт.
 *     В противном случае турист должен дождаться его открытия.
 *
 * Функция вовзвращает самое раннее возможное время, когда турист сможет
 * завершить посещение обоих аттракционов.
 *
 *
 * Пример для:
 *   landStartTime = [2, 8]
 *   landDuration = [4, 1]
 *   waterStartTime = [6]
 *   waterDuration = [3]
 *
 * Результат:
 *  9
 *
 * Пояснение:
 * План A (наземный аттракцион 0 → водный аттракцион 0):
 *   Начинаем кататься на наземном аттракционе 0 в момент времени 2.
 *   Завершаем поездку в момент 2 + 4 = 6.
 *   Водный аттракцион 0 открывается в момент времени 6.
 *   Сразу начинаем кататься и завершаем поездку в момент 6 + 3 = 9.
 *
 * План B (водный аттракцион 0 → наземный аттракцион 1):
 *   Начинаем кататься на водном аттракционе 0 в момент времени 6.
 *   Завершаем поездку в момент 6 + 3 = 9.
 *   Наземный аттракцион 1 открывается в момент времени 8.
 *   Начинаем кататься в момент времени 9 и завершаем поездку в момент 10.
 *
 * План C (наземный аттракцион 1 → водный аттракцион 0):
 *   Начинаем кататься на наземном аттракционе 1 в момент времени 8.
 *   Завершаем поездку в момент 8 + 1 = 9.
 *   Водный аттракцион 0 уже открыт.
 *   Начинаем кататься в момент времени 9 и завершаем поездку в момент 12.
 *
 * План D (водный аттракцион 0 → наземный аттракцион 0):
 *   Начинаем кататься на водном аттракционе 0 в момент времени 6.
 *   Завершаем поездку в момент 6 + 3 = 9.
 *   Наземный аттракцион 0 уже открыт.
 *   Начинаем кататься в момент времени 9 и завершаем поездку в момент 13.
 *
 * План A позволяет завершить обе поездки раньше всего - в момент времени 9.
 */
function earliestFinishTime(landStartTime, landDuration, waterStartTime, waterDuration) {

  // Поскольку нам нужно прокатиться ровно на одном аттракционе из каждой
  // категории, существует два возможных порядка: сначала наземный
  // аттракцион, затем водный, или сначала водный, затем наземный. Нам
  // нужно проверить оба варианта и найти тот, который позволит завершить
  // обе поездки как можно раньше.
  //
  // Для любого выбранного порядка главная задача - минимизировать общее
  // время. После завершения первой поездки мы хотим начать вторую как
  // можно скорее. Однако есть ограничение: нельзя начать вторую поездку
  // раньше времени её открытия.
  //
  // Рассмотрим оптимальную стратегию выбора аттракционов в фиксированном
  // порядке (например, сначала наземный, затем водный):
  // 1. Для первой категории (наземные аттракционы) нужно как можно раньше
  //    завершить поездку. Минимальное время завершения среди всех наземных
  //    аттракционов равно min(landStartTime[i] + landDuration[i]) для всех
  //    i. Это даёт самое раннее время окончания первой поездки.
  //
  // 2. Для второй категории (водные аттракционы) необходимо учитывать два
  //    ограничения:
  //    - Нельзя начать поездку раньше времени открытия водного аттракциона:
  //      waterStartTime[j].
  //
  //    - Нельзя начать поездку раньше завершения наземной поездки:
  //      minEnd, найденного на предыдущем шаге.
  //
  //    Поэтому время начала водной поездки равно
  //    max(waterStartTime[j], minEnd), а время её завершения -
  //    max(waterStartTime[j], minEnd) + waterDuration[j].
  //
  //    Чтобы найти минимальное общее время завершения, перебираем все
  //    водные аттракционы и выбираем тот, поездка на котором закончится
  //    раньше всего.
  //
  // Та же логика применяется при обратном порядке: сначала водный
  // аттракцион, затем наземный.
  //
  // Решение элегантно реализует эту идею с помощью функции calc, которая
  // принимает время начала работы и продолжительность аттракционов в
  // заданном порядке. Сначала функция находит минимальное время завершения
  // поездки на аттракционе первой категории, а затем вычисляет минимальное
  // общее время завершения, перебирая все варианты аттракционов второй
  // категории.
  //
  // Вызывая эту функцию дважды с переставленными параметрами, мы проверяем
  // оба возможных порядка поездок и возвращаем минимальное из полученных
  // времён.


  // Вычисляем минимальное время завершения для сценария, когда турист
  // сначала идет на наземный аттракцион, а затем на водный
  const landFirstFinishTime = calc(landStartTime, landDuration, waterStartTime, waterDuration);

  // Вычисляем минимальное время завершения для противоположного сценария,
  // когда первым посещается водный аттракцион, а затем наземный
  const waterFirstFinishTime = calc(waterStartTime, waterDuration, landStartTime, landDuration);

  // Возвращаем наименьшее значение из двух сценариев, которое и будет
  // самым ранним временем окончания обоих аттракционов
  return Math.min(landFirstFinishTime, waterFirstFinishTime);
}

/**
 * @param firstStartTimes - Массив возможных времен начала для первого действия
 * @param firstDurations - Массив длительностей для первого действия
 * @param secondStartTimes - Массив возможных времен начала для второго действия
 * @param secondDurations - Массив длительностей для второго действия
 * @returns Минимальное общее время завершения для этой последовательности
 *
 * Функция вычисляет минимальное время завершения при выполнении сначала
 * первого действия, затем второго действия.
 */
function calc(firstStartTimes, firstDurations, secondStartTimes, secondDurations) {

  // Объявляем переменную-аккумулятор для поиска самой ранней точки выхода
  // из первого аттракциона.
  //
  // Инициализируем ее константой Number.MAX_SAFE_INTEGER
  // (9007199254740991), чтобы любое реальное время гарантированно было
  // меньше при первом сравнении.
  let earliestFirstActivityEnd = Number.MAX_SAFE_INTEGER;

  // Запускаем итерационный цикл по индексам массива первой категории
  // аттракционов для поиска наилучшего (самого быстрого) варианта старта
  // программы
  for (let i = 0; i < firstStartTimes.length; i++) {

    // В каждой итерации вычисляем время окончания i-го аттракциона
    // (время его открытия + его длительность) и сохраняем наименьший
    // результат. Так как турист может пойти на него сразу в момент
    // открытия, нет смысла ждать, и мы получаем минимально возможное время
    // освобождения туриста.
    earliestFirstActivityEnd = Math.min(
      earliestFirstActivityEnd,
      firstStartTimes[i] + firstDurations[i]
    );
  }

  // Объявляем переменную для хранения минимального итогового времени
  // завершения обоих аттракционов
  //
  // Снова инициализируем её верхним безопасным пределом чисел в JavaScript
  // для корректного поиска минимума через Math.min.
  let minTotalFinishTime = Number.MAX_SAFE_INTEGER;

  // Запускаем второй цикл, который перебирает все доступные аттракционы из
  // второй (следующей по очереди) категории
  for (let i = 0; i < secondStartTimes.length; i++) {

    // Определяем реальное время старта второго аттракциона:
    //
    // Берем максимум между временем окончания первого и временем открытия
    // второго
    const actualSecondStartTime = Math.max(earliestFirstActivityEnd, secondStartTimes[i]);

    // Считаем общее время завершения как сумму реального времени старта
    // второго аттракциона и его длительности
    const totalFinishTime = actualSecondStartTime + secondDurations[i];

    // Обновляем глобальный минимум для текущей последовательности, если
    // полученное время оказалось меньше предыдущих вариантов
    minTotalFinishTime = Math.min(minTotalFinishTime, totalFinishTime);
  }

  // Возвращаем найденное минимальное время завершения для данного порядка
  // аттракционов
  return minTotalFinishTime;
}
