/**
 * @param {number[]} deck
 * @return {boolean}
 *
 * hasGroupsSizeX принимает массив целых чисел deck, где deck[i] - число,
 * написанное на i‑й карте, и проверяет, можно ли разбить переданную колоду
 * карт на одну или несколько групп одинакового размера x > 1, так чтобы в
 * каждой группе все карты имели одно и то же значение.
 *
 *
 * Пример для:
 *   deck = [1,2,3,4,4,3,2,1]
 * Результат:
 *   true
 * Пояснение:
 *   Возможное разбиение: [1,1], [2,2], [3,3], [4,4].
 *
 *
 * Пример для:
 *   deck = [1,1,1,2,2,2,3,3]
 * Результат:
 *   false
 * Пояснение:
 *   Невозможно выполнить разбиение.
 */
function hasGroupsSizeX(deck) {

  // Подумайте, какие условия должны выполняться, чтобы существовало
  // допустимое разбиение. Если некоторое число встречается 6 раз, эти
  // карты можно разбить на группы размера 2 (три группы), размера 3 (две
  // группы) или размера 6 (одна группа). Обратите внимание, что 2, 3 и 6
  // - делители 6.
  //
  // Теперь рассмотрим два разных числа: одно встречается 6 раз, другое - 9
  // раз. Чтобы оба можно было разделить на группы одного и того же размера
  // x, этот x должен делить и 6, и 9. Общие делители 6 и 9 - 1 и 3.
  // Поскольку размер группы должен быть больше 1, подходит только x = 3.
  //
  // Эта идея распространяется на любое количество различных значений карт.
  // Для того чтобы все карты можно было разбить на группы размера x:
  // - x должен делить количество каждой отдельной карточной метки в колоде
  // - x должен быть больше 1
  //
  // Множество возможных значений x - это общие делители всех количеств.
  // Наибольший общий делитель (НОД) всех количеств - наибольший такой x.
  // Если НОД >= 2, то можно использовать НОД (или любой его делитель > 1)
  // в качестве размера группы.
  //
  // Следовательно, задача сводится к нахождению НОД всех количеств карт и
  // проверке, не меньше ли он 2. Это математическое наблюдение превращает,
  // казалось бы, сложную задачу разбиения в простое вычисление НОД.


  // Создаём Map для подсчёта частот:
  // ключ - значение на карте,
  // значение - сколько раз оно встречается.
  const numToFreq = new Map();

  // Итерация по каждому элементу входного массива deck
  for (const num of deck) {

    // Получаем текущую частоту для числа num из Map.
    //
    // Если ключа ещё нет, get вернёт undefined.
    //
    // Оператор ?? заменяет undefined на 0, затем прибавляем 1 - это
    // стандартный приём для инкремента счётчика.
    //
    // После вычисления новой частоты сохраняем её обратно в Map под ключом
    // num.
    numToFreq.set(num, (numToFreq.get(num) ?? 0) + 1);
  }

  // Инициализация переменной commonGroupSize частотой первого элемента
  // deck.
  //
  // Это начальное значение для вычисления НОД по всем частотам.
  let commonGroupSize = numToFreq.get(deck[0]);

  // Проходим по всем записям Map numToFreq. Каждая итерация возвращает
  // пару [ключ, значение].
  for (const pair of numToFreq) {

    // pair - это массив из двух элементов:
    // pair[0] - ключ (число на карте),
    // pair[1] - значение (частота).
    //
    // Обновляем commonGroupSize, вычисляя НОД текущего commonGroupSize и
    // частоты текущего числа.
    //
    // После прохождения всех пар commonGroupSize станет НОДом всех частот.
    commonGroupSize = calculateGCD(commonGroupSize, pair[1]);
  }

  // Если общий делитель всех частот >= 2, значит существует размер группы
  // x > 1, на который делятся все частоты, и, следовательно, можно разбить
  // карты на группы одинакового размера x.
  //
  // Возвращаем логическое значение результата проверки.
  return commonGroupSize >= 2;
}

// Объявление вспомогательной функции calculateGCD для вычисления
// наибольшего общего делителя двух целых чисел a и b.
function calculateGCD(a, b) {

  // Реализация рекурсивного алгоритма Евклида:
  // - Если b равно 0, то НОД равен a (базовый случай рекурсии).
  //
  // - В противном случае рекурсивно вызываем calculateGCD(b, a % b), где
  //   a % b - остаток от деления a на b. Рекурсия продолжается, пока
  //   второй аргумент не станет 0 - тогда возвращается последний ненулевой
  //   остаток.
  return b === 0 ? a : calculateGCD(b, a % b);
}
