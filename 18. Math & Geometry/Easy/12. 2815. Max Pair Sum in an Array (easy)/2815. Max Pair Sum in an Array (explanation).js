/**
 * @param {number[]} nums
 * @return {number}
 *
 * maxSum принимает массив чисел nums, и возвращает максимальную
 * сумму двух чисел из этого массива, у которых совпадает
 * наибольшая цифра в их десятичном представлении. Если таких
 * пар нет, функция возвращает -1.
 *
 *
 * Пример для:
 *   nums = [2536, 1613, 3366, 162]
 * Результат:
 *   5902
 * Пояснение:
 *   Все числа в примере имеют в качестве наибольшей цифры цифру
 *   6, поэтому среди пар с одинаковой максимальной цифрой
 *   наибольшая сумма получается для пары 2536 + 3366 = 5902.
 */
function maxSum(nums) {
  const n = nums.length;

  // Создаём массив фиксированного типа Int32Array длины n для
  // хранения максимальной цифры каждого числа в его позиции.
  //
  // Использование Int32Array экономит память и ускоряет доступ
  // по сравнению с обычным массивом
  const maxDigits = new Int32Array(n);

  // Проходим по всем элементам входного массива, чтобы
  // заполнить массив maxDigits.
  for (let i = 0; i < n; i++) {

    // Для текущего элемента nums[i] вызываем вспомогательную
    // функцию getMaxDigit, которая возвращает наибольшую цифру
    // в десятичном представлении числа, и записываем результат
    // на ту же позицию в maxDigits[i].
    maxDigits[i] = getMaxDigit(nums[i]);
  }

  // Инициализируем переменную maxSum значением -1.
  //
  // Значение -1 используется как маркер "пары не найдены".
  let maxSum = -1;

  // Внешний цикл по индексам массива - перебираем первый
  // элемент пары.
  for (let i = 0; i < n; i++) {

    // Внутренний цикл начинается с i + 1, чтобы не
    // рассматривать одну и ту же пару дважды и не складывать
    // элемент сам с собой (i, i).
    for (let j = i + 1; j < n; j++) {

      // Сравниваем предварительно вычисленные максимальные
      // цифры двух чисел.
      //
      // Если они не равны, пара не удовлетворяет условию,
      // поэтому пропускаем дальнейшие действия.
      if (maxDigits[i] != maxDigits[j]) continue;

      // Если максимальные цифры совпадают, вычисляем сумму
      // nums[i] + nums[j] и обновляем maxSum, если новая
      // сумма больше текущего значения.
      maxSum = Math.max(maxSum, nums[i] + nums[j]);
    }
  }

  // Возвращаем итоговое значение maxSum: либо максимальную
  // сумму подходящей пары, либо -1, если таких пар не было.
  return maxSum;
}


// Объявление вспомогательной функции getMaxDigit, принимающей
// одно число num и возвращающей наибольшую цифру в его
// десятичном представлении.
function getMaxDigit(num) {

  // Инициализируем переменную maxDigit нулём
  let maxDigit = 0;

  // Цикл извлекает цифры числа по одной, пока num больше нуля.
  while (num > 0) {

    // Получаем последнюю цифру числа через остаток от деления
    // на 10 и сравниваем с текущим максимумом.
    //
    // Оператор % возвращает целую цифру в диапазоне 0..9 для
    // положительных num.
    maxDigit = Math.max(maxDigit, num % 10);

    // Отбрасываем последнюю цифру, деля число на 10 и округляя
    // вниз с помощью Math.floor, так как мы ее уже обработали
    num = Math.floor(num / 10);
  }

  // Возвращаем найденную максимальную цифру.
  return maxDigit;
}
