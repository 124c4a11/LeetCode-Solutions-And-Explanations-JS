/**
 * @param {string} s
 * @param {number} k
 * @return {number}
 *
 * getLucky принимает строку s и число итераций k, преобразует каждую
 * букву в её числовой эквивалент (a → 1, b → 2, …, z → 26),
 * складывает все десятичные цифры этих чисел в одну сумму, а затем
 * выполняет ещё k - 1 последовательных преобразований, где каждое
 * преобразование заменяет число на сумму его десятичных цифр.
 *
 * В результате функция возвращает итоговую сумму после всех
 * преобразований.
 *
 *
 * Пример для:
 *   s = "zbax"
 *   k = 2
 * Пояснение:
 *   Преобразование:
 *   "zbax" → "(26)(2)(1)(24)" → "262124" → 262124
 *
 *   Преобразование #1:
 *   262124 → 2 + 6 + 2 + 1 + 2 + 4 → 17
 *
 *   Преобразование #2:
 *   17 → 1 + 7 → 8
 */
function getLucky(s, k) {

  // Инициализация аккумулятора totalSum, в котором будет
  // накапливаться сумма всех цифр, извлечённых из числовых
  // представлений букв.
  let totalSum = 0;

  // Проход по каждому символу строки s.
  for (const char of s) {

    // Преобразование символа в его позицию в алфавите:
    // codePointAt(0) даёт числовой код Unicode, вычитаем 97
    // (код 'a') и прибавляем 1, чтобы привести его к диапазону 1..26,
    // где:
    // 'a' → 1, 'b' → 2 ... 'z' → 26
    let charNum = char.codePointAt(0) - 97 + 1;

    // Цикл while извлекает и суммирует все десятичные цифры числа
    // charNum.
    //
    // Условие charNum > 0 означает, что цикл выполняется, пока не
    // будут обработаны все цифры.
    while (charNum > 0) {

      // Добавляем последнюю цифру текущего charNum в общий
      // аккумулятор totalSum.
      //
      // Операция charNum % 10 возвращает остаток от деления на 10
      // - последнюю цифру charNum.
      totalSum += charNum % 10;

      // Удаляем последнюю цифру из charNum, выполняя целочисленное
      // деление на 10.
      //
      // Math.floor используется для корректного округления вниз при
      // положительных числах.
      charNum = Math.floor(charNum / 10);
    }
  }

  // Уменьшаем k на единицу, потому что первая "трансформация" суммы
  // цифр фактически уже выполнена выше. При разложении букв на цифры
  // мы получили первоначальную сумму, которая считается как первая
  // итерация по условию задачи.
  k--;

  // Выполняем оставшиеся k итераций.
  //
  // В каждой итерации заменяем totalSum на сумму его цифр.
  for (let i = 0; i < k; i++) {

    // Временная переменная currSum служит для накопления суммы цифр
    // текущего totalSum.
    //
    // Она обнуляется в начале каждой итерации.
    let currSum = 0;

    // Цикл while извлекает цифры из totalSum и суммирует их в
    // currSum.
    //
    // Важно:
    // Внутри этого цикла мы модифицируем totalSum, поэтому после
    // выхода из цикла original totalSum уже равен 0 и далее мы
    // присвоим ему currSum.
    while (totalSum > 0) {

      // Добавляем последнюю цифру totalSum в currSum.
      currSum += totalSum % 10;

      // Удаляем последнюю цифру из totalSum, сдвигая число вправо на
      // один разряд.
      totalSum = Math.floor(totalSum / 10);
    }

    // После того как все цифры исходного totalSum обработаны,
    // присваиваем totalSum значение currSum - это результат одной
    // итерации преобразования.
    totalSum = currSum;
  }

  // Возвращаем итоговое значение totalSum после выполнения всех
  // преобразований.
  return totalSum;
}
