/**
 * @param {string} coordinate1
 * @param {string} coordinate2
 * @return {boolean}
 *
 * checkTwoChessboards определяет, одинакового ли цвета две заданные клетки
 * на стандартной 8х8 шахматной доске. Она возвращает true, если клетки
 * одного цвета (обе белые или обе чёрные), и false, если они разного цвета.
 *
 * Параметры:
 * - coordinate1 (строка) - координата первой клетки.
 * - coordinate2 (строка) - координата второй клетки.
 *
 *
 * Пример для:
 *   coordinate1 = "a1",
 *   coordinate2 = "c3"
 * Результат:
 *   true
 * Пояснение:
 *   Оба поля черного цвета.
 *
 *
 * Пример для:
 *   coordinate1 = "a1",
 *   coordinate2 = "h3"
 * Результат:
 *   false
 * Пояснение:
 *   Поле "a1" черного цвета, а "h3" - белого.
 */
function checkTwoChessboards(coordinate1, coordinate2) {

  // Чтобы понять, какие клетки на шахматной доске имеют одинаковый цвет,
  // сначала рассмотрим закономерность. Если считать нижнюю левую клетку
  // (a1) чёрной, то при перемещении на одну клетку в любом направлении
  // (вверх, вниз, влево или вправо) цвет меняется. При перемещении на две
  // клетки в одном направлении цвет снова становится исходным.
  //
  // Получается следующая закономерность: если обозначить координаты каждой
  // клетки, где столбцы имеют номера от 1 до 8, а строки - от 1 до 8, то:
  // - Клетка (1,1) - чёрная
  // - Клетка (1,2) - белая (другой цвет)
  // - Клетка (2,1) - белая (другой цвет)
  // - Клетка (2,2) - чёрная (такого же цвета, как (1,1))
  //
  // Обратите внимание: когда обе координаты нечётные или обе чётные,
  // клетка чёрная. Когда одна координата нечётная, а другая чётная,
  // клетка белая.
  //
  // Это означает, что цвет зависит от того, является ли сумма
  // (столбец + строка) чётной или нечётной.
  //
  // Поэтому, чтобы проверить, имеют ли две клетки одинаковый цвет, нам не
  // нужно определять фактический цвет каждой клетки. Достаточно проверить,
  // имеют ли они одинаковую чётность.
  //
  // Если первая клетка имеет координаты (x1, y1), а вторая - (x2, y2),
  // то они имеют одинаковый цвет, если:
  //   (x1 + y1) и (x2 + y2) имеют одинаковую чётность
  //   (обе суммы чётные или обе нечётные).
  //
  // Это равносильно проверке того, является ли разность
  //     (x1 + y1) - (x2 + y2)
  //
  // чётным числом. После упрощения получаем:
  //     (x1 - x2) + (y1 - y2)
  //
  // Следовательно, вычисляем разницу между x-координатами и разницу между
  // y-координатами двух клеток. Если их сумма чётная, клетки имеют
  // одинаковый цвет. Если сумма нечётная - клетки имеют разные цвета.


  // Вычисляем разницу между столбцами:
  //
  // Метод codePointAt(0) возвращает  числовой Unicode-код первой буквы
  // (например, для 'a' это 97, для 'b' - 98).
  const colDiff = coordinate1.codePointAt(0) - coordinate2.codePointAt(0);

  // Вычисляем разницу между строками:
  //
  // Из символа цифры первой координаты (индекс 1) вычитаем символ цифры
  // второй.
  //
  // JavaScript автоматически преобразует эти строки в числа перед
  // выполнением математического вычитания.
  const rowDiff = coordinate1[1] - coordinate2[1];

  // Складываем разности координат и с помощью побитового "И" (& 1)
  // проверяем чётность:
  // - Если число чётное, возвращает 0.
  // - Если число нечётное, возвращает 1
  //
  // Если сумма чётная (результат 0), то клетки одного цвета - true,
  // иначе клетки разных цветов - false.
  return ((colDiff + rowDiff) & 1) === 0;
}
