/**
 * @param {number} num
 * @param {number} t
 * @return {number}
 *
 * theMaximumAchievableX принимает два целых числа: num и t.
 *
 * Число x называется достижимым, если оно может стать равным num
 * после применения следующей операции не более t раз:
 * - Увеличить или уменьшить x на 1 и одновременно увеличить или
 *   уменьшить num на 1.
 *
 * Возвращает максимально возможное значение x.
 *
 *
 * Пример для:
 *   num = 4,
 *   t = 1
 * Результат:
 *   6
 * Пояснение:
 *   Выполните следующую операцию один раз, чтобы максимальное
 *   достижимое число стало равным num:
 *
 *   Уменьшите максимальное достижимое число на 1 и увеличьте num
 *   на 1.
*/
function theMaximumAchievableX(num, t) {

  // Подумайте о том, что происходит при каждой операции. Когда мы
  // применяем операцию, мы можем либо:
  // - Уменьшить x на 1 и увеличить num на 1, либо
  // - Увеличить x на 1 и уменьшить num на 1
  //
  // Ключевое наблюдение: в обоих случаях расстояние между x и num
  // меняется ровно на 2. В первом случае разрыв уменьшается на 2, во
  // втором - увеличивается на 2.
  //
  // Поскольку мы хотим найти максимально возможное x, следует начать
  // с как можно большего x. Но насколько большим он может быть? Нам
  // нужно гарантировать, что после не более чем t операций x станет
  // равным num.
  //
  // Если начать с большого x (больше, чем num), его нужно уменьшить,
  // чтобы встретиться с num. Наиболее эффективный способ - в каждой
  // операции уменьшать x и увеличивать num, что сокращает разрыв на
  // 2 за операцию.
  //
  // Имея t операций, мы можем закрыть разрыв не более чем на 2 * t.
  // Следовательно, максимальное начальное значение x равно
  // num + 2 * t.
  //
  // Проверка: начав с x = num + 2 * t, после t операций уменьшения x
  // на 1 и увеличения num на 1:
  // - x станет: (num + 2 * t) - t = num + t
  // - num станет: num + t
  // - Они встретятся на num + t, что подтверждает наш ответ.
  //
  // Таким образом решение равно num + 2 * t.

  return num + t * 2;
}
