/**
 * @param {number} n
 * @return {number}
 *
 * mirrorDistance принимает число n и возвращает абсолютную
 * разницу между этим числом и числом, полученным из него путём
 * обращения порядка цифр (реверса). Вспомогательная функция
 * reverse принимает одно число x и возвращает целое число,
 * составленное из цифр x в обратном порядке.
 *
 *
 * Пример для:
 *   n = 25
 * Результат:
 *   27
 * Пояснение:
 *  reverse(25) = 52.
 *  Таким образом ответ равен abs(25 - 52) = 27.
 */
function mirrorDistance(n) {

  // Возвращаем абсолютную разницу между исходным числом n и его
  // "перевёрнутой" версией, полученной вызовом reverse(n).
  return Math.abs(n - reverse(n));
}


// Reverse принимает один параметр x - число, которое нужно
// "перевернуть" по цифрам.
function reverse(x) {

  // Инициализация аккумулятора y нулём.
  //
  // В процессе работы цикла в y будет накапливаться
  // перевёрнутое число.
  let y = 0;

  // Цикл выполняется, пока в x остаются цифры (пока x > 0).
  while (x > 0) {

    // Берём последнюю цифру x через x % 10 и добавляем её в
    // конец y:
    //
    // Сначала сдвигаем y в десятичном представлении (умножаем
    // на 10), затем прибавляем последнюю цифру.
    //
    // Пример для x=123 y=0:
    //   y = 0*10 + 3 → 3;
    //   y = 3*10 + 2 → 32;
    //   y = 32*10 + 1 → 321.
    y = y * 10 + (x % 10);

    // Удаляем последнюю цифру из x, выполняя целочисленное
    // деление на 10 через Math.floor.
    x = Math.floor(x / 10);
  }

  // После завершения цикла y содержит перевёрнутое по цифрам
  // значение исходного x. Возвращаем его.
  return y;
}
