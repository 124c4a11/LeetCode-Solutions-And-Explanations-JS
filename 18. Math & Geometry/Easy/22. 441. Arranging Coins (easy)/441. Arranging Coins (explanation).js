/**
 * @param {number} n
 * @return {number}
 *
 * У вас есть n монет, и вы хотите построить из них лестницу. Лестница
 * состоит из k рядов, где i-й ряд содержит ровно i монет. Последний ряд
 * лестницы может быть незавершенным.
 *
 * arrangeCoins принимает целое число n.
 *
 * Возвращает количество полных рядов лестницы, которые вы сможете
 * построить.
 *
 * Пример для:
 *   n = 5
 * Результат:
 *   2
 * Пояснение:
 *   Так как 3-й ряд заполнен не полностью, мы возвращаем 2.
 */
function arrangeCoins(n) {

  // Вычисляем точное количество рядов, используя формулу корней
  // квадратного уравнения, и возвращаем результат.
  //
  // Математическое обоснование:
  // Количество монет в k полностью заполненных рядах представляет собой
  // сумму арифметической прогрессии: 1 + 2 + 3 + ... + k. Эта сумма
  // вычисляется по формуле: S = k * (k + 1) / 2.
  //
  // Нам нужно найти максимальное целое k, при котором сумма монет не
  // превышает n, то есть: k * (k + 1) / 2 <= n. Если приравнять это
  // соотношение к уравнению k * (k + 1) / 2 = n и раскрыть скобки, мы
  // получим: k^2 + k = 2n.
  //
  // Переносим все члены в одну сторону, чтобы получить стандартное
  // квадратное уравнение: k^2 + k - 2n = 0. В этом уравнении коэффициенты
  // равны: a = 1, b = 1, c = -2n.
  //
  // Поиск корней:
  // Формула дискриминанта: D = b^2 - 4ac.
  // Подставляем значения: D = 1^2 - 4 * 1 * (-2n) = 1 + 8n.
  // Нам нужен только положительный корень k, так как количество рядов не
  // может быть отрицательным.
  // Формула положительного корня: k = (-b + sqrt(D)) / 2a.
  // Подставляем коэффициенты: k = (-1 + sqrt(1 + 8n)) / 2.
  //
  // Пошаговый разбор кода внутри return:
  // 1. 8 * n - умножаем количество монет на 8 для расчета дискриминанта.
  //
  // 2. 1 + 8 * n - прибавляем 1, получая полное значение дискриминанта под
  //    корнем.
  //
  // 3. Math.sqrt(...) - извлекаем квадратный корень из полученного
  //    дискриминанта.
  //
  // 4. -1 + Math.sqrt(...) - вычитаем единицу (коэффициент -b) из
  //    результата корня.
  //
  // 5. (... ) / 2 - делим полученное выражение на 2 (знаменатель 2a),
  //    получая точное вещественное число рядов.
  //
  // 6. Math.floor(...) - округляем результат вниз до ближайшего целого
  //    числа. Округление вниз необходимо, потому что если число рядов
  //    получилось дробным (например, 2.7), это означает, что 3-й ряд
  //    заполнен лишь частично, а по условию задачи нам нужно вернуть
  //    исключительно количество полностью завершенных рядов.
  return Math.floor((-1 + Math.sqrt(1 + 8 * n)) / 2);
}
